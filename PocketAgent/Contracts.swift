    public let stage: String
    /// Фраза, которую видит человек.
    public let human: String
    /// Точная подробность: вид ошибки и оригинальный текст библиотеки.
    public let technical: String

    public init(at: Date = Date(), stage: String, human: String, technical: String) {
        self.at = at
        self.stage = stage
        self.human = human
        self.technical = technical
    }
}

/// Небольшой журнал последних событий движка.
///
/// ⚠️ ЗДЕСЬ ЛЕЖИТ ВСЁ, В ТОМ ЧИСЛЕ ЛИЧНОЕ — И ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА, 10.08.2026.
/// Раньше правило было обратным: ни содержимого файлов, ни текста задач, ни ответов
/// модели. Владелец потребовал полноты дословно — «сделай так чтоб попадали, это
/// закрытый продукт только для меня», — потому что без этого журнал не разобрать:
/// по строке «параметров: 2» не видно, что помощник восемь раз просил файл
/// с опечаткой в имени.
/// Поэтому сюда пишутся и события, и текст задачи, и параметры действий, и ответы
/// модели, и куски прочитанных файлов. Журнал целиком уходит в буфер обмена
/// по кнопке — предупреждение об этом стоит прямо на экране журнала, чтобы человек
/// решал осознанно. Обрезаем длинное с явной пометкой, но не прячем.
/// ⚠️ В системный журнал телефона (os_log) уходит КОРОТКАЯ версия: его снимают
/// проводом, и это уже не «по кнопке человека».
///
/// ⚠️ Только память: ни файла на диске, ни отправки в сеть. Пережить перезапуск
/// приложения журнал не обязан — он нужен, чтобы объяснить поломку здесь и сейчас.
///
/// Замок вместо актора намеренно: журнал читает экран на главном потоке (рисование
/// списка), а пишет в него актор движка. Через актор чтение стало бы асинхронным,
/// и список пришлось бы обновлять задачей на каждый кадр.
public final class RuntimeJournal: @unchecked Sendable {

    public static let shared = RuntimeJournal()

    /// Сколько последних событий храним.
    ///
    /// ⚠️ БЫЛО 50, СТАЛО 150 — и это не «на всякий случай». С 10.08.2026 каждое действие
    /// модели даёт ДВА события (просьба и её итог), плюс отдельные события на текст задачи
    /// и на ответ модели. При прежних пятидесяти длинная задача вытесняла из журнала
    /// собственное начало — то есть саму задачу и первые шаги, без которых разбирать нечего.
    /// Восемнадцати шагов реальной задачи уже хватало, чтобы съесть весь буфер.
    public static let capacity = 150

    private let lock = NSLock()
    private var storage: [RuntimeEvent] = []
    private var failure: RuntimeFailure?
    private var garbledCount = 0

    public init() {}

    /// Записать событие. Зовётся откуда угодно, в том числе из актора движка.
    public func record(_ kind: RuntimeEventKind, _ text: String, detail: String? = nil) {
        let event = RuntimeEvent(kind: kind, text: text, detail: detail)
        lock.lock()
        storage.append(event)
        if storage.count > Self.capacity {
            storage.removeFirst(storage.count - Self.capacity)
        }
        lock.unlock()
    }

    /// Записать ошибку: и в журнал, и отдельно как «последнюю» — её показывает экран
    /// второй строкой под человеческой фразой.
    public func recordFailure(stage: String, human: String, technical: String) {
        let value = RuntimeFailure(stage: stage, human: human, technical: technical)
        lock.lock()
        failure = value
        lock.unlock()
        record(.failure, human, detail: "\(stage): \(technical)")
    }

    /// Отметить, что модель ответила так, что библиотека не смогла это разобрать.
    ///
    /// ⚠️ Счётчик нужен циклу агента: наружу кривой ответ отдаётся ПУСТЫМ ходом,
    /// и без этой отметки «модель промолчала» и «модель ответила мусором»
    /// выглядели бы для человека одинаково.
    public func noteGarbledAnswer() {
        lock.lock()
        garbledCount += 1
        lock.unlock()
    }

    public var garbledAnswerCount: Int {
        lock.lock()
        defer { lock.unlock() }
        return garbledCount
    }

    public var entries: [RuntimeEvent] {
        lock.lock()
        defer { lock.unlock() }
        return storage
    }

    public var lastFailure: RuntimeFailure? {
        lock.lock()
        defer { lock.unlock() }
        return failure
    }

    public func clear() {
        lock.lock()
        storage.removeAll()
        failure = nil
        lock.unlock()
    }

    /// Весь журнал одним текстом — то, что уходит в буфер обмена.
    public func plainText() -> String {
        let list = entries
        guard !list.isEmpty else { return "Журнал пуст: движок ещё ничего не делал." }
        return list.map(\.line).joined(separator: "\n")
    }

    /// Точная подробность любой ошибки: вид, текст и полный разбор значения.
    /// Единственное место, где ошибка превращается в техническую строку, —
    /// чтобы и движок, и цикл агента писали в журнал одинаково.
    public static func technicalText(for error: Error) -> String {
        var parts: [String] = ["вид: \(type(of: error))"]
        if let described = (error as? LocalizedError)?.errorDescription, !described.isEmpty {
            parts.append("текст: \(described)")
        }
        let nsError = error as NSError
        parts.append("код: \(nsError.domain) \(nsError.code)")
        parts.append("значение: \(String(reflecting: error))")
        return parts.joined(separator: " · ")
    }
}

