/// Инструмент, который РЕАЛЬНО делает работу (в отличие от структур схемы для LiteRT-LM).
/// Реализации живут в Tools/FileToolsImpl.swift и держат ссылку на FileWorkspace.
public protocol AgentTool: Sendable {
    /// Какой из четырёх.
    var kind: ToolKind { get }
    /// Имя для модели. По умолчанию kind.rawValue — переопределять нельзя.
    var name: String { get }
    /// Описание для модели.
    var details: String { get }
    /// Схема параметров.
    var parameters: [ToolParameterSpec] { get }
    /// Построить предпросмотр, ничего не меняя на диске.
    func preview(_ invocation: ToolInvocation) async throws -> ActionPreview
    /// Выполнить. Для write_file вызывается ТОЛЬКО после подтверждения пользователем.
    /// Работа с диском обязана идти вне главного потока.
    func execute(_ invocation: ToolInvocation) async throws -> ToolResult
    /// Забыть построенный предпросмотр: человек отклонил действие или ход отменён.
    /// Иначе содержимое, от которого отказались, живёт в памяти до вытеснения.
    func discardPreview(for invocationID: String)
    /// Забыть все предпросмотры (сброс разговора, смена папки).
    func discardAllPreviews()
}

public extension AgentTool {
    var name: String { kind.rawValue }
    var declaration: ToolDeclaration {
        ToolDeclaration(name: name, details: details, parameters: parameters)
    }
    /// По умолчанию инструменту нечего забывать — предпросмотры хранит только write_file.
    func discardPreview(for invocationID: String) {}
    func discardAllPreviews() {}
}

/// Реестр инструментов: четыре обязательных и, если человек включил поиск, пятый.
public protocol ToolRegistry: Sendable {
    var tools: [any AgentTool] { get }
    var declarations: [ToolDeclaration] { get }
    func tool(for invocation: ToolInvocation) -> (any AgentTool)?
}

