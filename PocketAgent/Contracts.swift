/// Запрос модели на один инструмент.
/// ⚠️ Имя специально НЕ ToolCall — так называется тип внутри LiteRTLM,
/// и совпадение имён в одном таргете даёт неоднозначность. Конвертация — в Runtime.
public struct ToolInvocation: Sendable, Equatable, Identifiable {
    /// Устойчивый идентификатор для SwiftUI и для сопоставления результата.
    /// ⚠️ ВСЕГДА наш собственный UUID и НИКОГДА не строка от модели: по этому ключу
    /// лежит показанный человеку дифф — единственный предохранитель записи.
    /// Дай модели управлять ключом — и она сможет подсунуть под подтверждение чужой дифф.
    public let id: String
    /// id вызова, который прислала модель (может быть пустым — тогда не кладём его в ответ).
    public let callID: String
    /// Имя инструмента ровно как его назвала модель.
    public let rawName: String
    /// Разобранный вид инструмента; nil — модель назвала что-то неизвестное.
    public let kind: ToolKind?
    /// Аргументы, приведённые к строкам (все четыре инструмента принимают только строки).
    public let arguments: [String: String]

    public init(rawName: String, callID: String, arguments: [String: String]) {
        self.rawName = rawName
        self.callID = callID
        self.arguments = arguments
        self.kind = ToolKind(rawValue: rawName)
        self.id = "\(rawName)-\(UUID().uuidString)"
    }

    /// Конвертация из нетипизированного словаря LiteRT-LM. Единственная точка приведения типов.
    public init(rawName: String, callID: String, rawArguments: [String: Any]) {
        self.init(rawName: rawName,
                  callID: callID,
                  arguments: ToolInvocation.normalize(rawArguments))
    }

    /// Числа и логические значения превращаем в строки, всё непонятное отбрасываем.
    /// ⚠️ Порядок веток важен: на Darwin и Bool, и Int, и Double приезжают из JSON
    /// одним типом NSNumber. Если сначала проверять число, то `true` превратится
    /// в строку "1". Поэтому логическое значение опознаём ПЕРВЫМ и по-честному —
    /// сравнением типа обёртки, а не приведением `as? Bool` (оно проходит и для 1).
    public static func normalize(_ raw: [String: Any]) -> [String: String] {
        var out: [String: String] = [:]
        for (key, value) in raw {
            if let text = value as? String {
                out[key] = text
            } else if let number = value as? NSNumber {
                if CFGetTypeID(number) == CFBooleanGetTypeID() {
                    out[key] = number.boolValue ? "true" : "false"
                } else {
                    out[key] = number.stringValue
                }
            } else if let flag = value as? Bool {
                // Запасной путь: на не-Darwin платформе Bool в NSNumber не бриджится.
                out[key] = flag ? "true" : "false"
            }
            // Всё остальное (массивы, словари, null) модели не нужно — отбрасываем.
        }
        return out
    }

    // Удобные обращения к аргументам наших четырёх инструментов.

    /// Путь к файлу или папке.
    ///
    /// ⚠️ СИНОНИМЫ ЗДЕСЬ ОБЯЗАТЕЛЬНЫ, И ЭТО НЕ ПЕРЕСТРАХОВКА. У номеров строк и у
    /// поискового запроса синонимы стояли с самого начала — ровно потому, что модель
    /// на 2–4 млрд параметров легко пишет `line` вместо `from_line`. А у САМОГО ЧАСТОГО
    /// параметра, пути, их не было вовсе: пришло `file` вместо `path` — и мы честно
    /// считали, что модель не назвала путь, отвечали «не хватает параметра» и тратили
    /// шаг человека впустую. На маленькой модели такой отказ почти всегда повторяется
    /// тем же вызовом, то есть превращается в тот самый круг.
    ///
    /// ⚠️ Порядок имён важен: `path` первым, дальше от точного к общему. `name` идёт
    /// последним нарочно — он самый двусмысленный.
    public var path: String {
        Self.firstArgument(in: arguments, names: Self.pathNames) ?? ""
    }

    public var content: String? {
        Self.firstArgument(in: arguments, names: Self.contentNames)
    }

    /// Короткий итог для finish.
    ///
    /// ⚠️ Без синонимов пустой `summary` означал «модель закончила молча»: человек
    /// видел завершение без единого слова ответа. Ради этого поля finish и существует.
    public var summary: String {
        Self.firstArgument(in: arguments, names: Self.summaryNames) ?? ""
    }

    private static let pathNames = [
        "path", "file_path", "filepath", "file", "filename", "file_name",
        "directory", "dir", "folder", "folder_path", "directory_path", "name"
    ]
    private static let contentNames = ["content", "text", "body", "new_content", "data"]
    private static let summaryNames = ["summary", "answer", "result", "text", "message", "итог"]

    /// Номер первой строки диапазона — КАК ЕГО ПРИСЛАЛА МОДЕЛЬ, без разбора числа.
    /// Пусто/отсутствует — диапазона нет.
    ///
    /// ⚠️ Здесь мы намеренно не превращаем текст в число: «модель прислала мусор вместо
    /// номера» и «модель номер не присылала» — разные случаи, и путать их нельзя.
    /// В первом случае надо честно отказать, во втором — работать как раньше, с файлом
    /// целиком. Разбор числа делает сам инструмент, он же и отказывает.
    ///
    /// ⚠️ Синонимы имён нужны потому, что модель на 2 млрд параметров легко пишет
    /// `start_line` или `line` вместо `from_line`. Не опознать синоним — значит молча
    /// принять правку куска за перезапись всего файла, а это потеря данных человека.
    public var rawFromLine: String? { Self.firstArgument(in: arguments, names: Self.fromLineNames) }
    /// Номер последней строки диапазона — тоже как есть, без разбора.
    public var rawToLine: String? { Self.firstArgument(in: arguments, names: Self.toLineNames) }

    /// Модель просит работать с диапазоном строк (хотя бы одна из границ названа).
    public var mentionsLineRange: Bool { rawFromLine != nil || rawToLine != nil }

    /// Что модель просит найти в интернете. Пусто — она не назвала запрос.
    ///
    /// ⚠️ Синонимы — по той же причине, что и у номеров строк: модель на 2 млрд
    /// параметров легко пишет `q` или `search` вместо `query`. Не опознать синоним —
    /// значит ответить «не хватает параметра» на совершенно понятный вызов
    /// и потратить шаг человека впустую.
    public var query: String {
        Self.firstArgument(in: arguments, names: Self.queryNames) ?? ""
    }

    private static let fromLineNames = ["from_line", "start_line", "line", "from", "first_line"]
    private static let toLineNames = ["to_line", "end_line", "to", "last_line"]
    private static let queryNames = ["query", "q", "search", "text", "question", "запрос"]

    private static func firstArgument(in arguments: [String: String], names: [String]) -> String? {
        for name in names {
            if let value = arguments[name], !value.trimmingCharacters(in: .whitespaces).isEmpty {
                return value
            }
        }
        return nil
    }

    /// Имена обязательных параметров, которых модель не прислала.
    ///
    /// ⚠️ СИНОНИМЫ УЧИТЫВАЕМ И ЗДЕСЬ, ИНАЧЕ ОНИ БЕСПОЛЕЗНЫ. Проверка «параметра нет»
    /// стоит РАНЬШЕ инструмента: пришло `file` вместо `path` — и вызов отвергался как
    /// неполный, не дойдя до места, где синоним понимают. Получалось так: синонимы
    /// вроде есть, а вызов всё равно отклонён. Разошлись бы эти два списка — ошибка
    /// была бы тихой и очень дорогой, поэтому имя ищем ровно тем же способом.
    public func missingArguments(for declaration: ToolDeclaration) -> [String] {
        declaration.parameters
            .filter { $0.isRequired && Self.value(named: $0.name, in: arguments) == nil }
            .map(\.name)
    }

    /// Значение параметра с учётом синонимов: сперва точное имя, затем известные замены.
    private static func value(named name: String, in arguments: [String: String]) -> String? {
        if let exact = arguments[name], !exact.trimmingCharacters(in: .whitespaces).isEmpty {
            return exact
        }
        for family in synonymFamilies where family.contains(name) {
            if let found = firstArgument(in: arguments, names: family) { return found }
        }
        return nil
    }

    /// Все семьи синонимов в одном месте — чтобы список нельзя было пополнить
    /// наполовину (в удобном обращении есть, в проверке обязательных нет).
    private static var synonymFamilies: [[String]] {
        [pathNames, contentNames, summaryNames, fromLineNames, toLineNames, queryNames]
    }
}

