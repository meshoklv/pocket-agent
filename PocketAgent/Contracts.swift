/// Вид события — по нему экран журнала подбирает значок и цвет.
public enum RuntimeEventKind: String, Sendable, Equatable, Codable {
    /// Запуск и остановка движка.
    case engine
    /// На чём считает модель: видеочип или процессор.
    case backend
    /// Ход модели: пришёл вызов инструмента, текст, пусто, неразборчиво.
    case turn
    /// Ошибка с точным текстом библиотеки.
    case failure
    /// Всё остальное.
    case note

    /// Название вида человеческим языком.
    public var title: String {
        switch self {
        case .engine:  return "Движок"
        case .backend: return "Расчёт"
        case .turn:    return "Ход модели"
        case .failure: return "Ошибка"
        case .note:    return "Событие"
        }
    }
}

/// Одна запись журнала: что случилось (по-русски) и точная подробность для разбора.
public struct RuntimeEvent: Sendable, Equatable, Identifiable {
    public let id: UUID
    public let at: Date
    public let kind: RuntimeEventKind
    /// Что случилось — человеческим языком.
    public let text: String
    /// Точная техническая подробность: вид ошибки, оригинальный текст библиотеки, числа.
    public let detail: String?

    public init(id: UUID = UUID(),
                at: Date = Date(),
                kind: RuntimeEventKind,
                text: String,
                detail: String? = nil) {
        self.id = id
        self.at = at
        self.kind = kind
        self.text = text
        self.detail = detail
    }

    /// «12:34:56» — время события для экрана.
    public var timeText: String {
        at.formatted(date: .omitted, time: .standard)
    }

    /// Одна строка для буфера обмена.
    public var line: String {
        var out = "\(timeText) · \(kind.title) · \(text)"
        if let detail, !detail.isEmpty {
            out += "\n            \(detail)"
        }
        return out
    }
}

/// Последняя ошибка движка целиком: и фраза для человека, и точный текст библиотеки.
