/// Тело ответа инструмента. Всё содержимое обязано быть JSON-совместимым.
public enum ToolPayload: Sendable, Equatable {
    case text(String)
    case lines([String])
    case fields([String: String])

    /// Представление для отправки в модель.
    public var jsonObject: Any {
        switch self {
        case .text(let value):    return value
        case .lines(let values):  return values
        case .fields(let values): return values
        }
    }

    /// Весь текст тела — по нему считаем, влезет ли ответ инструмента в кэш разговора.
    public var plainText: String {
        switch self {
        case .text(let value):    return value
        case .lines(let values):  return values.joined(separator: "\n")
        case .fields(let values): return values.map { "\($0.key): \($0.value)" }.joined(separator: "\n")
        }
    }

    /// Оценка длины в токенах (грубая, намеренно с запасом).
    public var estimatedTokens: Int {
        ConversationHistory.estimateTokens(plainText)
    }

    /// В теле лежит СОДЕРЖИМОЕ ФАЙЛА (ответ read_file).
    ///
    /// ⚠️ Такое тело запрещено подрезать: модель на 2 млрд параметров игнорирует приписку
    /// «текст неполный» и присылает write_file с обрезанным содержимым — то есть предлагает
    /// снести невидимый ей хвост файла. Когда содержимое не помещается в кэш разговора,
    /// мы отвечаем моделью честной ошибкой, а не куском.
    public var carriesFileContent: Bool {
        if case .fields(let values) = self { return values["content"] != nil }
        return false
    }

    /// Подрезанная копия, чтобы уложиться примерно в `tokenLimit` токенов.
    /// Обрезаем самое длинное значение и честно говорим модели, что текст неполный, —
    /// иначе она «допишет» файл по обрезанному куску и снесёт невидимый остаток.
    public func truncated(toApproximately tokenLimit: Int) -> ToolPayload {
        guard tokenLimit > 0, estimatedTokens > tokenLimit else { return self }
        // Оценка «латиница ~4 символа на токен, кириллица ~2» → берём худший случай.
        let characterBudget = max(200, tokenLimit * 2)

        func cut(_ text: String) -> String {
            guard text.count > characterBudget else { return text }
            return String(text.prefix(characterBudget))
                + "\n… ТЕКСТ ОБРЕЗАН: он не помещается в память разговора. "
                + "Не переписывай файл целиком по этому куску."
        }

        switch self {
        case .text(let value):
            return .text(cut(value))
        case .lines(let values):
            var out: [String] = []
            var used = 0
            for line in values {
                if used + line.count > characterBudget {
                    out.append("… список обрезан: показано \(out.count) из \(values.count)")
                    break
                }
                used += line.count
                out.append(line)
            }
            return .lines(out)
        case .fields(let values):
            guard let longest = values.max(by: { $0.value.count < $1.value.count }) else { return self }
            var copy = values
            copy[longest.key] = cut(longest.value)
            copy["truncated"] = "true"
            return .fields(copy)
        }
    }
}

/// Чем закончилось действие.
public enum ToolOutcome: String, Sendable, Equatable, Codable {
    /// Выполнено.
    case success
    /// Пользователь нажал «Отклонить».
    case rejectedByUser
    /// Не выполнилось (ошибка пути, файла, прав).
    case failed
}

/// Результат одного действия: что уходит в модель и что видит человек.
public struct ToolResult: Sendable, Equatable, Identifiable {
    public var id: String { invocationID }
    /// ToolInvocation.id, к которому относится результат.
    public let invocationID: String
    /// callID модели (пустой — не класть в ответ).
    public let callID: String
    /// Имя инструмента ровно как в запросе модели.
    public let toolName: String
    public let outcome: ToolOutcome
    /// То, что уходит в модель.
    public let payload: ToolPayload
    /// Короткая строка для ленты чата, человеческим языком.
    public let userSummary: String
    /// Наша типизированная ошибка, если действие не выполнилось.
    ///
    /// ⚠️ Нужна ровно затем, чтобы отличать «модель предложила ерунду» от «мир изменился».
    /// Раньше любой отказ считался кривым ходом модели, и два подряд «файл изменился
    /// снаружи» (папка в iCloud синхронизируется с компьютера) останавливали задачу
    /// совсем — хотя модель не виновата.
    public let failure: PocketAgentError?

    public init(invocationID: String,
                callID: String,
                toolName: String,
                outcome: ToolOutcome,
                payload: ToolPayload,
                userSummary: String,
                failure: PocketAgentError? = nil) {
        self.invocationID = invocationID
        self.callID = callID
        self.toolName = toolName
        self.outcome = outcome
        self.payload = payload
        self.userSummary = userSummary
        self.failure = failure
    }

    /// Файл на диске разошёлся с показанным человеком предпросмотром.
    /// Это не ошибка модели: предпросмотр надо пересобрать и показать заново.
    public var isFileChangedSinceDiff: Bool {
        if case .fileChangedSinceDiff = failure { return true }
        return false
    }

    /// Действие не выполнилось из-за СЕТИ, а не из-за кривого хода модели.
    ///
    /// ⚠️ Различать это важно ровно по той же причине, что и «файл изменился снаружи»:
    /// цикл агента считает неудачные ходы подряд и останавливает задачу на третьем.
    /// Метро, самолёт и лифт — не вина модели, и терять из-за них задачу человека
    /// нельзя. Свойство заведено для того, чтобы счётчик неудачных ходов его пропускал.
    public var isNetworkProblem: Bool {
        if case .webSearchFailed = failure { return true }
        return false
    }

    public static func success(for invocation: ToolInvocation,
                               payload: ToolPayload,
                               userSummary: String) -> ToolResult {
        ToolResult(invocationID: invocation.id,
                   callID: invocation.callID,
                   toolName: invocation.rawName,
                   outcome: .success,
                   payload: payload,
                   userSummary: userSummary)
    }

    public static func rejected(_ invocation: ToolInvocation,
                                reason: String) -> ToolResult {
        ToolResult(invocationID: invocation.id,
                   callID: invocation.callID,
                   toolName: invocation.rawName,
                   outcome: .rejectedByUser,
                   payload: .fields(["error": reason]),
                   userSummary: reason)
    }

    public static func failure(_ invocation: ToolInvocation,
                               reason: String,
                               error: PocketAgentError? = nil) -> ToolResult {
        ToolResult(invocationID: invocation.id,
                   callID: invocation.callID,
                   toolName: invocation.rawName,
                   outcome: .failed,
                   payload: .fields(["error": reason]),
                   userSummary: reason,
                   failure: error)
    }

    /// Отказ по нашей типизированной ошибке — текст берём из неё же.
    public static func failure(_ invocation: ToolInvocation,
                               error: PocketAgentError) -> ToolResult {
        failure(invocation,
                reason: error.errorDescription ?? "Действие не выполнено.",
                error: error)
    }

    /// Тот же результат с другим телом — нужно, чтобы подрезать слишком длинный ответ
    /// перед отправкой в модель, не трогая то, что уже показано человеку.
    public func withPayload(_ newPayload: ToolPayload) -> ToolResult {
        ToolResult(invocationID: invocationID,
                   callID: callID,
                   toolName: toolName,
                   outcome: outcome,
                   payload: newPayload,
                   userSummary: userSummary,
                   failure: failure)
    }
}

