    /// Список моделей у поставщика спросить не удалось.
    case remoteModelsUnavailable
    /// ⚠️ ГЛАВНАЯ ИЗ ЭТОЙ ГРУППЫ. Достигнут предел трат — работа останавливается.
    /// Числа в миллионных доллара, как их считает `RemoteSpend`.
    case remoteSpendLimitReached(spentMicros: Int, limitMicros: Int)
    /// Всё остальное, что не получилось по сети. Внутри — готовая русская фраза.
    case remoteRequestFailed(String)

    public var errorDescription: String? {
        switch self {
        case .modelFileMissing:
            return "Файл модели не найден — нужно скачать модель."
        case .modelFileCorrupted:
            return "Файл модели повреждён. Скачайте заново."
        case .notEnoughDiskSpace:
            return "Не хватает места на телефоне для модели. Освободите место и повторите."
        case .downloadStopped:
            return "Загрузка остановлена. Она сохранена — при следующей попытке продолжится "
                + "с этого места, качать заново не придётся."
        case .diskSpaceRanOutWhileDownloading(let freeBytes):
            return "Место на телефоне кончилось: свободно \(HumanFormat.bytes(freeBytes)). "
                + "Загрузка остановлена и сохранена — освободите место и нажмите «Продолжить», "
                + "качать заново не придётся."
        case .notEnoughMemory(let available, let required):
            return "Не хватает памяти: свободно \(available) МБ, нужно около \(required) МБ. "
                + "Закройте другие приложения и попробуйте снова."
        case .memoryPressureDuringLoad:
            return "Телефону не хватило памяти, пока загружалась модель. "
                + "Закройте другие приложения и попробуйте снова."
        case .runtimeNotReady:
            return "Модель ещё не готова."
        case .sessionNotStarted:
            return "Разговор не начат."
        case .generationFailed(let reason):
            // ⚠️ Текст отдаём КАК ЕСТЬ, без приставки «Модель не смогла ответить:».
            // Приставка склеивалась с английским системным текстом внутри и давала
            // фразу на двух языках. Все места, которые бросают эту ошибку, обязаны
            // класть внутрь готовую русскую фразу — что случилось и что делать.
            return reason
        case .generationCancelled:
            return "Ответ отменён."
        case .noProjectFolder:
            return "Папка проекта не выбрана."
        case .folderAccessDenied:
            return "Нет доступа к папке. Выберите её заново."
        case .protectedFolderChosen(let name):
            return "«\(name)» — служебная папка, приложение в ней не работает. "
                + "Выберите папку самого проекта."
        case .bookmarkUnusable:
            return "Доступ к папке потерян. Выберите папку заново."
        case .pathEscapesRoot(let path):
            return "Путь «\(path)» выходит за пределы выбранной папки."
        case .pathIsProtected(let path):
            return "«\(path)» — служебный файл или папка. Ни читать, ни менять их нельзя."
        case .fileLooksLikeSecret(let path):
            return "В файле «\(path)» похоже лежит пароль или ключ доступа. "
                + "Агент такие файлы не читает, чтобы они не попали в память модели."
        case .emptyPath:
            return "Пустой путь."
        case .fileNotFound(let path):
            return "Файл «\(path)» не найден."
        case .notARegularFile(let path):
            return "«\(path)» — не обычный файл."
        case .pathIsFolderNotFile(let path):
            return "«\(path)» — это папка, а не файл. Чтобы увидеть, что внутри, посмотрите её."
        case .pathIsFileNotFolder(let path):
            // ⚠️ Текст обязан НАЗВАТЬ ВЫХОД, а не только отказать: этот ответ читает
            // не только человек, но и модель, и без подсказки она повторяет тот же вызов.
            return "«\(path)» — это файл, а не папка. Чтобы увидеть, что внутри, прочитайте его."
        case .toolTimedOut:
            return "Действие не ответило за отведённое время — приложение его прекратило."
        case .fileNotDownloaded(let path):
            return "Файл «\(path)» лежит в iCloud и ещё не скачан на телефон. "
                + "Откройте его один раз в приложении «Файлы» — после этого он будет читаться сразу."
        case .fileTooLarge(let path, let bytes):
            return "Файл «\(path)» слишком большой — \(HumanFormat.bytes(bytes)). "
                + "Агент работает с файлами до \(AgentLimits.maxFileBytes / 1024) КБ. "
                + "Откройте его в редакторе на компьютере."
        case .notUTF8(let path):
            return "Файл «\(path)» не читается как текст."
        case .fileChangedSinceDiff(let path):
            // ⚠️ Здесь нельзя обещать, что предпросмотр уже пересобран. Этот текст
            // показывается ровно в тех случаях, когда пересобрать НЕ удалось или нельзя
            // (правка по номерам строк: после чужой правки номера указывают не туда).
            // Честная просьба перечитать файл — единственное, что тут правда.
            return "Файл «\(path)» изменился, пока вы смотрели предпросмотр — "
                + "его поменяли из другого приложения. Ничего не записано: "
                + "прочитайте файл заново и повторите правку."
        case .contextFullForFile(let path):
            return "Файл «\(path)» не помещается в память разговора. "
                + "Начните новую задачу — тогда памяти хватит."
        case .readFailed(let path, let reason):
            return "Не удалось прочитать «\(path)»: \(reason)"
        case .writeFailed(let path, let reason):
            return "Не удалось записать «\(path)»: \(reason)"
        case .unknownTool(let name):
            return "Неизвестное действие: \(name)"
        case .missingArgument(let tool, let argument):
            return "Для действия \(tool) не хватает параметра «\(argument)»."
        case .stepLimitReached(let limit):
            return "Достигнут предел в \(limit) шагов. Начните новую задачу."
        case .webSearchDisabled:
            // ⚠️ Текст читают двое: человек в переписке и модель следующим ходом.
            // Поэтому здесь и объяснение человеку, где включить, и понятный модели
            // приказ — не долбиться в поиск, а работать с файлами.
            return "Поиск в интернете выключен. Включить его можно в настройках приложения. "
                + "Работай с файлами в папке."
        case .webSearchFailed(let reason):
            return reason
        case .remoteNotConfigured(let what):
            // ⚠️ ДОРОГУ НАЗЫВАЕМ ТУ, ПО КОТОРОЙ МОЖНО ДОЙТИ. Раньше здесь стояло
            // «в меню» — а меню с этим пунктом есть только на рабочем экране чата,
            // до которого без поднятой модели не добраться. Экран «Работа по ключу»
            // живёт во вкладке «Модели»: туда человек попадает всегда.
            return "Работа по ключу не настроена. \(what) "
                + "Откройте вкладку «Модели» → «Работа по ключу» и заполните недостающее."
        case .remoteKeyRejected:
            return "Поставщик не принял ключ. Проверьте, что он скопирован целиком "
                + "и что это ключ именно того поставщика, который выбран."
        case .remoteOutOfFunds:
            return "На вашем счету у поставщика кончились деньги. Пополните счёт "
                + "или переключитесь на модель в телефоне."
        case .remoteModelUnknown(let name):
            return "Поставщик не знает модель «\(name)». Выберите её из списка заново — "
                + "у поставщиков модели появляются и исчезают."
        case .remoteBusy:
            return "Поставщик просит подождать: слишком много запросов. Повторите через минуту."
        case .remoteServerBroken:
            return "У поставщика поломка на его стороне. Повторите позже "
                + "или переключитесь на модель в телефоне."
        case .remoteBadAddress(let address):
            return "Адрес «\(address)» не похож на адрес. "
                + "Проверьте его во вкладке «Модели» → «Работа по ключу»."
        case .remoteModelsUnavailable:
            return "Список моделей у поставщика получить не удалось. "
                + "Имя модели можно вписать руками."
        case .remoteSpendLimitReached(let spent, let limit):
            // ⚠️ Текст должен отвечать сразу на три вопроса: почему остановились,
            // сколько потрачено и что делать. Иначе человек решит, что приложение сломалось.
            return "Достигнут предел трат: \(RemoteSpend.money(spent)) из \(RemoteSpend.money(limit)). "
                + "Работа по ключу остановлена. Поднять предел, начать счёт заново или "
                + "вернуться к модели в телефоне можно во вкладке «Модели» → «Работа по ключу»."
        case .remoteRequestFailed(let reason):
            return reason
        }
    }
