/// Предпросмотр записи файла: что было и что станет.
public struct FileDiff: Sendable, Equatable, Identifiable {
    public var id: String { relativePath }
    /// Путь относительно корня проекта.
    public let relativePath: String
    /// Файла ещё нет — будет создан.
    public let isNewFile: Bool
    /// Текст «до» (nil для нового файла).
    public let oldText: String?
    /// Текст «после» — ровно то, что запишем.
    public let newText: String
    public let hunks: [DiffHunk]
    public let addedCount: Int
    public let removedCount: Int
    /// Дата изменения файла на момент построения диффа.
    /// Перед записью сверяем: файл могли поменять из другого приложения.
    public let baseModificationDate: Date?
    /// Дифф оказался больше AgentLimits.maxDiffLines и показан не целиком.
    public let isTruncated: Bool
    /// Текст «до» и текст «после» совпадают ПОБАЙТОВО — записывать нечего.
    /// Считается ДО всякой нормализации переводов строк.
    public let isIdenticalToDisk: Bool
    /// Папки, которых ещё нет и которые появятся вместе с файлом (пути от корня проекта).
    public let createdDirectories: [String]

    public init(relativePath: String,
                isNewFile: Bool,
                oldText: String?,
                newText: String,
                hunks: [DiffHunk],
                addedCount: Int,
                removedCount: Int,
                baseModificationDate: Date?,
                isTruncated: Bool,
                isIdenticalToDisk: Bool = false,
                createdDirectories: [String] = []) {
        self.relativePath = relativePath
        self.isNewFile = isNewFile
        self.oldText = oldText
        self.newText = newText
        self.hunks = hunks
        self.addedCount = addedCount
        self.removedCount = removedCount
        self.baseModificationDate = baseModificationDate
        self.isTruncated = isTruncated
        self.isIdenticalToDisk = isIdenticalToDisk
        self.createdDirectories = createdDirectories
    }

    /// Построчный дифф пуст, а тексты при этом РАЗНЫЕ.
    /// Так выглядит смена переводов строк (\r\n → \n) и потеря завершающего переноса:
    /// на экране «изменений нет», а на диск уходит переписанный целиком файл.
    /// Человеку об этом обязаны сказать прямым текстом.
    public var hasInvisibleChangesOnly: Bool {
        hunks.isEmpty && !isIdenticalToDisk && !isNewFile
    }

    /// Сколько строк было в файле до правки (по переводам строк).
    public var oldLineCount: Int {
        guard let oldText, !oldText.isEmpty else { return 0 }
        var count = 1
        for character in oldText where character == "\n" { count += 1 }
        if oldText.hasSuffix("\n") { count -= 1 }
        return max(0, count)
    }

    /// Правка сносит больше трети файла.
    ///
    /// ⚠️ Самый опасный случай продукта: модель прочитала файл НЕ ЦЕЛИКОМ, дописала
    /// заголовок и вернула «полное» содержимое из тех строк, что видела. Человек,
    /// если торопится и смотрит только на зелёную строку сверху, подтвердит удаление
    /// половины файла. Карточка обязана в этом случае предупредить отдельно и заметно.
    public var isMassiveRemoval: Bool {
        guard !isNewFile, oldLineCount >= 10 else { return false }
        return Double(removedCount) / Double(oldLineCount) > 0.3
    }

    /// Готовая фраза для карточки подтверждения. nil — предупреждать не о чем.
    public var massiveRemovalNotice: String? {
        guard isMassiveRemoval, oldLineCount > 0 else { return nil }
        let percent = Int((Double(removedCount) / Double(oldLineCount) * 100).rounded())
        return "Удаляется \(percent) % файла — \(HumanFormat.lines(removedCount)) из \(oldLineCount). Проверьте внимательно."
    }

    /// Условия, при которых запись ещё имеет смысл. Проверяются перед самой записью.
    public var writeExpectation: WriteExpectation {
        WriteExpectation(isNewFile: isNewFile,
                         modificationDate: baseModificationDate,
                         previousText: oldText)
    }
}

/// Снимок состояния файла на момент показа диффа.
/// Перед записью сверяем его с диском: между «показали» и «применили» файл мог
/// поменять кто угодно — git-чекаут в Working Copy, догрузка из iCloud, другой редактор.
public struct WriteExpectation: Sendable, Equatable {
    /// Дифф был про НОВЫЙ файл: если файл успел появиться — это уже не создание, а перезапись.
    public let isNewFile: Bool
    /// Дата изменения на момент показа — быстрая предпроверка.
    public let modificationDate: Date?
    /// Содержимое «до» ровно в том виде, в каком его показали человеку.
    /// Главная проверка: сравниваем побайтово, а не по дате с допуском в секунду.
    public let previousText: String?

    public init(isNewFile: Bool, modificationDate: Date?, previousText: String?) {
        self.isNewFile = isNewFile
        self.modificationDate = modificationDate
        self.previousText = previousText
    }

    /// Ничего не проверять. Только для путей, где диффа не было вовсе (тесты).
    public static let unchecked = WriteExpectation(isNewFile: false,
                                                  modificationDate: nil,
                                                  previousText: nil)
}

