/// Выдача list_files вместе с честными оговорками: что не прочиталось и что не поместилось.
///
/// ⚠️ Без оговорок модель считает список полным. Часть папки может лежать в iCloud
/// и ещё не скачаться — тогда нужного файла в списке нет, и модель предлагает создать
/// его заново, то есть перезаписать существующий пустышкой.
public struct WorkspaceListing: Sendable, Equatable {
    public let entries: [WorkspaceEntry]
    /// Сколько папок обход не смог прочитать.
    public let unreadableCount: Int
    /// Упёрлись в потолок записей — показано не всё.
    public let didHitLimit: Bool
    /// Сколько записей в папке ВСЕГО (после наших отсевов), а не сколько показано.
    ///
    /// ⚠️ Ради этого числа обход не останавливается на пределе, а досчитывает остаток.
    /// Без него честная оговорка звучала бы «показаны первые 60 — есть ещё», и модель
    /// не понимала масштаба: 60 из 62 и 60 из 2000 — это разные решения (дочитать
    /// список или сразу спросить у человека, где искать).
    public let totalCount: Int
    /// Досчитать до конца не смогли — записей больше, чем AgentLimits.listCountCap.
    public let isCountApproximate: Bool

    public init(entries: [WorkspaceEntry],
                unreadableCount: Int = 0,
                didHitLimit: Bool = false,
                totalCount: Int? = nil,
                isCountApproximate: Bool = false) {
        self.entries = entries
        self.unreadableCount = unreadableCount
        self.didHitLimit = didHitLimit
        self.totalCount = totalCount ?? entries.count
        self.isCountApproximate = isCountApproximate
    }

    /// Оговорки готовыми строками — их дописываем и в ответ модели, и в ленту человеку.
    public var warnings: [String] {
        var out: [String] = []
        if didHitLimit {
            // ⚠️ Числом, а не намёком: модель обязана видеть словами, что список подрезан,
            // иначе она решит, что в проекте больше ничего нет, и соврёт об этом человеку.
            let total = isCountApproximate ? "более \(AgentLimits.listCountCap)" : "\(totalCount)"
            out.append("показаны первые \(entries.count) из \(total) — "
                       + "уточни папку, чтобы увидеть остальное")
        }
        if unreadableCount > 0 {
            out.append("прочитать не удалось \(unreadableCount) "
                       + HumanFormat.plural(unreadableCount, "папку", "папки", "папок")
                       + " (возможно, они ещё не скачаны из облака)")
        }
        return out
    }
}

/// Каким образом файл показан модели.
///
/// ⚠️ Три случая, и путать их нельзя: от этого зависит, можно ли переписывать файл целиком.
public enum WorkspaceReadView: String, Sendable, Equatable, Codable {
    /// Файл поместился целиком — модель видела всё.
    case whole
    /// Одна страница файла. Остальное модель НЕ видела.
    case page
    /// Оглавление: только строки-объявления с номерами, самого текста нет.
    case outline
}

/// Прочитанный (или записанный) файл.
public struct WorkspaceFile: Sendable, Equatable {
    public let relativePath: String
    public let text: String
    public let byteSize: Int
    public let modificationDate: Date?
    /// Файл отдан НЕ ЦЕЛИКОМ (страница или оглавление).
    public let isTruncated: Bool
    /// Сколько строк в файле всего.
    public let totalLineCount: Int
    /// Сколько строк из них попало в `text`.
    public let shownLineCount: Int
    /// Каким образом показан файл.
    public let view: WorkspaceReadView
    /// Номер первой показанной строки (нумерация с единицы).
    /// Для оглавления — 1: оно описывает файл целиком.
    public let firstLine: Int

    public init(relativePath: String,
                text: String,
                byteSize: Int,
                modificationDate: Date?,
                isTruncated: Bool,
                totalLineCount: Int = 0,
                shownLineCount: Int = 0,
                view: WorkspaceReadView = .whole,
                firstLine: Int = 1) {
        self.relativePath = relativePath
        self.text = text
        self.byteSize = byteSize
        self.modificationDate = modificationDate
        self.isTruncated = isTruncated
        self.totalLineCount = totalLineCount
        self.shownLineCount = shownLineCount
        self.view = view
        self.firstLine = max(1, firstLine)
    }

    /// Номер последней показанной строки.
    public var lastLine: Int {
        guard view != .outline else { return totalLineCount }
        return max(firstLine, firstLine + shownLineCount - 1)
    }

    /// За показанной страницей есть ещё текст.
    public var hasMoreAhead: Bool {
        view == .page && lastLine < totalLineCount
    }

    /// С какой строки просить продолжение. nil — продолжения нет.
    public var nextFromLine: Int? {
        hasMoreAhead ? lastLine + 1 : nil
    }

    /// Честная оговорка для модели: что именно показано и что с этим делать.
    /// nil — файл отдан целиком, оговаривать нечего.
    ///
    /// ⚠️ Имя оставлено прежним (на него смотрит инструмент чтения), но смысл шире:
    /// раньше это был тупик «файл слишком большой, правь его на компьютере», теперь —
    /// указание, как дочитать и как поправить нужный кусок, не трогая остальное.
    public var truncationNotice: String? {
        switch view {
        case .whole:
            return nil
        // ⚠️ ЗДЕСЬ НЕТ СИНТАКСИСА ВЫЗОВА, И ЭТО НЕ СЛУЧАЙНО. Раньше подсказка выглядела
        // как «Дальше: read_file(path, from_line: 41)». Живой прогон 09.08.2026 показал,
        // чем это кончается: Gemma 3 списала такую строку БУКВАМИ и отправила её человеку
        // вместо настоящего вызова. Маленькая модель повторяет форму, а не смысл, поэтому
        // подсказка говорит, ЧТО сделать, а как это записать — знает сама библиотека
        // по схеме действия.
        case .page:
            var text = "Показаны строки \(firstLine)–\(lastLine) из \(totalLineCount). "
            if let next = nextFromLine {
                text += "Дальше читай с \(next)-й строки. "
            }
            text += "Переписывать файл целиком нельзя — остального ты не видел. "
                + "Правь только нужные строки, назвав их номера."
            return text
        case .outline:
            return "Это ОГЛАВЛЕНИЕ файла (\(HumanFormat.lines(totalLineCount)) всего), а не его текст. "
                + "Выбери нужное место и прочитай его с этой строки. "
                + "Правь точечно, называя номера строк."
        }
    }
}

/// Вся работа с файлами внутри выбранной папки. За пределы папки не пускает.
public protocol FileWorkspace: AnyObject, Sendable {
    /// Корень (уже канонизированный).
    var rootURL: URL { get }
    /// Путь от модели → безопасный URL внутри корня. Бросает .pathEscapesRoot.
    func resolve(_ rawPath: String) throws -> URL
    func list(relativePath: String) throws -> [WorkspaceEntry]
    /// То же, что list, но с оговорками: что не прочиталось и что не поместилось.
    func listDetailed(relativePath: String) throws -> WorkspaceListing
    func readText(relativePath: String) throws -> WorkspaceFile
    /// Прочитать КУСОК файла: страницу с строки `from` или ровно строки `from`…`to`.
    /// `from == nil` — с начала файла (и тогда для большого файла вернётся оглавление).
    /// `to == nil` — сколько поместится в одну страницу.
    func readText(relativePath: String, from: Int?, to: Int?) throws -> WorkspaceFile
    /// Построить дифф, ничего не записывая.
    func diff(relativePath: String, newText: String) throws -> FileDiff
    /// Построить дифф ВОЗВРАТА: файл вернётся к тексту, который приложение сохранило
    /// само, до правки. Пустой текст значит «файла не было» — тогда дифф показывает,
    /// что именно исчезнет.
    ///
    /// ⚠️ ЗАЧЕМ ОТДЕЛЬНЫЙ ВХОД, А НЕ ОБЫЧНЫЙ `diff(relativePath:newText:)`. Обычный
    /// защищается от главной беды модели: она видела кусок большого файла и присылает
    /// «весь» файл из того, что видела, — такую правку мы не показываем вовсе.
    /// У возврата этой беды нет по устройству: текст не сочинён моделью, а списан
    /// с диска нами же. Гони мы возврат через ту же проверку — приложение отказывалось
    /// бы вернуть файл ровно в самом нужном случае: когда правка его сильно раздула.
    func revertDiff(relativePath: String, previousText: String) throws -> FileDiff
    /// Построить дифф ЗАМЕНЫ СТРОК: старые строки `lines` уступают место тексту `fragment`.
    ///
    /// ⚠️ Полный новый текст файла собирается ЗДЕСЬ, на телефоне, из содержимого диска
    /// и присланного куска. Дальше всё как при обычной записи: человек видит дифф,
    /// жмёт «Применить», пишется ровно показанное. Ни один шаг подтверждения не пропадает.
    func diff(relativePath: String, replacingLines lines: ClosedRange<Int>, with fragment: String) throws -> FileDiff
    /// Записать. Если файл на диске разошёлся с показанным человеку — .fileChangedSinceDiff.
    /// Условия берутся из показанного диффа (FileDiff.writeExpectation).
    @discardableResult
    func write(relativePath: String,
               newText: String,
               expecting: WriteExpectation) throws -> WorkspaceFile
}

public extension FileWorkspace {
    /// Запасная реализация для тех, кому оговорки не нужны (демонстрация, тесты).
    func listDetailed(relativePath: String) throws -> WorkspaceListing {
        WorkspaceListing(entries: try list(relativePath: relativePath))
    }

    /// Запасная реализация для рабочих папок без постраничного чтения:
    /// отдаём файл так же, как раньше. Хуже, но не сломано.
    func readText(relativePath: String, from: Int?, to: Int?) throws -> WorkspaceFile {
        try readText(relativePath: relativePath)
    }

    /// Запасная реализация для папок попроще (демонстрация, тесты): обычный дифф.
    /// Проверка «модель видела не весь файл» им не мешает — файлы там маленькие.
    func revertDiff(relativePath: String, previousText: String) throws -> FileDiff {
        try diff(relativePath: relativePath, newText: previousText)
    }

    /// Запасная реализация для рабочих папок без замены по строкам: честный отказ.
    /// Молча переписать файл целиком вместо куска здесь НЕЛЬЗЯ — это потеря данных.
    func diff(relativePath: String, replacingLines lines: ClosedRange<Int>, with fragment: String) throws -> FileDiff {
        throw PocketAgentError.writeFailed(
            path: relativePath,
            reason: "замена по номерам строк здесь не поддерживается — пришли файл целиком"
        )
    }
}

