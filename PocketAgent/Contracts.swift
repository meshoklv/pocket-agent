// MARK: - Числа и слова человеческим языком

/// Единственное место, где числа превращаются в текст для человека.
///
/// ⚠️ ЗАЧЕМ СВОЙ ФОРМАТИРОВЩИК, А НЕ `ByteCountFormatter`.
/// Тот берёт разделитель дробной части из региональных настроек ТЕЛЕФОНА: на устройстве
/// с русским регионом выходит «2,59 ГБ», а на любом другом (в том числе на симуляторе
/// в облаке, где снимаются экраны) — «2.59 ГБ». Единицы при этом наши, русские, и в одной
/// строке смешивались две записи числа. Здесь разделитель прибит к запятой всегда:
/// `String(format:)` без локали печатает точку, и мы меняем её на запятую сами.
public enum HumanFormat {

    /// Байты человеческим языком: «2,59 ГБ», «18,9 ГБ», «340 КБ», «512 Б».
    /// Приставки десятичные (1 КБ = 1000 Б) — ровно так же, как считает iOS в «Хранилище».
    public static func bytes(_ value: Int64) -> String {
        let negative = value < 0
        let magnitude = Double(value.magnitude)
        let sign = negative ? "−" : ""

        if magnitude < 1000 {
            return "\(sign)\(value.magnitude) Б"
        }
        if magnitude < 1_000_000 {
            return sign + number(magnitude / 1000) + " КБ"
        }
        if magnitude < 1_000_000_000 {
            return sign + number(magnitude / 1_000_000) + " МБ"
        }
        return sign + number(magnitude / 1_000_000_000) + " ГБ"
    }

    /// То же самое для обычного Int (размеры файлов внутри папки проекта).
    public static func bytes(_ value: Int) -> String {
        bytes(Int64(value))
    }

    /// Три значащие цифры и запятая вместо точки: 2,59 · 18,9 · 340.
    private static func number(_ value: Double) -> String {
        let digits: Int
        if value < 10 {
            digits = 2
        } else if value < 100 {
            digits = 1
        } else {
            digits = 0
        }

        // ⚠️ String(format:) без параметра locale печатает точку на любом устройстве —
        // именно на это мы и рассчитываем, запятую ставим сами.
        var text = String(format: "%.\(digits)f", value)
        if text.contains(".") {
            while text.hasSuffix("0") { text.removeLast() }
            if text.hasSuffix(".") { text.removeLast() }
        }
        return text.replacingOccurrences(of: ".", with: ",")
    }

    // MARK: Склонение

    /// Русское склонение по числу: 1 → one, 2–4 → few, остальное → many.
    /// Без него получалось «ещё 1 строк» и «ещё 2 строк».
    public static func plural(_ count: Int, _ one: String, _ few: String, _ many: String) -> String {
        let value = abs(count) % 100
        if value >= 11 && value <= 14 { return many }
        switch value % 10 {
        case 1:       return one
        case 2, 3, 4: return few
        default:      return many
        }
    }

    /// «1 строка» · «2 строки» · «11 строк».
    public static func lines(_ count: Int) -> String {
        "\(count) " + plural(count, "строка", "строки", "строк")
    }

    /// «1 запись» · «2 записи» · «11 записей».
    public static func entries(_ count: Int) -> String {
        "\(count) " + plural(count, "запись", "записи", "записей")
    }

    /// «1 файл» · «2 файла» · «11 файлов».
    public static func files(_ count: Int) -> String {
        "\(count) " + plural(count, "файл", "файла", "файлов")
    }

    /// «1 шаг» · «2 шага» · «11 шагов».
    public static func steps(_ count: Int) -> String {
        "\(count) " + plural(count, "шаг", "шага", "шагов")
    }
}

// MARK: - Системные ошибки по-русски

/// Перевод системных ошибок в человеческие русские фразы.
///
/// ⚠️ ЗАЧЕМ. Своих файлов локализации у приложения нет, все наши строки вшиты по-русски,
/// а `error.localizedDescription` система формирует НА ЯЗЫКЕ ТЕЛЕФОНА. На англоязычном
/// устройстве человек видел русское окно с английской начинкой вроде
/// «The Internet connection appears to be offline». Поэтому системные тексты наружу
/// не показываем вообще: разбираем ошибку по коду и подставляем свою фразу — что случилось
/// и что делать. Оригинал остаётся только в отладочной сборке, для нас.

/// Метка для НАШИХ ошибок, чей текст уже написан по-русски и предназначен человеку.
///
/// ⚠️ Нужна затем, чтобы такие тексты не превратились в общее «что-то пошло не так».
/// Пропускать наружу любой `LocalizedError` подряд нельзя: `URLError` и `CocoaError`
/// тоже соответствуют ему — и вернут системную фразу на языке телефона, ради борьбы
/// с которой весь этот разбор и написан. Поэтому пропускаем только помеченные типы.
public protocol HumanReadableError: LocalizedError {}

/// Разбор ошибок в русские фразы. Единственная дверь, через которую текст ошибки
/// попадает на экран.
public enum SystemErrorText {

    /// Готовая фраза для человека. Наши собственные ошибки уже написаны по-русски —
    /// они проходят как есть.
    public static func russian(for error: Error) -> String {
        if let known = error as? PocketAgentError {
            return known.errorDescription ?? fallback(for: error)
        }
        // Ошибки установки модели из файла: там объяснено, какой файл нужен и что не так.
        if let human = error as? HumanReadableError {
            return human.errorDescription ?? fallback(for: error)
        }
        if error is CancellationError {
            return "Действие отменено."
        }

        if let urlError = error as? URLError {
            switch urlError.code {
            case .notConnectedToInternet:
                return "Нет связи с интернетом. Подключитесь к Wi-Fi — загрузка продолжится с того места, где остановилась."
            case .dataNotAllowed:
                // ⚠️ Мобильная сеть приложению РАЗРЕШЕНА (ModelDownloader.allowsCellularAccess).
                // Эта ошибка приходит только когда её выключил сам человек — в настройках
                // телефона или Режимом экономии трафика. Раньше текст говорил «качаем
                // только по Wi-Fi» и был прямым враньём о самом приложении.
                return "Телефон не разрешает приложению качать по мобильной сети — либо подключитесь к Wi-Fi, "
                    + "либо включите мобильный интернет для приложения в настройках телефона."
            case .timedOut, .networkConnectionLost, .cannotConnectToHost, .cannotFindHost, .dnsLookupFailed:
                return "Связь оборвалась. Повторите — загрузка продолжится с того места, где остановилась."
            case .cancelled:
                return "Загрузка остановлена."
            case .secureConnectionFailed, .serverCertificateUntrusted, .serverCertificateHasBadDate:
                return "Не удалось установить защищённое соединение. Проверьте дату на телефоне и сеть, к которой подключены."
            case .internationalRoamingOff, .callIsActive:
                return "Сеть сейчас недоступна. Подключитесь к Wi-Fi и повторите."
            default:
                return "Не удалось скачать файл. Проверьте связь и повторите — загрузка продолжится с того места, где остановилась."
            }
        }

        if let cocoaError = error as? CocoaError {
            switch cocoaError.code {
            case .fileWriteOutOfSpace:
                return "На телефоне кончилось место. Освободите его и повторите."
            case .fileWriteNoPermission, .fileReadNoPermission:
                return "Нет доступа к этому файлу. Выберите папку проекта заново."
            case .fileNoSuchFile, .fileReadNoSuchFile:
                return "Файл не найден — возможно, его переименовали или удалили."
            case .fileReadInapplicableStringEncoding:
                return "Файл не читается как текст."
            case .userCancelled:
                return "Действие отменено."
            case .fileReadTooLarge:
                return "Файл слишком большой."
            default:
                return fallback(for: error)
            }
        }

        return fallback(for: error)
    }

    /// Всё, что мы не опознали. Английский системный текст человеку НЕ показываем.
    private static func fallback(for error: Error) -> String {
        #if DEBUG
        return "Что-то пошло не так. Повторите ещё раз. [отладка: \(error.localizedDescription)]"
        #else
        return "Что-то пошло не так. Повторите ещё раз, а если повторится — перезапустите приложение."
        #endif
    }
}

