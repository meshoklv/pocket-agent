// MARK: - Ограничения MVP

/// Числа, на которые опираются все модули. Меняются только здесь.
public enum AgentLimits {
    /// Максимум шагов «модель → подтверждение» на одну задачу.
    ///
    /// ⚠️ Было 12, и этого не хватало: болтливая модель на 2 млрд параметров тратит
    /// 2–3 хода на «осмотреться» (list_files, read_file) плюс кривые вызовы, и на саму
    /// работу оставалось 3–4 шага. Считаем шагом ТОЛЬКО принятый вызов инструмента —
    /// ходы, отменённые разбором (несуществующее имя, нет параметров), шагом не считаются.
    public static let maxSteps = 24
    /// На сколько шагов продлевает задачу кнопка «Продлить» — вместо тупика на пределе.
    public static let stepExtension = 10
    /// Максимум записей в выдаче list_files — столько уходит МОДЕЛИ.
    ///
    /// ⚠️ Было 400, и это главный пожиратель памяти разговора: 400 записей — примерно
    /// 4800 токенов при всей памяти в 4096. То есть на настоящем проекте список файлов
    /// не помещался в разговор ВООБЩЕ, и агент был неработоспособен с первого же шага.
    /// 60 записей — это ~600 токенов: одна папка обычного проекта показывается целиком,
    /// а если записей больше, модель видит честную строку «показаны первые 60 из 214».
    public static let maxListEntries = 60
    /// Максимальная глубина обхода папки.
    ///
    /// ⚠️ Было 3 — то есть один вызов вываливал всё дерево проекта. Глубина 1 значит
    /// «содержимое запрошенной папки, вложенные помечены косой чертой»: ответ всегда
    /// короткий и предсказуемый, а вглубь модель идёт следующим вызовом за ~150 токенов.
    /// Обрезанная правда («случайные 60 записей из всего дерева») хуже честного одного уровня.
    public static let maxListDepth = 1
    /// Сколько записей папки пересчитываем СВЕРХ предела, чтобы честно сказать «60 из 214».
    /// Дальше этого не считаем: на папке в сотни тысяч файлов подсчёт сам стал бы тормозом,
    /// и тогда говорим «больше 5000».
    public static let listCountCap = 5000
    /// Больше этого файл в модель не отдаём за один ответ (байты).
    /// ⚠️ Это верхний предохранитель по байтам. Настоящий предел чтения теперь
    /// считается в ТОКЕНАХ (readPageTokens): страница в 700 токенов — это 1,4 КБ
    /// русского текста и 2,8 КБ латиницы, то есть всегда меньше этого потолка.
    /// Раньше предел был только байтовый, и один и тот же файл в 6 КБ занимал
    /// то половину памяти разговора (код), то её всю (русский текст).
    public static let maxReadBytes = 6 * 1024

    /// Сколько токенов занимает ОДНА страница файла в ответе read_file — НИЖНЯЯ граница.
    ///
    /// ⚠️ Считаем страницу в токенах, а не в килобайтах, чтобы поведение перестало
    /// зависеть от языка файла. 700 токенов — примерно четверть памяти разговора
    /// на дне 4 096: страница влезает вместе с задачей, списком файлов и местом
    /// под ответ модели. На большей памяти страница растёт — см. `readPageTokens(forCeiling:)`.
    public static let readPageTokens = 700

    /// Размер страницы файла при ЗАДАННОЙ памяти разговора.
    ///
    /// ⚠️ ЗАЧЕМ ФУНКЦИЯ, А НЕ ЧИСЛО, И ПОЧЕМУ ЕЁ НЕЛЬЗЯ СЧИТАТЬ ОТ ВЫБОРА ЧЕЛОВЕКА.
    /// Страница обязана мериться той памятью, которую движок ВЫДАЛ, а не той, которую
    /// человек попросил на странице «О программе». Эти два числа расходятся: подобранная
    /// ступенька запуска может отдать 4 096, а на экране у человека остаться 32 000
    /// (см. LiteRTRuntime, запись в журнал «просил — дали — выбор человека»). Считай мы
    /// страницу от выбора — при выданных 4 096 в неё уходило бы 5 333 токена, то есть
    /// КАЖДОЕ чтение переполняло бы память разговора. Именно на этом 10.08.2026
    /// приложение отвечало «файл не помещается в память разговора» на любой файл.
    ///
    /// Шестая часть окна — это прежние ~680 токенов на 4 096 (то есть на дне поведение
    /// не меняется: нижняя граница 700 сильнее) и ~5 300 на 32 000.
    public static func readPageTokens(forCeiling ceiling: Int) -> Int {
        max(readPageTokens, ceiling / 6)
    }
    /// Файл длиннее этого числа страниц открывается ОГЛАВЛЕНИЕМ, а не первой страницей:
    /// листать большой файл с начала — самый дорогой способ найти нужное место.
    ///
    /// ⚠️ Было 2, и это оказалось слишком рано. Живой прогон 09.08.2026: человек просит
    /// «прочитай файл», README на 147 строк, модель получает голое оглавление — и вместо
    /// работы спрашивает «Что дальше?». Оглавление без единой строки текста маленькую
    /// модель не двигает: ей нечего пересказать и не за что зацепиться. Файл на пару-тройку
    /// страниц дешевле открыть с начала — там человек и получает ответ сразу.
    /// Оглавление остаётся для по-настоящему длинных файлов, где листать с начала разорительно.
    public static let outlinePageThreshold = 5
    /// Меньше этого числа найденных объявлений оглавление бессмысленно — отдаём обычную страницу.
    public static let outlineMinEntries = 3
    /// Больше этого строк в оглавление не кладём: оглавление обязано быть дешевле страницы.
    public static let outlineMaxEntries = 40
    /// Больше этого файл вообще не открываем — ни ради диффа, ни ради сверки перед записью.
    ///
    /// ⚠️ ЗАЧЕМ ОТДЕЛЬНОЕ ЧИСЛО. Раньше предел был один на всё: файл больше 12 КБ нельзя
    /// было ни прочитать, ни ИЗМЕНИТЬ — то есть на настоящем проекте (обычный исходник
    /// весит 20–40 КБ) агент отвечал «файл слишком большой» на каждом шаге и сдавался.
    /// Дифф считается на телефоне и кэш модели не занимает, поэтому его потолок другой:
    /// в модель уходит maxReadBytes, а с диском работаем до maxFileBytes.
    public static let maxFileBytes = 512 * 1024
    /// Больше этого дифф в предпросмотре обрезаем (строки).
    public static let maxDiffLines = 600
    /// Ниже этого свободной памяти модель не грузим (МБ).
    /// Историческое общее значение; фактический гейт считается по бэкенду
    /// (ModelDescriptor.cpuMemoryRequirementMB / gpuMemoryRequirementMB).
    public static let requiredFreeMemoryMB = 1400

    /// Безопасный размер кэша разговора у движка (вход + выход) в токенах.
    /// Это И значение по умолчанию, И то, куда приложение ОТСТУПАЕТ после неудачи.
    /// Сколько просить на самом деле, решает ЧЕЛОВЕК — см. `ContextSizeSettings`.
    ///
    /// ⚠️ 4096 — ЭТО НАША СЕГОДНЯШНЯЯ НАСТРОЙКА, А НЕ ДОКАЗАННЫЙ ПОТОЛОК ДВИЖКА.
    /// Здесь долго стояло обратное утверждение — «потолок движка, баг #6765 открыт», —
    /// и весь день оно мешало работать. Проверено запросом к серверу 09.08.2026:
    /// баг google-ai-edge/LiteRT #6765 ЗАКРЫТ 09.04.2026. Разбор — docs/CONTEXT-RAISE.md.
    ///
    /// Что при этом ПРАВДА и подтверждено замерами автора того отчёта
    /// (iPhone 16 Pro Max / iOS 26, ЕГО связка модели и устройства, не наша):
    ///     4096  — работает;
    ///     8192  — «send_message returns nil (no crash, but no output)»;
    ///     16384 — падение внутри библиотеки на первом же сообщении.
    /// У нас однажды стояло 8192, и владелец получил ровно описанное: модель загрузилась,
    /// но на первое же «Привет» не ответила НИЧЕМ. Пустой ответ библиотеки приложение
    /// показало как «Модель ответила неразборчиво», и мы полдня искали виноватого не там.
    ///
    /// ⚠️ НО ТОТ ПРОВАЛ БЫЛ НА ДРУГОМ КОДЕ И НА ЧУЖОМ ТЕЛЕФОНЕ. Карточка модели обещает
    /// 32 тысячи токенов; инженер Google в том же обсуждении говорит, что при достаточной
    /// памяти это должно работать и на телефоне. У владельца iPhone Air с 12 ГБ памяти —
    /// на нём запускается даже Bonsai 27B (ROADMAP, раздел 6).
    ///
    /// ⚠️ ПОЭТОМУ РЕШАЕТ ЧЕЛОВЕК, А НЕ МЫ. Размер выбирается на странице «О программе»
    /// (`ContextSizeSettings`), вплоть до 32 000. Философия проекта — предупреждение,
    /// а не запрет: мы говорим правду о риске и пропускаем. Приложение отступает сюда,
    /// только когда неудача СЛУЧИЛАСЬ на деле, и честно об этом пишет.
    public static let contextTokenBudget = 4096

    /// Сколько токенов кэша держим свободными под ответ модели.
    /// Если результат инструмента в остаток не влезает — его подрезаем.
    ///
    /// ⚠️ Было 1024 — столько резервировали под самый длинный возможный ответ модели,
    /// а самым длинным ответом была ПЕРЕЗАПИСЬ ФАЙЛА ЦЕЛИКОМ. С заменой по номерам строк
    /// (write_file с from_line/to_line) правка в пять строк — это ~120 токенов ответа,
    /// а не полторы тысячи. 768 токенов — это всё ещё около 3 КБ латиницы: хватает
    /// и на создание нового небольшого файла целиком. Освободившиеся 256 токенов
    /// уходят на работу: ровно на них станет длиннее допустимый ответ инструмента.
    ///
    /// ⚠️ Это запас ДЛЯ БЕЗОПАСНОГО ДНА (4096). Считать по нему при большом окне нельзя —
    /// см. `replyHeadroom(forCeiling:)`.
    public static let replyHeadroomTokens = 768

    /// Запас под ответ модели при ЗАДАННОМ потолке памяти разговора.
    ///
    /// ⚠️ ЗАЧЕМ ФУНКЦИЯ, А НЕ КОНСТАНТА. Потолок теперь не один: движок может дать
    /// и 4096, и 8192 (или вернуть нас на 4096 после неудачной попытки). Запас, посчитанный
    /// от одного числа, при другом становится неверным.
    /// Восьмая часть окна — это ровно прежние 768 токенов на дне 4096 (то есть на дне
    /// поведение НЕ меняется ни на токен) и 1024 на 8192. Растёт он потому, что растёт
    /// и самый длинный возможный ответ: на большом окне модель успевает прочитать
    /// файл целиком и предложить его целиком же переписать.
    public static func replyHeadroom(forCeiling ceiling: Int) -> Int {
        max(replyHeadroomTokens, ceiling / 8)
    }

    /// С какого занятого кэша разговор пора сворачивать и начинать заново — при ЗАДАННОМ потолке.
    ///
    /// ⚠️ ФОРМУЛА, А НЕ ЧИСЛО НА ГЛАЗ: потолок − запас под ответ модели − одна страница
    /// файла. То есть сворачиваемся ровно в тот момент, когда следующая страница ЕЩЁ
    /// поместится, а не когда она уже не влезла. Живой случай 09.08.2026: человек увидел
    /// «модель не смогла прочитать файл» и потерял задачу — обрезка включалась ПОСЛЕ того,
    /// как модель упёрлась.
    ///
    /// ⚠️ И ИМЕННО ПОЭТОМУ ЗДЕСЬ ФУНКЦИЯ. Прежнее число 2600 посчитано от 4096;
    /// на выданных 8192 оно означало бы «свернуть память, когда занята едва половина» —
    /// то есть выбросить половину того, ради чего потолок и поднимали.
    /// На дне 4096 функция даёт 2628 — прежние 2600 были тем же числом, округлённым вниз.
    ///
    /// ⚠️ И ПОЭТОМУ ЖЕ СТРАНИЦА ЗДЕСЬ — НЕ КОНСТАНТА 700. Страница растёт вместе с окном
    /// (`readPageTokens(forCeiling:)`), и пока тут стояло жёсткое число, «место под
    /// следующую страницу» на 32 000 резервировалось в семь раз меньше настоящего:
    /// порог говорил «ещё поместится», а страница в 5 333 токена уже не помещалась.
    public static func contextRestartThreshold(forCeiling ceiling: Int) -> Int {
        let usable = ceiling - replyHeadroom(forCeiling: ceiling) - readPageTokens(forCeiling: ceiling)
        // Потолок мог оказаться крошечным (чужая модель со своим размером кэша) —
        // тогда честнее свернуться рано, чем считать по отрицательному остатку.
        return max(contextReclaimMinTokens, min(usable, ceiling))
    }

    /// Меньше этого сворачиваться незачем: сам перезапуск стоит системной инструкции
    /// и описаний действий заново (~500 токенов). Освобождать 200 ради платы в 500 —
    /// не экономия, а лишняя пауза для человека.
    public static let contextReclaimMinTokens = 600

    /// Предел заметки о проекте (файл `AGENTS.md` в папке проекта) в токенах.
    ///
    /// ⚠️ Предел ЖЁСТКИЙ и намеренно маленький: 300 токенов — это десятая часть
    /// всего окна. Заметка лежит в памяти разговора постоянно, как системная
    /// инструкция, и каждый лишний абзац в ней отнимается у самой работы.
    /// Что не поместилось — обрезается, и модель об этом честно предупреждается.
    /// Окупается она тем, что заменяет обход папки и чтение файла ради вопроса
    /// «а что тут вообще лежит» — это 200–900 токенов на каждой задаче.
    public static let projectNoteTokens = 300

    /// Предел строки «сейчас делаю» в токенах.
    ///
    /// ⚠️ Строку ведёт ПРИЛОЖЕНИЕ, а не модель, и уходит она модели каждый ход —
    /// значит цена у неё повторяющаяся. Двадцать четыре токена — примерно
    /// полстроки текста; больше делать нельзя, иначе за десяток ходов она
    /// сама съест столько же, сколько экономит.
    public static let focusLineTokens = 24

    // MARK: Поиск в интернете
    //
    // ⚠️ ВСЕ ЧИСЛА ЗДЕСЬ — ПРО ОДНО: ОТВЕТ ПОИСКА ОБЯЗАН БЫТЬ КРОШЕЧНЫМ.
    // Память разговора 4096 токенов, и страница файла стоит 700. Поиск не имеет права
    // стоить дороже: он не работа, а справка по дороге к работе. Целых страниц из
    // интернета в модель не уходит НИКОГДА — только заголовок, две строки выжимки
    // и короткий адрес.

    /// Сколько находок всего уходит модели за один поиск.
    public static let webSearchMaxResults = 4
    /// Сколько находок берём у каждого источника, прежде чем перемешать и подрезать.
    /// Больше общего предела — намеренно: если один источник промолчал, второй добирает.
    public static let webSearchResultsPerSource = 3
    /// Предел заголовка находки в знаках.
    public static let webSearchTitleChars = 90
    /// Предел выжимки в знаках — это примерно две строки на экране телефона.
    public static let webSearchSnippetChars = 140
    /// Жёсткий потолок всего ответа поиска в знаках.
    ///
    /// ⚠️ 700 знаков кириллицы — это около 350 токенов, то есть ПОЛОВИНА страницы файла.
    /// Ответ длиннее подрезается по целым находкам (обрывать находку на полуслове нельзя:
    /// модель дочитает половину названия и уверенно перескажет её человеку как факт).
    public static let webSearchAnswerChars = 700
    /// Длиннее этого запрос в поиск не отправляем: длинный запрос — это почти всегда
    /// кусок файла человека, случайно попавший в поле поиска. Наружу такое не уходит.
    public static let webSearchQueryChars = 200
    /// Сколько ждём ответа от источника. Больше — человек смотрит в неподвижный экран.
    public static let webSearchTimeoutSeconds = 12
}

// MARK: - Память разговора: выбирает человек

/// Сколько памяти разговора просить у движка. ЕДИНСТВЕННОЕ место, где это решение
/// живёт: страница «О программе» показывает выбор, движок читает его отсюда же.
///
/// ⚠️ ЭТО НАСТРОЙКА ЧЕЛОВЕКА, А НЕ НАША ДОГАДКА. Философия проекта — предупреждение,
/// а не запрет (ROADMAP, раздел 6): большие значения не прячем, не запрещаем и не решаем
/// за человека. Мы говорим правду («чем больше, тем выше риск, что модель замолчит или
/// приложение закроется») и пропускаем. У владельца iPhone Air с 12 ГБ памяти —
/// на нём заводится даже модель на 27 миллиардов, так что занижать выбор из
/// осторожности было бы враньём в другую сторону.
///
/// ⚠️ ЗАЧЕМ ОТДЕЛЬНЫЙ ТИП, А НЕ ПРОСТО КЛЮЧ. Ровно тот же приём, что у поиска
/// (`WebSearchSettings`): экран и движок обязаны читать ОДНУ строку-ключ. Разъедься
/// они — человек двигал бы настройку, которую никто не читает.
public enum ContextSizeSettings {

    /// Ключ в настройках приложения. Одна строка на весь проект.
    public static let defaultsKey = "conversationMemoryTokens"

    /// Ключ жалобы: с каким числом НЕ получилось. 0 — жалобы нет.
    ///
    /// ⚠️ ЗАЧЕМ ХРАНИТЬ ЭТО НА ДИСКЕ. Неудача с большим окном может закрыть приложение
    /// целиком, и человек вернётся уже в новый запуск. Промолчи мы — он увидел бы, что
    /// выбор сам собой стал 4 096, и решил бы, что настройка не работает. Это ровно та
    /// болезнь, с которой борется весь проект: приложение обязано сказать, что случилось.
    public static let retreatKey = "conversationMemoryRetreatedFrom"

    /// Что можно выбрать. Первое значение — оно же по умолчанию.
    ///
    /// ⚠️ 32 000 стоит последним НЕ потому, что «запрещено», а потому что это край:
    /// столько обещает карточка модели. Проверяется живым запуском на телефоне —
    /// заранее знать, поедет или нет, нельзя ни нам, ни человеку.
    public static let options: [Int] = [AgentLimits.contextTokenBudget, 8192, 16384, 32000]

    /// Сколько человек выбрал. Ключа нет — безопасное значение по умолчанию.
    ///
    /// ⚠️ Чужое число из настроек не пропускаем как есть: файл настроек переживает
    /// обновления приложения, и значение из прошлой версии (или чья-то опечатка
    /// в отладке) не должно уехать в движок мимо нашего списка.
    public static var chosenTokens: Int {
        get {
            let saved = UserDefaults.standard.integer(forKey: defaultsKey)
            guard saved > 0 else { return AgentLimits.contextTokenBudget }
            return max(AgentLimits.contextTokenBudget, min(saved, options.last ?? saved))
        }
        set {
            UserDefaults.standard.set(newValue, forKey: defaultsKey)
        }
    }

    /// Ключ выданного движком размера: сколько памяти разговора получилось НА САМОМ ДЕЛЕ.
    private static let grantedKey = "conversationMemoryGrantedTokens"

    /// Движок поднялся — запоминаем, сколько памяти разговора он выдал.
    ///
    /// ⚠️ ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ ВЫБОРА ЧЕЛОВЕКА. Выбор — это просьба, а не факт: движок
    /// подбирает ступеньку запуска и может подняться на 4 096 там, где просили 32 000,
    /// причём без всякой жалобы (жалоба пишется только после настоящего провала).
    /// Всё, что считается от памяти разговора — размер страницы файла, обещание «этот
    /// файл прочитается целиком» в окне согласия, — обязано считаться от ВЫДАННОГО.
    /// Иначе приложение обещает человеку и модели место, которого нет.
    ///
    /// Хранится в настройках, а не в памяти процесса, по той же причине, что и жалоба:
    /// значение переживает перезапуск, а до первой загрузки модели спросить не у кого.
    public static func noteGranted(_ tokens: Int) {
        guard tokens > 0 else { return }
        UserDefaults.standard.set(tokens, forKey: grantedKey)
    }

    /// Сколько памяти разговора есть на самом деле — от этого и считаем всё остальное.
    ///
    /// ⚠️ БЕРЁМ МЕНЬШЕЕ ИЗ ДВУХ, И ЭТО НЕ ПЕРЕСТРАХОВКА. Выданное число могло остаться
    /// от прошлой модели (человек с тех пор опустил выбор — тогда врёт выданное),
    /// а движок мог ещё ни разу не подниматься (тогда выданного просто нет).
    /// Меньшее из двух верно в обоих случаях, а ошибка в меньшую сторону стоит лишней
    /// страницы чтения — тогда как ошибка в большую ломает каждое чтение подряд.
    public static var effectiveTokens: Int {
        let granted = UserDefaults.standard.integer(forKey: grantedKey)
        guard granted > 0 else { return chosenTokens }
        return max(AgentLimits.contextTokenBudget, min(granted, chosenTokens))
    }

    /// Движок не потянул выбранное число: возвращаем безопасное и запоминаем жалобу.
    ///
    /// ⚠️ Настройку переписываем НАСОВСЕМ, а не «на этот раз»: иначе следующий запуск
    /// снова пошёл бы в то же самое падение, и человек получил бы приложение, которое
    /// не открывается. Поднять число обратно — одно касание на той же странице.
    public static func retreat(from tokens: Int) {
        let defaults = UserDefaults.standard
        defaults.set(AgentLimits.contextTokenBudget, forKey: defaultsKey)
        defaults.set(tokens, forKey: retreatKey)
    }

    /// Человек сам передвинул выбор — прошлая жалоба больше не про то, что он видит.
    public static func forgetRetreat() {
        UserDefaults.standard.removeObject(forKey: retreatKey)
    }

    /// Число с разделителями: «4 096», «32 000».
    ///
    /// ⚠️ Пробел неразрывный, иначе «32 000» переносится посреди числа — на узком
    /// экране это выглядит как два разных числа. И ⚠️ считаем сами, без системного
    /// форматировщика: тот берёт разделитель из настроек ТЕЛЕФОНА и на англоязычном
    /// устройстве написал бы «32,000» — по той же причине, по какой заведён HumanFormat.
    public static func text(_ tokens: Int) -> String {
        let digits = Array(String(tokens))
        var out = ""
        for (index, digit) in digits.enumerated() {
            if index > 0, (digits.count - index) % 3 == 0 { out.append("\u{00A0}") }
            out.append(digit)
        }
        return out
    }
}

