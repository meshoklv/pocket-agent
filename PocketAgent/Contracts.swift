/// Состояние движка для экрана подготовки.
public enum ModelRuntimeStatus: Sendable, Equatable {
    case idle
    /// Качаем файл модели, progress 0…1.
    case downloading(progress: Double)
    case verifying
    /// Инициализация движка — секунды, экран загрузки обязателен.
    case loading
    case ready
    case failed(message: String)
}

/// Вид состояния движка БЕЗ вложенных значений.
/// ⚠️ Нужен ровно затем, чтобы отличать «поменялось по существу» от «тикнул прогресс»:
/// во время загрузки `downloading(progress:)` меняется десятки раз в секунду,
/// и вешать на него пересчёты (например, свободное место на диске) нельзя.
public enum ModelRuntimePhase: String, Sendable, Equatable {
    case idle, downloading, verifying, loading, ready, failed
}

public extension ModelRuntimeStatus {
    var phase: ModelRuntimePhase {
        switch self {
        case .idle:        return .idle
        case .downloading: return .downloading
        case .verifying:   return .verifying
        case .loading:     return .loading
        case .ready:       return .ready
        case .failed:      return .failed
        }
    }
}

/// Ровно один ход модели: либо просьба об инструменте, либо текст.
public enum ModelTurn: Sendable, Equatable {
    case toolRequest(ToolInvocation)
    case text(String)
}

/// Что умеет движок. UI и Agent знают ТОЛЬКО этот протокол — про LiteRT-LM они не знают ничего.
/// ⚠️ Реализация обязана делать ход через обычный (не стриминговый) вызов:
/// стриминг игнорирует запрет автовызова инструментов и выполнит их сам.
public protocol ModelRuntime: AnyObject, Sendable {
    func currentStatus() async -> ModelRuntimeStatus
    /// Поток изменений статуса для экрана подготовки.
    func statusStream() async -> AsyncStream<ModelRuntimeStatus>
    /// Скачать (если надо), проверить и загрузить модель.
    func prepare() async throws
    /// Начать новый разговор с системной инструкцией и схемой инструментов.
    func beginSession(systemPrompt: String, tools: [ToolDeclaration]) async throws
    /// Ход от пользователя.
    func send(userText: String) async throws -> ModelTurn
    /// Ход с результатом инструмента (в том числе с отказом пользователя).
    func send(toolResult: ToolResult) async throws -> ModelTurn
    /// Прервать текущую генерацию.
    func cancelTurn() async
    /// Закрыть разговор, оставив модель загруженной.
    func endSession() async
    /// Выгрузить модель из памяти (обнулить ссылки — явного close() у движка нет).
    func unload() async
    /// Сколько токенов занято в кэше — чтобы не упереться в лимит.
    func usedTokens() async -> Int?
    /// Каков потолок памяти разговора у ЖИВОГО движка — сколько он на самом деле дал.
    func contextLimitTokens() async -> Int

    // MARK: Жизнь приложения

    /// Приложение ушло в фон: движок прерывает начатый ход.
    ///
    /// ⚠️ ЭТИ ДВА ВЫЗОВА ЖИВУТ ИМЕННО ЗДЕСЬ, А НЕ У КОНКРЕТНОГО ДВИЖКА, И ВОТ ПОЧЕМУ.
    /// Пока они были обычными методами движка Google, композиционный корень был обязан
    /// держать его ТОЧНЫЙ тип — и второй движок подключить было просто некуда: любая
    /// попытка упиралась в «а этот метод у протокола не объявлен». Теперь сборщик зовёт
    /// их не глядя на то, чья модель сейчас работает.
    func handleEnteredBackground() async

    /// Система пожаловалась на память: движок выгружает веса целиком.
    func handleMemoryWarning() async
}

/// ⚠️ ПОТОЛОК СПРАШИВАЕМ У ДВИЖКА, А НЕ БЕРЁМ ИЗ КОНСТАНТЫ, И ВОТ ПОЧЕМУ.
/// Приложение просит у движка размер памяти разговора, но получить может ДРУГОЙ:
/// на лесенке настроек есть ступенька «сколько скажет сама модель», а прошлое
/// отступление после неудачи запоминается на диске. Счётчик на экране, который
/// показывает константу вместо выданного числа, врёт человеку ровно в тот момент,
/// когда он пытается понять, почему помощник «поглупел».
/// Значение по умолчанию — наш безопасный размер: его достаточно для тех реализаций
/// (демо-режим), у которых никакого движка под собой нет вовсе.
public extension ModelRuntime {
    func contextLimitTokens() async -> Int { AgentLimits.contextTokenBudget }

    /// ⚠️ ПУСТО ПО УМОЛЧАНИЮ НАМЕРЕННО. Реализации, у которых никаких весов в памяти нет
    /// (демонстрационный режим, заглушки в проверках), на уход в фон и на нехватку памяти
    /// отвечать нечем — и заставлять их писать два пустых метода значит ломать их
    /// на ровном месте при каждом расширении протокола.
    func handleEnteredBackground() async {}
    func handleMemoryWarning() async {}
}

