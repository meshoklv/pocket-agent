                author: ChatAuthor,
                text: String,
                createdAt: Date = Date(),
                diff: FileDiff? = nil,
                restorePointID: UUID? = nil) {
        self.id = id
        self.author = author
        self.text = text
        self.createdAt = createdAt
        self.diff = diff
        self.restorePointID = restorePointID
    }
}

// MARK: - Возврат применённой правки

/// Возврат, который ждёт решения человека.
///
/// ⚠️ ЗАЧЕМ ОТДЕЛЬНОЕ ПОЛЕ, А НЕ СОСТОЯНИЕ АГЕНТА. Возврат — это работа ПРИЛОЖЕНИЯ,
/// а не ход модели: она о нём не знает и результата не получает. Пусти мы его через
/// обычное «ждём подтверждения», итог записи ушёл бы модели в память разговора —
/// то есть возврат стоил бы токенов каждый следующий ход, ради ничего.
public struct PendingUndo: Sendable, Equatable, Identifiable {
    /// Опознаватель точки возврата (он же — опознаватель карточки).
    public let id: UUID
    /// То же самое, что у обычной карточки: что за файл, что было и что станет.
    public let action: PendingAction
    /// Правка создавала файл — возврат его удалит.
    public let isDeletion: Bool
    /// Возврат уже применяется.
    public var isApplying: Bool

    public init(id: UUID, action: PendingAction, isDeletion: Bool, isApplying: Bool = false) {
        self.id = id
        self.action = action
        self.isDeletion = isDeletion
        self.isApplying = isApplying
    }
}

/// Всё, что нужно экрану чата. UI читает только это.
public struct AgentSnapshot: Sendable, Equatable {
    public var state: AgentState
    public var messages: [ChatMessage]
    public var stepsUsed: Int
    public var folder: ProjectFolder?
    /// Предел шагов ИМЕННО ЭТОЙ задачи: человек мог продлить его кнопкой.
    /// Поэтому «Шаг N из M» берёт M отсюда, а не из общей настройки.
    public var stepLimit: Int

    // MARK: - Память разговора (то, что человек видит полоской в чате)

    /// Сколько памяти разговора занято у движка ПРЯМО СЕЙЧАС, в токенах.
    /// Число не наше и не расчётное — его отдаёт сам движок (`ModelRuntime.usedTokens()`).
    public var contextUsedTokens: Int

    /// Потолок памяти разговора ЭТОЙ сессии — сколько движок выдал на самом деле.
    /// Спрашивается у движка при начале разговора, а не берётся из константы.
    public var contextLimitTokens: Int

    /// Сколько занято СЛУЖЕБНЫМ — тем, что лежит в разговоре ещё до первого слова работы:
    /// инструкция агенту и описания четырёх действий.
    ///
    /// ⚠️ ЧИСЛО ИЗМЕРЕННОЕ, А НЕ ОЦЕНОЧНОЕ: движок спрашивают сразу после начала разговора,
    /// когда в нём больше нет ничего. По разбору настоящих переписок с телефона владельца
    /// это около 806 токенов — пятая часть всего окна, съеденная до начала работы,
    /// и при каждом сворачивании она оплачивается заново. Молчать об этом нельзя:
    /// иначе «занято 1 840 из 4 096» выглядит просторнее, чем есть.
    public var contextBaselineTokens: Int

    /// Когда разговор свернули в последний раз. nil — в текущей задаче не сворачивали.
    ///
    /// ⚠️ Пометка живёт до следующей задачи человека и НЕ гаснет по таймеру.
    /// Таймер здесь означал бы перерисовку чата раз в секунду ради одной подписи,
    /// а знать «в этой задаче память уже сворачивали» человеку полезно всю задачу:
    /// именно этим объясняется, почему счётчик вдруг рухнул с почти полного до пустого.
    public var contextFoldedAt: Date?

    // MARK: - Возврат правки

    /// У какой применённой правки сейчас живёт кнопка «Вернуть, как было».
    /// nil — возвращать нечего.
    ///
    /// ⚠️ КНОПКА ВСЕГДА ОДНА, У САМОЙ СВЕЖЕЙ ПРАВКИ, и это не экономия места.
    /// Правка из середины цепочки, положенная поверх более поздних, затёрла бы их
    /// молча — то есть «отмена» уничтожала бы работу. Вернул последнюю — кнопка
    /// перешла к предыдущей: так можно отступать по одному шагу, ничего не путая.
    public var undoablePointID: UUID?

    /// Возврат, который ждёт решения человека. Карточка «до и после» — та же самая,
    /// что у правки от модели: запись на диск идёт только через подтверждение.
    public var pendingUndo: PendingUndo?

    public init(state: AgentState = .idle,
                messages: [ChatMessage] = [],
                stepsUsed: Int = 0,
                folder: ProjectFolder? = nil,
                stepLimit: Int = AgentLimits.maxSteps,
                contextUsedTokens: Int = 0,
                contextLimitTokens: Int = AgentLimits.contextTokenBudget,
                contextBaselineTokens: Int = 0,
                contextFoldedAt: Date? = nil,
                undoablePointID: UUID? = nil,
                pendingUndo: PendingUndo? = nil) {
        self.undoablePointID = undoablePointID
        self.pendingUndo = pendingUndo
        self.state = state
        self.messages = messages
        self.stepsUsed = stepsUsed
        self.folder = folder
        self.stepLimit = stepLimit
        self.contextUsedTokens = contextUsedTokens
        self.contextLimitTokens = contextLimitTokens
        self.contextBaselineTokens = contextBaselineTokens
        self.contextFoldedAt = contextFoldedAt
    }

    /// Черта, за которой разговор начнут сворачивать.
    ///
    /// ⚠️ Считается от ТОГО ПОТОЛКА, КОТОРЫЙ ДВИЖОК ВЫДАЛ НА САМОМ ДЕЛЕ, а не от нашей
    /// константы: потолок бывает и 4096, и 8192, и меньше — см. `contextLimitTokens`.
    /// Сама формула (потолок − запас под ответ − страница файла) живёт в AgentLimits,
    /// чтобы полоска на экране и решение свернуть разговор считались ОДНИМ правилом.
    public var contextFoldThreshold: Int {
        AgentLimits.contextRestartThreshold(forCeiling: contextLimitTokens)
    }

    /// Насколько полоска заполнена: 0 — пусто, 1 — под потолок.
    public var contextFillFraction: Double {
        contextFraction(of: contextUsedTokens)
    }

    /// Какую долю полоски занимает служебное — то, что было в разговоре до начала работы.
    /// Больше занятого быть не может: служебное лежит внутри него, а не рядом.
    public var contextBaselineFraction: Double {
        min(contextFillFraction, contextFraction(of: contextBaselineTokens))
    }

    private func contextFraction(of tokens: Int) -> Double {
        guard contextLimitTokens > 0 else { return 0 }
        return min(1, max(0, Double(tokens) / Double(contextLimitTokens)))
    }

    /// Памяти осталось мало — разговор вот-вот свернётся.
    public var isContextNearFold: Bool { contextUsedTokens >= contextFoldThreshold }

    /// В текущей задаче переписку уже сворачивали.
    public var didFoldConversation: Bool { contextFoldedAt != nil }

    public var pendingAction: PendingAction? {
        if case .awaitingApproval(let action) = state { return action }
        return nil
    }

    public var isBusy: Bool {
        switch state {
        case .thinking, .applying: return true
        default: return false
        }
    }

    public var stepsLeft: Int { max(0, stepLimit - stepsUsed) }

    /// Шаги на исходе — можно предложить продлить, не доводя до тупика.
    public var isNearStepLimit: Bool { stepsLeft <= 3 && stepsUsed > 0 }
}

