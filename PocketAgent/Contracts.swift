    public let diff: FileDiff?
    /// Точка возврата этой правки: по ней работает кнопка «Вернуть, как было».
    ///
    /// ⚠️ Здесь лежит только опознаватель, а не прежний текст файла. Сам текст живёт
    /// на диске (`RestorePointStore`) и читается ровно в момент нажатия: держи мы его
