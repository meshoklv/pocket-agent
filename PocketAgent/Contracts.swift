/// Описания инструментов, которые видит модель.
/// ⚠️ Один и тот же текст обязан уходить И в схему LiteRT-LM (Runtime/LiteRTToolSchemas.swift),
/// И в реализацию инструмента (Tools/FileToolsImpl.swift). Раньше они были заданы дважды
