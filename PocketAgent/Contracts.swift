/// Четыре обязательных инструмента MVP плюс поиск, который человек включает сам.
/// rawValue = имя, которое видит модель.
/// Имена уже в snake_case — автоконвертация camelCase→snake_case их не меняет.
public enum ToolKind: String, CaseIterable, Codable, Sendable {
    case listFiles = "list_files"
    case readFile  = "read_file"
    case writeFile = "write_file"
    case finish    = "finish"
    /// ⚠️ ПЯТЫЙ, И ОН НЕ НАРУШАЕТ ПРАВИЛО «РОВНО ЧЕТЫРЕ». Правило про то, СКОЛЬКО
    /// действий модель видит одновременно: на большом наборе она начинает звать
    /// несуществующее. Поиск попадает в реестр ТОЛЬКО когда человек включил его
    /// сам; выключен — инструмента нет ни в реестре, ни в схеме для модели,
    /// и набор у неё снова из четырёх. Разрешение спрашивается один раз у человека,
    /// а не у модели.
    case webSearch = "web_search"

    /// Без этих четырёх агент неработоспособен: не осмотрится, не прочитает,
    /// не сделает работу и не сможет закончить задачу. Собранность реестра
    /// проверяется по ним, а не по `allCases`.
    public static let core: [ToolKind] = [.listFiles, .readFile, .writeFile, .finish]

    /// Инструмент появляется только по решению человека и обязательным не считается.
    public var isOptional: Bool { !ToolKind.core.contains(self) }

    /// Требует ли действие подтверждения пользователя.
    /// Читающие инструменты и finish подтверждения не требуют — тормозим только на записи.
    ///
    /// ⚠️ Поиск подтверждения тоже не требует, и это осознанно: разрешение на выход
    /// в сеть человек даёт ОДИН РАЗ переключателем, а каждый запрос видит в переписке
    /// строкой «Ищу в интернете: …». Карточка на каждое слово превратила бы поиск
    /// в пытку и ничего бы не добавила: в папке от него ничего не меняется.
    public var needsApproval: Bool {
        switch self {
        case .writeFile: return true
        case .listFiles, .readFile, .finish, .webSearch: return false
        }
    }
}

