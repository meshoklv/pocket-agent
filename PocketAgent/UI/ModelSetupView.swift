    private func sectionHeading<Accessory: View>(_ title: String,
                                                 icon: String,
                                                 @ViewBuilder accessory: () -> Accessory) -> some View {
        HStack(spacing: 8) {
            Image(systemName: icon)
                .foregroundStyle(Theme.textSecondary)
            Text(title)
