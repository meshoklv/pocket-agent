    /// Что разрешено выбрать в системном окне «Файлы».
    ///
    /// ⚠️ ЧЕТЫРЕ ТИПА, А НЕ ОДИН .litertlm — И ЭТО ГЛАВНАЯ ПРАВКА ЭТОГО ЭКРАНА.
    /// Раньше здесь стоял единственный тип файла модели, и всё остальное в «Файлах»
    /// было бледным и ненажимаемым. Человек с моделью для движка Apple (а она —
    /// ПАПКА из нескольких файлов) или с файлом, которому браузер дал другое имя,
    /// упирался в экран, где нельзя выбрать НИЧЕГО, и не получал ни слова объяснения.
    /// Бледная строка — это молчаливый отказ, а он у нас запрещён.
    ///
    /// Теперь выбрать можно что угодно и откуда угодно, а негодное объясняется словами:
    /// защита от мусора не ослабла — её делает `ModelVerifier`, и он умеет говорить.
    /// Ровно так же устроен выбор вложения в разговоре (`ChatView`).
    private var modelPickerTypes: [UTType] {
        var types: [UTType] = []
        // Файл модели идёт первым — система по нему подписывает окно выбора.
        if let model = UTType(filenameExtension: "litertlm") { types.append(model) }
        // GGUF — формат второго движка (Bonsai). Своего системного типа у формата НЕТ:
        // Apple его не регистрирует, из системы он не приходит, поэтому тип строим
        // динамически по расширению — иначе .gguf в окне выбора останется бледным
        // и ненажимаемым, а бледная строка у нас считается молчаливым отказом.
        if let gguf = UTType(filenameExtension: "gguf") { types.append(gguf) }
        // Папка: модель Apple лежит папкой, и выбирать её надо целиком.
        types.append(.folder)
        // Любой файл: причину отказа человек должен прочитать, а не догадаться
        // по бледной строке.
        types.append(.data)
        return types
    }

