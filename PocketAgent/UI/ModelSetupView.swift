        .padding(.horizontal, Theme.Metrics.cardPadding)
        // ⚠️ Своей высоты строка НЕ задаёт: площадь касания под палец приносит с собой
        // сама кнопка, а заголовки без кнопки от общего числа выросли бы на пустом месте.
