    /// Подводный камень модели, человеческим языком.
    ///
    /// ⚠️ Если каталог камня не назвал, но модель умеет считать ТОЛЬКО на видеочипе, —
    /// говорим об этом сами. Молчать нельзя: у такой модели нет запасного пути, и при
    /// нехватке памяти она просто не запустится, а человек не поймёт почему.
    /// ⚠️ ОГОВОРКА НЕ ДОЛЖНА ПОВТОРЯТЬ ТО, ЧТО СКАЖЕТ СТРОКА ПРО ПАМЯТЬ.
    /// У найденного на телефоне файла первая оговорка — это и есть предупреждение
    /// о памяти, и на экране владельца одна и та же фраза стояла ДВАЖДЫ подряд,
    /// друг под другом, с разными значками (снимок IMG_1250). Выглядело как поломка.
    private func caveatText(_ option: ModelOption) -> String? {
        if let caveat = option.caveat, !caveat.isEmpty, caveat != memoryText(option) { return caveat }
        if option.requiresGPU {
            return "Считает только на видеочипе телефона: быстрее, но если памяти не хватит, "
                 + "перейти на обычный расчёт эта модель не умеет."
        }
        return nil
    }

    /// Текст строки про память — он же нужен, чтобы не напечатать его вторым разом
    /// в оговорке (см. caveatText).
    private func memoryText(_ option: ModelOption) -> String? {
        switch option.memory {
        case .fits, .unknown:      return nil
        case .tight(let text):     return text
        case .tooBig(let text):    return text
        }
    }

    /// Что с памятью телефона под эту модель. Молчим, когда всё в порядке:
    /// лишняя зелёная строка на каждой карточке — шум.
    @ViewBuilder
    private func memoryNote(_ option: ModelOption) -> some View {
        switch option.memory {
        case .fits, .unknown:
            EmptyView()
        case .tight(let text):
            noteRow(icon: "memorychip",
                    color: Theme.Colors.warning,
                    text: text)
        case .tooBig(let text):
            noteRow(icon: "exclamationmark.triangle.fill",
                    color: Theme.removed,
                    text: text)
        }
    }

