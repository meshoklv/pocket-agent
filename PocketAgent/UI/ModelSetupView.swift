//  Вкладка «Модели»: что работает сейчас, что уже лежит на телефоне, что можно
//  поставить и где взять свой файл. Четыре вопроса — четыре блока, и каждый блок
//  отвечает ровно на один.
//
//  ПОРЯДОК СВЕРХУ ВНИЗ (10.08.2026, разбор владельца — не менять без причины):
//   1. заголовок;
//   2. что происходит прямо сейчас — загрузка с полосой, пауза, обрыв, «готовим движок».
//      В покое блока нет вовсе;
//   3. «Сейчас работает» — какая модель разложена в памяти. Модели нет — так и сказано,
//      одной строкой, без объяснений на пол-экрана;
//   3а. недокачанное с прошлого раза — ПОСЛЕ «Сейчас работает» (приёмка 10.08.2026):
//      огрызок загрузки не важнее ответа на вопрос «модель готова?»;
//   4. «Модели на телефоне» (`ModelsOnPhoneList`) — узкий список файлов, каждый
//      нажимается и ставится. Ниже — что не подошло и «Поискать ещё раз»;
//   5. «Поставить модель» — зашитый список моделей и вход в поиск по интернету;
//   6. «Свой файл» — выбрать готовый файл и страница «где его взять»;
//   7. место на телефоне, удаление про запас, лицензия.
//
//  ⚠️ СПИСКИ ВИДНЫ ВСЕГДА, В ЛЮБОМ СОСТОЯНИИ (10.08.2026, жалоба владельца: «список
//  моделей нельзя увидеть, если модель не загружена в память»). Раньше и «Модели на
//  телефоне», и «Поставить модель», и найденные файлы рисовались только в состоянии
//  покоя (`isRestingState`) — то есть во время загрузки, проверки файла, «готовим
//  движок», установки из файла и на паузе экран моделей ОСТАВАЛСЯ БЕЗ ЕДИНОГО СПИСКА.
//  Теперь наоборот: списки на месте всегда, а на время работы гасятся только НАЖАТИЯ
//  (`isBusy`) — менять выбор посреди загрузки нельзя, потому что имя и размер в полосе
//  прогресса берутся у выбранной модели и поехали бы вместе с выбором.
//
//  ⚠️ БЛОКА «СВЕЖЕЕ ИЗ ИНТЕРНЕТА» (`LiveModelsSection`) НА ЭТОЙ ВКЛАДКЕ БОЛЬШЕ НЕТ
//  (10.08.2026, слова владельца: «вкладка свежее из интернета — колхоз, убери это или
//  спрячь в раздел»). Живой список из справочника торчал прямо посреди вкладки вторым
//  списком моделей и спорил с зашитым. Он не потерян: весь справочник целиком — на
//  странице поиска (`ModelSearchView`), куда ведёт одна строка «Найти модель
//  в интернете» в разделе «Поставить модель». Человек заходит туда осознанно.
//
//  ТРИ пути получить модель, и все три равноправны:
//   • модель УЖЕ лежит на телефоне — нажать её строку в списке «Модели на телефоне»;
//   • скачать ту, что выбрана в списке «Поставить модель»;
//   • взять готовый файл из «Файлов» (компьютер, AirDrop, iCloud, другое
//     приложение) — раздел «Свой файл».
//
//  ⚠️ ЧТО ЗДЕСЬ ИЗМЕНИЛОСЬ ПОСЛЕ ЖАЛОБЫ ВЛАДЕЛЬЦА (не откатывать):
//   1. Модель больше не одна. На экране список: чем модели отличаются, что советуем
//      и какие у каждой подводные камни. Раньше экран знал ровно один файл.
//   2. Папка приложения перечисляется, и найденный файл предлагается карточкой.
//      Раньше приложение проверяло существование одного пути с одним зашитым именем.
//   3. Отказ «Это не тот файл: весит 3,66 ГБ, а нужен ровно 2,01 ГБ» из интерфейса
//      исчез. Незнакомая, но годная модель проходит с предупреждением и вопросом.
//   4. У КАЖДОЙ строки списка своё состояние (работает · качается · файл на телефоне),
//      а кнопка действия стоит ВНУТРИ выбранной строки. Раньше состояние было одно
//      на весь экран, и на любой открытой модели читалось «Скачать — уже стоит»:
//      скачать вторую модель было нельзя вообще.
//   5. Большая карточка «Где взять файл» (`ModelFileHelpCard`) с экрана УБРАНА
//      (09.08.2026, вторая жалоба владельца: «бесит, когда листаешь что-то, а она
//      на треть экрана»). Инструкция не удалена — она переехала на отдельную страницу
//      `ModelFileHelpSheet`, которая открывается из раздела «Свой файл».
//   7. БОЛЬШОЙ КАРТОЧКИ «Нашли модель на телефоне» БОЛЬШЕ НЕТ (10.08.2026). Один и тот
//      же файл человек видел дважды: карточкой с кнопкой «Использовать» и строкой
//      в узком списке ниже. Осталась строка: она нажимается и ставит модель.
//   6. НИЖНЕЙ ПЛАВАЮЩЕЙ ПАНЕЛИ ИЗ ДВУХ КНОПОК БОЛЬШЕ НЕТ (09.08.2026, третья жалоба
//      владельца: «работает — эта модель уже загружена — из файла — уже скачан — вот эта
//      плашка из двух кнопок. В этом беда»). Панель висела поверх списка всегда, съедала
//      низ экрана и стояла вторым рядом органов управления прямо над системными вкладками.
//      Куда всё переехало — и ничего не потеряно:
//        • «Скачать · 2,59 ГБ» / «Использовать» — В САМУ СТРОКУ выбранной модели.
//          Там же, где человек выбирает, — значит по-прежнему один шаг, и кнопка
//          физически не может соврать про то, к какой модели она относится;
//        • «Из файла» — в меню «…» → «Выбрать файл на телефоне»;
//        • «Скачиваю · 46 %» с паузой, «Проверяю файл», «Готовим движок», «Начинаю
//          загрузку», «Продолжить» после обрыва — в карточку состояния (`statusBlock`),
//          и она поднята НАВЕРХ экрана, сразу под заголовок. Полоса прогресса, пауза,
//          продолжение и отмена живут в одном месте, а не на двух слоях сразу.
//
//  Дизайн: тёмная тема, контент обычными карточками, стекло — ТОЛЬКО на круглой кнопке
//  меню сверху (внизу стеклу взяться неоткуда: своей панели у экрана больше нет).
//  Цвета — только из Theme, проверки версии iOS — только внутри UI/Design.
//
//  ⚠️ Системной панели навигации на экране НЕТ (решение из design notes,
//  раздел «Решения по волне доведение до идеала»): её роль играют круглые
//  плавающие кнопки, а заголовок у экрана ровно один — крупный, в контенте.
//

import SwiftUI
import UniformTypeIdentifiers

struct ModelSetupView: View {

    @ObservedObject var app: AppViewModel

    /// Меню и «О программе» открываются прямо отсюда: системной панели больше нет,
    /// а текст лицензии Apache 2.0 обязан быть доступен человеку с любого экрана.
    @State private var isMenuShown = false
    @State private var isAboutShown = false
    /// Страница «Где взять файл» — открывается пунктом меню «Взять готовый файл».
    /// Раньше это была карточка прямо на экране; см. пункт 5 в шапке файла.
    @State private var isFileHelpShown = false
    /// Человек нажал «Выбрать файл» НА СТРАНИЦЕ помощи: системное окно открываем
    /// только когда страница уже закрылась (`.sheet(onDismiss:)` ниже) — одновременно
    /// два модальных слоя на экране не держим.
    @State private var openFilePickerAfterHelp = false
    /// Системное окно выбора уже скачанного файла модели.
    @State private var isFilePickerShown = false
    /// Страница поиска моделей в интернете (`ModelSearchView`).
    ///
    /// ⚠️ ДЕРЖИМ ЕЁ ЗДЕСЬ, А НЕ ВНУТРИ САМОЙ КНОПКИ. Раньше страницу открывала кнопка
    /// «Найти модель в интернете», объявленная в одном файле со страницей, — и со стороны
    /// это читалось как «страницу никто не открывает»: поиск по её имени находил только
    /// её собственный файл. Дважды из-за этого решали, что экран поиска мёртвый, и шли
    /// подключать заново то, что и так работало. Теперь вход виден оттуда, откуда его
    /// и станут искать, — с экрана, на котором он стоит.
    @State private var isModelSearchShown = false
    /// Страница «Работа по ключу» — думает не телефон, а поставщик.
    ///
    /// ⚠️⚠️ ВХОД СТОИТ ЗДЕСЬ, И ЭТО НЕ УДОБСТВО, А ЕДИНСТВЕННОЕ РАБОЧЕЕ МЕСТО ДЛЯ НЕГО.
    /// Раньше вход был один — пункт меню на экране чата. Но экран чата открывается ТОЛЬКО
    /// когда местная модель уже поднята, и получался замкнутый круг: чтобы включить работу
    /// по сети, нужна модель в телефоне; а нужна работа по сети как раз тому, кому модель
    /// качать некуда. Тот же круг запирал человека, упёршегося в предел трат: движок по
    /// ключу падал, чат пропадал, а поднять предел было негде. Вкладка «Модели» доступна
    /// всегда — значит и выход есть всегда.
    @State private var isRemoteAccessShown = false
    /// Экран «Картинки».
    @State private var isImageStudioShown = false
    /// С какой моделью открыть «Картинки», если туда привёл поиск. nil — с прошлой.
    @State private var imageStudioFamilyID: String?
    /// На странице «Работа по ключу» тронули то, из-за чего движок надо поднять заново.
    @State private var remoteSettingsChanged = false
    /// Страница «Скорость загрузки» — итог прошлой загрузки, число потоков и размер куска.
    ///
    /// ⚠️ ВХОД ТОЛЬКО ИЗ МЕНЮ «…», И ЭТО РЕШЕНИЕ, А НЕ ЛЕНЬ. Настройками загрузки человек
    /// пользуется в редком случае («качается медленно — попробую иначе»), а экран моделей
    /// и без них плотный. Строка с двумя рядами переключателей висела бы на нём всегда
    /// и была бы нужна раз в жизни — ровно тот мусор, за который экран уже разбирали.
    @State private var isDownloadSpeedShown = false
    /// Подтверждение удаления модели с телефона.
    @State private var isDeleteConfirmShown = false
    /// В этот заход что-то реально качалось — значит итог загрузки про него и есть.
    /// Нужен, чтобы не приписать цифры чужой загрузки модели, взятой с телефона.
    @State private var justDownloaded = false
    /// Человек прочитал приговор «эта модель не запустится» и нажал «Понятно».
    /// Пусто — карточка приговора показывается, как только он появился.
    @State private var dismissedDeadEndKey: String?
    /// Человек нажал «стереть скачанное» и ждёт вопроса «точно?».
    @State private var isEraseConfirmShown = false
    /// Человек развернул список файлов, которые приложение видит, но взять не может.
    /// Свёрнут по умолчанию: этот ответ нужен редко, а места занимал десять строк.
    @State private var isRejectedShown = false
    /// Черновик оборванной загрузки, который человек собрался стереть. nil — не собрался.
    /// Стирание начинается только из вопроса ниже, а не по нажатию на строку.
    @State private var draftToDiscard: ModelStorage.UnfinishedModelDownload?
    /// Модель, чей приговор «не запустится» надо забыть, КОГДА скачанное сотрётся.
    ///
    /// ⚠️ Забываем не по нажатию, а по успеху: если стереть не удалось, недокачанный
    /// файл остался лежать — и приговор про него по-прежнему правда.
    @State private var deadEndToForget: String?
    /// Действие, которое сменит рабочую модель, — ждёт подтверждения человека.
    /// nil — спрашивать не о чем.
    @State private var pendingModelChange: (() -> Void)?

    /// Порядок и отбор в списке «Поставить модель». Живёт между
    /// запусками: человек, разобравший список один раз, не должен делать это снова.
    ///
    /// ⚠️ ОТБОР ЕСТЬ ТОЛЬКО У ЭТОГО СПИСКА, И ЭТО РЕШЕНИЕ, А НЕ НЕДОДЕЛКА. Второй
    /// список на экране — «Модели на телефоне» — это одна-три строки того, что человек
    /// уже принёс; сортировать и отбирать там нечего, а кнопка над ним была бы ровно
    /// тем визуальным шумом, из-за которого весь этот экран и разбирали.
    @State private var installFilter = ModelListFilter.load(.installList)

    /// Наши незаконченные загрузки: что не докачалось до конца в прошлый раз.
    ///
    /// ⚠️ ЖИВОЙ СЛУЧАЙ ВЛАДЕЛЬЦА 10.08.2026, ради которого это и заведено. Он бросил
    /// загрузку на 68 кусках из 76 и перезапустил приложение — и на экране не осталось
    /// ни слова про недокачанные 2,28 ГБ: сама модель была найдена поиском по интернету,
    /// а такую строку приложение помнит только до перезапуска. Продолжить было нечем
    /// и удалить черновик тоже нечем.
    @State private var unfinishedDownloads: [ModelStorage.UnfinishedModelDownload] = []

    /// Насколько далеко зашла загрузка в последний раз, когда это было известно.
    ///
    /// ⚠️ ЗАЧЕМ ОТДЕЛЬНАЯ ПАМЯТЬ. Пауза приходит от движка обычным «упало»
    /// («Загрузка остановлена…»), и `app.downloadProgress` в этот момент пустеет.
    /// Без этой памяти кольцо на паузе показывало бы ноль — то есть говорило бы,
    /// что скачанного нет вовсе, хотя на телефоне уже лежат гигабайты.
    @State private var lastKnownProgress: Double = 0

    /// Колонка под иконку в строках «иконка + текст». Растёт вместе с системным шрифтом.
    @ScaledMetric(relativeTo: .title3) private var iconGutter: CGFloat
        = Theme.Metrics.iconGutterWidth

    var body: some View {
        // ⚠️ Своего фона во весь экран здесь нет намеренно: его рисует корневой экран.
        // Дважды нарисованный фон — лишняя перерисовка всего экрана каждый кадр.
        ScrollView {
            VStack(alignment: .leading, spacing: Theme.Metrics.sectionSpacing) {
                header

                // ⚠️ ЧТО ПРОИСХОДИТ ПРЯМО СЕЙЧАС — ПЕРВЫМ, СРАЗУ ПОД ЗАГОЛОВКОМ.
                // Раньше загрузка жила на нижней панели, а карточка с той же полосой
                // стояла в самом низу списка. Панели больше нет — значит прогресс, пауза,
                // «Продолжить» и отмена обязаны быть на виду, а не под тремя экранами
                // прокрутки. Когда ничего не происходит, блок пустой и места не занимает.
                statusBlock

                // 1. Что стоит сейчас.
                runningSection

                // Недокачанное с прошлого раза — СРАЗУ ПОСЛЕ рабочей модели, а не перед ней.
                //
                // ⚠️ РАНЬШЕ ЭТОТ БЛОК СТОЯЛ ВЫШЕ, И ЭТО БЫЛА ОШИБКА ПОРЯДКА: человек
                // с работающей моделью и старым огрызком загрузки первым делом читал
                // жёлтое «Загрузка не докачана» — тревогу о черновике вместо ответа
                // на главный вопрос «модель готова?». Огрызок никуда не торопится:
                // он лежит на диске и ждёт, а рабочая модель — это то, ради чего
                // человек и открыл вкладку.
                unfinishedDownloadsBlock

                // 2. Что уже лежит на телефоне — и почему приложение чего-то не видит.
                phoneSection

                // 3. Что можно поставить: наш список и вход в поиск по интернету.
                installSection

                // 4. Где взять свой файл.
                ownFileSection

                // 5. Не телефон, а поставщик по ключу человека. Стоит после всех местных
                // способов намеренно: модель в телефоне — главный путь, это альтернатива.
                remoteSection

                // 6. Картинки — отдельная модель и отдельный экран, помощнику не инструмент.
                imageSection

                spaceNotice
                maintenance
                footnote
            }
            .padding(.horizontal, Theme.Metrics.screenPadding)
        }
        .scrollIndicators(.hidden)
        // ⚠️ ПОРЯДОК МОДИФИКАТОРОВ ВАЖЕН И МЕНЯТЬ ЕГО НЕЛЬЗЯ.
        // Вставка безопасной зоны идёт ПЕРВОЙ — прямо на ScrollView, до эффектов края.
        //
        // ⚠️ НИЖНЕЙ ВСТАВКИ ЗДЕСЬ БОЛЬШЕ НЕТ, И ВОЗВРАЩАТЬ ЕЁ НЕ НАДО. Она держала свою
        // плавающую панель из двух кнопок — панель убрана целиком (пункт 6 в шапке файла).
        // Место под системные вкладки резервирует система, а не мы: своё число или своя
        // вставка снизу здесь означали бы пустую полосу над вкладками.
        .safeAreaInset(edge: .top, spacing: 0) { topLayer }
        // Оба края, а не только нижний: на iOS 26 верх экрана держится именно системным
        // растворением — своей подложки позади плавающего слоя там нет и быть не должно.
        .adaptiveScrollEdge(.soft, for: [.top, .bottom])
        // ⚠️ Раньше здесь стоял ещё `.toolbar(.hidden, for: .navigationBar)` — убран
        // вместе с NavigationStack в ContentView.swift: без
        // NavigationStack нет и панели, которую он прятал бы, модификатор ничего не делал.
        .preferredColorScheme(.dark)
        // Свободное место считает AppViewModel — вне главного потока и только при
        // смене вида состояния. Экран в файловую систему не лезет вообще.
        .onAppear { app.refreshFreeSpace() }
        // Недокачанное считаем при появлении экрана и каждый раз, когда работа с моделью
        // началась или кончилась: после докачки план исчезает, и карточка обязана уйти
        // сама, без «Поискать ещё раз».
        .task { await reloadUnfinishedDownloads() }
        .onChange(of: isBusy) { _, _ in
            Task { await reloadUnfinishedDownloads() }
        }
        .onReceive(NotificationCenter.default.publisher(for: .pocketAgentModelsChanged)) { _ in
            Task { await reloadUnfinishedDownloads() }
        }
        // Запоминаем последний известный ход — он нужен кольцу на паузе, когда движок
        // перестаёт его сообщать. Присваивание дешёвое: одно число, без диска и сети.
        .onChange(of: app.downloadProgress) { _, newValue in
            if let newValue {
                lastKnownProgress = newValue
                // Загрузка в этот заход была — значит итог, который движок запишет
                // в конце, относится именно к ней, и его можно показать.
                justDownloaded = true
            }
        }
        // Модель поднялась — цифры загрузки своё отжили. Без сброса они прицепились бы
        // к следующей модели, которую человек просто взял с телефона, ничего не качая.
        .onChange(of: app.isModelReady) { _, isReady in
            if isReady { justDownloaded = false }
        }
        // Выбранный порядок и отбор человек находит на месте и завтра, и через неделю.
        .onChange(of: installFilter) { _, newValue in
            newValue.save(.installList)
        }
        // Скачанное стёрлось — приговор «эта модель не запустится» больше не о чем
        // помнить: файла нет, а решит человек качать её снова — движок проверит заново.
        //
        // ⚠️ Ошибку стирания приложение кладёт в errorText, а перед стиранием обнуляет
        // его само — значит непустой текст здесь означает именно свежую неудачу.
        // Тогда приговор оставляем: недокачанный файл остался лежать.
        .onChange(of: app.isDiscardingDownload) { _, isDiscarding in
            guard !isDiscarding, let modelID = deadEndToForget else { return }
            deadEndToForget = nil
            if app.errorText == nil { ModelDeadEnds.shared.forget(modelID: modelID) }
        }
        .confirmationDialog("Pocket Agent",
                            isPresented: $isMenuShown,
                            titleVisibility: .visible) {
            // ⚠️ ПУНКТОВ ПРО МОДЕЛИ ЗДЕСЬ БОЛЬШЕ НЕТ (10.08.2026). «Найти модель
            // в интернете», «Выбрать файл на телефоне» и «Взять готовый файл» стоят
            // теперь на самом экране, каждый в своём разделе. Дублировать их в меню —
            // это два входа в одно и то же и лишний повод гадать, где правильный.
            Button("О программе") { isAboutShown = true }
            // ⚠️ Именно «Загрузка моделей», а не «Скорость загрузки»: на странице
            // «О программе» рядом уже стоит «Скорость работы» (это про то, как быстро
            // модель отвечает), и два похожих названия про разные вещи путали бы.
            Button("Загрузка моделей") { isDownloadSpeedShown = true }
            Button("Отмена", role: .cancel) { }
        }
        .confirmationDialog("Удалить модель с телефона?",
                            isPresented: $isDeleteConfirmShown,
                            titleVisibility: .visible) {
            Button("Удалить", role: .destructive) { app.deleteModel() }
            Button("Отмена", role: .cancel) { }
        } message: {
            Text(deleteConfirmMessage)
