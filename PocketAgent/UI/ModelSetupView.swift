            .buttonStyle(.plain)
            .foregroundStyle(Theme.removed)
            .padding(.horizontal, Theme.Metrics.cardPadding)
        }
    }

    private var deleteConfirmMessage: String {
        // Разговор без модели не продолжить — говорим об этом прямо, а не постфактум.
        let conversationNote = app.hasLiveConversation
            ? " Начатый разговор закроется — задача попадёт в «Задачи»."
            : ""
        if let sizeText = app.installedModelSizeText {
            return "Освободится \(sizeText). Чтобы снова пользоваться помощником, файл придётся скачать или взять из «Файлов» заново.\(conversationNote)"
        }
        return "Чтобы снова пользоваться помощником, файл придётся скачать заново.\(conversationNote)"
    }

    /// Карточка «идёт работа»: вертушка и заголовок. Пояснение — по желанию.
    ///
    /// ⚠️ Пояснение НЕОБЯЗАТЕЛЬНОЕ намеренно. Когда сказать нечего кроме пересказа
    /// заголовка («Убираю скачанное» — «освобождаю место»), второй строки быть
    /// не должно: вертушка уже говорит, что идёт работа. Пояснение остаётся там,
    /// где оно предупреждает — сколько ждать и что нельзя закрывать приложение.
    private func busyCard(title: String, detail: String? = nil, footnote: String? = nil) -> some View {
        card {
            HStack(alignment: .top, spacing: 12) {
                ProgressView()
                VStack(alignment: .leading, spacing: 4) {
                    Text(title)
                        .font(Theme.Fonts.sectionTitle)
                        .foregroundStyle(Theme.textPrimary)
                    if let detail {
                        Text(detail)
                            .font(.footnote)
                            .foregroundStyle(Theme.textSecondary)
                    }
                    // Цифры доехавшей загрузки: чем всё кончилось. Мелко и последней
                    // строкой — ждущему они не нужны, а вспоминающему нужны.
                    if let footnote {
                        Text(footnote)
                            .font(.caption)
                            .foregroundStyle(Theme.textSecondary)
                            .fixedSize(horizontal: false, vertical: true)
                    }
                }
            }
        }
    }

    private var footnote: some View {
        VStack(alignment: .leading, spacing: 6) {
            // ⚠️ Про лицензию говорим про СЕМЕЙСТВО, а не про конкретный файл: человек
            // может принести модель, которой мы не знаем, и подписывать её именем
            // и лицензией нашей — враньё.
            Text("Модели Gemma — от Google, лицензия \(app.modelLicense).")
            Text("Файл модели не попадает в резервную копию iCloud.")
        }
        .font(.caption)
        .foregroundStyle(Theme.textSecondary)
        // По внутреннему краю карточки — та же колонка, что и у остального текста.
        .padding(.horizontal, Theme.Metrics.cardPadding)
        // Страница «Загрузка моделей» и вопрос перед стиранием живут на подписи внизу:
        // она есть в любом состоянии экрана, поэтому ни пункт меню, ни вопрос не могут
        // однажды перестать открываться вместе с исчезнувшей карточкой.
        .sheet(isPresented: $isDownloadSpeedShown) {
            DownloadSpeedSheet()
        }
        .confirmationDialog("Стереть скачанное?",
                            isPresented: $isEraseConfirmShown,
                            titleVisibility: .visible) {
            Button("Стереть", role: .destructive) { app.cancelModelDownloadAndDelete() }
            Button("Отмена", role: .cancel) { deadEndToForget = nil }
        } message: {
            Text(eraseConfirmMessage)
        }
    }

    // MARK: - Кнопки внутри контента

    /// Главное действие карточки или строки списка: широкая синяя капсула.
    ///
    /// ⚠️ Синяя, а не зелёная: зелёный у нас означает «получилось», а белая подпись
    /// на зелёном даёт контраст около 2:1 при норме 4,5:1.
    /// Погашенная кнопка остаётся ВИДНОЙ и называет причину прямо в подписи —
    /// молча серая кнопка читается как поломка приложения.
    private func primaryButton(_ title: String,
                               systemImage: String,
                               isEnabled: Bool = true,
                               action: @escaping () -> Void) -> some View {
        Button(action: action) {
            HStack(spacing: 8) {
                Image(systemName: systemImage)
                Text(title)
                    .font(.subheadline.bold())
            }
            .frame(maxWidth: .infinity)
            .frame(minHeight: Theme.Metrics.minimumTapTarget)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .foregroundStyle(isEnabled ? Theme.Colors.textOnAccent : Theme.Colors.textTertiary)
        .background(isEnabled ? Theme.Colors.accent : Theme.surfaceHigh, in: Capsule())
        .disabled(!isEnabled)
        .accessibilityLabel(Text(title))
    }

    /// Второстепенное действие: та же капсула, но серая.
    private func secondaryButton(_ title: String,
                                 systemImage: String,
                                 action: @escaping () -> Void) -> some View {
        Button(action: action) {
            HStack(spacing: 8) {
                Image(systemName: systemImage)
                Text(title)
                    .font(.subheadline.bold())
            }
            .frame(maxWidth: .infinity)
            .frame(minHeight: Theme.Metrics.minimumTapTarget)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .foregroundStyle(Theme.textPrimary)
        .background(Theme.surfaceHigh, in: Capsule())
        .accessibilityLabel(Text(title))
    }

    // MARK: - Мелочи

    private var divider: some View {
        Rectangle()
            .fill(Theme.hairline)
            .frame(height: Theme.Metrics.hairlineWidth)
    }

    /// Обычная карточка контента. Стекла на ней нет и быть не должно.
    private func card<Content: View>(@ViewBuilder content: () -> Content) -> some View {
        VStack(alignment: .leading, spacing: 10) {
            content()
        }
        .padding(Theme.Metrics.cardPadding)
        .frame(maxWidth: .infinity, alignment: .leading)
        // Единственное описание поверхности карточки — Theme.cardSurface().
        .cardSurface()
    }
