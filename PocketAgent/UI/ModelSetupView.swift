    /// Что кольцо вокруг кнопки «…» показывает прямо сейчас.
    ///
    /// ⚠️ ВЕТКИ ПОВТОРЯЮТ `statusBlock` ОДНА В ОДНУ, И ЭТО ГЛАВНОЕ ЗДЕСЬ. Кольцо
    /// и карточка состояния — два лица одного и того же. Разойдись они хоть в одном
    /// случае — человек увидел бы красное кольцо над карточкой «Беру модель в работу»
    /// и перестал бы верить обоим.
    ///
    /// ⚠️ Своего счётчика хода здесь НЕТ. Проценты берутся у `AppViewModel` — оттуда же,
    /// откуда их берёт отметка на вкладке «Модели» в нижней панели.
    private var workRing: ModelWorkRing {
        // Ставим из файла: копирование считает свои проценты, они такие же честные.
        if app.isImportingModel {
            if let progress = app.importProgress { return .working(progress) }
            return .unknown
        }
        // Файл уже в папке приложения — дело на мгновение, считать нечего.
        if app.isAdoptingModel { return .unknown }

        switch app.modelStatus {
        case .idle:
            return app.isPreparingModel ? .unknown : .none

        case .downloading(let progress):
            // ⚠️ Во время паузы может долететь последний тик хода — тогда кольцо уже
            // не «идёт», а «стоит»: крутить его в этот момент означало бы врать.
            return app.isDownloadPaused ? .paused(progress) : .working(progress)

        case .verifying, .loading:
            return .unknown

        case .ready:
            return .none

        case .failed:
            // ⚠️ Уборка и пауза приходят от движка тем же «упало», что и обрыв связи.
            // Красное кольцо на решение самого человека — это ложная тревога.
            if app.isDeletingModel || app.isDiscardingDownload { return .unknown }
            if app.isDownloadPaused { return .paused(lastKnownProgress) }
            return .failed
        }
    }

