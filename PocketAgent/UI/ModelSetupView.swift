    // MARK: - Что происходит сейчас

    @ViewBuilder
    private var statusBlock: some View {
        if app.isImportingModel {
            importingCard
        } else if app.isAdoptingModel {
            // Файл уже лежит в папке приложения — копировать нечего, поэтому здесь
            // не полоса прогресса, а короткое «беру». Дело занимает мгновение.
            busyCard(title: "Беру модель в работу")
        } else {
            switch app.modelStatus {
            case .idle:
                // ⚠️ «Начинаю загрузку» жило на нижней панели и вместе с ней исчезло бы
                // совсем: между нажатием и первым процентом проходит пара секунд, и без
                // этой карточки экран выглядел бы так, будто нажатие не сработало.
                if app.isPreparingModel {
                    busyCard(title: "Начинаю загрузку",
                             detail: "Договариваюсь с сервером.")
                } else {
                    EmptyView()
                }

            case .downloading:
                downloadingCard

            case .verifying:
                // Предупреждение про ожидание и «не закрывайте» остаётся дословно —
                // режется только рассказ о том, зачем сверка нужна.
                busyCard(title: "Проверяю файл",
                         detail: "Сверяю целиком — это до минуты. Не закрывайте приложение.")

            case .loading:
                // Отдельное состояние: файл уже скачан, но движку нужно ещё около десяти секунд.
                //
                // ⚠️ ИТОГ ЗАГРУЗКИ ЧЕЛОВЕК ВИДИТ ИМЕННО ЗДЕСЬ, И ТОЛЬКО ЗДЕСЬ НА ЭКРАНЕ.
                // Как только файл доехал, карточка загрузки исчезает вместе со всеми
                // цифрами — «сколько же это заняло» спросить было не у кого. Строка живёт
                // те самые десять секунд и только после НАСТОЯЩЕЙ загрузки: поднятие
                // модели, которую просто взяли с телефона, к этим цифрам отношения
                // не имеет, и показывать их там значило бы приписывать чужой результат.
                busyCard(title: "Готовим движок",
                         detail: "Раскладываю модель в памяти — секунд десять. Не закрывайте приложение, телефон может немного нагреться.",
                         footnote: justDownloaded ? ModelDownloader.lastRunLine : nil)

            case .ready:
                // ⚠️ Карточки «Модель готова» здесь больше нет: ровно то же самое
                // говорит блок «Сейчас работает» ниже, и две галочки подряд про одно
                // и то же — это и есть тот мусор, из-за которого экран разбирали.
                EmptyView()

            case .failed(let message):
                // ⚠️ Пауза и отмена, которые сделал человек, приходят сюда тем же
                // состоянием, что и обрыв связи. Называть их «Загрузка прервалась»
                // нельзя: человек сам нажал кнопку, а надпись про поломку пугает
                // на ровном месте.
                if app.isDeletingModel || app.isDiscardingDownload {
                    busyCard(title: "Убираю скачанное")
                } else if let verdict = deadEndVerdict(afterFailure: message), !isDeadEndDismissed {
                    // ⚠️ ЭТУ МОДЕЛЬ ПРОДОЛЖАТЬ НЕЛЬЗЯ — И «Продолжить» ЗДЕСЬ БЫЛО БЫ
                    // ОБМАНОМ. Живая жалоба владельца 10.08.2026: он качал модель,
                    // увидел «Загрузка прервалась… Повторите ещё раз» и синюю кнопку —
                    // и жал её, хотя эта модель не заработает никогда, сколько ни качай.
                    //
                    // ⚠️ ПРИГОВОР ПРОВЕРЯЕТСЯ РАНЬШЕ ПАУЗЫ, И ЭТО НЕ ПРИДИРКА К ПОРЯДКУ.
                    // Пауза — факт про передачу байтов, приговор — факт про саму модель,
                    // и он сильнее: пока пауза стояла выше, оставалась щель, в которой
                    // на неподнимаемой модели человеку опять предлагали «Продолжить ▶».
                    deadEndCard(verdict)
                } else if app.isDownloadPaused {
                    pausedCard
                } else {
                    card {
                        HStack(spacing: 8) {
                            Image(systemName: "wifi.exclamationmark")
                                .foregroundStyle(Theme.removed)
                            Text("Загрузка прервалась")
                                .font(Theme.Fonts.sectionTitle)
                                .foregroundStyle(Theme.textPrimary)
                        }
                        Text(message)
                            .font(.footnote)
                            .foregroundStyle(Theme.textSecondary)

                        // ⚠️ ИМЯ И ЦИФРЫ СТОЯТ ЗДЕСЬ, И ЭТО СЛИЯНИЕ ДВУХ КАРТОЧЕК-БЛИЗНЕЦОВ.
                        // Раньше про один и тот же обрыв говорили ДВЕ карточки подряд:
                        // эта («Загрузка прервалась» + «Продолжить») и следующая ниже
                        // («Загрузка не докачана · 2,28 из 2,55 ГБ» + «Докачать» + «Стереть»).
                        // Человек видел две кнопки-синонима и гадал, какая настоящая,
                        // причём цифры и выход были только во второй, а первая стояла выше.
                        // Теперь всё в одной: что случилось → сколько скачано → продолжить →
                        // стереть, а вторая карточка про эту же модель больше не рисуется.
                        if let draft = draftOfCurrentModel {
                            Text("\(draft.displayName) · \(draft.progressText)")
                                .font(.caption)
                                .foregroundStyle(Theme.textSecondary)
                                .fixedSize(horizontal: false, vertical: true)
                        } else {
                            Text("Скачанное сохранено — докачаем с этого места.")
                                .font(.caption)
                                .foregroundStyle(Theme.textSecondary)
                        }

                        // ⚠️ Кнопка стояла на нижней панели, и вместе с панелью пропала бы
                        // единственная возможность продолжить оборванную загрузку.
                        primaryButton("Продолжить", systemImage: "arrow.clockwise") {
                            app.retryModel()
                        }

                        // ⚠️ ВТОРОЙ ВЫХОД ИЗ ОБРЫВА. Раньше здесь было
                        // только «Продолжить»: человек, у которого продолжать не выходит,
                        // не мог ни бросить эту загрузку, ни освободить место — выбирался
                        // окольным путём через «О программе».
                        cancelAndEraseButton(title: "Стереть недокачанное")
                    }
                }
            }
        }
    }

    // MARK: - Недокачанное с прошлого раза

    /// Загрузка, оборванная в прошлый раз: сколько скачано, чем продолжить и как стереть.
    ///
    /// ⚠️ ПОКАЗЫВАЕМ ТОЛЬКО В ПОКОЕ. Пока идёт работа, про неё рассказывает карточка
    /// состояния выше, и вторая карточка с теми же цифрами спорила бы с ней.
    @ViewBuilder
    private var unfinishedDownloadsBlock: some View {
        if !isBusy, !visibleUnfinishedDownloads.isEmpty {
            ForEach(visibleUnfinishedDownloads) { item in
                card {
                    HStack(spacing: 8) {
                        Image(systemName: "arrow.down.circle")
                            .foregroundStyle(Theme.Colors.warning)
                        Text("Загрузка не докачана")
                            .font(Theme.Fonts.sectionTitle)
                            .foregroundStyle(Theme.textPrimary)
                    }

                    // Имя и цифры — одной строкой: «Gemma 4 E2B · 2,28 из 2,55 ГБ».
                    Text("\(item.displayName) · \(item.progressText)")
                        .font(.footnote)
                        .foregroundStyle(Theme.textSecondary)
                        .fixedSize(horizontal: false, vertical: true)

                    if item.canResume {
                        primaryButton("Докачать", systemImage: "arrow.down") {
                            resumeUnfinishedDownload(item)
                        }
                    } else {
                        // Молчать нельзя: человек должен понимать, почему кнопки нет.
