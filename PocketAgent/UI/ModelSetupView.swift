    // MARK: - Модель, которая не запустится никогда

    /// Приговор «эта модель не запустится никогда». nil — тупика нет, продолжать можно.
    ///
    /// ⚠️ СПРАШИВАЕМ ДВАЖДЫ, И ВТОРОЙ ВОПРОС — НЕ ПЕРЕСТРАХОВКА. Движок объявляет приговор
    /// самой ошибкой (её текст и лежит в `message`) и отдельно помнит его между запусками,
    /// но помнит ПО ОПОЗНАВАТЕЛЮ МОДЕЛИ, а у файла, лежащего на телефоне, опознаватель
    /// строки — путь внутри приложения, и с опознавателем модели он не совпадает никогда.
    /// Спроси мы только память — карточка не появлялась бы у половины случаев;
    /// спроси только ошибку — она пропадала бы после перезапуска приложения.
    private func deadEndVerdict(afterFailure message: String) -> String? {
        if message.hasPrefix(MLXArchitectures.notRunnableHeadline) { return message }
        guard let modelID = app.selectedOption?.id else { return nil }
        return ModelDeadEnds.shared.reason(forModelID: modelID)
    }

    /// Есть ли у приговора что сказать СВЕРХ заголовка карточки. nil — сказать нечего.
    ///
    /// ⚠️ Первую фразу приговора («Эта модель устроена иначе — приложение её не запустит»)
    /// отрезаем: ровно это написано в заголовке карточки, и напечатанная дважды подряд
    /// она читалась бы как заедание, а не как объяснение. Осталась одна первая фраза —
    /// возвращаем nil и строки не рисуем вовсе, иначе тот же повтор и получится.
    private func withoutHeadline(_ reason: String) -> String? {
        let headline = MLXArchitectures.notRunnableHeadline
        guard reason.hasPrefix(headline) else { return reason }
        let rest = reason.dropFirst(headline.count).trimmingCharacters(in: .whitespacesAndNewlines)
        return rest.isEmpty ? nil : rest
    }

    /// Опознаватель тупика — по нему помним, что человек уже сказал «понятно».
    private var deadEndKey: String { app.selectedOption?.id ?? "" }

    private var isDeadEndDismissed: Bool { dismissedDeadEndKey == deadEndKey }

    /// Есть ли что стирать: недокачанный черновик или уже лежащий на телефоне файл.
    ///
    /// ⚠️ ЧАЩЕ ВСЕГО СТИРАТЬ НЕЧЕГО. Устройство модели проверяется ДО первого байта —
    /// значит на диске пусто, и кнопка «стереть скачанное» говорила бы про то, чего нет.
    private var deadEndHasFilesToErase: Bool {
        if draftOfCurrentModel != nil { return true }
        guard let option = app.selectedOption else { return false }
        return app.fileOnPhone(for: option) != nil
    }

    /// Тупик: качать дальше нечего. Вместо кнопки «Продолжить» — то единственное,
    /// что человеку здесь остаётся.
    ///
    /// ⚠️ СТРОКИ «Скачанное сохранено — докачаем с этого места» ЗДЕСЬ НЕТ НАМЕРЕННО.
    /// Она правда для оборванной связи и ложь для этого случая: докачивать нечего.
    private func deadEndCard(_ verdict: String) -> some View {
        card {
            HStack(spacing: 8) {
                Image(systemName: "xmark.octagon.fill")
                    .foregroundStyle(Theme.removed)
                Text("Эта модель не запустится")
                    .font(Theme.Fonts.sectionTitle)
                    .foregroundStyle(Theme.textPrimary)
            }
            if let detail = withoutHeadline(verdict) {
                Text(detail)
                    .font(.footnote)
                    .foregroundStyle(Theme.textSecondary)
                    .fixedSize(horizontal: false, vertical: true)
            }

            // ⚠️ ПОДПИСЬ И ДЕЙСТВИЕ — ПО СОСТОЯНИЮ, А НЕ ОДНИ НА ВСЕ СЛУЧАИ.
            // Отказ приходит ещё до первого скачанного байта — тогда стирать нечего,
            // и «Отменить и стереть скачанное» не только непонятно, но и опасно:
            // за ним стоит удаление модели, а оно выгружает движок и закрывает
            // начатый разговор. Человеку в этот момент нужно всего лишь убрать
            // карточку и не встречать эту модель снова.
            if deadEndHasFilesToErase {
                cancelAndEraseButton(title: eraseTitleForDeadEnd,
                                     forgetDeadEndOf: deadEndKey)
            } else {
                Button {
                    dismissedDeadEndKey = deadEndKey
                    ModelDeadEnds.shared.forget(modelID: deadEndKey)
                } label: {
                    Text("Понятно")
                        .font(.footnote.bold())
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .frame(minHeight: Theme.Metrics.minimumTapTarget)
                        .contentShape(Rectangle())
                }
                .buttonStyle(.plain)
                .foregroundStyle(Theme.Colors.accent)
            }
        }
    }

    /// «Стереть скачанное — освободит 2,28 ГБ». Цифру называем, когда знаем её.
    private var eraseTitleForDeadEnd: String {
        let size = draftOfCurrentModel?.occupiedText ?? app.installedModelSizeText
        guard let size else { return "Стереть скачанное" }
        return "Стереть скачанное — освободит \(size)"
    }

    /// Отменить загрузку насовсем и стереть скачанное.
    ///
    /// ⚠️ ОДНО действие, а не «пауза, потом удалить» подряд. Пауза только ПРОСИТ систему
    /// снять задачу и возвращается сразу — удаление в том же кадре видело «загрузка ещё
    /// идёт» и показывало человеку ошибку «Сначала дождитесь её окончания», хотя он
    /// только что её остановил. Теперь это делает AppViewModel.cancelModelDownloadAndDelete().
    ///
    /// ⚠️ И ТЕПЕРЬ ОНА ПЕРЕСПРАШИВАЕТ. За этой строкой стоит не только уборка огрызка:
    /// вместе со скачанным уходит установленная модель, движок выгружается, а начатый
    /// разговор закрывается. Человек же читает короткое «стереть недокачанное» и жмёт
    /// не глядя. Соседнее удаление модели на этом экране спрашивает — значит и это обязано.
    ///
    /// `forgetDeadEndOf` — модель, чей приговор «не запустится» надо забыть, когда
    /// стирание удастся (см. `deadEndToForget`). nil — забывать нечего.
    private func cancelAndEraseButton(title: String = "Стереть недокачанное",
                                      forgetDeadEndOf modelID: String? = nil) -> some View {
        Button(role: .destructive) {
            deadEndToForget = modelID
            isEraseConfirmShown = true
        } label: {
            Text(title)
                .font(.footnote)
                .frame(maxWidth: .infinity, alignment: .leading)
                .frame(minHeight: Theme.Metrics.minimumTapTarget)
                .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .foregroundStyle(Theme.removed)
    }

