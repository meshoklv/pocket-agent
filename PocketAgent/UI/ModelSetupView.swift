    private func modelChoiceRow(_ option: ModelOption) -> some View {
        let isPicked = app.selectedOption?.id == option.id
        // Голосовой доступ обязан называть выбранную строку выбранной.
        // ⚠️ Собираем набор отдельной переменной, а не тернаром прямо в модификаторе:
        // тернар из «.isSelected» и пустого литерала выводится по-разному в разных
        // версиях компилятора, а собирать проект здесь нечем.
        var traits = AccessibilityTraits()
        if isPicked { traits.formUnion(.isSelected) }

        return VStack(alignment: .leading, spacing: 0) {
            Button {
                app.selectModel(option)
            } label: {
                HStack(alignment: .top, spacing: 12) {
                    // Кружок выбора: заполненный — выбрано. Только он, без галочек и рамок:
                    // на карточке и так много текста.
                    Image(systemName: isPicked ? "largecircle.fill.circle" : "circle")
                        .font(.title3)
                        .frame(minWidth: iconGutter, alignment: .leading)
                        .foregroundStyle(isPicked ? Theme.Colors.accent : Theme.Colors.textTertiary)

                    VStack(alignment: .leading, spacing: 5) {
                        HStack(spacing: 8) {
                            Text(option.displayName)
                                .font(.subheadline.bold())
                                .foregroundStyle(Theme.textPrimary)
                            if option.isRecommended {
                                badge("советуем", color: Theme.apply)
                            }
                            Spacer(minLength: 0)
                            Text(option.sizeText)
                                .font(Theme.Fonts.counter)
                                .foregroundStyle(Theme.textSecondary)
                        }

                        // ⚠️ Состояние У КАЖДОЙ СТРОКИ СВОЁ, и это главная правка раздела.
                        // Раньше состояние было одно на весь экран, и человек видел «уже
                        // стоит» на любой модели, которую откроет.
                        rowStateBadge(option)

                        if !option.summary.isEmpty {
                            Text(option.summary)
                                .font(.footnote)
                                .foregroundStyle(Theme.textSecondary)
                                .frame(maxWidth: .infinity, alignment: .leading)
                        }

                        // Подводные камни говорим прямо, а не прячем в мелкий шрифт внизу.
                        if let caveat = caveatText(option) {
                            noteRow(icon: "exclamationmark.circle",
                                    color: Theme.Colors.warning,
                                    text: caveat)
                        }
                        memoryNote(option)

                        // ⚠️ ПРИГОВОР ВИДЕН И В САМОЙ СТРОКЕ, А КНОПКИ «Скачать» У НЕЁ НЕТ.
                        // Без этого получался круг: человек читает наверху честное
                        // «Эта модель не запустится», прокручивает пол-экрана — и жмёт
                        // ту же синюю «Скачать · 2,59 ГБ», что и раньше. Пара секунд —
                        // и та же карточка. Кнопка «Продолжить» ушла, а её двойник остался.
                        if isDeadEnd(option) {
                            noteRow(icon: "xmark.octagon.fill",
                                    color: Theme.removed,
                                    text: "Эта модель не запустится — приложение такие не поднимает.")
                        }

                        if !option.canDownload {
                            noteRow(icon: "icloud.slash",
                                    color: Theme.Colors.textTertiary,
                                    text: "Скачать её отсюда нельзя — только положить файлом.")
                        }
                    }
                }
                .padding(Theme.Metrics.cardPadding)
                .frame(maxWidth: .infinity, alignment: .leading)
                .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            // ⚠️ ВО ВРЕМЯ ЗАГРУЗКИ СТРОКА ВИДНА, НО НЕ НАЖИМАЕТСЯ. Не `.disabled`,
            // а именно так: погашенная кнопка красит весь свой текст в серый, и весь
            // список выглядел бы выключенным. А переключать выбор посреди загрузки
            // нельзя — имя и размер в полосе прогресса берутся у выбранной модели
            // и уехали бы вместе с выбором на чужие цифры.
            .allowsHitTesting(!isBusy)
            // Строку целиком читаем вслух одним куском — но ТОЛЬКО её.
            // ⚠️ Объединение съедает вложенные кнопки, поэтому оно висит на кнопке
            // выбора, а не на всей карточке: иначе до «Скачать» было бы не добраться
            // голосом.
            .accessibilityElement(children: .combine)
            .accessibilityAddTraits(traits)

            // ⚠️ ГЛАВНОЕ ДЕЙСТВИЕ ЖИВЁТ ЗДЕСЬ, В САМОЙ СТРОКЕ, А НЕ НА ПАНЕЛИ ВНИЗУ.
            // Так «Скачать · 2,59 ГБ» физически не может относиться к другой модели:
            // кнопка нарисована внутри той строки, про которую говорит. Ровно на этом
            // расхождении раньше и рождалось «на всех моделях написано уже стоит».
            // Один шаг сохранён: выбрал строку — кнопка сразу под рукой, листать некуда.
            //
            // ⚠️ Пока идёт работа, кнопки нет: что происходит, рассказывает блок
            // состояния наверху, а второе предложение скачать спорило бы с ним.
            if isPicked, !isBusy, showsRowAction(option) {
                selectedRowAction
                    .padding(.horizontal, Theme.Metrics.cardPadding)
                    .padding(.bottom, Theme.Metrics.cardPadding)
            }
        }
        .frame(maxWidth: .infinity, alignment: .leading)
        .cardSurface()
        // Обводка у выбранной строки: один только кружок при беглом взгляде теряется.
        .overlay {
            RoundedRectangle(cornerRadius: Theme.Metrics.cardCorner, style: .continuous)
                .strokeBorder(isPicked ? Theme.Colors.accent : Color.clear,
                              lineWidth: Theme.Metrics.hairlineWidth * 2)
        }
    }

    /// Нужна ли выбранной строке кнопка действия.
    ///
    /// ⚠️ У работающей модели её нет: строка и так помечена «работает сейчас», а вторая
    /// надпись про то же самое (погашенное «Работает — эта модель уже загружена») —
    /// это ровно та бесполезная кнопка, из-за которой нижнюю панель и убрали.
    private func showsRowAction(_ option: ModelOption) -> Bool {
        // Модель, которую движок не поднимет, качать незачем — кнопки у неё нет.
        if isDeadEnd(option) { return false }
        return app.rowState(for: option) != .running
    }

    /// Движок уже сказал про эту модель «не запустится».
    private func isDeadEnd(_ option: ModelOption) -> Bool {
        ModelDeadEnds.shared.reason(forModelID: option.id) != nil
    }

    /// Кнопка про ВЫБРАННУЮ модель: «Скачать · 2,59 ГБ», «Использовать · файл уже
    /// на телефоне», «Скачать · мало места».
    ///
    /// ⚠️ Что на ней написано и что она сделает — решает `AppViewModel.selectedModelAction`,
    /// а не этот файл. Рисуем её только внутри выбранной строки, поэтому «выбранная
    /// модель» у экрана и у неё — всегда одна и та же.
    private var selectedRowAction: some View {
        let action = app.selectedModelAction
        let title = action.subtitle.isEmpty
            ? action.title
            : "\(action.title) · \(action.subtitle)"
        return primaryButton(title,
                             systemImage: action.systemImage,
                             isEnabled: action.isEnabled) {
            askBeforeModelChange { app.runSelectedModelAction() }
        }
    }

    /// Что с ЭТОЙ моделью прямо сейчас: работает · качается · лежит на телефоне.
    /// У модели, которой на телефоне нет, метки нет вовсе — про неё всё скажет кнопка
    /// действия в самой строке, а лишняя серая надпись на каждой строке это просто шум.
    @ViewBuilder
    private func rowStateBadge(_ option: ModelOption) -> some View {
        switch app.rowState(for: option) {
        case .running:
            badge("работает сейчас", color: Theme.apply)
        case .busy(let text):
            badge(text, color: Theme.Colors.accent)
        case .onPhone:
            badge("файл на телефоне", color: Theme.Colors.accent)
        case .absent:
            EmptyView()
        }
    }

    private func badge(_ text: String, color: Color) -> some View {
        Text(text)
            .font(Theme.Fonts.barLabel)
            .foregroundStyle(color)
            .padding(.horizontal, Theme.Metrics.badgePaddingHorizontal)
            .padding(.vertical, Theme.Metrics.badgePaddingVertical)
            .background(color.opacity(0.16), in: Capsule())
    }

