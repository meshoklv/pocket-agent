    /// Вопрос «точно стереть?» перед тем, как расстаться с недокачанными гигабайтами.
    ///
    /// ⚠️ ВИСИТ НА «СЕЙЧАС РАБОТАЕТ», А НЕ НА САМОЙ КАРТОЧКЕ. Карточка недокачанного
    /// исчезает, как только черновик стёрся, — вопрос ушёл бы с экрана вместе с ней,
    /// не успев дождаться ответа. И не на самом экране: там уже два листа действий
    /// (меню и удаление модели), а два листа на одной ветке спорят между собой —
    /// открывается описанный последним.
    private var discardDraftBinding: Binding<Bool> {
        Binding(get: { draftToDiscard != nil },
                set: { isShown in if !isShown { draftToDiscard = nil } })
    }

    /// Огрызок ИМЕННО ТОЙ загрузки, о которой говорит карточка состояния наверху.
    /// nil — карточка состояния молчит или говорит про другую модель.
    private var draftOfCurrentModel: ModelStorage.UnfinishedModelDownload? {
        guard let option = app.selectedOption else { return nil }
        return unfinishedDownloads.first {
            $0.modelID == option.id
                || $0.fileName.caseInsensitiveCompare(option.fileName) == .orderedSame
        }
    }

    /// Недокачанное, о котором ещё никто не рассказал.
    ///
    /// ⚠️ Пока карточка состояния говорит про оборванную загрузку, её огрызок отсюда
    /// убран: две карточки-близнеца про одну модель — это не забота, а путаница.
    private var visibleUnfinishedDownloads: [ModelStorage.UnfinishedModelDownload] {
        guard case .failed = app.modelStatus, let current = draftOfCurrentModel else {
            return unfinishedDownloads
        }
        return unfinishedDownloads.filter { $0.id != current.id }
    }

    /// Пересчитать недокачанное. Работа с диском — только вне главного потока.
    private func reloadUnfinishedDownloads() async {
        let list = await Task.detached(priority: .utility) {
            ModelStorage.unfinishedDownloads()
        }.value
        if unfinishedDownloads != list { unfinishedDownloads = list }
    }

    /// Продолжить оборванную загрузку.
    ///
    /// ⚠️ Тот же путь, что и у модели, найденной поиском по интернету: сначала говорим
    /// движку, ЧТО качать, и только потом просим начать. Загрузчик сам увидит свой план
    /// на диске и докачает только недостающее — скачанные гигабайты не теряются.
    private func resumeUnfinishedDownload(_ item: ModelStorage.UnfinishedModelDownload) {
        guard let descriptor = item.descriptor else { return }
        askBeforeModelChange {
            ModelSpec.select(descriptor, fileURL: nil)
            app.downloadModelFromHub(unfinishedOption(for: item, descriptor: descriptor))
        }
    }

    /// Строка для полосы прогресса: пока идёт докачка, на экране должны стоять имя
    /// и размер ИМЕННО этой модели.
    private func unfinishedOption(for item: ModelStorage.UnfinishedModelDownload,
                                  descriptor: ModelDescriptor) -> ModelOption {
        ModelOption(id: descriptor.id,
                    displayName: descriptor.displayName,
                    fileName: descriptor.fileName,
                    byteSize: descriptor.byteSize,
                    sizeText: HumanFormat.bytes(descriptor.byteSize),
                    origin: .catalog,
                    isKnown: false,
                    canDownload: true,
                    locationText: "недокачана")
    }

    /// Стереть черновик оборванной загрузки и освободить место.
    private func discardUnfinishedDownload(_ item: ModelStorage.UnfinishedModelDownload) {
        Task {
            await Task.detached(priority: .utility) {
                ModelStorage.discardUnfinishedDownload(item)
            }.value
            await reloadUnfinishedDownloads()
            app.refreshFreeSpace()
        }
    }

