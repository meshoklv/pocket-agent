// MARK: - Кольцо хода вокруг круглой кнопки

/// Что кольцо вокруг кнопки «…» говорит человеку прямо сейчас.
///
/// ⚠️ ЭТО ТОЛЬКО СПОСОБ ПОКАЗА. Считает ход `AppViewModel`, и он же кормит отметку
/// с процентами на вкладке «Модели» в нижней панели. Второго счётчика в приложении
/// нет и заводить его нельзя: разойдясь на пару процентов, два счётчика начали бы
/// спорить друг с другом на одном экране.
enum ModelWorkRing: Equatable {

    /// Ничего не происходит — кольца нет вовсе.
    case none
    /// Ход известен: 0…1.
    case working(Double)
    /// Работа идёт, а сколько её осталось — неизвестно: договариваемся с сервером,
    /// проверяем файл, раскладываем модель в памяти.
    case unknown
    /// Человек нажал паузу. Ход застыл там, где остановился.
    case paused(Double)
    /// Загрузка прервалась.
    case failed

    /// Вид состояния БЕЗ числа.
    ///
    /// ⚠️ Нужен ровно затем же, зачем `ModelRuntimePhase` рядом с `ModelRuntimeStatus`:
    /// отличить «кольцо сменило смысл» от «проценты подросли». Первое проявляется
    /// коротким плавным переходом, второе — линейным движением дуги. Повесь на них
    /// одну анимацию — и на каждом тике процентов кольцо моргало бы целиком.
    enum Kind: Equatable { case none, working, unknown, paused, failed }

    var kind: Kind {
        switch self {
        case .none:    return .none
        case .working: return .working
        case .unknown: return .unknown
        case .paused:  return .paused
        case .failed:  return .failed
        }
    }
}

/// Тонкая обводка вокруг круглой кнопки: далеко ли зашла установка модели.
///
/// ⚠️ ПОЧЕМУ КОЛЬЦО ВООБЩЕ НУЖНО, КОГДА НА ЭКРАНЕ ЕСТЬ КАРТОЧКА С ПОЛОСОЙ.
/// Карточка стоит в самом верху ленты и уезжает при первой же прокрутке, а кнопка «…»
/// висит поверх экрана всегда. Пролистав список моделей вниз, человек терял из виду
/// вообще всё о загрузке — кольцо возвращает ему этот ответ, не занимая ни строчки.
struct ModelWorkRingView: View {

    let state: ModelWorkRing

    /// Человек попросил систему поменьше двигать картинку.
    @Environment(\.accessibilityReduceMotion) private var reduceMotion

    /// Крутится ли дуга «сколько осталось — неизвестно».
    @State private var isSpinning = false

    /// За сколько дуга догоняет новое значение.
    ///
    /// ⚠️ ЭТО И ЕСТЬ СГЛАЖИВАНИЕ. Загрузчик сообщает ход десятки раз в секунду, и без
    /// плавного догона дуга дёргалась бы рывками на каждом сообщении. Значение НЕ
    /// округляем и шагами не режем намеренно: на быстром канале шаги слились бы,
    /// а на медленном дуга стояла бы неподвижно и прыгала раз в несколько секунд —
    /// то есть ровно тот рывок, от которого мы уходим. Непрерывный догон ровен всегда.
    private static let catchUp: Double = 0.5

    /// За сколько дуга «неизвестно» делает полный оборот. Спокойно: это фон,
    /// а не то, на что человек должен смотреть.
    private static let spinTurn: Double = 1.2

    /// Какую долю круга занимает дуга «идёт, а сколько — неизвестно».
    /// ⚠️ Короткая намеренно: длинную можно принять за «уже почти всё скачано».
    private static let unknownArc: Double = 0.18

    var body: some View {
        ZStack {
            switch state {
            case .none:
                EmptyView()

            case .working(let value):
                track(Theme.Colors.accent)
                arc(upTo: value, color: Theme.Colors.accent)

            case .paused(let value):
                // Жёлтый и неподвижный: работа стоит, но скачанное на месте.
                track(Theme.Colors.warning)
                arc(upTo: value, color: Theme.Colors.warning)

            case .unknown:
                unknownRing

            case .failed:
                // ⚠️ ПОЛНОЕ кольцо, а не обрубок. Обрубок читался бы как «столько
                // успели скачать», а это не про ход — это про то, что всё встало.
                // И кольцо не исчезает само: пока карточка на экране говорит
                // «Загрузка прервалась», обводка говорит то же самое.
                Circle()
                    .stroke(Theme.Colors.danger, lineWidth: Theme.Metrics.progressRingWidth)
            }
        }
        // Выносим обводку ЗА край кнопки: отрицательный отступ внутри накладки
        // не меняет ни её размер снаружи, ни размер самой кнопки.
        .padding(-Theme.Metrics.progressRingGap)
        // Кольцо не орган управления: нажатие обязано доставать до кнопки под ним.
        .allowsHitTesting(false)
        // ⚠️ Голосом это НЕ читаем. Кнопка называется «Меню», и второй смысл на ней
        // сбивал бы: про загрузку голосом рассказывает карточка состояния — там же,
        // где живут «Пауза» и «Отменить».
        .accessibilityHidden(true)
        // Появление и смена смысла — одним коротким переходом. Проценты сюда
        // не попадают: у них своя, линейная анимация внутри дуги.
        .animation(Theme.Motion.swap, value: state.kind)
    }

    /// Бледный полный круг — «сколько всего». Без него дуга висит в пустоте
    /// и по ней не видно, далеко ли ещё.
    private func track(_ color: Color) -> some View {
        Circle()
            .stroke(color.opacity(0.22), lineWidth: Theme.Metrics.progressRingWidth)
    }

    private func arc(upTo value: Double, color: Color) -> some View {
        Circle()
            .trim(from: 0, to: min(max(value, 0), 1))
            .stroke(color,
                    style: StrokeStyle(lineWidth: Theme.Metrics.progressRingWidth,
                                       lineCap: .round))
            // Начало — сверху и по часовой стрелке, как у любого циферблата.
            .rotationEffect(.degrees(-90))
            .animation(.linear(duration: Self.catchUp), value: value)
    }

    /// «Идёт, а сколько — неизвестно»: короткая дуга, ровно бегущая по кругу.
    ///
    /// ⚠️ Бледного круга под ней НЕТ намеренно. С кругом дуга читалась бы как доля
    /// («18 % скачано»), а мы про долю сейчас ничего не знаем и обещать её не вправе.
    /// И это именно ровный ход, а не мигание: моргающее кольцо в углу экрана —
    /// та самая ёлка, из-за которой на интерфейс потом ругаются.
    @ViewBuilder
    private var unknownRing: some View {
        if reduceMotion {
            // Человек попросил не двигать картинку. Показываем приглушённое полное
            // кольцо: оно честно говорит «занято» и при этом не называет никакой доли.
            Circle()
                .stroke(Theme.Colors.accent.opacity(0.45),
                        lineWidth: Theme.Metrics.progressRingWidth)
        } else {
            Circle()
                .trim(from: 0, to: Self.unknownArc)
                .stroke(Theme.Colors.accent,
                        style: StrokeStyle(lineWidth: Theme.Metrics.progressRingWidth,
                                           lineCap: .round))
                .rotationEffect(.degrees(isSpinning ? 270 : -90))
                .animation(.linear(duration: Self.spinTurn).repeatForever(autoreverses: false),
                           value: isSpinning)
                .onAppear { isSpinning = true }
                .onDisappear { isSpinning = false }
        }
    }
}
