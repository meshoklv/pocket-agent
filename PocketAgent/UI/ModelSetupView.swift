    /// Спросить, прежде чем менять рабочую модель.
    ///
    /// ⚠️ Молча этого делать нельзя: смена модели закрывает начатый разговор —
    /// половина переписки была бы от прежней модели, а продолжала бы её другая.
    /// Когда терять нечего, вопроса нет — действие идёт сразу.
    private func askBeforeModelChange(_ action: @escaping () -> Void) {
        guard app.willModelChangeRestartConversation else {
            action()
            return
        }
        pendingModelChange = action
    }

    private func runPendingModelChange() {
        let action = pendingModelChange
        pendingModelChange = nil
        action?()
    }

    private var modelChangeBinding: Binding<Bool> {
        Binding(get: { pendingModelChange != nil },
                set: { isShown in if !isShown { pendingModelChange = nil } })
    }

