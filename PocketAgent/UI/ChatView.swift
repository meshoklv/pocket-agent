    // MARK: - Новая задача

    /// Кнопка «Новая задача» стирает всю переписку. Раньше она делала это одним
    /// нажатием и без вопроса — а нарисована прямо над лентой, промахнуться легко.
    ///
    /// ⚠️ РАБОТАЕТ В ЛЮБОЙ МОМЕНТ, В ТОМ ЧИСЛЕ ПОСРЕДИ ХОДА. Раньше кнопку на это
    /// время гасили, и человек оказывался заперт в задаче, которая ему уже не нужна.
    /// Теперь спрашиваем — и по «да» честно останавливаем ход, а потом чистим
    /// (`startNewTaskAnyway`). Без вопроса начинаем только с пустого экрана.
    private func requestReset() {
        if app.snapshot.messages.isEmpty, !isBusy, visibleAction == nil {
            app.startNewTaskAnyway()
        } else {
            isResetConfirmShown = true
        }
    }

    /// Что человек потеряет, начав новую задачу. Три случая — три разных
    /// предупреждения: один текст на все случаи либо пугал бы зря, либо умалчивал
    /// о самом важном.
    private var resetWarningText: String {
        if isBusy {
            return "Помощник сейчас работает — он остановится. Что уже записано в файлы, "
                + "останется как есть, а эта задача уйдёт в «Задачи»."
        }
        if visibleAction != nil {
            return "Правка, которая ждёт вашего решения, будет отклонена — в файлы она "
                + "не попадёт. Задача уйдёт в «Задачи»."
        }
        return "Переписка с агентом будет очищена. Файлы, которые вы уже применили, "
            + "останутся как есть."
    }

    // MARK: - Объявления для VoiceOver

    private func announce(_ state: AgentState) {
        let phrase: String
        switch state {
        case .idle:
            return
        case .thinking:
            phrase = "Думаю над следующим шагом"
        case .awaitingApproval(let action):
            phrase = "Нужно ваше решение. \(action.title)"
        case .applying:
            phrase = "Применяю"
        case .finished:
            phrase = "Задача выполнена"
        case .failed(let message):
            phrase = "Не получилось. \(message)"
        }
        AccessibilityNotification.Announcement(phrase).post()
    }

    // MARK: - Исход шага (для тактильного отклика)

    /// Что уже случилось с ходом. Меняется ТОЛЬКО когда действие завершилось:
    /// файл записан (в ленте появилось сообщение с диффом), задача закончена
    /// или агент остановился на ошибке.
    private struct OutcomeToken: Equatable {
        var appliedWrites: Int
        var isFinished: Bool
        var isFailed: Bool
    }

    private var outcomeToken: OutcomeToken {
        OutcomeToken(appliedWrites: app.snapshot.messages.reduce(into: 0) { count, message in
                        if message.diff != nil { count += 1 }
                     },
                     isFinished: isFinished,
                     isFailed: isFailed)
    }

    private var isFinished: Bool {
        if case .finished = app.snapshot.state { return true }
        return false
    }

    private var isFailed: Bool {
        if case .failed = app.snapshot.state { return true }
        return false
    }

    /// Сколько задач человек уже отправил в этом разговоре.
    /// Считаем именно свои реплики: отклик в палец нужен на отправку, а не на
    /// каждую служебную строку, которых за один ход прилетает несколько.
    private var sentTaskCount: Int {
        app.snapshot.messages.reduce(into: 0) { count, message in
            if message.author == .user { count += 1 }
        }
    }

    /// Какое действие ждёт решения прямо сейчас. `nil` — не ждём ничего.
    private var awaitingActionID: String? {
        if case .awaitingApproval(let action) = app.snapshot.state { return action.id }
        return nil
    }

    // MARK: - Действия из меню по долгому нажатию

    /// «Повторить задачу»: текст прошлой задачи ложится в поле ввода, клавиатура
    /// открывается, курсор — в конце.
    ///
    /// ⚠️ ОТПРАВКИ ЗДЕСЬ НЕТ И БЫТЬ НЕ ДОЛЖНО. Меню кладёт текст в поле — отправляет
    /// его человек кнопкой, как обычно. Так он успевает поправить формулировку,
    /// а главное — ни один пункт меню не запускает работу агента сам по себе.
    /// Поле ввода при этом перезаписывается: человек прямо попросил повторить.
    private func repeatTask(_ text: String) {
        app.draft = text
        isInputFocused = true
    }

    /// Действие «Открыть папку в „Файлах“» — или `nil`, если папки нет и открывать нечего.
    /// Пункт меню появляется ровно тогда, когда он не пустышка.
    private var openFolderAction: (() -> Void)? {
        guard app.projectFolderURL != nil else { return nil }
        return { openFolderInFiles() }
    }

    /// Открыть папку проекта в системном приложении «Файлы».
    ///
    /// Тот же приём, что и в меню корневого экрана: «Файлы» понимают собственный
    /// способ обращения к папке. Сработало или нет — видно по ответу системы,
    /// и молчать в случае отказа мы не будем.
    private func openFolderInFiles() {
        guard let folder = app.projectFolderURL,
              var parts = URLComponents(url: folder, resolvingAgainstBaseURL: false) else {
            app.errorText = "Не получилось открыть папку в «Файлах»."
            return
        }
        parts.scheme = "shareddocuments"
        guard let url = parts.url else {
            app.errorText = "Не получилось открыть папку в «Файлах»."
            return
        }
        openURL(url) { accepted in
            guard !accepted else { return }
            app.errorText = "Не получилось открыть папку в «Файлах». "
                + "Откройте «Файлы» сами — папка называется «\(folder.lastPathComponent)»."
        }
    }

    // MARK: - Лента

    private var timeline: some View {
        ScrollViewReader { proxy in
            ScrollView {
                LazyVStack(alignment: .leading, spacing: 14) {
                    // Воздух под круглыми кнопками: без него верх ленты прижимается
                    // к ним вплотную и плашка «Нужно ваше решение» выглядит подрезанной.
                    Color.clear.frame(height: Theme.Metrics.contentSpacing)

                    header

                    if app.snapshot.messages.isEmpty {
                        emptyState
                    }

                    ForEach(app.snapshot.messages) { message in
                        // Строка сама не знает ни про папку, ни про доступ к ней —
                        // она только спрашивает, есть ли файл, которым можно поделиться,
                        // и зовёт готовые действия обратно сюда.
                        //
                        // ⚠️ Ни одно из этих действий ничего не пишет на диск:
                        // буфер обмена, поле ввода, системное окно «Поделиться»
                        // и переход в «Файлы». Запись файла живёт ТОЛЬКО за кнопкой
                        // «Применить» на карточке ниже.
                        ChatMessageRow(message: message,
                                       shareableFileURL: { app.shareableFileURL(for: $0) },
                                       onRepeatTask: { repeatTask($0) },
                                       onOpenFolder: openFolderAction,
                                       // ⚠️ Кнопка возврата живёт РОВНО У ОДНОЙ строки —
                                       // у самой свежей применённой правки. Вешать её
                                       // на каждую строку значило бы и засорить ленту,
                                       // и разрешить откат из середины цепочки поверх
                                       // более поздних правок — то есть молча стереть
                                       // работу. Вернул последнюю — кнопка перешла
                                       // к предыдущей (см. AgentSnapshot.undoablePointID).
                                       onUndo: undoAction(for: message))
                            .transition(messageTransition)
                    }

                    if let action = visibleAction {
                        ApprovalCard(action: action,
                                     isApplying: isApplying,
                                     onApprove: { app.approve() },
                                     onReject: { app.reject() })
                        // Якорь для прокрутки: лента целится в ВЕРХ карточки,
                        // иначе её шапка уезжает за край и выглядит обрезанной.
                        .id(action.id)
                        .transition(cardTransition)
                    }

                    // Возврат правки спрашивается ТОЙ ЖЕ карточкой «до и после»:
                    // это такая же запись на диск, и решает её человек так же.
                    if let undo = app.snapshot.pendingUndo {
                        ApprovalCard(action: undo.action,
                                     isApplying: undo.isApplying,
                                     intent: undo.isDeletion ? .undoDelete : .undoRestore,
                                     onApprove: { app.confirmUndo() },
                                     onReject: { app.cancelUndo() })
                            .id(undo.action.id)
                            .transition(cardTransition)
                    }

                    // ⚠️ Полоски памяти разговора здесь БОЛЬШЕ НЕТ — она переехала
                    // наверх, в `topBar`, и не прокручивается вместе с лентой.
                    // Возвращать её сюда не надо: внизу она уезжала за край экрана.
                    stepLimitHint
                    stateBanner
                    toolsOffBanner
                    attachmentRow
                    repeatRow

                    Color.clear
                        .frame(height: 1)
                        .id(bottomAnchor)
                }
                // Одна колонка на всё приложение: контент по screenPadding, как на
                // экранах подготовки и «О программе». Плавающий слой (панель ввода,
                // круглые кнопки) живёт по своему, чуть меньшему отступу — так и надо,
                // это разные слои.
                .padding(.horizontal, Theme.Metrics.screenPadding)
                .animation(motion(Theme.Motion.smooth), value: app.snapshot.state)
                // Новое сообщение не возникает рывком, а проявляется за 0,18 секунды.
                // ⚠️ Анимация повешена на КОЛИЧЕСТВО, а не на сам список: список
                // сравнивается поэлементно, и на длинной переписке это лишняя работа
                // на каждый кадр прокрутки.
                .animation(motion(Theme.Motion.appear), value: app.snapshot.messages.count)
            }
            .scrollDismissesKeyboard(.interactively)
            // ⚠️ ПОРЯДОК МОДИФИКАТОРОВ ЗДЕСЬ ЗНАЧИМ.
            // Обе безопасные зоны вешаются на САМ ScrollView и первыми — тогда место
            // под верхнюю строку и под панель ввода резервируется по их фактической
            // высоте. Эффект края идёт ПОСЛЕ них, иначе он оборачивает уже обёрнутую
            // вьюху и вставка до списка не доезжает.
            .safeAreaInset(edge: .top, spacing: 0) { topBar }
            // Панель ввода — именно так, как требует её собственная документация.
            // Место под неё лента резервирует сама и по фактической высоте: поле ввода
            // растёт до пяти строк, шрифт может быть крупным. Раньше панель лежала
            // поверх ленты, а место под неё задавалось числом 96 — и последняя карточка
            // при выросшей панели уезжала под стекло насовсем.
            //
            // ⚠️ Здесь стоит `bottomLayer`, а не сама панель: пока ждут решения, панели
            // внизу нет вовсе (см. шапку файла и `bottomLayer`).
            .safeAreaInset(edge: .bottom, spacing: 0) { bottomLayer }
            // Мягкое затемнение края: контент подныривает под панель ввода снизу
            // и под круглые кнопки сверху. Боковых краёв у вертикальной ленты нет —
            // раньше здесь стояло .all, и эффект просили там, где прокрутки не бывает.
            //
            // ⚠️ `adaptiveBottomFade` отсюда убран намеренно. Он маскировал ленту
            // градиентом у нижней кромки ЭКРАНА (внутри стоял ignoresSafeArea), то есть
            // ПОД самой панелью, а не там, где контент ныряет под стекло: работы ноль,
            // а маска — лишний проход рендера на каждый кадр. Растворение у верхней
            // кромки рисует подложка самой верхней строки (topBar).
            .adaptiveScrollEdge(.soft, for: [.top, .bottom])
            // ⚠️ initial: true обязателен. Без него прокрутка запускается только на
            // ИЗМЕНЕНИИ, а лента может родиться уже непустой — тогда экран остаётся
            // наверху и низ (карточка правки с кнопками) в кадр не попадает.
            // В бою лента новой сессии пуста, и первый холостой вызов ничего не двигает.
            .onChange(of: app.snapshot.messages.count, initial: true) { _, _ in
                scrollToBottom(proxy)
            }
            .onChange(of: app.snapshot.state, initial: true) { _, _ in
                scrollToBottom(proxy)
            }
            // Полоска про приложенный файл появляется внизу ленты — её надо показать,
            // а не оставить за нижним краем.
            .onChange(of: app.attachmentNotice) { _, _ in
                scrollToBottom(proxy)
            }
            // Строка про заход появляется там же, внизу ленты, — её тоже надо показать.
            .onChange(of: app.repeatNotice) { _, _ in
                scrollToBottom(proxy)
            }
            // Полоска про выключенные действия — тоже внизу ленты.
            .onChange(of: app.taskNeedingTools) { _, _ in
                scrollToBottom(proxy)
            }
            // Повтор через мгновение после появления. Первая прокрутка случается
            // раньше, чем лента разложила содержимое, и на непустой ленте может уйти
            // вхолостую. Второй заход делается уже по готовой раскладке.
            // Для пустой ленты это тоже холостой ход — двигать нечего.
            // Намеренно через очередь главного потока, а не через .task:
            // прокрутка и анимация обязаны идти строго на главном потоке.
            .onAppear {
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.4) {
                    self.scrollToBottom(proxy)
                }
            }
        }
    }

    private func scrollToBottom(_ proxy: ScrollViewProxy) {
        // ⚠️ Когда на экране висит карточка правки, ехать в самый низ НЕЛЬЗЯ.
        // Карточка высокая: у низа оказываются кнопки, а её шапка — файл, счётчики
        // и плашка «Нужно ваше решение» — уезжает за верхний край и выглядит
        // обрезанной. Человек должен сначала увидеть, ЧТО ему предлагают,
        // и только потом кнопки. Поэтому целимся в верх карточки.
        //
        // ⚠️ Целиться в верх можно ровно потому, что низ достижим по-честному:
        // панели ввода под кнопками решения больше нет (`bottomLayer`), а дифф
        // на карточке подрезан (ApprovalCard.cardDiffLines). До 09.08.2026 было иначе —
        // лента вставала на верх карточки, а кнопки в это время лежали под стеклом
        // панели ввода, и до них надо было догадаться долистать.
        let target: AnyHashable
        let anchor: UnitPoint
        if let action = visibleAction {
            target = action.id
            anchor = .top
        } else if let undo = app.snapshot.pendingUndo {
            // Карточка возврата такая же высокая, и правило то же: сначала человек
            // видит, ЧТО ему предлагают, и только потом кнопки.
            target = undo.action.id
            anchor = .top
        } else {
            target = bottomAnchor
            anchor = .bottom
        }
        // При включённом «Уменьшении движения» лента не едет сама — она просто
        // оказывается на месте. Дёргающаяся без спроса прокрутка — ровно то, ради чего
        // эту настройку и включают.
        guard let animation = motion(Theme.Motion.gentle) else {
            proxy.scrollTo(target, anchor: anchor)
            return
        }
        withAnimation(animation) {
            proxy.scrollTo(target, anchor: anchor)
        }
    }

    /// Анимация, которой может и не быть: при включённом «Уменьшении движения»
    /// возвращаем nil, и SwiftUI меняет состояние мгновенно.
    private func motion(_ animation: Animation) -> Animation? {
        reduceMotion ? nil : animation
    }

    /// Появление карточки правки. С выключенным движением — простое проявление,
    /// без масштабирования: именно оно и вызывает тошноту.
    private var cardTransition: AnyTransition {
        reduceMotion
            ? .opacity
            : .opacity.combined(with: .scale(scale: 0.97, anchor: .bottom))
    }

    /// Появление сообщения в ленте.
    ///
    /// ⚠️ Масштаб, а НЕ сдвиг по вертикали. Сдвиг пришлось бы делать заметным,
    /// чтобы его было видно, — и тогда соседние строки читались бы как прыгнувшие.
    /// Масштаб рисуется поверх раскладки: место под сообщение занимается сразу,
    /// содержимое ленты никуда не дёргается. Убирается сообщение только вместе
    /// со всей перепиской, поэтому на исчезновение — просто угасание.
    private var messageTransition: AnyTransition {
        reduceMotion
            ? .opacity
            : .asymmetric(insertion: .opacity.combined(with: .scale(scale: 0.97, anchor: .bottom)),
                          removal: .opacity)
    }

    // MARK: - Верхняя строка рабочего экрана

    /// Круглые кнопки на собственной подложке.
    ///
    /// Подложка обязательна: системной панели навигации на этом экране нет, и без
    /// неё лента проезжала прямо по часам, значкам сети и по самим кнопкам.
    /// Сплошная часть закрывает статус-бар и кнопки целиком, нижние `topFadeHeight`
    /// точек — мягкое растворение: контент уходит под кнопки, а не обрывается ножом.
    private var topBar: some View {
        VStack(spacing: 6) {
            GlassCircleButtonRow {
                GlassCircleButton(systemImage: "square.and.pencil",
                                  accessibilityTitle: "Новая задача") {
                    // ⚠️ КНОПКА ЖИВАЯ ВСЕГДА, И ЭТО ИСПРАВЛЕНИЕ ЖИВОЙ ЖАЛОБЫ
                    // 09.08.2026 («не могу делать новые задачи, кнопка пропадает»).
                    // Раньше здесь стояло `isEnabled: !isBusy`: во время хода кнопка
                    // гасла, потому что очистка через агента в этот момент молча
                    // не срабатывала. Лечить это гашением — значит запирать человека
                    // в чужой задаче до её конца. Теперь ход честно останавливается,
                    // и только потом начинается новая задача (см. requestReset).
                    requestReset()
                }
            } trailing: {
                GlassCircleButton(systemImage: "ellipsis",
                                  accessibilityTitle: "Меню") {
                    onMenu()
                }
            }

            // Память разговора — прибита к верху экрана и не уезжает с лентой.
            // Отступ по краям как у контента ленты, чтобы полоска шла с ней в одну
            // колонку, а не жила по отступу плавающего слоя.
            contextMeter
                .padding(.horizontal, Theme.Metrics.screenPadding)
        }
        .padding(.top, Theme.Metrics.floatingBarPaddingVertical)
        .padding(.bottom, topFadeHeight)
        .background(alignment: .top) { topScrim }
        // VoiceOver читает элементы в порядке иерархии. Без этого свайп от начала
        // экрана вёл через всю переписку и весь дифф, и только потом — к кнопкам,
        // которые человек видит вверху.
        .accessibilitySortPriority(1)
    }

    /// Подложка верхней строки — ТОЛЬКО для iOS 17–18: сплошной фон под статус-баром
    /// и кнопками, ниже — растворение в прозрачность.
    ///
    /// ⚠️ НА iOS 26 ПОДЛОЖКИ НЕТ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ. Стекло показывает то, что
    /// проезжает под ним; свой непрозрачный прямоугольник позади плавающего слоя
    /// оставляет ему для съёма только этот прямоугольник, и «стеклянная капсула»
    /// вырождается в плоскую тёмную таблетку. Растворение края там делает система —
    /// `.adaptiveScrollEdge(.soft, for: [.top, .bottom])` ниже по ленте.
    /// Запрет дословно записан в design notes и в шапке FloatingGlassBar.
    @ViewBuilder
    private var topScrim: some View {
        // ⚠️ Подложка нужна ВСЕГДА, а не только на старых iOS.
        // Раньше здесь стояла проверка «если стекла нет» — в расчёте на то, что
        // на новых системах фон размоет само стекло. Но стекло лежит только под
        // круглыми кнопками, а МЕЖДУ ними и над ними — ничего, и лента ехала
        // прямо по часам и значкам сети. Это видно на снимках с симулятора.
        VStack(spacing: 0) {
            Theme.background
            LinearGradient(colors: [Theme.background, Theme.background.opacity(0)],
                           startPoint: .top,
                           endPoint: .bottom)
                .frame(height: topFadeHeight)
        }
        // Подложка обязана уходить ПОД часы и значки сети — их зона в безопасную
        // зону не входит, а закрывать её надо.
        .ignoresSafeArea(edges: .top)
        // Касания сквозь подложку идут в ленту: между кнопками экран прокручивается.
        .allowsHitTesting(false)
    }

