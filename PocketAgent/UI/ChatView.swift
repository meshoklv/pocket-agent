    /// ⚠️ В спокойном состоянии справа стоит НЕ пустота, а цена служебного. Разбор живых
    /// переписок показал: инструкция и описания действий съедают около 806 токенов
    /// из 4 096 ещё до первого слова работы. Без этой подписи «занято 1 840 из 4 096»
