//
//  Рабочий экран: крупный заголовок, лента сообщений пузырями,
//  карточка подтверждения и плавающая стеклянная панель ввода снизу.
//
//  ГРАНИЦА СЛОЁВ (проверяется отдельно, не нарушать):
//  стекло живёт ТОЛЬКО на плавающей панели ввода (FloatingGlassBar) и на круглых
//  кнопках сверху. Пузыри, карточки и ячейки — обычные непрозрачные подложки
//  Theme.*, никакого стекла на контенте.
//
//  ⚠️ ВЕРХНЯЯ ГРАНИЦА ЛЕНТЫ — САМОЕ ХРУПКОЕ МЕСТО ЭКРАНА.
//  Круглые кнопки стоят через `.safeAreaInset(edge: .top)` ИМЕННО ЗДЕСЬ, а не слоем
//  поверх ленты в корневом экране. Так система резервирует под них ровно столько
//  места, сколько они занимают на самом деле, и у ленты появляется верхняя кромка.
//  Раньше кнопки плавали в ZStack корневого экрана, а место под них лента отмеряла
//  выдуманным числом (topControlsClearance = 52) — и переписка ехала прямо по часам,
//  значкам сети и по самим кнопкам. Под кнопками лежит непрозрачная подложка,
//  переходящая в мягкое растворение, — контент уходит под них, а не режется.
//
//  ⚠️⚠️ ПОКА ЖДУТ РЕШЕНИЯ ЧЕЛОВЕКА, ПАНЕЛИ ВВОДА ВНИЗУ НЕТ. НЕ ВОЗВРАЩАТЬ «КАК БЫЛО».
//  Найдено снимком экрана с симулятора 09.08.2026 (iPhone 17 Pro, iOS 26.3): панель
//  ввода и вкладки закрывали собой «Отклонить» и «Применить» — кнопки просвечивали
//  сквозь стекло размытыми пятнами, надписи не читались, а нажатие уходило в панель,
//  а не в кнопку. То есть ломалось ровно то, ради чего приложение существует: правку
//  нельзя было принять. Панель тут ни при чём как «слой» — она просто лишняя в этот
//  момент: задачу человек уже поставил, отправлять всё равно нечего (`canSend` при
//  ждущем действии равен false), от него ждут одного из двух нажатий на карточке.
//  Поэтому мы не подкладываем под кнопки ещё один свой слой и не двигаем панель —
//  мы её УБИРАЕМ на время решения (`bottomLayer`), и кнопки остаются единственным,
//  что есть внизу экрана. Набранный черновик при этом никуда не девается: он живёт
//  в `app.draft` и вернётся в поле, как только решение принято.
//
//  ⚠️ ОБМЕН ФАЙЛАМИ С ЧЕЛОВЕКОМ ЖИВЁТ ЗДЕСЬ ЖЕ, И ПРАВИЛО У НЕГО ТО ЖЕ САМОЕ.
//  Скрепка слева в панели ввода отдаёт агенту файл человека, кнопка «Поделиться»
//  на строке результата отдаёт файл человеку. Копирование файла в папку — это
//  изменение папки человека, поэтому оно начинается ТОЛЬКО после нажатия в окне,
//  где прямо написано, что именно произойдёт. Ни один файл не появляется в папке
//  молча — ровно как ни один файл не записывается моделью без «Применить».
//
//  ⚠️ МЕНЮ ПО ДОЛГОМУ НАЖАТИЮ — ЧЕТЫРЕ БЕЗОБИДНЫХ ДЕЙСТВИЯ И НИ ОДНИМ БОЛЬШЕ.
//  Зажать можно любую строку ленты. В меню бывает только: скопировать текст,
//  скопировать путь к файлу, положить прошлую задачу обратно в поле ввода, открыть
//  системное окно «Поделиться» и открыть папку в «Файлах». Ни один пункт не пишет
//  на диск, не отправляет задачу и не подтверждает правку. Правка попадает в файлы
//  человека единственной дорогой — кнопкой «Применить» на карточке, где показана
//  разница «до и после». Короткого пути в обход карточки нет и не будет.
//
//  ⚠️ ПАМЯТЬ РАЗГОВОРА ВИДНА ПОСТОЯННО — И ЖИВЁТ ОНА НАВЕРХУ, ПОД КРУГЛЫМИ КНОПКАМИ.
//  У модели на телефоне память разговора крошечная и кончается молча: переписку
//  сворачивают прямо посреди задачи, и со стороны это выглядит как «помощник поглупел».
//  Полоска показывает занятое из выданного, тусклым куском — служебное (инструкция
//  и описания действий, съедающие пятую часть окна ещё до начала работы), а сам момент
//  сворачивания объявляется в ленте отдельной строкой. Числа берутся у движка через
//  снимок состояния и обновляются раз в ход, а не на кадр.
//
//  ⚠️ ПОЧЕМУ НАВЕРХУ, А НЕ ВНИЗУ ЛЕНТЫ (просьба владельца 09.08.2026, дословно:
//  «хочу чтоб полоска с контекстом была сверху а не снизу, бесит»). Внизу ленты она
//  уезжала за край вместе с перепиской: стоило человеку отлистать вверх — и главного
//  числа на экране не было вовсе. Теперь полоска стоит внутри `topBar`, то есть
//  в той же безопасной зоне, что и круглые кнопки, и НЕ прокручивается. Своего слоя
//  поверх системного мы при этом не заводим: строка добавлена в уже существующую
//  вставку `.safeAreaInset(edge: .top)`, и место под неё система резервирует сама —
//  ровно тем же способом, которым лечили баг «текст едет от горизонтального свайпа».
//
//  ⚠️ РАЗМЕР ПАМЯТИ МЕНЯЕТСЯ ПРЯМО ОТСЮДА, И РЕШЕНИЕ ОДНО НА ВСЁ ПРИЛОЖЕНИЕ.
//  Нажатие на полоску открывает короткое меню с четырьмя числами. Своей копии выбора
//  здесь нет: и чат, и страница «О программе» читают и пишут ОДИН ключ настроек
//  (`ContextSizeSettings.defaultsKey`), тот же самый, из которого его берёт движок.
//  Полоска при этом показывает ВЫДАННЫЙ движком потолок, а не выбранное число:
//  движок умеет отступить, и врать про действующий размер нельзя.
//
//  ⚠️ ДЛИТЕЛЬНОСТИ ДВИЖЕНИЯ. Появление сообщения — 0,18 с, подмена подписи и значка —
//  0,15 с, прокрутка к новому — 0,20 с, раскрытие диффа — 0,24 с. Дольше в чате нет
//  ничего: это телефон в руке, а не заставка, и анимация обязана успевать за пальцем.
//  Всё, что двигается, двигается МАСШТАБОМ и ПРОЗРАЧНОСТЬЮ поверх раскладки —
//  тогда место под новое содержимое занимается сразу и соседние строки не прыгают.
//  При включённом «Уменьшении движения» анимаций нет вовсе (см. `motion(_:)`).
//
//  Зависимости из PocketAgent/UI/Design/:
//  FloatingGlassBar { … }, Theme.background / surface / surfaceHigh /
//  bubbleUser / bubbleAgent / textPrimary / textSecondary / added / removed / hairline.
//
//  ⚠️ РАЗМЕТКА ОТВЕТОВ МОДЕЛИ — В ОТДЕЛЬНОМ ФАЙЛЕ (MarkdownRendering.swift, рядом
//  в PocketAgent/UI/). Звёздочки, списки, заголовки и блоки кода в ответах модели
//  раньше показывались сырым текстом. Теперь пузырь агента ВСЕГДА зовёт
//  `MarkdownContent(blocks:)` с результатом `MarkdownDocument.parse`, посчитанным
//  ОДИН РАЗ на сообщение (`.task(id: message.id)` в `ChatMessageRow.body`).
//
//  ⚠️ И В СВЁРНУТОМ ВИДЕ ТОЖЕ. Длинный ответ показывается началом, и раньше это
//  начало шло сырым текстом «потому что обрезать блоки нечем» — а в ленте почти
//  каждый разбор файла длинный, так что человек видел звёздочки практически всегда.
//  Теперь для свёрнутого вида отдельно разбирается НАЧАЛО текста (`collapsedPrefix`),
//  и оба разбора лежат в `markdownBlocks` / `collapsedMarkdownBlocks`.
//
//  У человека, инструмента и служебных строк разметки не бывает — они как
//  показывались сырым текстом, так и показываются. Вывод инструмента особенно:
//  там куски файла с номерами строк («19| ### Кишечник»), и решётки в них —
//  содержимое файла, а не разметка; разобрать их значило бы соврать про файл.
//

import SwiftUI
import UniformTypeIdentifiers

struct ChatView: View {

    @ObservedObject var app: AppViewModel

    /// Открыть меню приложения. Диалог со списком пунктов живёт в корневом экране,
    /// а кнопка, которая его вызывает, — здесь, в верхней строке ленты.
    let onMenu: () -> Void

    @FocusState private var isInputFocused: Bool
    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    @Environment(\.dynamicTypeSize) private var dynamicTypeSize
    /// Нужен ровно для одного: открыть папку проекта в «Файлах» из меню по долгому нажатию.
    @Environment(\.openURL) private var openURL

    /// Спросить перед тем, как стереть переписку.
    @State private var isResetConfirmShown = false

    /// Открыт журнал событий движка.
    @State private var isJournalShown = false
    /// Открыто системное окно выбора файла, который человек хочет отдать агенту.
    @State private var isAttachPickerShown = false
    /// Подробности только что скопированы — подпись на кнопке меняется на «Скопировано».
    @State private var didCopyDetails = false

    /// Сколько памяти разговора выбрал человек.
    ///
    /// ⚠️ ЭТО НЕ ВТОРАЯ КОПИЯ РЕШЕНИЯ. Ключ ровно тот же, что читает движок и страница
    /// «О программе» — разъедься они, человек двигал бы настройку, которую никто
    /// не читает. Здесь она лежит только для того, чтобы меню знало, что уже выбрано.
    @AppStorage(ContextSizeSettings.defaultsKey) private var contextTokens
        = AgentLimits.contextTokenBudget

    /// Может ли помощник трогать файлы. Тот же ключ читает сборка помощника —
    /// второй копии решения здесь нет, как и у размера памяти выше.
    @AppStorage(AgentToolsSettings.defaultsKey) private var isToolsOn = true
    /// Сколько заходов подряд делать по одной задаче. 1 — не повторять.
    @AppStorage(TaskRepeatSettings.defaultsKey) private var repeatAttempts = 1
    /// Кнопку «Инструменты» тронули посреди задачи: набор действий у живого помощника
    /// уже не поменять, и человеку надо честно об этом сказать.
    @State private var needsNewTaskForTools = false
    /// Открыта заметка о проекте (AGENTS.md) — та же страница, что и в разделе «Папки».
    @State private var isNoteShown = false
    /// Что лежит в заметке сейчас. Читается с диска перед открытием страницы.
    @State private var noteText = ""

    /// Размер круглой кнопки отправки. Растёт вместе с системным шрифтом
    /// (иконку внутри тоже задаём ролью, а не числом) и при этом остаётся КРУГОМ:
    /// ширина и высота всегда равны.
    @ScaledMetric(relativeTo: .headline) private var sendButtonSize: CGFloat
        = Theme.Metrics.sendButtonSize

    // ⚠️ Своего @ScaledMetric на круглые кнопки здесь больше НЕТ.
    // Он жил только в этом экране, поэтому одна и та же кнопка в чате при крупном
    // системном шрифте росла, а на экранах подготовки, «О программе» и на страницах-шитах
    // оставалась мелкой. Теперь масштаб и потолок живут внутри самой GlassCircleButton —
    // и все пять мест ведут себя одинаково. Передавать сюда `size` не нужно.

    private let bottomAnchor = "pocketagent.chat.bottom"

    /// Высота мягкого растворения контента у верхней кромки — одна на всё приложение.
    private var topFadeHeight: CGFloat { Theme.Metrics.topFadeHeight }

    init(app: AppViewModel, onMenu: @escaping () -> Void) {
        self.app = app
        self.onMenu = onMenu
    }

    var body: some View {
        // Фон рисует корневой экран — второй такой же прямоугольник здесь не нужен
        // и вредит: лишний слой под размывающей панелью перерисовывается каждый кадр.
        //
        // Панель ввода стоит через safeAreaInset, а НЕ поверх контента:
        // так система знает её настоящую высоту (поле ввода растёт до пяти строк,
        // шрифт может быть крупным) и сама резервирует под неё место в ленте.
        // Выдуманное число «96 снизу» рано или поздно оставляло последнюю карточку
        // навсегда под стеклом.
        timeline
            .sensoryFeedback(trigger: outcomeToken) { was, now in
                // ⚠️ Отклик даём по ИСХОДУ, а не по началу записи: раньше «успех»
                // приходил в палец в момент нажатия «Применить», и человек получал
                // радостный отклик даже тогда, когда запись потом падала.
                if now.isFailed && !was.isFailed { return .error }
                if now.appliedWrites > was.appliedWrites { return .success }
                if now.isFinished && !was.isFinished { return .success }
                return nil
            }
            // Задача ушла — короткий толчок в палец. Ровно как у отправленного
            // сообщения в мессенджере: подтверждение, что нажатие сработало.
            .sensoryFeedback(trigger: sentTaskCount) { was, now in
                guard now > was else { return nil }
                return .impact(weight: .light)
            }
            // ⚠️ Появилась карточка — отклик обязателен. Модель думает секунды,
            // за это время человек успевает отвести взгляд, и вопрос «пускать ли
            // правку в файлы» может провисеть незамеченным. Это НЕ «успех»:
            // ничего ещё не произошло, у нас просто спрашивают.
            .sensoryFeedback(trigger: awaitingActionID) { was, now in
                guard let now, now != was else { return nil }
                return .impact(weight: .medium)
            }
            // Смена состояния объявляется голосом. Без этого незрячий человек
            // отправлял задачу и молча ждал: карточка правки появлялась в конце
            // ленты, а экран об этом ничего не говорил.
            .onChange(of: app.snapshot.state) { _, newState in
                announce(newState)
            }
            // ⚠️ Пока человек печатает, корневой экран убирает нижние вкладки.
            // Две плавающие панели над клавиатурой съедали бы половину экрана,
            // а уходить из чата в этот момент и не нужно. Знать про клавиатуру может
            // только сам чат — поэтому он и говорит об этом остальному приложению.
            .onChange(of: isInputFocused) { _, focused in
                app.isComposing = focused
            }
            // ⚠️ Появилась карточка — клавиатуру убираем сами.
            // Поля ввода в этот момент на экране больше нет (`bottomLayer`), а открытая
            // клавиатура без поля — это полэкрана, занятые ничем, ровно поверх кнопок
            // решения. Заодно снимается признак «человек печатает», иначе вкладки
            // остались бы спрятанными до конца разговора.
            .onChange(of: isDecisionPending) { _, isPending in
                guard isPending else { return }
                isInputFocused = false
            }
            // Экран закрылся с открытой клавиатурой — вкладки обязаны вернуться,
            // иначе человек остался бы вообще без них.
            .onDisappear {
                app.isComposing = false
            }
            // ⚠️ СПРАШИВАЕМ ДВИЖОК, С КАКИМ РАЗМЕРОМ ПАМЯТИ ОН ПОДНЯТ, — ИНАЧЕ ВЫБОР
            // В МЕНЮ СРАБАТЫВАЛ БЫ ВХОЛОСТУЮ. Приложение решает, поднимать ли модель
            // заново, сравнивая выбор с ответом движка; не спроси мы его ни разу,
            // оно сочло бы, что всё и так совпадает, и молча ничего не сделало.
            .onAppear {
                app.contextSizeBinding.refresh()
            }
            .onChange(of: app.snapshot.contextLimitTokens) { _, _ in
                app.contextSizeBinding.refresh()
            }
            .confirmationDialog("Начать новую задачу?",
                                isPresented: $isResetConfirmShown,
                                titleVisibility: .visible) {
                // Подпись говорит, что произойдёт на самом деле: посреди хода это
                // не просто «начать заново», а «сначала остановить помощника».
                Button(isBusy ? "Остановить и начать" : "Начать заново",
                       role: .destructive) {
                    app.startNewTaskAnyway()
                }
                Button("Отмена", role: .cancel) { }
            } message: {
                Text(resetWarningText)
            }
            // Журнал движка открывается со строки состояния модели и с красной плашки.
            .sheet(isPresented: $isJournalShown) {
                EngineJournalSheet(app: app)
            }
            // Выбор файла, который человек хочет отдать агенту.
            //
            // ⚠️ Разрешаем ЛЮБОЙ файл (.item), а не список «правильных» расширений.
            // Что с файлом сможет агент — приложение честно скажет в окне подтверждения;
            // решать за человека, какой файл ему нужен в его же папке, мы не будем.
            .fileImporter(isPresented: $isAttachPickerShown,
                          allowedContentTypes: [.item],
                          allowsMultipleSelection: false) { (result: Result<[URL], any Error>) in
                switch result {
                case .success(let urls):
                    guard let file = urls.first else { return }
                    app.considerAttachment(from: file)
                case .failure(let error):
                    app.errorText = AppViewModel.describe(error)
                }
            }
            // ⚠️ ГЛАВНОЕ ОКНО ЭТОЙ ФУНКЦИИ. Файл появится в ПАПКЕ ЧЕЛОВЕКА — это такое же
            // изменение его папки, как запись файла моделью, и спрашиваем мы так же прямо.
            // Копирование начинается ТОЛЬКО отсюда, по нажатию.
            //
            // ⚠️ Именно `alert`, а не второй `confirmationDialog`: на этом экране лист
            // действий уже есть («Начать новую задачу?»), а два листа на одной ветке
            // спорят между собой — открывается тот, что описан последним. Здесь окно
            // и уместнее: человеку надо прочитать, что произойдёт с его папкой.
            .alert(app.pendingAttachment?.consentTitle ?? "Скопировать файл в вашу папку?",
                   isPresented: attachmentDialogBinding,
                   presenting: app.pendingAttachment) { plan in
                if plan.hasNameConflict {
                    Button("Положить рядом: «\(plan.sideBySideName)»") {
                        app.confirmAttachment(plan, .keepBoth)
                    }
                    Button("Заменить файл", role: .destructive) {
                        app.confirmAttachment(plan, .replace)
                    }
                } else {
                    Button("Скопировать в папку") {
                        app.confirmAttachment(plan, .newFile)
                    }
                }
                Button("Отмена", role: .cancel) { app.cancelAttachment() }
            } message: { plan in
                Text(plan.consentText)
            }
    }

