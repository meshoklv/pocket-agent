    /// Один пузырь: сам текст и, если он длинный, кнопка «Показать полностью».
    ///
    /// ⚠️ ОЧЕНЬ ДЛИННОЕ СООБЩЕНИЕ НЕ ПОКАЗЫВАЕТСЯ ЦЕЛИКОМ, И ЭТО ВАЖНО.
    /// Модель на телефоне легко выдаёт ответ на двести строк. Такой пузырь занимал
