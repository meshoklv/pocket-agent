    /// Подпись и полоска — то, что человек видит и на что нажимает.
    ///
    /// ⚠️ ЧИСЛО СПРАВА — ВЫДАННОЕ ДВИЖКОМ, А НЕ ВЫБРАННОЕ ЧЕЛОВЕКОМ. Движок умеет
    /// отступить к меньшему окну (сам, посреди задачи), и показать здесь выбор
    /// значило бы обещать память, которой нет: ровно на этом человек 09.08.2026
    /// и обжёгся — «хочу 32 000, а получаю 4 096».
    private func contextMeterLabel(state: (color: Color, note: String?, noteColor: Color)) -> some View {
        VStack(alignment: .leading, spacing: 5) {
            HStack(alignment: .firstTextBaseline, spacing: 6) {
                Text(contextMeterTitle)
                    .font(Theme.Fonts.counter)
                    .foregroundStyle(Theme.textSecondary)
                    // Одна строка: перенос посреди «1 840 из 4 096» превратил бы
                    // тонкую полоску в двухэтажную плашку над лентой.
                    .lineLimit(1)
                    // Цифра перещёлкивается на месте, как счётчик шагов рядом.
                    .contentTransition(.numericText())

                // Единственный признак, что строку можно нажать. Мельче подписи:
                // это подсказка, а не украшение.
                Image(systemName: "chevron.up.chevron.down")
                    .font(.caption2)
                    .foregroundStyle(Theme.Colors.textTertiary)

                Spacer(minLength: 8)

                if let note = state.note {
                    Text(note)
                        .font(.caption)
                        .foregroundStyle(state.noteColor)
                        .lineLimit(1)
                        .contentTransition(.opacity)
                }
            }

            // Полоска появляется только когда движок назвал занятое: пустая дорожка
            // до первого слова разговора показывала бы расход, которого ещё не было.
            if app.snapshot.contextUsedTokens > 0, app.snapshot.contextLimitTokens > 0 {
                contextMeterBar(fill: state.color)
            }
