    /// Число с пробелом между разрядами: «1 840», а не «1840».
    ///
    /// ⚠️ Пробел НЕРАЗРЫВНЫЙ и разбивка своя, без NumberFormatter. Обычный пробел
    /// разрешает перенос строки прямо посреди числа, а системный форматировщик берёт
    /// разделитель из языка телефона — и на английской раскладке подпись стала бы
    /// «1,840», хотя весь остальной текст экрана русский.
    private static func groupedNumber(_ value: Int) -> String {
        let digits = String(abs(value))
        var grouped = ""
        for (index, digit) in digits.enumerated() {
            if index > 0, (digits.count - index) % 3 == 0 { grouped.append("\u{00A0}") }
            grouped.append(digit)
        }
        return value < 0 ? "−" + grouped : grouped
    }

