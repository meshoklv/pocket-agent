    /// Копирование от этого не пострадало: «Скопировать текст» есть в меню, и оно
    /// копирует сообщение целиком, а не то, что удалось поймать пальцем на ходу.
    private func bubble(fill: Color, textColor: Color, linkColor: Color) -> some View {
