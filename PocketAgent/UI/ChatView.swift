    /// Само тело пузыря: у ответов модели — разобранная разметка (жирный, курсив,
    /// списки, код, ссылки), у всех остальных — сырой текст, как и было всегда.
    ///
    /// ⚠️ РАЗМЕТКА ПОКАЗЫВАЕТСЯ И В СВЁРНУТОМ ВИДЕ. Раньше свёрнутый пузырь шёл
    /// сырым текстом — и владелец видел звёздочки почти в каждом ответе: разбор
    /// файла в ленте почти всегда длиннее свёрнутого предела, то есть «исключение»
    /// оказалось правилом. Теперь свёрнутый вид — это разметка начала ответа
    /// (`collapsedPrefix`), а «Показать полностью» доразворачивает её до целого.
    @ViewBuilder
    private func bubbleText(textColor: Color, linkColor: Color) -> some View {
        if message.author == .agent, let blocks = shownMarkdownBlocks {
            MarkdownContent(blocks: blocks, textColor: textColor, linkColor: linkColor)
        } else {
            Text(message.text)
                .font(.body)
                .foregroundStyle(textColor)
                .multilineTextAlignment(.leading)
                .lineLimit(isLongMessage && !isFullMessageShown ? Self.collapsedMessageLines : nil)
                .fixedSize(horizontal: false, vertical: true)
        }
    }

    /// Какие блоки показывать: свёрнутый пузырь — начало ответа, развёрнутый — весь.
    /// `nil` бывает у чужих реплик (разбирать нечего) и один кадр до того, как
