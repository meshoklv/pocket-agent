    /// и в поле не теряется.
    ///
    /// ⚠️ Пустая ветка здесь означает высоту ноль — место под панель резервирует
    /// `safeAreaInset` по факту, а не выдуманным числом. Значит, стоит панели исчезнуть,
    /// и лента сразу получает эти точки себе: кнопки решения оказываются в кадре, а не
    /// «где-то ниже».
    @ViewBuilder
    private var bottomLayer: some View {
        if !isDecisionPending {
            inputLayer
        }
    }

    /// На экране висит карточка, и от человека ждут «Применить» или «Отклонить»
    /// (или правка уже пишется — панель не должна возвращаться на эту секунду
    /// и дёргать раскладку прямо под пальцем).
    /// ⚠️ Карточка возврата считается тем же решением: под ней тоже две кнопки,
    /// и прятать их под панелью ввода нельзя ровно по той же причине.
    private var isDecisionPending: Bool { visibleAction != nil || app.snapshot.pendingUndo != nil }

    /// Что делает кнопка «Вернуть, как было» у этой строки ленты.
    /// nil — у неё этой кнопки нет (а нет она у всех, кроме самой свежей правки).
    private func undoAction(for message: ChatMessage) -> (() -> Void)? {
        guard let pointID = message.restorePointID,
              pointID == app.snapshot.undoablePointID,
              // Пока идёт ход или уже висит вопрос — не предлагаем второе решение
              // поверх первого.
              !isBusy,
              !isDecisionPending else { return nil }
        return { app.requestUndo(pointID) }
    }

    private var inputLayer: some View {
        // Отступы от краёв экрана задаёт сам FloatingGlassBar — здесь их не дублируем.
        //
        // interactive: false — внутри капсулы лежат поле ввода и отдельная кнопка
        // отправки, то есть панель НЕ является одним органом управления. С включённой
        // реакцией стекла вся панель подпрыгивала и бликовала от касания текстового поля.
        FloatingGlassBar(interactive: false) {
            // ⚠️ Выравнивание ПО НИЖНЕМУ КРАЮ — не вкусовщина. Поле ввода растёт
            // вверх, до пяти строк; при выравнивании по центру обе круглые кнопки
            // ползли бы вниз на полстроки с каждой новой строкой текста, то есть
            // прямо под пальцем, который целится в «Отправить». По нижнему краю
            // кнопки стоят намертво, а растёт только поле.
            HStack(alignment: .bottom, spacing: 8) {
                toolsControl
                attachControl

                // ⚠️ Подсказка в поле меняется вместе с кнопкой «Инструменты», и это
                // не украшение: она и есть второй, самый заметный признак режима.
                // «Что сделать в этой папке?» в разговоре без действий было бы прямым
                // обманом — сделать помощник сейчас ничего не может.
                TextField(isToolsOn ? "Что сделать в этой папке?" : "О чём поговорим?",
                          text: $app.draft,
                          axis: .vertical)
                    .lineLimit(inputLineLimit)
                    .textInputAutocapitalization(.sentences)
                    .font(Theme.Fonts.body)
                    .foregroundStyle(Theme.Colors.glassTextPrimary)
                    .focused($isInputFocused)
                    .padding(.leading, 8)
                    .padding(.vertical, 8)

                trailingControl
            }
            .animation(motion(Theme.Motion.control), value: app.snapshot.state)
        }
        // ⚠️ Потолок роста панели. Пять строк крупным шрифтом на маленьком телефоне
        // с открытой клавиатурой съедали экран целиком: ни переписки, ни карточки
        // правки видно не было. Дальше accessibility2 панель не растёт.
        .dynamicTypeSize(...DynamicTypeSize.accessibility2)
    }

    /// Сколько строк разрешаем полю ввода. При крупном системном шрифте — меньше:
    /// одна строка там втрое выше обычной.
    private var inputLineLimit: ClosedRange<Int> {
        dynamicTypeSize >= .accessibility1 ? 1...2 : 1...5
    }

    // MARK: - Инструменты

    /// Кнопка «Инструменты» — первая в панели ввода.
    ///
    /// ⚠️ КОРОТКОЕ НАЖАТИЕ ПЕРЕКЛЮЧАЕТ ДЕЙСТВИЯ, ДОЛГОЕ ОТКРЫВАЕТ МЕНЮ, И ЭТО ДЕЛАЕТ
    /// СИСТЕМА, А НЕ НАШИ ЖЕСТЫ. `Menu(content:label:primaryAction:)` устроен ровно так:
    /// касание зовёт primaryAction, удержание раскрывает меню. Свой `LongPressGesture`
    /// поверх обычной кнопки дал бы то, за что этот проект уже платил, — двойное
    /// срабатывание (сначала меню, потом ещё и нажатие на отпускании) и потерянную
    /// доступность для голосового управления.
    ///
    /// ⚠️ СОСТОЯНИЕ ВИДНО ДВАЖДЫ, И ОБА РАЗА БЕЗ ЕДИНОГО ЛИШНЕГО СЛОВА: значок
    /// (закрашенный и цветной — действия есть; контурный, но такой же яркий — их нет) и подсказка
    /// в самом поле ввода. Отдельной подписи «режим такой-то» на экране нет намеренно:
    /// это ровно тот текст, который висел бы всегда, а нужен один раз.
    private var toolsControl: some View {
        Menu {
            ToolsMenuContent(isToolsOn: $isToolsOn,
                             repeatAttempts: $repeatAttempts,
                             onTemplate: { useTemplate($0) },
                             onOpenNote: openNoteAction)
        } label: {
            // ⚠️ ВЫКЛЮЧЕННОЕ СОСТОЯНИЕ КРАСИМ ПОЛНОЙ ЯРКОСТЬЮ, А НЕ ТУСКЛЫМ. Это починка
            // живой жалобы владельца 10.08.2026, дословно: «ЛЕВЕЕ СКРЕПКИ НЕТУ НИЧЕГО».
            // Кнопка была на месте, но выключенной красилась той же ролью, что и
            // НЕДОСТУПНАЯ скрепка с недоступной «Отправить», — то есть «действия
            // выключены» и «кнопка не работает» рисовались одним и тем же. Рядом стоит
            // скрепка полной яркости, и четвертьяркий контур поверх стекла читается
            // не как «приглушено», а как грязь на экране.
            //
            // Состояние показывает ЗАЛИВКА глифа (закрашенный против контурного) и цвет
            // включённого, а тусклая роль остаётся строго за недоступными кнопками —
            // иначе три разных смысла снова сольются в один.
            circleFace(icon: isToolsOn ? "wrench.and.screwdriver.fill" : "wrench.and.screwdriver",
                       foreground: isToolsOn
                           ? AnyShapeStyle(Theme.Colors.accent)
                           : AnyShapeStyle(Theme.Colors.glassTextPrimary),
                       background: Theme.surfaceHigh)
        } primaryAction: {
            isInputFocused = false
            isToolsOn.toggle()
        }
        // Кнопка стоит ВНУТРИ стеклянной панели — своего стекла и своей рамки у неё
        // быть не должно, ровно как у скрепки и «Отправить».
        .buttonStyle(.plain)
        .accessibilityLabel("Инструменты")
        .accessibilityValue(isToolsOn ? "действия включены" : "действия выключены")
        .accessibilityHint("Долгое нажатие — заготовки задач, повтор и заметка о проекте")
        // Набор действий помощника фиксируется на весь разговор — значит посреди задачи
        // переключатель подействовать не может. Молчать об этом нельзя: человек нажал бы
        // кнопку и решил, что она сломана (ровно так уже было с поиском в интернете).
        .onChange(of: isToolsOn) { _, _ in
            needsNewTaskForTools = !app.applyToolsSetting()
        }
        // ⚠️ Именно `alert` и именно ЗДЕСЬ, на самой кнопке: на экране уже есть свой лист
        // действий и своё окно про приложенный файл, а два таких на одной ветке спорят
        // между собой — открывается описанный последним.
        // ⚠️ Заголовок говорит про СРОК, а не про положение кнопки. «Действия включены»
        // тут было бы полуправдой: кнопка-то включена, а в этом разговоре их всё равно нет.
        .alert("Подействует со следующей задачи", isPresented: $needsNewTaskForTools) {
            Button("Начать новую задачу") { app.startNewTaskForTools() }
            Button("Позже", role: .cancel) { }
        } message: {
            Text("Задача уже идёт — помощник узнает про это со следующей. "
                 + "Прежняя останется в «Задачах».")
        }
        // Заметка о проекте — та же страница, что и в разделе «Папки»: правка идёт
        // обычной карточкой «до и после» с кнопкой «Применить», как любая запись файла.
        .sheet(isPresented: $isNoteShown) {
            if let root = app.projectFolderURL {
                ProjectNoteSheet(root: root,
                                 initialText: noteText,
                                 // Перечитывать нечего: заметку берёт с диска сам помощник,
                                 // в начале каждой задачи.
                                 onSaved: { })
            }
        }
    }

    /// Чем открыть заметку о проекте. nil — папки нет, и пункта в меню тоже нет:
    /// строка, которая ничего не делает, хуже отсутствующей.
    private var openNoteAction: (() -> Void)? {
        guard app.projectFolderURL != nil else { return nil }
        return { openProjectNote() }
    }

    /// Заготовка задачи из меню: текст встаёт в поле ввода, курсор — там, где дописывать.
    ///
    /// ⚠️ ЗАГОТОВКА САМА ВКЛЮЧАЕТ ДЕЙСТВИЯ, И ЭТО НЕ САМОДЕЯТЕЛЬНОСТЬ. Все заготовки —
    /// про файлы: прочитать, найти, переписать. Оставь мы разговор без действий, помощник
    /// на «объясни файл» честно ответил бы выдумкой, не открыв ничего. Человек, выбравший
    /// такой пункт в меню «Инструменты», просит именно работу — а переключатель прямо
    /// над списком на его глазах встаёт в положение «включено».
    private func useTemplate(_ template: TaskTemplate) {
        app.applyTaskTemplate(template)
        if !isToolsOn { isToolsOn = true }
        // Курсор в конце строки, клавиатура открыта — дописывать имя файла или слова
        // поиска человек начинает сразу, без ещё одного касания.
        isInputFocused = true
    }

    /// Открыть заметку о проекте.
    ///
    /// ⚠️ Читаем с диска ВНЕ главного потока: папка может лежать в iCloud и отвечать
    /// медленно — так же, как это делает раздел «Папки».
    private func openProjectNote() {
        guard let root = app.projectFolderURL else { return }
        Task { @MainActor in
            let state = await Task.detached(priority: .userInitiated) {
                ProjectNote.read(root: root)
            }.value

            switch state {
            case .text(let text):
                noteText = text
            case .missing:
                // Заметки ещё нет — страница откроется с заготовкой.
                noteText = ""
            case .unreadable(let reason):
                // Содержимого мы не видели — открыть правку значит предложить человеку
                // затереть вслепую то, чего ему не показали.
                app.errorText = "Заметку о проекте открыть не получилось: \(reason)."
                return
            }
            isNoteShown = true
        }
    }

    /// Скрепка слева в панели ввода: отдать агенту свой файл.
    ///
    /// ⚠️ Кнопка стоит ВНУТРИ стеклянной капсулы — своего стекла у неё быть не должно,
    /// иначе получится стекло на стекле.
    private var attachControl: some View {
        circleControl(icon: "paperclip",
                      label: "Приложить файл",
                      foreground: app.canAttachFile
                          ? AnyShapeStyle(Theme.Colors.glassTextPrimary)
                          : AnyShapeStyle(Theme.Colors.glassTextTertiary),
                      background: Theme.surfaceHigh) {
            isInputFocused = false
            isAttachPickerShown = true
        }
        .disabled(!app.canAttachFile)
        .accessibilityHint("Файл будет скопирован в вашу папку проекта — приложение сначала спросит")
    }

    /// Правый орган управления панели: отправить · остановить · идёт запись.
    ///
    /// ⚠️ ВСЁ ЭТО ЛЕЖИТ В ЖЁСТКОМ КВАДРАТЕ РАЗМЕРОМ С КНОПКУ, И ЭТО ГЛАВНОЕ ЗДЕСЬ.
    /// Раньше три состояния подставлялись друг вместо друга прямо в строку, и на
    /// смене «отправить → стоп → кружок ожидания» ширина строки менялась: поле ввода
    /// дёргалось, а сама кнопка успевала сдвинуться под пальцем. Теперь место
    /// занято раз и навсегда, а внутри квадрата одно проявляется вместо другого.
    private var trailingControl: some View {
        ZStack {
            if isThinking {
                // Во время генерации кнопка отправки превращается в кнопку отмены.
                circleControl(icon: "stop.fill",
                              label: "Остановить генерацию",
                              foreground: AnyShapeStyle(Theme.Colors.textOnAccent),
                              background: Theme.removed) {
                    app.cancel()
                }
                .transition(.scale.combined(with: .opacity))
            } else if isApplying {
                ProgressView()
                    .controlSize(.small)
                    .frame(width: sendButtonSize, height: sendButtonSize)
                    .transition(.opacity)
            } else {
                circleControl(icon: "arrow.up",
                              label: "Отправить задачу",
                              // Отправлять нечего — иконка тускнеет смысловой ролью:
                              // она лежит на плавающей панели, и жёсткий белый с прозрачностью
                              // не подхватил бы «Увеличение контраста».
                              foreground: app.canSend
                                  ? AnyShapeStyle(Theme.Colors.textOnAccent)
                                  : AnyShapeStyle(Theme.Colors.glassTextTertiary),
                              background: app.canSend ? Theme.bubbleUser : Theme.surfaceHigh) {
                    isInputFocused = false
                    app.send()
                }
                .disabled(!app.canSend)
                .transition(.scale.combined(with: .opacity))
            }
        }
        .frame(width: sendButtonSize, height: sendButtonSize)
    }

    /// Кружок со значком — общий вид всех органов управления панели ввода.
    ///
    /// ⚠️ Вынесен отдельно от `circleControl`, потому что «Инструменты» — не кнопка,
    /// а меню (`Menu`), и своей копии этой отрисовки у него быть не должно: разъедься
    /// они на полпикселя, соседние кружки в одной панели стали бы разного размера.
    private func circleFace(icon: String,
                            foreground: AnyShapeStyle,
                            background: Color) -> some View {
        Image(systemName: icon)
            // Роль вместо выдуманного размера: при крупном системном шрифте
            // иконка растёт вместе с полем ввода, а кружок — вместе с ней.
            .font(.headline.weight(.bold))
            .foregroundStyle(foreground)
            .frame(width: sendButtonSize, height: sendButtonSize)
            .background(background, in: Circle())
    }

    private func circleControl(icon: String,
                               label: String,
                               foreground: AnyShapeStyle,
                               background: Color,
                               action: @escaping () -> Void) -> some View {
        Button(action: action) {
            circleFace(icon: icon, foreground: foreground, background: background)
        }
        // ⚠️ Кнопка стоит ВНУТРИ стеклянной панели — своего стекла у неё быть не должно.
        .buttonStyle(.plain)
        .accessibilityLabel(label)
        .animation(motion(Theme.Motion.control), value: app.canSend)
    }
}

// MARK: - Живой индикатор «думаю»

/// Три точки, которые по очереди разгораются. При включённом «уменьшении движения»
/// анимация выключается — остаются просто три точки.
struct ThinkingDots: View {

    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    @State private var isPulsing = false

    var body: some View {
        HStack(spacing: 5) {
            ForEach(0..<3, id: \.self) { index in
                Circle()
                    .fill(Theme.textSecondary)
                    .frame(width: 7, height: 7)
                    .opacity(isPulsing ? 1 : 0.28)
                    .scaleEffect(isPulsing ? 1 : 0.72)
                    .animation(pulse(index), value: isPulsing)
            }
        }
        .onAppear { isPulsing = true }
        .accessibilityHidden(true)
    }

    /// Тип указан явно: с тернарником и `nil` вывод типа анимации капризничает.
    private func pulse(_ index: Int) -> Animation? {
        guard !reduceMotion else { return nil }
        return Animation
            .easeInOut(duration: 0.62)
            .repeatForever()
            .delay(Double(index) * 0.18)
    }
}

// MARK: - Пузырь одного сообщения

struct ChatMessageRow: View {

    let message: ChatMessage
    /// Где лежит файл, о котором эта строка, — чтобы человек мог его забрать.
    /// nil — спрашивать некого (превью, демонстрация), кнопки «Поделиться» тогда нет.
    let shareableFileURL: ((String) -> URL?)?
    /// «Повторить задачу»: отдать текст обратно экрану, он положит его в поле ввода.
    /// nil — экран этого не умеет (список прошлых задач), и пункта в меню не будет.
    let onRepeatTask: ((String) -> Void)?
    /// «Открыть папку в „Файлах“». nil — папки нет или её адрес неизвестен.
    let onOpenFolder: (() -> Void)?
    /// «Вернуть, как было». nil — у этой строки возврата нет (так у всех строк,
    /// кроме самой свежей применённой правки).
    ///
    /// ⚠️ Нажатие НИЧЕГО не записывает: оно показывает такую же карточку «до и после»,
    /// какую человек видел перед самой правкой. Запись живёт только за её кнопкой.
    let onUndo: (() -> Void)?

    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    @State private var isDiffShown = false
    /// Длинный вывод инструмента развёрнут целиком.
    @State private var isFullOutputShown = false
    /// Длинный пузырь сообщения развёрнут целиком.
    @State private var isFullMessageShown = false
    /// Файл этой строки, если он и правда лежит в папке. Считается один раз
    /// при появлении строки: спрашивать файловую систему на каждый кадр ленты нельзя.
    @State private var fileToShare: URL?
    /// Разобранная разметка ответа МОДЕЛИ (жирный/курсив/списки/код/ссылки).
    /// Считается один раз на сообщение и запоминается — разбор идёт на каждое
    /// обновление ленты, и парсить одну и ту же реплику заново незачем.
    /// У всех остальных авторов (человек, инструмент, служебная строка) разметки
    /// не бывает — для них это поле так и остаётся `nil`, и `nil` здесь читается
    /// именно как «разбирать нечего», а не как «ещё не успели».
    @State private var markdownBlocks: [MarkdownBlock]?
    /// То же самое, но разобрано только НАЧАЛО ответа — для свёрнутого вида длинного
    /// пузыря. Отдельный разбор, а не первые блоки от полного: обрезанный текст даёт
    /// другие блоки (у последнего пункта списка не хватает хвоста, оборванный блок
    /// кода закрывается сам). Считается там же, один раз на сообщение.
    @State private var collapsedMarkdownBlocks: [MarkdownBlock]?
    /// Открыто системное окно «Поделиться».
    @State private var isShareShown = false
    /// Файла, о котором эта строка, в папке уже нет — человек его удалил сам.
    @State private var isFileGone = false
    /// Счётчик копирований — по нему даём короткий отклик в палец.
    /// Именно счётчик, а не флаг: два копирования подряд должны отозваться дважды.
    @State private var copyCount = 0

    init(message: ChatMessage,
         shareableFileURL: ((String) -> URL?)? = nil,
         onRepeatTask: ((String) -> Void)? = nil,
         onOpenFolder: (() -> Void)? = nil,
         onUndo: (() -> Void)? = nil) {
        self.message = message
        self.shareableFileURL = shareableFileURL
        self.onRepeatTask = onRepeatTask
        self.onOpenFolder = onOpenFolder
        self.onUndo = onUndo
    }

    /// Колонка под мелкую иконку служебной строки. Растёт вместе с системным шрифтом:
    /// иконка набрана ролью, и в жёсткую колонку она при крупном тексте не помещалась.
    @ScaledMetric(relativeTo: .footnote) private var iconGutter: CGFloat
        = Theme.Metrics.compactIconGutterWidth

    /// Со скольких строк вывод инструмента считаем длинным и прячем под «Показать полностью».
    private static let collapsedOutputLines = 8
    /// Сколько строк диффа показывать прямо в ленте. Остальное — по кнопке, отдельной страницей.
    private static let timelineDiffLines = 16
    /// Со скольких строк пузырь сообщения считаем длинным.
    private static let collapsedMessageLines = 14
    /// …и со скольких знаков — тоже. Модель умеет выдать простыню в одну строку
    /// без единого переноса: по строкам она бы прошла как короткая, а экран заняла весь.
    private static let collapsedMessageCharacters = 700

    /// Вывод инструмента не помещается в свёрнутый вид.
    private var isLongOutput: Bool {
        message.text.split(separator: "\n", omittingEmptySubsequences: false).count
            > Self.collapsedOutputLines
    }

    /// Сообщение слишком длинное, чтобы показывать его целиком в ленте.
    private var isLongMessage: Bool {
        if message.text.count > Self.collapsedMessageCharacters { return true }
        return message.text.split(separator: "\n", omittingEmptySubsequences: false).count
            > Self.collapsedMessageLines
    }

    /// Начало ответа для СВЁРНУТОГО вида длинного пузыря.
    ///
    /// ⚠️ Режем сам текст, а не готовый вид, и это вынужденно: размеченный ответ —
    /// это набор отдельных блоков (заголовок, пункт списка, кусок кода), а счётчик
    /// строк, которым обычный `Text` обрезает себя сам, работает только внутри одного
    /// `Text`. Поэтому берём начало текста и разбираем разметку уже в нём — иначе
    /// свёрнутый пузырь пришлось бы показывать сырым, со звёздочками, а свёрнуты
    /// в ленте почти все ответы.
    private static func collapsedPrefix(of text: String) -> String {
        var lines = text.split(separator: "\n", omittingEmptySubsequences: false)
        var didCut = lines.count > collapsedMessageLines
        if didCut { lines = Array(lines.prefix(collapsedMessageLines)) }
        var prefix = lines.joined(separator: "\n")

        // Модель умеет выдать простыню в одну строку без единого переноса: по строкам
        // она пройдёт как короткая, а экран займёт весь. Отсюда второй предел — по
        // знакам; рвём по последнему пробелу, чтобы не разрезать слово пополам.
        if prefix.count > collapsedMessageCharacters {
            let limit = prefix.index(prefix.startIndex, offsetBy: collapsedMessageCharacters)
            let head = prefix[prefix.startIndex..<limit]
            prefix = String(head.lastIndex(where: \.isWhitespace).map { head[..<$0] } ?? head)
            didCut = true
        }

        prefix = prefix.trimmingCharacters(in: .whitespacesAndNewlines)
        // Многоточие — тот же знак обрыва, который рисовал обычный `Text`, когда
        // обрезал сообщение сам. Без него оборванный ответ читается как законченный.
        return didCut ? prefix + "…" : prefix
    }

    var body: some View {
        content
            // Скопировали — короткий отклик в палец. Иначе меню закрывается,
            // на экране не меняется ничего, и непонятно, сработало ли.
            .sensoryFeedback(.success, trigger: copyCount)
            // Разбор разметки — только для ответов модели, и только один раз:
            // `.task(id:)` перезапускается лишь при смене САМОГО сообщения
            // (`message.id` неизменен всю его жизнь — реплики не редактируются
            // задним числом), а не на каждой перерисовке ленты при прокрутке.
            .task(id: message.id) {
                guard message.author == .agent else { return }
                markdownBlocks = MarkdownDocument.parse(message.text)
                collapsedMarkdownBlocks = isLongMessage
                    ? MarkdownDocument.parse(Self.collapsedPrefix(of: message.text))
                    : nil
            }
    }

