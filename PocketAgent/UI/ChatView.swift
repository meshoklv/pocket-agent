    /// Смахивание вниз считаем отказом — файл не трогаем.
    private var attachmentDialogBinding: Binding<Bool> {
        Binding(get: { app.pendingAttachment != nil },
                set: { isShown in if !isShown { app.cancelAttachment() } })
