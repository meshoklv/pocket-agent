        message.diff == nil ? "arrow.turn.down.right" : "checkmark.circle.fill"
    }

    /// Раскрыть или свернуть кусок. При включённом «Уменьшении движения» — без анимации.
    private func toggle(_ flag: Binding<Bool>) {
        if reduceMotion {
            flag.wrappedValue.toggle()
        } else {
            withAnimation(Theme.Motion.expand) { flag.wrappedValue.toggle() }
        }
    }

    // Служебное сообщение.
    private var systemRow: some View {
        Group {
            if AgentPrompt.isQuietNotice(message.text) { quietSystemRow } else { loudSystemRow }
        }
        // У служебной строки в меню один пункт: скопировать текст. Ни повторить,
        // ни поделиться тут нечего — и предлагать этого мы не будем.
        .contextMenu { copyTextButton }
    }

    /// Приложение поправило помощника — это НЕ предупреждение человеку.
    ///
    /// ⚠️ ВЫБОР ВЛАДЕЛЬЦА 08.09.2026: «тусклая по центру, без значка». Раньше такая
    /// строка рисовалась оранжевым значком на подложке во всю ширину — то есть весила
    /// ровно столько же, сколько ответ помощника, и лента выглядела списком ошибок,
    /// хотя ошибок нет: приложение просто работает. Тусклая строка по центру читается
    /// как разделитель — видно, что вмешались, и не спорит с разговором.
    private var quietSystemRow: some View {
        Text(message.text)
            .font(.caption)
            .foregroundStyle(Theme.textSecondary)
            .multilineTextAlignment(.center)
            .fixedSize(horizontal: false, vertical: true)
            .frame(maxWidth: .infinity, alignment: .center)
            .padding(.horizontal, Theme.Metrics.toolRowPaddingHorizontal)
            .padding(.vertical, Theme.Metrics.toolRowPaddingVertical)
    }

    /// Настоящее предупреждение человеку: кончилась память, приложение перезапускалось,
    /// предел шагов. Такие строки остаются заметными — их пропускать нельзя.
    private var loudSystemRow: some View {
        HStack(alignment: .top, spacing: 9) {
            Image(systemName: "info.circle.fill")
                .font(.footnote)
                .foregroundStyle(Theme.Colors.warning)
            Text(message.text)
                .font(.footnote)
                .foregroundStyle(Theme.Colors.bubbleSystemText)
                .fixedSize(horizontal: false, vertical: true)
                .frame(maxWidth: .infinity, alignment: .leading)
        }
        .padding(.horizontal, Theme.Metrics.toolRowPaddingHorizontal)
        .padding(.vertical, Theme.Metrics.toolRowPaddingVertical)
        .background(Theme.Colors.bubbleSystem,
                    in: RoundedRectangle(cornerRadius: Theme.Metrics.controlCorner, style: .continuous))
    }
}

