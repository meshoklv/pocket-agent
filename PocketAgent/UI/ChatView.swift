    private func requestShare(_ diff: FileDiff) {
        guard let url = shareableFileURL?(diff.relativePath) else {
            fileToShare = nil
            isFileGone = true
            return
        }
        fileToShare = url
        isFileGone = false
        isShareShown = true
    }

