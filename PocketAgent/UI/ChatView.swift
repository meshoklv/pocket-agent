    /// ⚠️ СТЕКЛА ЗДЕСЬ НЕТ И БЫТЬ НЕ МОЖЕТ: это обычный контент, а не плавающий слой
    ///. Подложки тоже нет — полоска обязана быть незаметной,
    /// пока с памятью всё хорошо; фон ей даёт подложка верхней строки.
    ///
    /// ⚠️ ПОЛОСКА — ЕЩЁ И ОРГАН УПРАВЛЕНИЯ: нажатие открывает выбор размера памяти.
    /// Отдельной кнопки рядом нет намеренно — в чате и так тесно, а число, которое
    /// человек читает, и число, которое он меняет, честнее держать одним местом.
    @ViewBuilder
    private var contextMeter: some View {
        let state = contextMeterState
        VStack(alignment: .leading, spacing: 5) {
            Menu {
                contextSizeMenu
            } label: {
                contextMeterLabel(state: state)
            }
            // Меню не должно красить подпись в системный синий: это тихая служебная
            // строка, а не ссылка.
            .buttonStyle(.plain)
            .accessibilityLabel(contextAccessibilityLabel(state: state))
            .accessibilityHint("Открывает выбор размера памяти разговора")

            contextChoiceWaitingNote
        }
        .frame(maxWidth: .infinity, alignment: .leading)
        // ⚠️ Потолок роста — по той же причине, что и у панели ввода. Строка стоит
        // в безопасной зоне сверху: вырасти ей вчетверо крупным системным шрифтом —
        // и от переписки на маленьком телефоне не останется ничего.
        .dynamicTypeSize(...DynamicTypeSize.accessibility1)
        .animation(motion(Theme.Motion.smooth), value: app.snapshot.contextUsedTokens)
        .animation(motion(Theme.Motion.swap), value: app.snapshot.contextFoldedAt)
