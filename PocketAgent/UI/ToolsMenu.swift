//  Содержимое меню кнопки «Инструменты» в панели ввода чата.
//
//  Короткое нажатие на кнопку включает и выключает действия с файлами — это делает
//  сам чат. Долгое нажатие открывает ЭТО меню: что помощник умеет и чем ему помочь.
//
//  ⚠️ ПОЧЕМУ ЭТО СИСТЕМНОЕ МЕНЮ, А НЕ СВОЯ СТРАНИЦА. Меню появляется прямо у большого
//  пальца, поверх клавиатуры, закрывается касанием мимо и ничего не двигает на экране.
//  Своя страница ради четырёх строк — это лишний слой, лишний путь назад и лишний
//  визуальный шум ровно там, где человек хотел одного касания.
//
//  ⚠️ ЗДЕСЬ НЕТ И НЕ ДОЛЖНО БЫТЬ ПУНКТОВ-ОБЕЩАНИЙ. Каждая строка меню делает работу
//  СЕЙЧАС. Серых заглушек «скоро будет» тут не бывает: приложение и так слишком часто
//  обещало человеку больше, чем умело.
//
//  ⚠️ И НИ ОДИН ПУНКТ НЕ ПИШЕТ НА ДИСК. Заготовка кладёт текст в поле ввода, повтор
//  отправляет ту же фразу заново, заметка открывает обычную карточку «до и после»
//  с кнопкой «Применить». Правка попадает в файлы человека единственной дорогой —
//  через подтверждение, как и всё остальное в этом приложении.
//

import SwiftUI

struct ToolsMenuContent: View {

    /// Действия с файлами включены. Тот же ключ настроек, что читает сборка помощника, —
    /// своей копии решения здесь нет.
    @Binding var isToolsOn: Bool

    /// Сколько заходов подряд приложение делает по одной задаче. 1 — не повторять.
    @Binding var repeatAttempts: Int

    /// Человек выбрал заготовку — её текст встаёт в поле ввода.
    let onTemplate: (TaskTemplate) -> Void

    /// Открыть заметку о проекте. nil — папки нет, и открывать нечего.
    let onOpenNote: (() -> Void)?

    var body: some View {
        // ⚠️ Порядок разделов = порядок важности. Сверху то, что объясняет саму кнопку
        // (её короткое нажатие), потом то, ради чего меню открывают чаще всего
        // (заготовки), и лишь потом редкие настройки захода.
        Section {
            Toggle(isOn: $isToolsOn) {
                Label("Действия с файлами", systemImage: "wrench.and.screwdriver")
            }
        }

        Section("Заготовки задач") {
            ForEach(TaskTemplates.all) { template in
                Button {
                    onTemplate(template)
                } label: {
                    Label(template.title, systemImage: template.icon)
                }
            }
        }

        Section {
            // ⚠️ Повтор ведёт ПРИЛОЖЕНИЕ, а не модель: она про заходы не знает вовсе.
            // Подписи человеческие («До 3 заходов»), и рядом сказано главное — что
            // повтор прекращается, как только задача удалась.
            Picker(selection: $repeatAttempts) {
                ForEach(TaskRepeatSettings.options, id: \.self) { attempts in
                    Text(TaskRepeatSettings.text(attempts)).tag(attempts)
                }
            } label: {
                Label("Повторять, пока не выйдет", systemImage: "repeat")
            }

            if let onOpenNote {
                Button {
                    onOpenNote()
                } label: {
                    Label("Заметка о проекте", systemImage: "note.text")
                }
            }
        }
    }
}
