//
//  SystemPrompt.swift
//  PocketAgent
//
//  Системная инструкция для модели и все тексты, которыми агент разговаривает
//  с моделью и с человеком. Держим их в одном месте: промпт маленькой модели —
//  такая же часть продукта, как код, и его правят чаще всего.
//
//  Модель у нас 2 млрд параметров. Поэтому инструкция:
//   • короткая (каждая строка съедает память разговора в 4096 токенов);
//   • без вежливой воды и без «подумай пошагово»;
//   • приказами, а не отрицаниями: «сначала прочитай» вместо «не выдумывай»;
//   • БЕЗ ПРИМЕРОВ ВЫЗОВА. Прежняя строка этой шапки советовала обратное —
//     «с готовыми примерами, они работают лучше правил», — и это оказалось неправдой
//     для моделей такого размера. Живой прогон 09.08.2026: Gemma 3 списала пример
//     буквами и отправила его человеку вместо действия. Явление известное и описанное:
//     чем подробнее пример вызова, тем выше шанс получить его текстом.
//
//  ⚠️ Короче здесь — не экономия, а КАЧЕСТВО: на моделях около 1,5 млрд параметров
//  сжатие инструкции даёт заметно больший прирост послушания, чем на больших
//  (порядка +11% против +2%). Соблазн «дописать ещё одно правило» почти всегда вреден.
//

import Foundation

public enum AgentPrompt {

    /// Дописывать ли к правилу про пути оговорку «имя самой папки в путь не повторяй».
    ///
    /// ⚠️ Как и близнец в `SafePath.tolerateRedundantProjectPrefix`, это НЕ настройка
    /// для человека: значение всегда `true`, снимает его только замер (`Bench/`),
    /// чтобы измерить, чего стоит сама подсказка.
    public static var includeFolderPathHint = true

    // MARK: - Системная инструкция

    /// Имена инструментов ровно в том порядке, в котором их видит модель.
    public static let toolNames: [String] = ToolKind.allCases.map(\.rawValue)

    /// Главная инструкция. `projectName` — имя выбранной папки (для ориентира модели).
    ///
    /// ⚠️ Сжато по `docs/CONTEXT-PLAN.md` п.1: правила, которые умеет проверить код
    /// (пути, повтор непрочитанного, отказ человека), отсюда убраны — они возвращаются
    /// модели подсказкой в момент нарушения (см. секцию «Что уходит обратно в модель» ниже).
    /// Здесь остаются только правила, которые код проверить не может.
    ///
    /// `projectNote` — заметка о проекте из `AGENTS.md` (пусто, если её нет),
    /// `focus` — строка «сейчас делаю», которую ведёт приложение. Обе части
    /// НЕОБЯЗАТЕЛЬНЫЕ и обе уже урезаны по своим пределам вызывающей стороной;
    /// здесь они только ставятся на место.
    ///
    /// ⚠️ Порядок частей не случаен: правила — сверху, заметка — следом, цель —
    /// ПОСЛЕДНЕЙ строкой, вплотную к разговору. Маленькая модель тем внимательнее
    /// к строке, чем ближе та к её собственному ходу, а цель терять нельзя.
    /// - Parameter withTools: у помощника есть действия с файлами. `false` — человек
    ///   выключил их кнопкой «Инструменты» в чате, и тогда сюда идёт совсем другая,
    ///   короткая инструкция: правила про пути, вызовы и подтверждение записи
    ///   в разговоре не только бесполезны, но и вредны — модель по ним пытается
    ///   позвать действие, которого ей не дали.
    public static func system(projectName: String?,
                              withTools: Bool = true,
                              projectNote note: String = "",
                              focus goal: String = "") -> String {
        guard withTools else { return talkSystem() }
        let folderLine: String
        if let projectName, !projectName.isEmpty {
            folderLine = "Правишь файлы только внутри папки «\(projectName)»."
        } else {
            folderLine = "Правишь файлы только внутри выбранной папки."
        }

        // Оговорка про имя папки — отдельной строкой, чтобы замер мог её снять.
        let pathHint = includeFolderPathHint ? " Имя самой папки в путь не повторяй." : ""

        // ⚠️ «ИМЯ САМОЙ ПАПКИ В ПУТЬ НЕ ПОВТОРЯЙ» — ПРАВКА ПО ЖИВЫМ ПЕРЕПИСКАМ 10.08.2026.
        // Строка выше называет папку по имени, и модель приклеивала это имя к каждому
        // пути: list_files отдавал «README.md», а read_file звался с «имя-папки/README.md»
        // и получал отказ. Дальше — повтор того же вызова и пересказ проекта по одним
        // именам файлов. Полсотни знаков здесь дешевле, чем провалившаяся задача.
        // Приложение с 06.09.2026 такой путь ещё и терпит молча (SafePath.resolve),
        // но лечить только терпимостью нельзя: лишний сегмент модель пишет и в отчёте
        // человеку, и в аргументах записи — пусть не пишет вовсе.
        //
        // ⚠️ В ИНСТРУКЦИИ НЕТ И НЕ ДОЛЖНО БЫТЬ ПРИМЕРА ВЫЗОВА, ЗАПИСАННОГО ТЕКСТОМ.
        // Живой прогон 09.08.2026, Gemma 3 1B: здесь стоял пример вида
        // read_file(path: "README.md") → …, и модель СПИСАЛА ЕГО БУКВАМИ — прислала
        // человеку строки «list_files(path: "")» и «finish(summary: …)» вместе с выдуманным
        // содержимым папки из нашего же примера, не позвав при этом ни одного действия.
        // Маленькая модель повторяет ФОРМУ примера, а не его смысл: покажешь вызов буквами —
        // получишь буквы. Настоящий вызов собирает сама библиотека по описаниям действий;
        // наше дело — описать действия словами, а не изображать их синтаксис.
        // Похоже, отсюда же росло и «модель ответила неразборчиво» на Gemma 4:
        // библиотека пыталась разобрать как вызов то, что модель написала текстом.
        // ⚠️⚠️ ГЛАВНАЯ ПРАВКА 09.08.2026 — ЖИВАЯ ПЕРЕПИСКА С ТЕЛЕФОНА ВЛАДЕЛЬЦА.
        // Человек: «изучи проект» → модель: «Я готов изучить. Для начала мне нужно
        // прочитать содержимое папки или выполнить действие, которое укажете вы.»
        // Человек: «дай список» → модель: «Я начну с просмотра корневой папки.» —
        // и НЕ начинает. Дальше человек четыре раза подряд писал «И», «И», «Давай».
        // Его слова: «он буквально не слушается меня… нужно, чтоб он ДЕЛАЛ, а не спрашивал».
        //
        // Виноваты были три строки ЭТОЙ инструкции, и вот чем именно:
        //  • «потом жди результат» модель читала как «жди слова человека», а не
        //    «дождись ответа действия» — и честно ждала;
        //  • «Запись подтверждает человек» она обобщала на ВСЁ, включая просмотр папки
        //    и чтение файла, — хотя эти два действия приложение делает само и молча;
        //  • «либо один вызов, либо короткий ответ человеку» давало ей законный способ
        //    вместо работы написать фразу. Именно этой лазейкой она и пользовалась.
        // Поэтому: первая строка правил — приказ делать; про подтверждение записи
        // модели не сообщается вовсе (это забота приложения, а не её); лазейки «можно
        // ответить фразой вместо вызова» больше нет.
        //
        // ⚠️ И РОВНО ОДНА ПОБЛАЖКА ОБРАТНО — СТРОКА ПРО «СПРОСИЛИ ПРО ТЕБЯ» (10.08.2026).
        // Без неё правила читались как «на всё отвечай действием», и на человеческое
        // «Кто ты» модель шла смотреть чужую папку. Одна строка, около десятка токенов;
        // разговор от задачи приложение отличает и само (AgentSession.looksLikeChat),
        // но модель должна знать, что отвечать словами тут МОЖНО, — иначе она честно
        // пытается выполнить вопрос как задание.
        //
        // ⚠️ ЧЕТЫРЕ СТРОКИ ПРО ЗАПИСЬ ОТСЮДА УБРАНЫ 10.08.2026, И ЭТО НЕ СОКРАЩЕНИЕ
        // РАДИ СОКРАЩЕНИЯ. Замер того самого JSON, который уходит модели (счётчик
        // приложения, estimateTokens): инструкция была 353 токена, стала 230 — минус
        // 123 в КАЖДОМ ходу КАЖДОГО разговора и заново при каждом сворачивании.
        // Куда делось каждое правило — по пунктам, потому что «убрал и надеюсь» тут
        // не годится:
        //  • «Меняешь часть файла — назови номера строк» (37) и «Создаёшь файл или
        //    переписываешь целиком — content без номеров строк» (30) — это дословный
        //    пересказ описаний полей в самой схеме: ToolTexts.writeFileFromLine говорит
        //    «С какой строки заменять. Пусто — весь файл.», writeFileToLine — «По какую
        //    включительно. Пусто — одна строка.», а сам write_file — «Записать файл
        //    целиком или заменить строки.» Схема уходит модели тем же ходом и теми же
        //    словами. Мы платили за одно и то же дважды.
        //  • «Про запись спросит само приложение — не выпрашивай» (24) — это ровно то,
        //    что приложение уже ловит делом: выпрашивание разрешения опознаётся по
        //    оборотам («разреш», «можно ли», «подтвердите», «запишу», «создам» —
        //    AgentEngine.intentMarkers) и получает подсказку `actInsteadOfTalking`
        //    в момент нарушения. До нарушения она стоит ноль.
        //  • «Файл человеку отдаёт приложение…» (33) — тоже переведено в подсказку
        //    по нарушению, `appHandsFileOver` ниже: модель обещает «отправить» файл
        //    редко, а платили мы за это правило постоянно.
        // ⚠️ ДВА ВАРИАНТА ПРАВИЛ, И ВТОРОЙ — ПРОВЕРЯЕМАЯ ГИПОТЕЗА, А НЕ УЛУЧШЕНИЕ.
        //
        // Разбор этой самой инструкции (10.09.2026) нашёл в ней прямое противоречие:
        // строка «делай сразу, не спрашивай разрешения и не переспрашивай» и строка
        // «спрашивай, только если без ответа никак» отменяют друг друга. Для модели
        // на 4 млрд вторая читается просто как «спрашивать можно» — и это ровно то
        // самое «пожалуйста, сформулируйте задачу», которым владелец получал десять
        // ходов подряд 07.09.2026. Вторая беда — строка «суди только по прочитанному»
        // запрещает, но не говорит, ЧТО делать вместо; маленькой модели нужен шаг,
        // а не запрет.
        //
        // Короткий вариант убирает разрешение спрашивать и превращает запрет в шаг.
        // ⛔ Внедрять его без замера нельзя: точно так же «очевидно полезной» выглядела
        // глубина просмотра в два уровня — и оказалась хуже на шесть прогонов из
        // восьмидесяти одного. Поэтому он под выключателем замера.
        #if DEBUG
        let short = BenchMode.promptVariant == "short"
        #else
        let short = false
        #endif

        // ⚠️⚠️ ПРО СТРАНИЦЫ — ОДНА СТРОКА, И ОНА НЕ ИМЕЕТ ПРАВА СПОРИТЬ САМА С СОБОЙ.
        // Раньше их было две подряд: «интернета тут нет, Bootstrap и другие ссылки
        // не загрузятся» — и тут же «эти библиотеки уже внутри, ссылку оставляй
        // обычную», причём Bootstrap стоял в обоих списках. Модели на 4 млрд такого
        // не разобрать: она верит первой половине, пишет стили руками, и полка,
        // ради которой всё делалось, наполовину мертва.
        //
        // Теперь одна фраза и один смысл: что есть на полке — зови ссылкой,
        // остального в интернете тут нет. Длиннее её делать нельзя: длинные добавки
        // в инструкцию у нас уже портили качество ответов (ROADMAP §18.10).
        let shelfNames = PlaygroundShelf.shared.namesForPrompt
        let pageLine = shelfNames.isEmpty
            ? "Делаешь страницу или игру — стили и скрипты пиши сам внутри файла: интернета тут нет, чужие ссылки не загрузятся."
            : "Делаешь страницу или игру — эти библиотеки уже внутри, ссылку на них пиши обычную: "
              + shelfNames.joined(separator: ", ")
              + ". Чего в списке нет — пиши сам внутри файла: интернета тут нет."

        var text = short
        ? """
        Ты — кодинг-агент на iPhone. \(folderLine)

        Правила:
        Получил задачу — делай сразу, не спрашивай и не переспрашивай.
        list_files и read_file выполняй молча: они ничего не портят.
        За ход — один вызов; пришёл результат — сразу следующий.
        Пути — от корня папки.\(pathHint)
        Спрашивают про проект или папку — открой файл и прочитай, потом отвечай: по именам не суди.
        \(pageLine)
        Поздоровались или спросили про тебя — ответь словами, без действий.
        Всё сделано — вызови finish с коротким итогом по-русски.
        """
        : """
        Ты — кодинг-агент на iPhone. \(folderLine)

        Правила:
        Получил задачу — делай сразу, не спрашивай разрешения и не переспрашивай.
        list_files и read_file выполняй молча: они ничего не портят.
        За ход — один вызов; пришёл результат — сразу следующий.
        Пути — от корня папки.\(pathHint)
        О проекте и файлах суди только по прочитанному, не по именам.
        \(pageLine)
        Спрашивай, только если без ответа никак.
        Спросили про тебя или поздоровались — ответь словами, без действий.
        Всё сделано — вызови finish с коротким итогом по-русски.
        """

        // ⚠️ Имена параметров внутри — note/goal, а не projectNote/focus: рядом лежат
        // статические projectNote(_:) и focusLine(_:), и одинаковые имена читались бы
        // как вызов функции, а не как значение.
        let noteBlock = note.trimmingCharacters(in: .whitespacesAndNewlines)
        if !noteBlock.isEmpty {
            text += "\n\n" + noteBlock
        }
        let goalLine = goal.trimmingCharacters(in: .whitespacesAndNewlines)
        if !goalLine.isEmpty {
            text += "\n\n" + goalLine
        }
        return text
    }

    // MARK: - Инструкция для разговора (действия выключены)

    /// Три строки вместо тринадцати — и ни слова про действия.
    ///
    /// ⚠️ ГЛАВНОЕ ЗДЕСЬ — ЧЕГО НЕТ. Нет ни имён действий, ни правил про пути, ни строки
    /// «про запись спросит приложение»: описания действий модели в этом режиме не уходят
    /// вовсе (`AgentAssembly.makeSession`), и упоминать в инструкции то, чего у неё нет, —
    /// вернейший способ получить вызов несуществующего действия. Маленькая модель
    /// повторяет форму того, что видит.
    ///
    /// ⚠️ Имени папки тут тоже нет намеренно: файлов в этом режиме не касаются, а строка
    /// «Правишь файлы только внутри папки …» подсказывала бы модели ровно то занятие,
    /// которого человек её только что лишил.
    ///
    /// ⚠️ И ЗАМЕТКИ О ПРОЕКТЕ ТУТ НЕТ — ЧЕСТНО, А НЕ ПО ЗАБЫВЧИВОСТИ. Читается она
    /// действием `read_file`, которого в этом режиме не существует, а лезть в чужую папку
    /// в обход собственного обещания «файлов не касаемся» приложение не станет. Нужна
    /// заметка — значит нужна и работа: включите действия.
    private static func talkSystem() -> String {
        """
        Ты — помощник в приложении на iPhone. Отвечай словами, коротко и по-русски.
        Файлов сейчас не касаешься — разговор идёт без них.
        Не знаешь — так и скажи, не выдумывай.
        """
    }

    // MARK: - Заметка о проекте (долгая память без роста окна)

    /// Имя файла с заметкой в папке проекта.
    ///
    /// ⚠️ ЗАМЕТКУ ПИШЕТ ЧЕЛОВЕК ИЛИ МОДЕЛЬ ОБЫЧНОЙ ЗАПИСЬЮ ФАЙЛА — С КНОПКОЙ.
    /// Приложение её только ЧИТАЕТ и подаёт модели в начале разговора. Так и должно
    /// быть: это файл в чужой папке, а у нас записи без подтверждения не бывает
    /// в принципе. Соблазн «пусть приложение само дописывает выводы после каждой
    /// задачи» экономит человеку нажатие и ломает главное правило продукта —
    /// поэтому его здесь нет и быть не должно.
    ///
    /// Имя `AGENTS.md` выбрано не случайно: так этот файл называют и другие
    /// подобные инструменты, поэтому в чужом проекте он вполне может уже лежать —
    /// и тогда агент получает знание о проекте бесплатно, с первого хода.
    public static let projectNoteFileName = "AGENTS.md"

    /// Готовый блок заметки для системной инструкции. Пусто — заметки нет.
    ///
    /// Предел жёсткий: что не влезло — обрезано, и модель об этом предупреждена прямо,
    /// иначе она будет считать обрывок полной картиной проекта.
    public static func projectNote(_ text: String,
                                   maxTokens: Int = AgentLimits.projectNoteTokens) -> String {
        let clean = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !clean.isEmpty else { return "" }

        let header = "О проекте (\(projectNoteFileName)):\n"
        let allowance = maxTokens - ConversationHistory.estimateTokens(header)
        // Предел настолько мал, что от заметки остался бы огрызок — тогда лучше ничего.
        guard allowance >= 40 else { return "" }

        return header + trimmed(clean, toTokens: allowance, tail: projectNoteCutTail)
    }

    private static let projectNoteCutTail = "\n… (заметка дальше не поместилась)"

    // MARK: - Строка «сейчас делаю» (её ведёт приложение, не модель)

    /// Одна короткая строка с текущей задачей человека и, если понятно, текущим файлом.
    ///
    /// ⚠️ ЭТУ СТРОКУ МОДЕЛЬ НЕ ПИШЕТ И ИСПОРТИТЬ НЕ МОЖЕТ. Полноценный список задач
    /// модель на 2–4 млрд параметров не удержит — она его переписывает, теряет и
    /// начинает отчитываться о выдуманном. Поэтому список задач мы не заводим вовсе,
    /// а держим ровно одну строку, и держит её приложение.
    ///
    /// Предел соблюдается ФАКТОМ, а не расчётом на бумаге: собираем варианты от
    /// полного к короткому и берём первый, который в предел укладывается.
    public static func focusLine(task: String,
                                 subject: String = "",
                                 maxTokens: Int = AgentLimits.focusLineTokens) -> String {
        let goal = task
            .replacingOccurrences(of: "\n", with: " ")
            .trimmingCharacters(in: .whitespacesAndNewlines)
        guard !goal.isEmpty else { return "" }

        let file = subject
            .replacingOccurrences(of: "\n", with: " ")
            .trimmingCharacters(in: .whitespacesAndNewlines)

        var candidates: [String] = []
        if !file.isEmpty {
            candidates.append("Цель: \(goal). Файл: \(file)")
            candidates.append("Цель: \(goal)")
            candidates.append("Файл: \(file)")
        } else {
            candidates.append("Цель: \(goal)")
        }
        for candidate in candidates where ConversationHistory.estimateTokens(candidate) <= maxTokens {
            return candidate
        }

        // Не влезла даже одна цель — режем саму задачу. Полстроки цели полезнее,
        // чем ничего: модель хотя бы помнит, о каком файле и о чём вообще речь.
        let prefixTokens = ConversationHistory.estimateTokens("Цель: …")
        return "Цель: " + cut(goal, toTokens: max(4, maxTokens - prefixTokens)) + "…"
    }

    // MARK: - Обрезка по токенам

    /// Текст, укладывающийся в предел вместе с хвостовой пометкой.
    /// Рвём по границе строки, если она близко: заметка должна читаться, а не обрываться
    /// на полуслове.
    private static func trimmed(_ text: String, toTokens limit: Int, tail: String) -> String {
        guard ConversationHistory.estimateTokens(text) > limit else { return text }

        let tailTokens = ConversationHistory.estimateTokens(tail)
        var body = cut(text, toTokens: max(20, limit - tailTokens))
        if let lastBreak = body.lastIndex(of: "\n"),
           body.distance(from: body.startIndex, to: lastBreak) > 40 {
            body = String(body[body.startIndex..<lastBreak])
        }
        return body + tail
    }

    /// Обрезка по числу знаков, посчитанному из худшего случая нашей же оценки:
    /// кириллица — два знака на токен. На латинице выйдет вдвое короче предела,
    /// и это нарочно: ошибаться надо в сторону экономии.
    private static func cut(_ text: String, toTokens limit: Int) -> String {
        String(text.prefix(max(8, limit * 2)))
    }

