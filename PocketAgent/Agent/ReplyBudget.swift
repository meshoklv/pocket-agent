//
//  ReplyBudget.swift
//  PocketAgent / Agent
//
//  Сколько памяти разговора держать свободной под ответ модели — и почему это
//  число не должно быть одним на всю задачу.
//
//  ⚠️ ЗАЧЕМ ОТДЕЛЬНЫЙ ТИП, А НЕ ДВЕ СТРОЧКИ В AgentEngine. Одно и то же число нужно
//  в трёх разных местах (когда сворачивать разговор, сколько отдать историей,
//  сколько ответа инструмента влезет), и разъехаться они не имеют права: разъезд
//  здесь означает либо переполненную память движка, либо свёрнутый раньше времени
//  разговор. Один тип — одно решение.
//

import Foundation

/// Запас под ответ модели, который МЕНЯЕТСЯ по ходу задачи.
///
/// ⚠️ ГЛАВНАЯ МЫСЛЬ, РАДИ КОТОРОЙ ЭТО ЗАВЕДЕНО. Сегодня под ответ модели заморожено
/// столько, сколько занимает САМЫЙ ДЛИННЫЙ её возможный ответ, — а самый длинный
/// ответ ровно один: перезапись файла целиком. Но пока модель осматривается и читает,
/// такого ответа от неё не бывает физически: её ход в это время — вызов `read_file`
/// на полсотни токенов. То есть половину задачи мы держим пустым место под ответ,
/// которого в эту половину не может быть.
///
/// Поэтому запас держим половинный, пока модель не собралась переписать файл целиком.
/// Собралась — поднимаем до полного и до конца задачи больше не опускаем.
///
/// Что это даёт на дне 4096 (посчитано, а не прикинуто): запас 768 → 384, порог
/// сворачивания разговора 2628 → **3012**, то есть +384 токена на саму работу — как
/// раз в разведочной части, где память и кончается. На 8192 — 1024 → 512 и порог
/// 5803 → 6315.
///
/// ⚠️ ЧЕСТНО ПРО РИСК, А НЕ ТОЛЬКО ПРО ПРИБЫЛЬ. Половинный запас означает, что у модели
/// на ответ остаётся на 384 токена меньше. Пока она зовёт `list_files` и `read_file`,
/// это незаметно. Но ПЕРВАЯ перезапись файла целиком случается ещё при половинном
/// запасе — узнаём мы о ней ровно в тот момент, когда она пришла. Если файл длинный,
/// такой ответ может не поместиться; путь на этот случай в приложении уже написан
/// и обкатан (`fitToContext` подрезает, `restartConversation` сворачивает разговор
/// и уносит свежий результат). Живьём на телефоне это НЕ ПРОВЕРЕНО.
public struct ReplyBudget: Sendable, Equatable {

    /// Модель уже присылала запись файла БЕЗ номеров строк — значит длинные ответы
    /// в этой задаче возможны, и запас должен быть полным.
    private var expectsLongAnswer = false

    public init() {}

    /// Запас нужен полный? Наружу — только для журнала и объяснений человеку.
    public var isFull: Bool { expectsLongAnswer }

    /// Новая задача — считаем заново: то, что человек просил прошлый раз,
    /// про длину нынешних ответов ничего не говорит.
    public mutating func startTask() {
        expectsLongAnswer = false
    }

    /// Посмотреть на вызов модели и решить, не пора ли поднять запас.
    ///
    /// ⚠️ Смотрим на ВЫЗОВ, а не на применённую запись, и это принципиально: человек
    /// может нажать «Отклонить», но модель-то уже показала, что умеет отвечать длинно,
    /// и следующий её ход будет таким же. Опустить запас обратно после отказа значило бы
    /// наступить на те же грабли следующим ходом.
    ///
    /// Возвращает true, если решение поменялось, — вызывающей стороне это нужно, чтобы
    /// пересчитать пороги, а не пересчитывать их вхолостую на каждом ходу.
    @discardableResult
    public mutating func note(invocation: ToolInvocation) -> Bool {
        guard !expectsLongAnswer else { return false }
        guard invocation.kind == .writeFile, !invocation.mentionsLineRange else { return false }
        expectsLongAnswer = true
        return true
    }

    /// Сколько держать свободным под ответ модели при заданном потолке.
    public func headroom(forCeiling ceiling: Int) -> Int {
        let full = AgentLimits.replyHeadroom(forCeiling: ceiling)
        guard !expectsLongAnswer else { return full }
        // Половина полного — то есть ровно 384 на дне 4096, как и было задумано.
        // Ниже некуда: короткий ответ модели («вызвал read_file») тоже чего-то стоит,
        // и запас, из которого не влезает даже он, — это не экономия, а поломка.
        return max(Self.floorTokens, full / 2)
    }

    /// С какого занятого места пора сворачивать разговор — при заданном потолке.
    ///
    /// Формула та же, что у `AgentLimits.contextRestartThreshold(forCeiling:)`
    /// (потолок − запас под ответ − одна страница файла), и повторена она здесь
    /// ровно потому, что запас теперь наш, а не постоянный.
    public func restartThreshold(forCeiling ceiling: Int) -> Int {
        let usable = ceiling
            - headroom(forCeiling: ceiling)
            - AgentLimits.readPageTokens(forCeiling: ceiling)
        return max(AgentLimits.contextReclaimMinTokens, min(usable, ceiling))
    }

    /// Меньше этого запас не бывает ни при каком потолке.
    private static let floorTokens = 256
}
