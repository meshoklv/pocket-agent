    public init(runtime: any ModelRuntime,
                registry: any ToolRegistry,
                folder: ProjectFolder? = nil,
                stepLimit: Int = AgentLimits.maxSteps,
                invalidTurnLimit: Int = 2,
                tokenBudget: Int = ConversationHistory.defaultTokenBudget,
                workspace: (any FileWorkspace)? = nil,
                pendingDiffs: PendingDiffStore? = nil) {
        self.runtime = runtime
        self.registry = registry
        self.workspace = workspace
        self.pendingDiffs = pendingDiffs
        self.stepLimit = max(1, stepLimit)
        self.invalidTurnLimit = max(1, invalidTurnLimit)
        self.snapshot = AgentSnapshot(state: .idle,
                                      messages: [],
                                      stepsUsed: 0,
                                      folder: folder,
                                      stepLimit: max(1, stepLimit))
        self.history = ConversationHistory(
            // ⚠️ Про действия спрашиваем ПАРАМЕТР, а не `usesTools`: свойство читает
            // `self.registry`, а он в этот момент ещё не считается готовым.
            systemPrompt: AgentPrompt.system(projectName: folder?.displayName,
                                             withTools: !registry.tools.isEmpty),
            tokenBudget: tokenBudget
        )
        // Точки возврата переживают перезапуск приложения — значит и кнопка обязана
        // вернуться вместе с восстановленной перепиской, а не пропасть до первой правки.
        refreshUndoAvailability()
    }

    /// Есть ли у помощника действия с файлами в ЭТОМ разговоре.
    ///
    /// ⚠️ ПРИЗНАК БЕРЁТСЯ ФАКТОМ — пустым реестром, — а не второй копией настройки.
    /// Набор действий фиксируется один раз, при сборке сессии (`AgentAssembly.makeSession`),
    /// и живёт до конца разговора. Спроси мы здесь настройку напрямую, переключатель,
    /// тронутый посреди задачи, тут же разошёлся бы с тем, что модель на самом деле видит:
    /// инструкция обещала бы ей действия, которых в разговоре нет.
    private var usesTools: Bool { !registry.tools.isEmpty }

    /// Сменилась папка проекта: обновляем системную инструкцию и начинаем разговор заново.
    public func updateFolder(_ folder: ProjectFolder?) async {
        snapshot.folder = folder
        // Заметка и цель принадлежали ПРОШЛОЙ папке: в новой они в лучшем случае
        // бесполезны, в худшем — врут про чужой проект. Чистим до сборки инструкции.
        projectNote = ""
        focusTask = ""
        focusSubject = ""
        history.setSystemPrompt(AgentPrompt.system(projectName: folder?.displayName,
                                                   withTools: usesTools))
        await reset()
        // Точки возврата принадлежат папке: в новой папке возвращать нечего,
        // пока в ней не применят первую правку.
        refreshUndoAvailability()
    }

    // MARK: - AgentControlling

    /// Новая задача от человека.
    public func submit(task: String) async {
        let text = task.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return }
        guard !snapshot.isBusy, snapshot.pendingAction == nil else { return }

        // ⚠️ ОТВЕТ НА ВОПРОС МОДЕЛИ — НЕ РАЗГОВОР И НЕ НОВАЯ ЗАДАЧА, А ПРОДОЛЖЕНИЕ ТЕКУЩЕЙ.
        // Разделение «вопрос ≠ задача» ниже осталось как было — сузили только этот случай.
        // Пока его не было, выходило так: модель посреди работы спрашивает «Заменить оба
        // вхождения?», человек отвечает «да» — и голое «да» попадало в список коротких
        // реплик-болтовни. Цель обнулялась, строка «Цель:» пропадала из инструкции и из
        // каждого ответа инструмента, оба толчка против застревания выключались — и всё
        // это в тот момент, когда работа шла полным ходом.
        //
        // Признак ответа двойной: модель ДЕЙСТВИТЕЛЬНО ждёт ответа (её последняя реплика —
        // вопрос, и человек на него ещё не отвечал) И сама фраза похожа на ответ, а не на
        // новое поручение. Иначе человек, проигнорировавший вопрос и попросивший другое,
        // остался бы со старой целью.
        let answersQuestion = history.isAwaitingAnswer && Self.looksLikeChat(text)
        startsNewTask = !answersQuestion

        if !answersQuestion {
            // Разговор или задача — решаем ЗДЕСЬ, до всего остального: от этого зависит
            // и цель в инструкции, и толчки, и итоговые полосы.
            //
            // ⚠️ БЕЗ ДЕЙСТВИЙ ЛЮБАЯ ФРАЗА — РАЗГОВОР, И ЭТО НЕ УПРОЩЕНИЕ. Толчки
            // («делай, а не рассказывай») гонят модель к действию, а действий у неё
            // сейчас нет ни одного: человек получил бы три круга уговоров и в конце
            // приговор «осталась на месте» за то, что она честно ответила словами.
            // По той же причине не заводится и цель: строка «Цель: …» подгоняла бы
            // модель к работе, которой в этом режиме не бывает.
            // ⚠️ ПРИЗНАК БЕРЁМ ЗА ВЕСЬ РАЗГОВОР, А НЕ ЗА ПРОШЛУЮ ЗАДАЧУ. `didAnythingSucceed`
            // обнуляется на каждой фразе человека: посреди разговора достаточно одной
            // болтливой реплики, и следующий короткий вопрос («а что там ещё?») снова
            // считался бы посторонним, хотя файлы в этом разговоре давно открывали.
            // `didReadAnyFile` живёт весь разговор — он и есть настоящая память о работе.
            isChatTurn = !usesTools
                || Self.looksLikeChat(text, afterFileWork: didAnythingSucceed || didReadAnyFile)

            // ⚠️ У РАЗГОВОРА ЦЕЛИ НЕТ, И ЭТО НЕ МЕЛОЧЬ. Строка «Цель: …» стоит в системной
            // инструкции и дописывается к ответам инструментов КАЖДЫЙ ход — то есть «Цель:
            // Кто ты» подгоняла модель снова и снова, пока та не перечитала пол-папки.
            // Вопросу цель не нужна: на него отвечают и на этом заканчивают.
            focusTask = isChatTurn ? "" : text
            focusSubject = ""
            // Просят рассказать — правок не заказывали.
            isExplainOnlyTask = !isChatTurn && !Self.asksToChangeFiles(text)
            unaskedWriteNudges = 0
            // ⚠️ ОТДЕЛЬНО ПРО ВОПРОСЫ-ПЕРЕСЧЁТЫ, И ЭТО ПОПРАВКА К МОЕЙ ЖЕ ПРАВКЕ.
            // Я думал, что двадцать четыре просмотра папки подряд случились на «что это
            // за проект», и велел приложению после первого же просмотра называть файл
            // для чтения. Заглянул в саму запись: задача была «Сколько тут файлов».
            // На неё чтением файла не ответишь — подсказка гнала бы помощника не туда.
            // Правки такие вопросы всё равно не заказывают, поэтому от карточки записи
            // они защищены по-прежнему; не подсказываем им только ЧТЕНИЕ.
            asksForCount = Self.asksToCount(text)
            wantsFileRead = Self.asksToRead(text)
            didReadThisTurn = false
            // ⚠️ Память о посланных подсказках живёт ровно ОДНУ задачу. Человек написал
            // новое — положение изменилось, и та же подсказка на новом ходу законна.
            // Не обнулять здесь — значит на длинном разговоре остаться вовсе без
            // подсказок к третьему-четвёртому ходу.
            sentNudges.removeAll()
        }

        // Текст задачи — в журнал целиком. ⚠️ Раньше он туда намеренно НЕ попадал, но
        // владелец решил иначе (10.08.2026): продукт закрытый и личный, а без задачи
        // журнал не разобрать — по одним номерам шагов не понять, чего от помощника
        // вообще хотели. Предупреждение «делиться можно не со всеми» стоит в шапке журнала.
        EngineJournal.shared.noteTaskSubmitted(text)

        // ⚠️ СЧЁТЧИК ШАГОВ БОЛЬШЕ НЕ ОБНУЛЯЕТСЯ НА КАЖДОМ СООБЩЕНИИ, и вот почему.
        // Каждая фраза человека — это новая задача, и раньше счётчик начинался с нуля.
        // В записи разговора оказывалось «Шагов сделано: 0», хотя агент в этом же
        // разговоре успел посмотреть папку и прочитать файлы: в последней задаче он
        // просто ничего не сделал. Человек читал запись и не понимал, было хоть что-то
        // или нет. Теперь счётчик считает ВСЕ действия разговора, а предел сдвигается:
        // каждой новой задаче честно даётся полный запас шагов сверх уже сделанных.
        stepsAtTaskStart = snapshot.stepsUsed
        stepLimit = snapshot.stepsUsed + max(1, AgentLimits.maxSteps)
        snapshot.stepLimit = stepLimit
        invalidTurnStreak = 0
        didApplyWrite = false
        didAnythingSucceed = false
        didChallengeFinish = false
        talkNudges = 0
        lastStepWasRead = false
        // Новая задача — снова осматриваемся, значит и запас под ответ снова половинный.
        replyBudget.startTask()
        applyContextBudget()
        seenGarbledCount = RuntimeJournal.shared.garbledAnswerCount
        // Пометка о сворачивании принадлежит ЗАКОНЧЕННОЙ задаче: висеть над новой ей незачем.
        // Занятое при этом НЕ обнуляем — разговор с движком продолжается, и в нём
        // по-прежнему лежит всё, что помнит модель.
        snapshot.contextFoldedAt = nil

        await startRun { [weak self] runID in
            await self?.beginTask(text, runID: runID)
        }
    }

    /// «Применить»: выполняем подтверждённое действие и возвращаем результат модели.
    ///
    /// ⚠️ Состояние переводим в «Применяю» СРАЗУ, до всякого ожидания. Это и есть защита
    /// от двойного нажатия: второй вызов не найдёт состояния «ждём решения» и выйдет.
    /// Ниже по цепочке стоит второй замок — показанный дифф забирается из хранилища
    /// один раз, и повторная запись без него невозможна в принципе.
    public func approve() async {
        guard case .awaitingApproval(let action) = snapshot.state else { return }
        snapshot.state = .applying(action)

        await startRun { [weak self] runID in
            guard let self else { return }
            await self.applyApproved(action, runID: runID)
        }
    }

    /// Продлить задачу ещё на несколько шагов — вместо тупика «достигнут предел».
    public func extendSteps() async {
        stepLimit += AgentLimits.stepExtension
        snapshot.stepLimit = stepLimit
        if case .failed = snapshot.state {
            snapshot.state = .idle
        }
        append(.system, AgentPrompt.stepsExtendedNotice(AgentLimits.stepExtension, total: stepLimit))
    }

    /// Вернуть в ленту переписку прошлого запуска приложения.
    /// Карточку подтверждения НЕ восстанавливаем: дифф строился по старому состоянию файла.
    public func restoreConversation(messages: [ChatMessage]) async {
        guard !messages.isEmpty, snapshot.messages.isEmpty else { return }
        snapshot.messages = Array(messages.suffix(messageLimit))
        // Плашку добавляем только если её ещё нет: иначе после нескольких перезапусков
        // подряд лента копила бы одинаковые напоминания одно под другим.
        if snapshot.messages.last?.text != AgentPrompt.restoredConversationNotice {
            append(.system, AgentPrompt.restoredConversationNotice)
        }
    }

    /// «Отклонить»: сообщаем модели об отказе тем же каналом, что и результат.
    public func reject() async {
        guard case .awaitingApproval(let action) = snapshot.state else { return }

        await startRun { [weak self] runID in
            guard let self else { return }
            let result = ToolResult.rejected(action.invocation, reason: AgentPrompt.rejectionNotice)
            // Отклонённый дифф забираем из хранилища сразу: содержимое, от которого
            // человек отказался, не должно лежать в памяти до вытеснения по счётчику.
            self.registry.tool(for: action.invocation)?.discardPreview(for: action.invocation.id)
            self.append(.system, AgentPrompt.rejectedSummary(action.title))
            self.history.append(role: .tool, text: "\(result.toolName): отклонено человеком")
            // От текста, который человек отверг, в памяти остаётся одна строка.
            // Раньше он лежал там до конца разговора — а это самый длинный ход модели.
            self.history.noteWriteRejected(path: action.invocation.path)

            // ⚠️⚠️ ОТКАЗ ЧЕЛОВЕКА — ЭТО НЕУДАЧНЫЙ ХОД, И РАНЬШЕ ИМ НЕ СЧИТАЛСЯ.
            // Отклонение шло мимо `record`, то есть счётчик кривых ходов не двигало
            // вовсе: модель могла предлагать одну и ту же правку до предела шагов,
            // а человек — жать «Отклонить» столько же раз. Живая переписка владельца
            // 08.09.2026: две карточки «Записать sima-profile-main/index.html» подряд,
            // обе отклонены, и его ответ дословно — «Зачем ты это делаешь блять».
            // Теперь два отказа подряд останавливают задачу честно, как и любые
            // два неверных хода подряд.
            self.invalidTurnStreak += 1

            guard let next = await self.sendToModel(result, runID: runID) else { return }
            await self.runTurnLoop(startingWith: next, runID: runID)
        }
    }

    /// Прервать текущую генерацию или выполнение.
    public func cancel() async {
        let wasBusy = snapshot.isBusy || currentTask != nil
        // Запись уже пошла на диск. Прервать её нечем: обычный синхронный ввод-вывод
        // отмену не слушает, и файл к этому моменту почти наверняка уже изменён.
        // Значит и говорить «Отменено» нельзя — это прямая ложь про файлы человека.
        let wasApplying: Bool
        if case .applying = snapshot.state { wasApplying = true } else { wasApplying = false }
        // Человек стоит над карточкой правки — её трогать нельзя ни при каких отменах:
        // именно так выглядит «свернул приложение, не решив» и «нажал Стоп во время
        // применения». Показанный дифф обязан пережить это, иначе «Применить» умрёт.
        // ⚠️ Во время записи предпросмотры тоже не трогаем: подтверждённая запись уже
        // идёт и сама заберёт свой дифф из хранилища. Выдернуть его из-под неё — значит
        // отменить запись, которую человек только что разрешил, посреди работы.
        // ⚠️ Карточка возврата здесь тоже считается: её дифф лежит в том же хранилище
        // предпросмотров, и выдернуть его — значит убить «Вернуть» ровно тогда, когда
        // человек свернул приложение, не решив.
        let hasPendingCard = snapshot.pendingAction != nil || wasApplying || snapshot.pendingUndo != nil

        // Сдвигаем номер хода: всё, что вернётся из отменённого хода, будет отброшено.
        activeRunID += 1
        currentTask?.cancel()
        currentTask = nil

        await runtime.cancelTurn()

        if !hasPendingCard {
            // Предпросмотры прерванного хода больше не нужны: подтверждать нечего,
            // а каждый из них держит в памяти полную копию файла.
            for tool in registry.tools {
                tool.discardAllPreviews()
            }
        }

        if snapshot.isBusy {
            snapshot.state = .idle
        }
        if wasBusy {
            append(.system, wasApplying
                   ? AgentPrompt.cancelledWhileApplyingNotice
                   : AgentPrompt.cancelledNotice)
        }
    }

    /// Начать разговор заново (смена папки, кнопка «Новая задача»).
    public func reset() async {
        activeRunID += 1
        currentTask?.cancel()
        currentTask = nil

        // Показанные предпросмотры больше не действительны: подтверждать нечего.
        for tool in registry.tools {
            tool.discardAllPreviews()
        }

        await runtime.cancelTurn()
        if sessionStarted {
            await runtime.endSession()
        }
        sessionStarted = false
        forgetReadPages()
        needsSessionRestart = false
        invalidTurnStreak = 0
        didWarnAboutTrim = false
        didApplyWrite = false
        didAnythingSucceed = false
        didChallengeFinish = false
        talkNudges = 0
        // Кривые ответы прошлой задачи к новой отношения не имеют: счётчик сверяем
        // с текущим значением журнала, иначе первый же пустой ход новой задачи
        // назвался бы «непонятным».
        seenGarbledCount = RuntimeJournal.shared.garbledAnswerCount
        stepLimit = max(1, AgentLimits.maxSteps)
        // Разговор начинается с чистого листа — вот тут счётчик шагов и обнуляется,
        // единственный раз. Внутри разговора он сквозной (см. submit).
        stepsAtTaskStart = 0
        didReadAnyFile = false
        didReadThisTurn = false
        listedFiles = []
        readFiles = []
        sawFolderListing = false
        didHitMissingFile = false
        lastStepWasRead = false
        replyBudget.startTask()
        isChatTurn = false
        // Разговор начат с чистого листа — отвечать не на что, следующая фраза начнёт работу.
        startsNewTask = true
        // Цель и заметка — часть системной инструкции, поэтому собираем её заново
        // от чистого листа: иначе в новой задаче осталась бы цель старой.
        focusTask = ""
        focusSubject = ""
        projectNote = ""
        history.reset(systemPrompt: AgentPrompt.system(projectName: snapshot.folder?.displayName,
                                                       withTools: usesTools))

        snapshot = AgentSnapshot(state: .idle,
                                 messages: [],
                                 stepsUsed: 0,
                                 folder: snapshot.folder,
                                 stepLimit: stepLimit,
                                 // Занятое обнуляется вместе с разговором — его закрыли выше.
                                 // А вот потолок принадлежит ЗАГРУЖЕННОЙ МОДЕЛИ, а не разговору:
                                 // сбросить его к константе значило бы подменить настоящее число
                                 // выдуманным до первого хода следующей задачи.
                                 contextLimitTokens: snapshot.contextLimitTokens)
        // ⚠️ Сами точки возврата чисткой ленты НЕ уничтожаются — файлы человека
        // никуда не делись, и «Новая задача» не должна отнимать у него право
        // отменить последнюю правку. Кнопку он всё равно не увидит: она живёт
        // у строки ленты, а лента чиста. Увидит — только если вернётся к этой
        // переписке после перезапуска приложения.
        refreshUndoAvailability()
    }

    // MARK: - Один ход задачи

    private func beginTask(_ text: String, runID: Int) async {
        // Пересказ нужен, только если прошлый разговор пришлось закрыть по нехватке контекста.
        // ⚠️ Сворачиваем ПЕРЕД пересказом, а не после: иначе в новый разговор уехали бы
        // страницы файлов, ради выброса которых мы разговор и закрываем.
        if needsSessionRestart { history.compact() }
        // ⚠️ Карточка-перенос, а не хронологический пересказ: у прежнего пересказа
        // первой выпадала самая старая запись — то есть исходная просьба человека,
        // а имена файлов из просмотра папки терялись всегда. См. handoffCard.
        // Задачу сюда не дублируем: она стоит строкой «Цель:» в свежей инструкции.
        let recap = needsSessionRestart ? history.handoffCard(goalAlreadyStated: focusTask) : ""

        // Заметка о проекте и строка «сейчас делаю» едут в системной инструкции,
        // а её движок принимает ТОЛЬКО в начале разговора — значит собрать её надо
        // до ensureSession, иначе она уедет на ход позже, чем нужна.
        await refreshProjectNote()
        if isStale(runID) { return }
        refreshSystemPrompt()

        do {
            try await ensureSession()
        } catch {
            if !isStale(runID) { handle(error) }
            return
        }
        if isStale(runID) { return }

        let outgoing = recap.isEmpty ? text : AgentPrompt.recapPrefix(recap) + "\n" + text

        append(.user, text)
        // Модели уходит задача ВМЕСТЕ с пересказом — по нему и считаем цену,
        // иначе первый же ход нового разговора окажется дешевле, чем он есть.
        //
        // ⚠️ И ЗДЕСЬ ЖЕ ОТМЕЧАЕТСЯ, ЧТО РАБОТА ТЕПЕРЬ ПРО ЭТУ ФРАЗУ. Разговор живёт дольше
        // одной задачи, и без отметки память защищала от выбрасывания самую первую просьбу
        // разговора, а карточка-перенос говорила модели «Просили: создай README», когда
        // человек давно попросил другое. Ответ на вопрос модели задачу не подменяет.
        let cost = ConversationHistory.estimateTokens(outgoing)
        if startsNewTask {
            history.appendTask(text, modelTokens: cost)
        } else {
            history.append(role: .user, text: text, modelTokens: cost)
        }
        snapshot.state = .thinking

        do {
            let turn = try await runtime.send(userText: outgoing)
            if isStale(runID) { return }
            await runTurnLoop(startingWith: turn, runID: runID)
        } catch {
            if !isStale(runID) { handle(error) }
        }
    }

    /// Выполнение подтверждённой записи файла.
    private func applyApproved(_ action: PendingAction, runID: Int) async {
        // Состояние уже переведено в approve() — там это защита от двойного нажатия.
        // Сюда можно прийти и другим путём (пересборка карточки), поэтому подстраховываемся.
        if case .applying = snapshot.state {
            // уже применяем — ничего не меняем
        } else {
            snapshot.state = .applying(action)
        }

        guard let tool = registry.tool(for: action.invocation) else {
            // До карточки инструмент был — сюда попасть можно только при пересборке реестра.
            let result = ToolResult.failure(action.invocation,
                                            reason: AgentPrompt.unknownTool(name: action.invocation.rawName,
                                                                            available: registry.availableNames))
            record(result, for: action.invocation, diff: nil)
            guard let next = await sendToModel(result, runID: runID) else { return }
            await runTurnLoop(startingWith: next, runID: runID)
            return
        }

        let result = await execute(tool, action.invocation)

        // Файл поменяли снаружи, пока человек смотрел карточку (папка в iCloud, git-чекаут
        // в Working Copy). Ничего не записано — и это НЕ вина модели: не гоняем её по кругу
        // и не тратим ход, а пересобираем предпросмотр по свежему содержимому и спрашиваем
        // человека заново. Отменённому ходу пересобирать нечего — там сразу вниз, к записи
        // итога в ленту.
        if result.isFileChangedSinceDiff, !isStale(runID) {
            let didRebuild = await rebuildApproval(tool: tool, action: action, runID: runID)
            if didRebuild { return }
        }

        // ⚠️ ИТОГ ЗАПИСИ ПОПАДАЕТ В ЛЕНТУ ВСЕГДА — даже если ход уже отменён.
        // Отмена (кнопка «Стоп» или уход в фон) не прерывает саму запись на диск:
        // она обычная и синхронная, к моменту возврата файл уже изменён. Раньше здесь
        // стояла проверка «ход устарел» и результат выбрасывался целиком — на диске файл
        // был переписан, а человеку показывали «Отменено» и потом ещё «файлы не менялись».
        // Проверка устаревания осталась ниже: она решает только, продолжать ли цикл.
        var restorePointID: UUID?
        if result.outcome == .success {
            didApplyWrite = true
            // Текст записан на диск — держать его ещё и в памяти разговора незачем.
            // Заодно устаревают прежние чтения этого файла: там уже другое содержимое.
            history.noteWriteApplied(path: action.invocation.path,
                                     lines: Self.lineFragment(of: action.invocation))
            // ⚠️ ВОТ ЗДЕСЬ И ЗАВОДИТСЯ ТОЧКА ВОЗВРАТА — ровно в тот миг, когда прежнее
            // содержимое ещё у нас в руках (оно лежит в показанном человеку диффе)
            // и уже перестало быть содержимым файла. Позже взять его будет неоткуда.
            // Модель об этом не узнаёт ни словом: в память разговора не идёт ничего.
            restorePointID = rememberRestorePoint(for: action)
        }
        record(result, for: action.invocation, diff: action.fileDiff, restorePointID: restorePointID)

        // Дальше крутить цикл нельзя: ход отменён или начат новый.
        if isStale(runID) { return }

        // Папка пропала (её удалили, отозвали доступ, отключили провайдер) —
        // дальше крутить цикл нельзя, человеку нужно выбрать папку заново.
        if isFolderGone(result) {
            fail(result.userSummary)
            return
        }

        if invalidTurnStreak > invalidTurnLimit {
            fail(AgentPrompt.tooManyInvalidTurns)
            return
        }
        guard let next = await sendToModel(result, runID: runID) else { return }
        await runTurnLoop(startingWith: next, runID: runID)
    }

    /// Пересобрать карточку подтверждения по свежему содержимому файла.
    /// Возвращает true, если карточка показана заново и ход на этом остановлен.
    private func rebuildApproval(tool: any AgentTool,
                                 action: PendingAction,
                                 runID: Int) async -> Bool {
        // ⚠️ ПРАВКУ ПО НОМЕРАМ СТРОК ПЕРЕСОБИРАТЬ НЕЛЬЗЯ. Номера строк модель взяла
        // из ТОГО текста файла, который читала. Файл изменился снаружи — значит номера
        // указывают уже неизвестно куда, и пересобранная карточка выглядела бы для
        // человека обычной правкой, а заменила бы не то место. Здесь честный отказ:
        // модель получит «файл изменился», перечитает его и возьмёт свежие номера.
        guard !action.invocation.mentionsLineRange else { return false }

        do {
            let preview = try await tool.preview(action.invocation)
            if isStale(runID) {
                // ⚠️ Предпросмотр уже сложил в память полную копию файла, а ход отменён —
                // забираем её сразу, как в requestApproval. Иначе копия висит в памяти
                // до вытеснения по счётчику, а телефон и так держит веса модели.
                tool.discardPreview(for: action.invocation.id)
                return true
            }

            append(.system, AgentPrompt.fileChangedOutsideNotice(action.invocation.path))
            let fresh = PendingAction(invocation: action.invocation,
                                      preview: preview,
                                      title: action.title)
            snapshot.state = .awaitingApproval(fresh)
            return true
        } catch {
            // Пересобрать не вышло (файл удалили, доступ пропал) — идём обычным путём:
            // расскажем модели и человеку, что случилось.
            return false
        }
    }

    // MARK: - Цикл ходов

    /// Что делать после разбора хода модели.
    private enum Step {
        /// Остановились: ждём человека, закончили или упали.
        case stop
        /// Результат готов — отдаём его модели и продолжаем.
        case send(ToolResult)
        /// Ответ модели уже получен другим путём (напоминание вместо ответа инструмента).
        case turn(ModelTurn)
    }

    private func runTurnLoop(startingWith first: ModelTurn, runID: Int) async {
        var turn = first

        while true {
            if isStale(runID) { return }

            let step = await process(turn, runID: runID)
            // Счётчик памяти обновляем РОВНО ЗДЕСЬ — один раз на ход модели, после того
            // как ход разобран. Раньше по этому месту проходили молча, и человек видел
            // только последствия: помощник вдруг переставал помнить, о чём речь.
            // Ход остановился (ждём решения, задача кончилась) — число тоже обновится:
            // спрашиваем ДО разбора `step`, а не в каждой ветке ниже.
            await refreshContextUsage(runID: runID)

            switch step {
            case .stop:
                return

            case .turn(let next):
                turn = next

            case .send(let result):
                // Модель второй раз подряд предлагает ерунду — дальше не крутим.
                if invalidTurnStreak > invalidTurnLimit {
                    fail(AgentPrompt.tooManyInvalidTurns)
                    return
                }
                guard let next = await sendToModel(result, runID: runID) else { return }
                turn = next
            }
        }
    }

    /// Разбор одного ответа модели.
    private func process(_ turn: ModelTurn, runID: Int) async -> Step {
        switch turn {

        // Модель ответила текстом — отдаём человеку и останавливаемся.
        case .text(let raw):
            let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)

            // Пустой ход — обычное дело для модели на 2 млрд параметров после длинного
            // результата инструмента. Это НЕ падение задачи: подталкиваем модель ещё раз
            // и только на третьем пустом ходе подряд останавливаемся, не теряя переписку.
            if text.isEmpty {
                invalidTurnStreak += 1
                // Кривой ответ движок отдаёт таким же пустым ходом — но человеку
                // об этом обязаны сказать другими словами, иначе он видит зависшее
                // приложение вместо честного «модель ответила непонятно, прошу повторить».
                let wasGarbled = consumeGarbledMark()
                guard invalidTurnStreak <= invalidTurnLimit else {
                    // ⚠️ ОДИН СЛУЧАЙ, КОГДА МОЛЧАНИЕ ОБЪЯСНЯЕТСЯ ЗАДАЧЕЙ, А НЕ МОДЕЛЬЮ.
                    // Замер 11.09.2026: на просьбу «прочитай ../../../etc/passwd» модель
                    // трижды подряд вернула пустоту, и человек получал «дело не в вашей
                    // задаче — смените модель». Это неправда: дело ровно в задаче, и
                    // сказать надо про неё, а не отправлять человека качать другую модель.
                    let lastAsk = snapshot.messages.last(where: { $0.author == .user })?.text ?? ""
                    append(.system, Self.askedOutsideFolder(lastAsk)
                           ? Self.outsideFolderSilenceNotice
                           : (wasGarbled
                              ? Self.garbledGaveUpNotice(attempts: invalidTurnLimit + 1)
                              : AgentPrompt.emptyAnswerNotice))
                    snapshot.state = .idle
                    return .stop
                }
                // ⚠️ КАЖДАЯ попытка оставляет след в ленте. Раньше первые две проходили
                // молча, и для человека это выглядело так: отправил «Привет» — и тишина.
                append(.system, Self.retryNotice(garbled: wasGarbled,
                                                 attempt: invalidTurnStreak,
                                                 total: invalidTurnLimit + 1))
                history.append(role: .tool,
                               text: AgentPrompt.emptyTurnRetry,
                               modelTokens: ConversationHistory.estimateTokens(
                                   AgentPrompt.emptyTurnRetry))
                // Три напоминания подряд — три одинаковые строки в памяти. Держим одну.
                history.noteAttemptFailed(what: "")
                guard let next = await sendNudge(AgentPrompt.emptyTurnRetry, runID: runID) else {
                    return .stop
                }
                return .turn(next)
            }

            invalidTurnStreak = 0
            append(.agent, text)
            history.append(role: .model, text: text)

            // Признак «прошлый шаг был чтением» действует ровно на эту фразу и гаснет:
            // вторая подряд фраза без единого действия между ними — уже не пересказ.
            let answersFreshRead = lastStepWasRead
            lastStepWasRead = false

            // ⚠️⚠️ ГЛАВНОЕ МЕСТО ПРАВКИ 09.08.2026. Раньше здесь цикл ВСЕГДА
            // останавливался: любая фраза модели означала «ход человека». Из-за этого
            // владелец получил переписку, где на «изучи проект» агент отвечает
            // «я готов изучить» и замирает, а человек четыре раза подряд пишет «И».
            // Останавливаться надо не на всякой фразе, а только на той, после которой
            // человеку ДЕЙСТВИТЕЛЬНО есть что ответить.
            // ⚠️⚠️ ОДНУ И ТУ ЖЕ ПОДСКАЗКУ ДВАЖДЫ НЕ ШЛЁМ — И ЭТО ПРОВЕРКА НА НАС САМИХ.
            // Живая переписка владельца 07.09.2026, папка sklad-main: помощник дал
            // нормальный ответ про папку — а мы сочли это «просьбой уточнить задачу»
            // и подтолкнули его работать. Он послушался и попросил задачу. Мы толкнули
            // снова. И ещё раз. И ещё. Четыре НАШИ одинаковые подсказки подряд, между
            // ними четыре «пожалуйста, сформулируйте задачу», и разговор умер.
            // То есть в круг его загнали мы сами — своей же помощью.
            //
            // Почему повтор бессмыслен: наша подсказка уходит модели ОБЫЧНЫМ сообщением,
            // то есть выглядит для неё как слова человека. На одни и те же слова
            // маленькая модель отвечает одним и тем же — других слов у неё нет.
            // Не сработало с первого раза — не сработает и со второго; вместо круга
            // честно выходим к человеку (ветка ниже) и говорим, что делать.
            if let nudge = talkNudge(for: text, answersFreshRead: answersFreshRead),
               claimNudge(nudge.modelText) {
                append(.system, nudge.userText)
                history.append(role: .tool,
                               text: nudge.modelText,
                               modelTokens: ConversationHistory.estimateTokens(nudge.modelText))
                // Отговорка и наше возражение — та же неудачная попытка: дословно
                // в памяти держим только последнюю.
                history.noteAttemptFailed(what: "")
                guard let next = await sendNudge(nudge.modelText, runID: runID) else {
                    return .stop
                }
                return .turn(next)
            }

            // Толчки кончились, а модель так и не сдвинулась. Молча замереть здесь
            // нельзя: человек уже видел это и писал одно и то же три раза подряд.
            // Говорим правду и даём выход — назвать файл прямо или сменить модель.
            // ⚠️ ОБВИНЕНИЕ ДОЛЖНО СОВПАДАТЬ С ФАКТОМ. Прежний текст говорил «осталась
            // на месте» всегда, и в живой переписке 10.08.2026 это была неправда: модель
            // прочитала три файла и сделала восемь шагов. Человек читает эту строку как
            // приговор приложению, поэтому случай «работала, но задачу не закрывает»
            // теперь называется своим именем.
            if talkNudges >= Self.talkNudgeLimit {
                append(.system, didAnythingSucceed
                       ? AgentPrompt.modelWorkedButKeepsTalkingNotice
                       : AgentPrompt.modelKeepsTalkingNotice)
            }

            snapshot.state = .idle
            noteContextPressure()
            return .stop

        // Модель попросила инструмент.
        case .toolRequest(let invocation):
            // ⚠️ В историю кладём короткую строку вызова, а ЦЕНУ указываем настоящую.
            // Самый дорогой ход модели — write_file: в аргументе content лежит весь новый
            // текст файла, и в кэше движка он занимает столько же, сколько сам файл.
            // У нас же от него остаётся 120 знаков, и раньше мы именно их и считали.
            history.append(role: .model,
                           text: describe(invocation),
                           topic: Self.topic(of: invocation),
                           modelTokens: Self.callTokens(invocation))

            // ⚠️ Кривые вызовы шагом НЕ считаются: раньше болтливая модель проедала
            // предел задачи на собственных опечатках, и на работу шагов не оставалось.
            if let problem = registry.problem(with: invocation) {
                return recover(from: problem.modelFacingMessage,
                               userText: problem.userFacingMessage,
                               invocation: invocation)
            }

            guard let tool = registry.tool(for: invocation) else {
                let hint = AgentPrompt.unknownTool(name: invocation.rawName,
                                                   available: registry.availableNames)
                return recover(from: hint,
                               userText: "Модель попросила несуществующее действие «\(invocation.rawName)».",
                               invocation: invocation)
            }

            // finish подтверждения не требует — это конец задачи.
            if tool.kind == .finish {
                invalidTurnStreak = 0

                // Модель зовёт finish, ничего не сделав, и отчитывается о выдуманной
                // работе — либо пересказывает проект, не открыв ни одного файла.
                // Один раз честно возражаем: сначала действие, потом отчёт.
                //
                // ⚠️ Вторую половину проверки добавил живой прогон 09.08.2026: закрыть
                // задачу итогом «это проект, связанный с игрой osu!» после одного лишь
                // просмотра папки — то же самое враньё, только через другую дверь.
                if !didChallengeFinish, let objection = finishObjection(invocation) {
                    didChallengeFinish = true
                    append(.system, objection.userText)
                    history.append(role: .tool,
                                   text: objection.modelText,
                                   modelTokens: ConversationHistory.estimateTokens(objection.modelText))
                    // Отчёт о невыполненной работе — тоже неудачная попытка: и сам
                    // пустой finish, и наше возражение свернутся при первом же исходе.
                    history.noteAttemptFailed(what: "")
                    guard let next = await sendNudge(objection.modelText, runID: runID) else {
                        return .stop
                    }
                    return .turn(next)
                }

                let summary = invocation.summary.trimmingCharacters(in: .whitespacesAndNewlines)
                var text = summary.isEmpty ? "Готово." : summary
                // Честность важнее красивого итога: файлы не менялись — так и говорим.
                // ⚠️ Но только когда правок и ждали. После вопроса «кто ты» приписка
                // «ни одной правки применено не было» звучит как отчёт о провале там,
                // где никто ничего не правил и не собирался.
                // ⚠️ И НЕ ПОСЛЕ ВОПРОСА-ОБЪЯСНЕНИЯ ТОЖЕ. Замер 10.09.2026: на «Сколько
                // тут файлов» помощник верно ответил «В проекте 235 файлов» — и следом
                // получил приписку «ни одной правки применено не было». Человек спросил
                // ЧИСЛО, правок не заказывал, и такая приписка читается как отчёт
                // о провале там, где всё получилось. Признак «просили рассказать,
                // а не править» в движке уже есть — пользуемся им.
                if !didApplyWrite, !isChatTurn, !isExplainOnlyTask {
                    text += "\n\n" + AgentPrompt.nothingWasWrittenNotice
                }
                append(.agent, text)
                history.append(role: .model, text: text)
                snapshot.state = .finished(summary: text)
                return .stop
            }

            // Шагом считаем ТОЛЬКО принятый вызов настоящего инструмента.
            snapshot.stepsUsed += 1
            if snapshot.stepsUsed > stepLimit {
                // ⚠️ Человеку называем шаги ЭТОЙ задачи, а не сквозной счётчик разговора:
                // «агент сделал 24 шага» понятно, «агент сделал 51 шаг» — пугает и врёт
                // о том, сколько он потратил на его просьбу.
                fail(AgentPrompt.stepLimitNotice(stepLimit - stepsAtTaskStart))
                return .stop
            }

            // ⚠️ ЗДЕСЬ МЕНЯЕТСЯ ЗАПАС ПОД ОТВЕТ МОДЕЛИ, И МЕСТО ВЫБРАНО НАРОЧНО.
            // Пришла запись файла без номеров строк — значит модель в этой задаче умеет
            // отвечать длинно, и держать под её ответ половинный запас больше нельзя.
            // Смотрим на сам вызов, а не на применённую запись: человек может нажать
            // «Отклонить», но следующий ход модели всё равно будет таким же длинным.
            if replyBudget.note(invocation: invocation) {
                applyContextBudget()
            }

            // ⚠️ НЕЗВАНАЯ ПРАВКА. Человек просил рассказать — карточку «записать файл»
            // он в ответ получить не должен. Один раз одёргиваем модель словами и
            // даём ей ход переиграть; будет настаивать — покажем карточку, потому что
            // решение о собственном файле всё равно за человеком, а не за нами.
            if Self.appliesRealUseFixes,
               tool.kind.needsApproval,
               isExplainOnlyTask,
               unaskedWriteNudges == 0 {
                unaskedWriteNudges += 1
                // Шаг возвращаем: несделанная правка шагом не была.
                snapshot.stepsUsed -= 1
                return recover(from: AgentPrompt.noChangeWasAsked,
                               userText: AgentPrompt.noChangeWasAskedForHuman,
                               invocation: invocation,
                               countsAsInvalid: false)
            }

            // Запись файла: строим предпросмотр и останавливаемся до решения человека.
            if tool.kind.needsApproval {
                return await requestApproval(tool: tool, invocation: invocation, runID: runID)
            }

            // Чтение и список — выполняем сразу, они ничего не портят.
            append(.agent, AgentPrompt.actionTitle(for: invocation, kind: tool.kind))
            // watched: список и чтение ничего не портят, повторить их безопасно —
            // значит и прервать по времени безопасно.
            let result = await execute(tool, invocation, watched: true)
            if isStale(runID) { return .stop }
            record(result, for: invocation, diff: nil)

            // Доступ к папке пропал — гонять модель дальше бессмысленно: все действия
            // будут падать одинаково. Останавливаемся сразу и говорим, что делать.
            if isFolderGone(result) {
                fail(result.userSummary)
                return .stop
            }
            return .send(result)
        }
    }

    /// Готовим карточку подтверждения для write_file.
    private func requestApproval(tool: any AgentTool,
                                 invocation: ToolInvocation,
                                 runID: Int) async -> Step {
        // Предпросмотр читает прежний текст файла — на файле из облака это те же
        // секунды тишины, что и обычное чтение. Человеку говорим, что мы живы.
        let slowNotice = startSlowNotice()
        defer { slowNotice.cancel() }
        do {
            let preview = try await tool.preview(invocation)
            if isStale(runID) {
                // ⚠️ Предпросмотр уже сложил в память ПОЛНЫЙ текст файла. Ход отменён —
                // значит, забираем его сразу: иначе от каждой остановки на карточке
                // в памяти оседает целая копия файла, а телефон и так держит веса модели.
                tool.discardPreview(for: invocation.id)
                return .stop
            }
            invalidTurnStreak = 0

            let action = PendingAction(invocation: invocation,
                                       preview: preview,
                                       title: AgentPrompt.actionTitle(for: invocation, kind: tool.kind))
            snapshot.state = .awaitingApproval(action)
            noteContextPressure()
            return .stop
        } catch {
            if isStale(runID) { return .stop }
            // Предпросмотр не собрался (путь наружу, файл не читается) —
            // это не падение приложения, а подсказка модели.
            let reason = message(for: error)
            return recover(from: AgentPrompt.failureNotice(reason),
                           userText: reason,
                           invocation: invocation)
        }
    }

    /// Действие не выполнилось потому, что пропала сама папка проекта.
    /// Это тупик для всей задачи: следующий шаг упрётся в то же самое.
    private func isFolderGone(_ result: ToolResult) -> Bool {
        switch result.failure {
        case .folderAccessDenied, .bookmarkUnusable, .noProjectFolder:
            return true
        default:
            return false
        }
    }

    /// Свой совет модели для отказов, где общее «попробуй ещё раз» ведёт в тупик.
    /// `nil` — обычный отказ, ему хватает общей приписки.
    /// ⚠️ ОПОЗНАЁМ СЛУЧАЕМ ОШИБКИ, А НЕ СРАВНЕНИЕМ ТЕКСТА. Первая редакция ловила
    /// просрочку строкой `reason == AgentPrompt.toolTookTooLong` — работало, но это
    /// мина: любая правка формулировки МОЛЧА лишила бы модель отдельного совета,
    /// и никакая сборка об этом не сказала бы.
    private static func ownAdvice(for failure: PocketAgentError?) -> String? {
        switch failure {
        case .pathIsFileNotFolder(let path):
            return "«\(path)» — это файл, а не папка. Позови read_file с path=\"\(path)\"."
        case .pathIsFolderNotFile(let path):
            return "«\(path)» — это папка, а не файл. Позови list_files с path=\"\(path)\"."
        case .fileNotDownloaded(let path):
            return "«\(path)» лежит в облаке и на телефон ещё не приехал. Повтор не поможет: "
                + "возьми другой файл, а про этот скажи человеку, что его надо один раз открыть в «Файлах»."
        case .fileTooLarge(let path, _):
            return "«\(path)» слишком большой — прочитать его нельзя ни сейчас, ни потом. Возьми другой файл."
        case .toolTimedOut:
            return "Это действие не ответило вовсе. Повторять его не надо: возьми другой файл "
                + "или скажи человеку, что этот, похоже, надо один раз открыть в «Файлах»."
        default:
            return nil
        }
    }

    /// Путаница «файл или папка» — не кривой ход, а промах в имени, у которого
    /// в самом ответе уже назван выход.
    private static func isNamingMixUp(_ failure: PocketAgentError?) -> Bool {
        switch failure {
        case .pathIsFileNotFolder, .pathIsFolderNotFile: return true
        default: return false
        }
    }

    /// Виновато окружение, а не модель: файл существует, назван правильно, но
    /// физически лежит в облаке и на телефон ещё не скачан.
    ///
    /// ⚠️ ПОЧЕМУ ЭТО ОТДЕЛЬНО. Замер 10.09.2026 в настоящей папке владельца, длинный
    /// разговор провален 3 раза из 3. Помощник вёл себя БЕЗУПРЕЧНО: попросил agent.py —
    /// «лежит в iCloud, не скачан»; взял другой, cli.py — то же; взял третий,
    /// launcher_bootstrap.py — то же. И на этом разговор убило наше собственное
    /// «помощник два раза подряд предложил неверное действие». Он не предлагал
    /// неверное — у него под ногами не оказалось файлов. Наказывать за это нельзя:
    /// в папке владельца из iCloud так лежит половина проекта, и любая честная работа
    /// упирается в остановку через два шага.
    private static func isNotOurFault(_ failure: PocketAgentError?) -> Bool {
        if case .fileNotDownloaded = failure { return true }
        return false
    }

    /// Кривой ход модели: рассказываем ей, что не так, и даём ещё попытку.
    /// - Parameter countsAsInvalid: считать ли этот ход кривым. `false` — когда ход
    ///   модели сам по себе исправен, а не подошёл по смыслу задачи (незваная правка):
    ///   наказывать за это счётчиком нельзя, иначе одна вежливая ошибка плюс одна
    ///   настоящая — и задача остановлена.
    private func recover(from modelMessage: String,
                         userText: String,
                         invocation: ToolInvocation,
                         countsAsInvalid: Bool = true) -> Step {
        if countsAsInvalid { invalidTurnStreak += 1 }
        append(.system, userText)
        history.append(role: .tool,
                       text: modelMessage,
                       modelTokens: ConversationHistory.estimateTokens(modelMessage) + focusCost())
        // ⚠️ Провалы дословно НЕ КОПИМ: прежние сворачиваются в одну строку прямо здесь.
        // Дословной остаётся только эта, последняя попытка — иначе модель видит перед
        // собой два своих кривых вызова и присылает третий такой же.
        history.noteAttemptFailed(what: Self.attemptLabel(invocation))
        return .send(ToolResult.failure(invocation, reason: modelMessage))
    }

    // MARK: - Заметка о проекте и строка «сейчас делаю»

    /// Перечитать заметку о проекте — файл `AGENTS.md` в корне папки.
    ///
    /// ⚠️ ЧИТАЕМ ТЕМ ЖЕ ИНСТРУМЕНТОМ, ЧТО И МОДЕЛЬ, и это не лень, а безопасность:
    /// у read_file уже проверены путь, размер, права и «похоже на секрет». Читать файл
    /// мимо него значит завести второй путь к диску, за которым никто не следит.
    ///
    /// Заметку приложение только ЧИТАЕТ. Пишет её человек — или модель обычной записью
    /// файла, через ту же кнопку «Применить», что и любую другую правку. Записи без
    /// подтверждения у нас не бывает, и ради удобной памяти агента исключения не будет.
    private func refreshProjectNote() async {
        projectNote = ""
        guard snapshot.folder != nil else { return }

        let invocation = ToolInvocation(rawName: ToolKind.readFile.rawValue,
                                        callID: "",
                                        arguments: ["path": AgentPrompt.projectNoteFileName])
        guard let tool = registry.tool(for: invocation), tool.kind == .readFile else { return }
        // Заметки нет — инструмент вернёт обычный отказ. Это не беда и не событие:
        // человеку про отсутствие файла, которого он не заводил, говорить нечего.
        // ⚠️ ЧЕРЕЗ СТОРОЖ, КАК И ОБЫЧНОЕ ЧТЕНИЕ. Заметку приложение читает САМО перед
        // КАЖДОЙ задачей, и делало это в обход предела по времени: незакачанный
        // AGENTS.md подвешивал бы начало каждой задачи, а человек видел бы, что
        // помощник не отвечает на его первую же фразу.
        // Заметку приложение читает ДО первого хода модели — и человек в этот момент
        // уже отправил просьбу и смотрит в пустой экран. Молчать тут хуже всего.
        let slowNotice = startSlowNotice()
        defer { slowNotice.cancel() }
        guard let result = try? await Self.runWatched(tool: tool,
                                                      invocation: invocation,
                                                      seconds: Self.toolAnswerLimit),
              result.outcome == .success,
              case .fields(let values) = result.payload,
              let content = values["content"] else { return }

        projectNote = AgentPrompt.projectNote(content)
    }

    /// Пересобрать системную инструкцию: правила + заметка + цель.
    ///
    /// ⚠️ Кладём её в историю целиком, а не подмешиваем при отправке. Иначе наш счётчик
    /// занятого места не знал бы про заметку и строку цели — то есть врал бы в меньшую
    /// сторону ровно на те токены, которые мы только что добавили.
    /// `carryingProjectNote` — везти ли с собой заметку о проекте (`AGENTS.md`).
    ///
    /// ⚠️ ЗАЧЕМ ЗДЕСЬ ВЫКЛЮЧАТЕЛЬ, А НЕ ПРОСТО «ВСЕГДА ВЕЗТИ». Заметка стоит до 300
    /// токенов — десятую часть всего окна, — и лежит она в системной инструкции, то есть
    /// пересылается заново при КАЖДОМ сворачивании разговора. За задачу с тремя
    /// сворачиваниями мы платили за неё четыре раза, хотя написана она один раз и не
    /// менялась. Теперь заметка едет в первый разговор задачи, а в свёрнутых её место
    /// занимает карточка-перенос: та несёт то, что модель уже сделала и видела, — вещи,
    /// которых в заметке нет вовсе.
    ///
    /// ⚠️ И ПОЧЕМУ ЭТО НЕ «ПРОСТО ВЫКИНУЛИ ЗНАНИЕ О ПРОЕКТЕ». Отказ от заметки случается
    /// ровно там, где память УЖЕ кончилась и разговор всё равно сворачивается: выбор
    /// стоит не между «с заметкой и без», а между «заметка» и «300 токенов работы».
    /// Пока места хватает, заметка на месте и ничего не меняется.
    private func refreshSystemPrompt(carryingProjectNote: Bool = true) {
        history.setSystemPrompt(AgentPrompt.system(projectName: snapshot.folder?.displayName,
                                                   withTools: usesTools,
                                                   projectNote: carryingProjectNote ? projectNote : "",
                                                   focus: focusLine()))
    }

    /// Строка «сейчас делаю» — или пусто, пока задачи нет.
    private func focusLine() -> String {
        AgentPrompt.focusLine(task: focusTask, subject: focusSubject)
    }

    /// Во сколько токенов обходится строка цели. Нужно, чтобы честно считать
    /// цену хода: строка уходит модели вместе с ответом инструмента.
    private func focusCost() -> Int {
        let line = focusLine()
        return line.isEmpty ? 0 : ConversationHistory.estimateTokens(line)
    }

    /// Приписать строку цели к ответу инструмента — ТОЛЬКО туда, где у неё есть имя.
    ///
    /// ⚠️ Тут и живёт «каждый ход»: маленькая модель теряет цель после длинного ответа
    /// инструмента, и напомнить о ней дешевле всего прямо в этом ответе.
    ///
    /// ⚠️⚠️ НО ГОЛОЙ СТРОКОЙ — НИКОГДА. ЭТО ИСПРАВЛЕНИЕ ЖИВОГО ПРОМАХА 09.08.2026,
    /// и он стоил владельцу шага в КАЖДОЙ задаче. Раньше строка дописывалась и в конец
    /// списка файлов (`.lines`), и в конец свободного текста (`.text`). Список файлов —
    /// это ровно то, из чего модель выбирает, что открыть. Она и открывала: в переписке
    /// владельца сразу после «Найдено: 8 записей» шло «Читаю файл Цель: Сделай сайт
    /// про симу…» — вместе с НАШИМ ЖЕ многоточием, которым `focusLine` обрезает длинную
    /// задачу. Дальше «Файл не найден», сгоревший шаг, сгоревшее место в памяти
    /// разговора — и владелец, который видит тупящую модель и жмёт «Стоп». Повторилось
    /// дважды за одну переписку.
    ///
    /// Поэтому цель уходит модели ровно двумя путями, и оба именованные: в системной
    /// инструкции (там она лежит постоянно, `refreshSystemPrompt`) и полем `goal` рядом
    /// с прочитанным текстом. Ни один из них нельзя прочитать как имя файла.
    /// Не возвращать `.lines`/`.text` обратно — цена этой строки уже измерена.
    private func withFocus(_ result: ToolResult) -> ToolResult {
        let line = focusLine()
        guard !line.isEmpty, case .fields(var values) = result.payload else { return result }

        guard values["goal"] == nil else { return result }
        values["goal"] = line
        return result.withPayload(.fields(values))
    }

    /// Во что обойдётся строка цели ИМЕННО У ЭТОГО ответа.
    ///
    /// ⚠️ Спрашиваем про конкретный ответ, а не вообще: к списку файлов и к свободному
    /// тексту цель больше не приписывается, и записывать им её цену — значит завышать
    /// занятое место и сворачивать разговор раньше, чем нужно. Счётчик обязан считать
    /// то, что действительно уходит модели.
    private func focusCost(for result: ToolResult) -> Int {
        guard case .fields(let values) = result.payload, values["goal"] == nil else { return 0 }
        return focusCost()
    }

    // ⚠️ ЗДЕСЬ БЫЛ `withFocus(text:)` — ДОПИСЫВАНИЕ ЦЕЛИ К СЛУЖЕБНОМУ НАПОМИНАНИЮ.
    // Убран 09.08.2026, и возвращать его не надо. Он приписывал цель ГОЛОЙ СТРОКОЙ
    // в конец сообщения — то есть делал её последним, что модель видит перед выбором
    // следующего действия. В переписке владельца ровно после такого напоминания шло
    // «Читаю файл Цель: Че так долго тупень.»: модель приняла нашу строку за путь.
    //
    // Пользы при этом не было НИКАКОЙ: цель уже лежит в системной инструкции
    // (`refreshSystemPrompt` собирает её перед каждым заходом и при перезапуске
    // разговора), а инструкция живёт в памяти разговора постоянно. То есть мы платили
    // 24 токена за каждое напоминание, чтобы повторить модели то, что у неё и так
    // перед глазами, — и получали сгоревший шаг. Убрать честнее, чем чинить.

    /// Что именно пробовали — коротко, для следа в памяти: «write_file README.md».
    private static func attemptLabel(_ invocation: ToolInvocation) -> String {
        let name = invocation.rawName.trimmingCharacters(in: .whitespacesAndNewlines)
        let path = invocation.path.trimmingCharacters(in: .whitespacesAndNewlines)
        if name.isEmpty { return path }
        return path.isEmpty ? name : "\(name) \(path)"
    }

    // MARK: - Разговор с движком

    private func ensureSession() async throws {
        if sessionStarted && !needsSessionRestart { return }

        if sessionStarted {
            // Контекст кончился: закрываем разговор и начинаем новый.
            await runtime.endSession()
            sessionStarted = false
            forgetReadPages()
        }

        try await runtime.beginSession(systemPrompt: currentSystemPrompt(),
                                       tools: registry.declarations)
        sessionStarted = true
        needsSessionRestart = false
        // Потолок памяти спрашиваем у движка, а не берём из константы: он пробует
        // увеличенное окно и может отступить — см. ModelRuntime.contextLimitTokens().
        adoptContextCeiling(await runtime.contextLimitTokens())
        await measureContextBaseline()
        // В кэше нового разговора лежит ровно то, что мы перешлём пересказом:
        // прежние страницы файлов остались в закрытом разговоре и места больше не занимают.
        history.rebaseAfterRestart()
    }

    /// Замеряет служебную часть разговора — то, что занято ещё до первого слова работы.
    ///
    /// ⚠️ ЗВАТЬ СТРОГО СРАЗУ ПОСЛЕ `beginSession`, ПОКА РАЗГОВОР ПУСТ. В этот момент
    /// занятое движком — это ровно инструкция агенту плюс описания четырёх действий,
    /// то есть настоящая измеренная цена шапки, а не наша оценка. По разбору живых
    /// переписок это около 806 токенов из 4096 — пятая часть окна, и человеку надо
    /// видеть, что она уходит независимо от того, что он попросил.
    /// Цена замера — один дешёвый вопрос движку на разговор, не на ход.
    private func measureContextBaseline() async {
        guard let baseline = await runtime.usedTokens() else { return }
        snapshot.contextBaselineTokens = baseline
        // Заодно это и есть занятое прямо сейчас: разговор пуст, работы в нём ещё нет.
        snapshot.contextUsedTokens = baseline
    }

    /// Спрашивает движок, сколько памяти разговора занято, и кладёт число в снимок.
    ///
    /// ⚠️ ЗОВЁТСЯ ТОЛЬКО МЕЖДУ ХОДАМИ, И ЭТО НЕ ПРИДИРКА. Внутри это `getTokenCount()` —
    /// чтение счётчика у живого разговора, дешёвое само по себе; дорого другое —
    /// лезть к разговору, пока движок генерирует ответ. Поэтому вызовов ровно столько,
    /// сколько ходов модели: на кадр отрисовки счётчик никто не дёргает.
    private func refreshContextUsage(runID: Int) async {
        // ⚠️ ПОТОЛОК ПЕРЕСПРАШИВАЕМ КАЖДЫЙ ХОД, И ЭТО НЕ ЛИШНЯЯ РАБОТА. Движок умеет
        // отступить к безопасному размеру ПРЯМО ПОСРЕДИ ЗАДАЧИ: увидел, что на увеличенном
        // окне модель отвечает пусто, — пересобрал себя на меньшем и повторил тот же ход.
        // Спроси мы потолок только при начале разговора, полоска в чате до конца задачи
        // обещала бы человеку место, которого уже нет, а пороги сворачивания считались бы
        // от несуществующего числа. Стоит это чтения одного числа у актора, не у библиотеки.
        let ceiling = await runtime.contextLimitTokens()
        let used = await runtime.usedTokens()
        // Ход успели отменить или начать новый — своё число уже неактуально.
        guard !isStale(runID) else { return }
        // Потолок принимаем ДАЖЕ ЕСЛИ движок не сказал, сколько занято: это разные вопросы,
        // и молчание про занятое не повод считать пороги от устаревшего окна.
        adoptContextCeiling(ceiling)
        guard let used else { return }
        snapshot.contextUsedTokens = used
    }

    /// Принять выданный движком потолок памяти разговора: и на экран, и в пересчёт порогов.
    ///
    /// ⚠️ ПОРОГ ПЕРЕСКАЗА ЗАВИСИТ ОТ ПОТОЛКА, А НЕ ЗАДАН ЧИСЛОМ. Пересказ — это то,
    /// что поедет в новый разговор, когда мы свернём нынешний. Оставь его посчитанным
    /// от 4096, и на выданных 8192 приложение сворачивало бы память вдвое раньше нужного,
    /// то есть выбрасывало бы ровно ту память, ради которой окно и поднимали.
    private func adoptContextCeiling(_ ceiling: Int) {
        guard ceiling > 0 else { return }
        // ⚠️ ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ВЫДАННЫЙ ПОТОЛОК СТАНОВИТСЯ ИЗВЕСТЕН ВСЕМУ ПРИЛОЖЕНИЮ.
        // Инструменты живут отдельно от движка и спросить его не могут, а размер страницы
        // чтения обязан считаться именно от выданного окна. Пока этого не было, страница
        // считалась от ВЫБОРА человека — и при выданных 4 096 против выбранных 32 000
        // каждое чтение переполняло память разговора. Записываем ДО проверки на «то же
        // самое число»: в снимке потолок мог уже стоять, а наружу ещё не уехать.
        ContextSizeSettings.noteGranted(ceiling)
        guard ceiling != snapshot.contextLimitTokens else { return }
        snapshot.contextLimitTokens = ceiling
        applyContextBudget()
    }

    /// Пересчитать порог сворачивания разговора и сообщить его ленте.
    ///
    /// ⚠️ ОТДЕЛЬНЫМ МЕТОДОМ, ПОТОМУ ЧТО ПОВОДОВ ПЕРЕСЧИТАТЬ ТЕПЕРЬ ДВА, А НЕ ОДИН.
    /// Раньше порог зависел только от выданного движком потолка и менялся вместе с ним.
    /// Теперь на него влияет ещё и запас под ответ модели (`ReplyBudget`), а тот
    /// поднимается посреди задачи — в тот ход, когда модель впервые собралась переписать
    /// файл целиком. Забудь мы пересчитать порог в этот момент — лента считала бы, что
    /// места ещё вагон, ровно тогда, когда запас под ответ вырос вдвое.
    private func applyContextBudget() {
        history.setTokenBudget(replyBudget.restartThreshold(forCeiling: contextCeiling))
    }

    /// Разговор с моделью начинается с чистого листа — значит и наша память о том,
    /// какие страницы файлов ей уже показаны, обязана обнулиться.
    ///
    /// ⚠️ ИНАЧЕ ПОЛУЧАЕТСЯ ЛОЖЬ. Инструмент чтения не отдаёт то же место дважды и
    /// говорит модели «эти строки ты уже видел». После закрытия разговора она их
    /// НЕ видит — они остались в закрытом кэше. Не забыть здесь — значит навсегда
    /// отказать ей в куске файла, который ей нужен.
    private func forgetReadPages() {
        for tool in registry.tools {
            (tool as? WorkspaceReadFileTool)?.forgetReadPages()
        }
    }

    /// Отменить пометку о последней показанной странице: до модели она не доехала.
    /// Зовётся ровно из одного места — оттуда, где содержимое файла заменяется ошибкой.
    private func undoLastReadNote(path: String) {
        for tool in registry.tools {
            (tool as? WorkspaceReadFileTool)?.undoLastReadNote(path: path)
        }
    }

    private func currentSystemPrompt() -> String {
        history.entries.first(where: { $0.role == .system })?.text
            ?? AgentPrompt.system(projectName: snapshot.folder?.displayName,
                                  withTools: usesTools)
    }

    /// Служебное напоминание модели обычным сообщением (не ответом инструмента).
    ///
    /// ⚠️ Именно сообщением, а не `ToolResult`: ответ инструмента без вызова инструмента —
    /// нарушение протокола вызовов, движок такой ход не примет.
    /// Пометить служебную подсказку так, чтобы модель не приняла её за слова человека.
    ///
    /// ⚠️⚠️ ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. У Gemma НЕТ служебной роли — официальная дока
    /// Google прямо говорит: модель знает только «человек» и «модель». Значит наша
    /// подсказка физически приходит ей тем же самым ходом, что и речь владельца, и
    /// она отвечает на неё РАЗГОВОРОМ, а не действием. Ровно это убило его живой
    /// разговор 07.09.2026: помощник дал нормальный ответ → мы решили, что он просит
    /// уточнений → подсказка → он извинился словами → подсказка → и так четыре раза.
    /// Приём взят у этого же харнесса Claude Code: служебный текст отличается от речи
    /// человека не ролью, а ЯВНЫМ МАРКЕРОМ в самом тексте.
    ///
    /// ⚠️ Под выключателем варианта инструкции — внедрять на веру нельзя, проверяем
    /// числом на телефоне владельца рядом с обычным и коротким вариантом.
    static func markedForModel(_ text: String) -> String {
        #if DEBUG
        guard BenchMode.promptVariant == "marked" else { return text }
        return "[СЛУЖЕБНОЕ СООБЩЕНИЕ ПРИЛОЖЕНИЯ, ЭТО НЕ ЧЕЛОВЕК] " + text
            + "\n[Не отвечай на это словами и не извиняйся — сделай названное действие.]"
        #else
        return text
        #endif
    }

    private func sendNudge(_ text: String, runID: Int) async -> ModelTurn? {
        snapshot.state = .thinking
        do {
            // ⚠️ ЦЕЛЬ СЮДА БОЛЬШЕ НЕ ПРИПИСЫВАЕТСЯ. Раньше здесь стояло «цель тут дороже
            // всего: без неё „повтори“ звучит как „повтори что угодно“» — рассуждение
            // верное, но исполнение было негодным: цель уходила голой строкой в самый
            // конец сообщения, и модель принимала её за путь к файлу (см. `withFocus`).
            // А сама цель никуда не девалась: она лежит в системной инструкции, которая
            // живёт в памяти разговора постоянно. «Повтори» и так звучит при цели.
            let turn = try await runtime.send(userText: Self.markedForModel(text))
            if isStale(runID) { return nil }
            return turn
        } catch {
            if isStale(runID) { return nil }
            handle(error)
            return nil
        }
    }

    /// Отправляет результат инструмента модели. nil — ход прерван или упал.
    private func sendToModel(_ result: ToolResult, runID: Int) async -> ModelTurn? {
        snapshot.state = .thinking

        // Сколько кэша разговора уже занято — спрашиваем движок ПЕРЕД каждой отправкой.
        // Движок промолчал — идём по своей оценке, она намеренно завышена.
        let engineUsed = await runtime.usedTokens()
        let used = engineUsed ?? history.engineTokens
        if isStale(runID) { return nil }
        // Число уже в руках — кладём его на экран бесплатно, без второго вопроса движку.
        // ⚠️ Но ТОЛЬКО ответ самого движка. Наша завышенная оценка годится, чтобы не
        // переполнить кэш, и не годится, чтобы показывать её человеку как факт: полоска
        // обещает измеренное число, и подсовывать под видом него прикидку нельзя.
        if let engineUsed { snapshot.contextUsedTokens = engineUsed }

        // ⚠️ СВОРАЧИВАЕМСЯ ДО СТЕНЫ, А НЕ ПОСЛЕ НЕЁ. Раньше единственной защитой была
        // подрезка ответа в тот момент, когда он уже не помещался, — и человек видел
        // «модель не смогла прочитать файл» вместо работы. Теперь, пока в разговоре есть
        // что освободить (устаревшие страницы, отклонённые правки), мы закрываем его
        // и открываем новый, унося свежий результат с собой.
        if shouldRestartConversation(used: used, result: result) {
            return await restartConversation(carrying: result, runID: runID)
        }

        // Строка цели приписывается ДО подрезки, а не после: иначе мы бы отправили
        // на два десятка токенов больше, чем сами же насчитали как «влезающее».
        let outgoing = fitToContext(withFocus(explained(await steered(result))), used: used)

        do {
            let turn = try await runtime.send(toolResult: outgoing)
            if isStale(runID) { return nil }
            return turn
        } catch {
            if isStale(runID) { return nil }
            handle(error)
            return nil
        }
    }

    /// Помощник ходит по папкам и не открывает файлы — назвать ему файл прямо.
    ///
    /// ⚠️ ПОЧЕМУ ПОДСКАЗКА ЕДЕТ В ОТВЕТЕ ИНСТРУМЕНТА, А НЕ В ИНСТРУКЦИИ. Инструкция
    /// уходит модели один раз в начале и к двадцатому шагу для неё уже далеко. Ответ
    /// действия она читает ПРЯМО СЕЙЧАС, перед самым своим ходом, — и слушается его.
    /// Тот же приём, что и у остальных толчков: не общий призыв, а названный файл.
    ///
    /// ⚠️ Меняем только тело для модели. Человеку в ленту эта строка не идёт: ему
    /// незачем читать приказ, обращённый не к нему.
    /// Приклеить к любому ответу инструмента служебную подсказку для модели.
    /// Человеку она не видна — в ленту идёт свой, короткий текст.
    private static func withHint(_ result: ToolResult, _ hint: String) -> ToolResult {
        switch result.payload {
        case .text(let value):
            return result.withPayload(.fields(["ответ": value, "подсказка": hint]))
        case .lines(let values):
            return result.withPayload(.fields(["записи": values.joined(separator: "\n"),
                                               "подсказка": hint]))
        case .fields(var values):
            values["подсказка"] = hint
            return result.withPayload(.fields(values))
        }
    }

    private func steered(_ result: ToolResult) async -> ToolResult {
        // ⚠️⚠️ ШАГИ ПОЧТИ КОНЧИЛИСЬ — ПРОСИМ ОТВЕТ, А НЕ ЖДЁМ ОБРЫВА.
        // Так делает opencode: у края бюджета шагов у модели забирают инструменты и
        // форсируют финальный ответ. У нас до сих пор было иначе: на 24-м шаге задача
        // просто умирала строкой «агент сделал 24 шага и остановился», и человек
        // оставался вообще без ответа. Ровно это и видно в живой переписке владельца
        // 08.09.2026: двадцать четыре просмотра папок подряд и ни слова ему в итоге.
        // Предупреждать надо ЗАРАНЕЕ: модели нужен ход на сам ответ.
        if Self.appliesRealUseFixes, result.outcome == .success {
            let left = stepLimit - snapshot.stepsUsed
            if left <= Self.stepsReservedForAnswer {
                return Self.withHint(result, AgentPrompt.stepsAlmostGone(left: max(0, left)))
            }
        }
        // ⚠️⚠️ СНАЧАЛА — СЛУЧАЙ «ПАПКУ УЖЕ СМОТРЕЛИ», КОГДА ЧЕЛОВЕК ПРОСИТ ЧИТАТЬ.
        // Замер 10.09.2026 в настоящей папке владельца, задача провалена 3 раза из 3:
        //     человек: «Окей, прочитай файлы и скажи что там»
        //     помощник: просит список корня (он его уже видел ходом раньше)
        //     наша память о папках: «уже смотрел — открой файл ИЛИ ответь тем, что знаешь»
        //     помощник: «Я уже видел список файлов. Он включает: ядро проекта…»
        // То есть он пересказал ИМЕНА как содержимое — ровно то враньё, на которое
        // владелец жаловался скриншотами. Виновата наша же подсказка: она предложила
        // выход «ответь не читая» на ходу, где человек прямым текстом просил читать.
        // Убираем этот выход и называем конкретный ещё не прочитанный файл.
        if Self.appliesRealUseFixes, wantsFileRead, !didHitMissingFile, !suggestedFileToRead.isEmpty,
           case .fields(var fields) = result.payload, fields["подсказка"] != nil,
           registry.tool(for: ToolInvocation(rawName: result.toolName,
                                             callID: "", arguments: [:]))?.kind == .listFiles {
            fields["подсказка"] = AgentPrompt.readThisFileNotTheListing(file: suggestedFileToRead)
            return result.withPayload(.fields(fields))
        }

        // ⚠️ ДВА РАЗНЫХ СЛУЧАЯ, И ВТОРОЙ ВАЖНЕЕ ПЕРВОГО.
        //  • Спросили «что это за проект» — файл называем СРАЗУ после первого же
        //    просмотра папки. Ждать трёх лишних шагов незачем: ответ на такой вопрос
        //    всегда начинается с чтения, а у нас предел в 24 шага и модель на 4 млрд,
        //    которой каждый лишний ход стоит связности.
        //  • Просили что-то определённое («где задан порт») — не мешаем искать, но
        //    после третьего просмотра подряд без чтения всё равно называем файл.
        // ⚠️ И НЕ ТОЛКАЕМ К ЧУЖОМУ ФАЙЛУ, ЕСЛИ ЧЕЛОВЕК ПРОСИЛ КОНКРЕТНЫЙ, КОТОРОГО НЕТ.
        // Замер 09.09.2026: на «Прочитай todo.md и скажи, что там написано» файла нет,
        // и честный ответ — сказать об этом. Подсказка «открой README.md» уводила
        // помощника читать полпапки вместо простого честного «такого файла нет».
        // Признак `didHitMissingFile` для этого в движке уже есть — пользуемся им.
        let asksAboutProject = isExplainOnlyTask && !asksForCount && !didHitMissingFile
            && !didReadAnyFile && listsWithoutRead >= 1
        // ⚠️ ВОПРОСУ-ПЕРЕСЧЁТУ ПОДСКАЗЫВАЕМ СРАЗУ, А НЕ ПОСЛЕ ТРЁХ ОБХОДОВ. Замер
        // 09.09.2026: на «Сколько тут файлов» помощник обошёл ДВАДЦАТЬ ЧЕТЫРЕ папки
        // подряд и упёрся в предел шагов. Он не сломан — он честно считает единственным
        // доступным способом, обходом дерева, и шагов на это не хватает никогда.
        // Значит выход надо назвать сразу и конкретно, а не ждать третьего круга.
        // ⚠️ Под общим выключателем правок «под живое использование»: замер в плече
        // «до» обязан показать поведение БЕЗ этой подсказки, иначе сравнивать нечего.
        guard Self.appliesRealUseFixes,
              result.outcome == .success,
              asksAboutProject
                || (asksForCount && listsWithoutRead >= 1)
                || listsWithoutRead >= Self.folderWalkLimit,
              case .lines(var lines) = result.payload else { return result }

        let asked = ToolInvocation(rawName: result.toolName, callID: "", arguments: [:])
        guard registry.tool(for: asked)?.kind == .listFiles else { return result }

        // ⚠️⚠️ ПОДСКАЗКУ КЛАДЁМ ОТДЕЛЬНЫМ ПОЛЕМ, А НЕ СТРОКОЙ В СПИСОК. Первая редакция
        // дописывала её к списку имён — и модель честно попробовала ПРОЧИТАТЬ ЕЁ КАК
        // ФАЙЛ: «Читаю файл ⚠️ Папок посмотрено достаточно…» → «файл не найден» →
        // второй такой ход → задача остановлена. Ответ списка для модели это массив
        // имён, и всё, что в него положено, она читает как имя. Замер 09.09.2026 поймал
        // это на живой задаче; урок ровно тот же, что и с примером вызова в инструкции.
        // ⚠️ ВАРИАНТ «В» ИЗ КАРТЫ: на вопрос-пересчёт отдаём НАСТОЯЩЕЕ ЧИСЛО,
        // сосчитанное самим приложением, а не совет ответить примерно по корню.
        // Сосчитать не вышло (нет папки, облако не отвечает) — падаем на прежний текст:
        // приблизительный ответ всё равно лучше двадцати четырёх обходов и молчания.
        let hint: String
        if asksForCount {
            if let count = await treeCountIfPossible() {
                hint = AgentPrompt.answerCountExactly(files: count.files,
                                                      folders: count.folders,
                                                      isApproximate: count.isApproximate)
            } else {
                hint = AgentPrompt.stopWalkingAnswerCount
            }
        } else {
            hint = AgentPrompt.stopWalkingStartReading(file: suggestedFileToRead)
        }
        return result.withPayload(.fields([
            "записи": lines.joined(separator: "\n"),
            "подсказка": hint
        ]))
    }

    /// Сосчитать дерево проекта — в стороне от главного потока и со сроком.
    ///
    /// ⚠️ ОБХОД ИДЁТ НЕ НА ГЛАВНОМ ПОТОКЕ, И ЭТО НЕ ПРИДИРКА. Папка владельца лежит
    /// в iCloud, а обход не догруженной из облака папки умеет уходить в себя на
    /// секунды. Сделай мы это прямо здесь — на это время замирает вся переписка,
    /// и человек видит подвисшее приложение вместо ответа.
    ///
    /// ⚠️ Срок 6 секунд: не успели — отвечаем «больше чем N», а не молчим. Ровно тот
    /// же урок, что и с чтением файлов из облака: бесконечное ожидание
    /// выглядит для человека как поломка, а честное «примерно» — как ответ.
    private func treeCountIfPossible() async -> DirectoryLister.TreeCount? {
        if let treeCount { return treeCount }
        guard let workspace, let root = try? workspace.resolve("") else { return nil }
        let value = await Self.countedTree(at: root)
        treeCount = value
        return value
    }

    private nonisolated static func countedTree(at root: URL) async -> DirectoryLister.TreeCount {
        await withCheckedContinuation { continuation in
            Task.detached(priority: .userInitiated) {
                continuation.resume(returning: DirectoryLister.countTree(startURL: root))
            }
        }
    }

    /// Приклеить к неудаче короткое объяснение ДЛЯ МОДЕЛИ — то, чего в наших текстах нет.
    ///
    /// ⚠️ ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ В САМИХ ТЕКСТАХ ОШИБОК. Тексты ошибок читают ДВОЕ,
    /// и читают по-разному: человек в переписке и модель следующим ходом. Человеку
    /// нужна правда и вежливость («файл изменился, пока вы смотрели предпросмотр»),
    /// модели — приказ («перечитай файл и повтори по свежим номерам»). Впиши приказ
    /// в текст ошибки — и человек прочитает в своей ленте команду, обращённую не к нему.
    /// Поэтому лента получает исходную фразу, а модель — её же плюс одну строку дела.
    ///
    /// ⚠️ Меняем ТОЛЬКО тело, уходящее модели (`payload`). `userSummary` не трогаем
    /// ни на знак: он уже показан человеку, и переписывать показанное нельзя.
    private func explained(_ result: ToolResult) -> ToolResult {
        guard result.outcome == .failed,
              case .fields(var values) = result.payload,
              let reason = values["error"], !reason.isEmpty else { return result }

        // Отказ, который мы завернули сами (кривой вызов, отказ человека), уже с приказом.
        guard !reason.hasPrefix(AgentPrompt.failureNoticePrefix),
              !reason.hasPrefix(AgentPrompt.writeFailedNoticePrefix) else { return result }

        // Пропала папка или кончилась память разговора — там задача останавливается
        // совсем, и звать модель «повтори» было бы обманом: повторять некуда.
        if isFolderGone(result) { return result }
        if case .contextFullForFile = result.failure { return result }

        // ⚠️ ПЯТЬ ОТКАЗОВ, У КОТОРЫХ СВОЙ ТЕКСТ ДЛЯ МОДЕЛИ, И ОБЩАЯ ПРИПИСКА
        // «исправь и попробуй ещё раз» ИМ ВРЕДИТ. Общая приписка означает «повтори
        // тот же вызов» — а здесь повторять ровно нельзя: путаница файла с папкой
        // повторится точно так же, нескачанный файл не приедет от повтора, слишком
        // большой не уменьшится, а безответный уже съел полминуты. Каждому из них
        // нужен СВОЙ следующий шаг, названный по имени действия.
        if let own = Self.ownAdvice(for: result.failure) {
            values["error"] = own
            return result.withPayload(.fields(values))
        }

        // ⚠️ Имя инструмента берём из ответа модели, а она пишет его как придётся
        // («WriteFile», «write_file()»), поэтому опознаём через реестр, а не сравнением
        // строк: иначе правка, названная моделью по-своему, получила бы общую подсказку
        // вместо той единственной, ради которой всё и затевалось.
        let asked = ToolInvocation(rawName: result.toolName, callID: "", arguments: [:])
        let isWrite = registry.tool(for: asked)?.kind == .writeFile
        values["error"] = isWrite ? AgentPrompt.writeFailedNotice(reason)
                                  : AgentPrompt.failureNotice(reason)
        return result.withPayload(.fields(values))
    }

    // MARK: - Тихий перезапуск разговора

    /// Пора ли закрыть разговор и открыть новый, чтобы освободить место.
    ///
    /// ⚠️ ВСЕ ЧИСЛА ЗДЕСЬ — ОТ ПОТОЛКА, КОТОРЫЙ ВЫДАЛ ДВИЖОК, а не от нашей константы.
    /// Потолок теперь не один (движок пробует увеличенное окно и может отступить),
    /// и порог, посчитанный от 4096, на выданных 8192 означал бы «свернуть память,
    /// когда занята едва половина» — то есть выбросить ровно то, ради чего окно и поднимали.
    private func shouldRestartConversation(used: Int, result: ToolResult) -> Bool {
        // Освобождать нечего — перезапуск только заплатит инструкцией и описаниями заново.
        guard history.reclaimableTokens >= AgentLimits.contextReclaimMinTokens else { return false }

        let ceiling = contextCeiling

        // Ответ уже не помещается — сворачиваться надо прямо сейчас.
        let needed = used + result.payload.estimatedTokens + replyBudget.headroom(forCeiling: ceiling)
        if needed > ceiling { return true }

        // Или мы подошли к черте, за которой следующая страница файла точно не влезет.
        return used >= replyBudget.restartThreshold(forCeiling: ceiling)
    }

    /// Потолок памяти разговора у ЖИВОГО движка — единственный источник для всех порогов.
    ///
    /// ⚠️ Ноль здесь означает «разговор ещё не начинался, спрашивать было не у кого»
    /// (движок отвечает при `beginSession`). Считать пороги от нуля нельзя — они уехали бы
    /// в минус и мы сворачивали бы разговор до первого слова. В этот момент честнее всего
    /// безопасное дно: именно на нём приложение и работает, пока не доказано большее.
    private var contextCeiling: Int {
        snapshot.contextLimitTokens > 0 ? snapshot.contextLimitTokens : AgentLimits.contextTokenBudget
    }

    /// Закрыть разговор и продолжить задачу в новом, унеся свежий результат с собой.
    ///
    /// ⚠️ ЭТО НЕ `reset()`, И ПУТАТЬ ИХ НЕЛЬЗЯ. `reset()` выбрасывает все показанные диффы
    /// (`discardAllPreviews`) — сделай так здесь, и карточка, над которой стоит человек,
    /// перестанет применяться. Хранилище предпросмотров от разговора с движком не зависит,
    /// поэтому перезапуск для него безопасен ровно до тех пор, пока его не трогают руками.
    ///
    /// Ядро продукта тут ни при чём: подтверждения, дифф и кнопка «Применить» работают
    /// как работали — меняется только то, что помнит модель.
    private func restartConversation(carrying result: ToolResult, runID: Int) async -> ModelTurn? {
        await runtime.endSession()
        sessionStarted = false
        forgetReadPages()

        // Сворачиваем всё, что можно, ПЕРЕД пересылкой: в новый разговор поедет журнал
        // шагов и следы вида «(ранее читал строки 1–66 файла …)», а не сами страницы.
        history.compact()
        // Карточка-перенос: задача, что уже сделано, что видели в папке, открытый вопрос
        // и две последние реплики. Задача в неё не дублируется — инструкцию мы тут же
        // пересобираем со свежей строкой «Цель:» (ниже), и платить за неё дважды незачем.
        let recap = history.handoffCard(dropLastToolEntry: true, goalAlreadyStated: focusTask)

        // Новый разговор — единственный момент, когда инструкцию можно обновить.
        // Пересобираем её со свежей целью: пересказ короткий и задачу человека
        // вполне может не донести, а вот эта строка донесёт её всегда.
        //
        // ⚠️ А ЗАМЕТКУ О ПРОЕКТЕ ВТОРОЙ РАЗ НЕ ВЕЗЁМ. Мы попали сюда потому, что память
        // разговора кончилась; платить её последними тремя сотнями токенов за пересылку
        // текста, который модель уже читала в этой же задаче, — самое дорогое, что можно
        // тут сделать. Место заметки занимает карточка-перенос ниже.
        refreshSystemPrompt(carryingProjectNote: false)

        do {
            try await runtime.beginSession(systemPrompt: currentSystemPrompt(),
                                           tools: registry.declarations)
        } catch {
            if !isStale(runID) { handle(error) }
            return nil
        }
        sessionStarted = true
        needsSessionRestart = false
        history.rebaseAfterRestart()
        if isStale(runID) { return nil }

        // Человеку — одна честная строка вместо необъяснимой паузы на несколько секунд.
        // Пишем её КАЖДЫЙ раз: каждая такая пауза настоящая, и молчать о ней нельзя.
        append(.system, Self.conversationFoldedNotice)
        // И помечаем сам момент: по этой пометке полоска памяти в чате меняет цвет
        // и подписывается «переписку свернул». Без неё счётчик просто падал с почти
        // полного до пустого, и это выглядело как сбой, а не как объяснение.
        snapshot.contextFoldedAt = Date()

        // Спрашиваем движок заново: сколько занял свежий разговор на самом деле.
        // Если страница не помещается даже в пустой разговор — честно скажем об этом,
        // тем же путём, что и раньше.
        let occupiedAfterRestart = (await runtime.usedTokens()) ?? 0
        let freshUsed = occupiedAfterRestart + ConversationHistory.estimateTokens(recap)
        if isStale(runID) { return nil }
        // Полоска обязана опустеть В ТУ ЖЕ СЕКУНДУ, что и появилась строка о сворачивании:
        // иначе рядом со словами «свернул переписку» ещё целый ход висело бы старое,
        // почти упёршееся число — и строка выглядела бы враньём. Отдельного вопроса
        // движку это не стоит: берём то же число, что посчитали для подрезки.
        snapshot.contextUsedTokens = occupiedAfterRestart
        // ⚠️ И служебное замеряем ЗАНОВО, а не переносим прежнее. Свёрнутый разговор
        // начинается с той же шапки — инструкция и описания действий оплачиваются второй
        // раз, третий, четвёртый. В живых переписках на это уходило до 2 418 токенов
        // из 4 096. Полоска обязана это показывать, иначе повторная плата невидима.
        snapshot.contextBaselineTokens = occupiedAfterRestart
        // Здесь строку цели к ответу НЕ приписываем: инструкцию мы только что
        // переслали заново, и цель в ней свежая. Второй раз — лишние токены.
        // А вот объяснение неудачи приклеиваем и тут: иначе правка, не легшая ровно
        // в тот ход, когда кончилась память, уехала бы в новый разговор молчаливым
        // отказом — и модель повторила бы её слово в слово.
        let outgoing = fitToContext(explained(result), used: freshUsed)

        // ⚠️ Ответ инструмента можно слать ТОЛЬКО в ответ на вызов инструмента, а новый
        // разговор ни о каком вызове не знает — движок такой ход не примет. Поэтому
        // свежий результат уходит обычным сообщением, как служебные напоминания.
        do {
            let turn = try await runtime.send(userText: Self.continuation(recap: recap, result: outgoing))
            if isStale(runID) { return nil }
            return turn
        } catch {
            if !isStale(runID) { handle(error) }
            return nil
        }
    }

    /// Первое сообщение нового разговора: что было раньше и что только что вышло.
    private static func continuation(recap: String, result: ToolResult) -> String {
        var text = ""
        if !recap.isEmpty {
            text += "Переписку свернули, чтобы хватило памяти. Что было:\n\(recap)\n\n"
        }
        text += "Свежий результат \(result.toolName):\n\(result.payload.plainText)\n\n"
        text += "Продолжай задачу: один вызов действия."
        return text
    }

    /// Подрезает ответ инструмента, если он не влезает в остаток кэша разговора.
    ///
    /// Зачем это здесь, а не в подрезке нашей ленты: ConversationHistory.compact()
    /// подрезает ТОЛЬКО нашу локальную ленту и на кэш живого разговора движка не влияет
    /// вообще, а перезапуск разговора применяется лишь к СЛЕДУЮЩЕЙ задаче. Значит внутри
    /// текущей задачи единственная честная защита — спросить движок, сколько занято,
    /// и не отправлять то, что заведомо не поместится.
    /// `used == nil` — движок не ответил; тогда идём по грубой оценке от бюджета.
    private func fitToContext(_ result: ToolResult, used: Int?) -> ToolResult {
        let occupied = used ?? 0
        // Остаток считаем от ВЫДАННОГО потолка: на увеличенном окне прежняя константа
        // отрезала бы у человека половину места, которое движок на самом деле дал.
        let ceiling = contextCeiling
        let remaining = ceiling
            - occupied
            - replyBudget.headroom(forCeiling: ceiling)
        // Совсем впритык — оставляем хотя бы минимум, иначе модель не поймёт, что случилось.
        let allowance = max(256, remaining)

        guard result.payload.estimatedTokens > allowance else { return result }

        // ⚠️ СОДЕРЖИМОЕ ФАЙЛА НЕ РЕЖЕМ НИКОГДА. Приписку «текст обрезан, не переписывай
        // файл целиком» модель на 2 млрд параметров игнорирует и присылает write_file
        // с обрезанным содержимым — то есть предлагает снести невидимый ей хвост файла.
        // Единственный барьер после этого — внимательность человека, а на это
        // рассчитывать нельзя. Честно отвечаем, что памяти разговора не хватило.
        if result.outcome == .success, result.payload.carriesFileContent {
            needsSessionRestart = true
            let path = fileName(in: result)
            // ⚠️ СОДЕРЖИМОЕ МЫ ТОЛЬКО ЧТО ВЫБРОСИЛИ — ЗНАЧИТ И ПОМЕТКА «МОДЕЛЬ ЭТО ВИДЕЛА»
            // СТАЛА ЛОЖЬЮ. Инструмент чтения ставит её у себя, ещё не зная, доедет ли текст;
            // решаем это здесь. Не сними мы пометку — на повторную просьбу модель получила бы
            // «строки 1–66 ты уже видел» и была бы отправлена на 67-ю, то есть начало файла
            // стало бы недостижимым до конца задачи. Ровно этот круг ловили 10.08.2026.
            undoLastReadNote(path: path)
            return result.withPayload(.fields([
                "error": PocketAgentError.contextFullForFile(path).errorDescription
                    ?? "Файл не помещается в память разговора.",
                "hint": AgentPrompt.contextFullHint
            ]))
        }

        return result.withPayload(result.payload.truncated(toApproximately: allowance))
    }

    /// Имя файла из ответа инструмента — только чтобы честно назвать его в ошибке.
    private func fileName(in result: ToolResult) -> String {
        if case .fields(let values) = result.payload, let path = values["path"] {
            return path
        }
        return "файл"
    }

    /// Сколько ждём ответа от безобидного действия (список, чтение), прежде чем
    /// признать его безответным.
    ///
    /// ⚠️ ЭТОТ СТОРОЖ ПОЯВИЛСЯ ПО ЖИВЫМ ПЕРЕПИСКАМ ВЛАДЕЛЬЦА 09.09.2026. Четыре разговора
    /// подряд обрывались на строке «Читаю файл README.md»: за ней не было НИЧЕГО —
    /// 65, 91, 128 секунд тишины, а однажды система убила приложение целиком. Со стороны
    /// это выглядит как «модель ничего не может», хотя модель просто ждала файл.
    /// Само чтение теперь тоже ограничено по времени, но сторож стоит выше и страхует
    /// от ЛЮБОЙ причины — включая те, которых мы ещё не нашли. Приложение не имеет права
    /// молчать бесконечно: не дождались — так и скажем.
    ///
    /// ⚠️ Сторож НЕ ставится на запись файла, и это осознанно: запись уже подтверждена
    /// человеком, она не повторяема, и сказать «не получилось» про правку, которая всё
    /// же легла на диск, — хуже, чем подождать.
    private static let toolAnswerLimit: TimeInterval = 30


    /// Через сколько секунд молчания говорим человеку, что мы живы.
    ///
    /// ⚠️ ВОСЕМЬ, А НЕ ТРИДЦАТЬ, И ЭТО ГЛАВНОЕ. Сторож спасает от вечного зависания,
    /// но полминуты пустого экрана человек всё равно читает как «сломалось» — именно
    /// так владелец и останавливал помощника сам, четыре раза подряд. Одна строка
    /// в ленте стоит дёшево и меняет ощущение целиком: видно, что приложение работает.
    private static let slowActionNotice: TimeInterval = 8

    /// Сказать в ленту, что действие идёт дольше обычного. Успело быстро — строки не будет.
    private func startSlowNotice() -> Task<Void, Never> {
        Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: UInt64(Self.slowActionNotice * 1_000_000_000))
            guard !Task.isCancelled, let self else { return }
            self.append(.system, AgentPrompt.actionIsSlowNotice)
        }
    }

    private func execute(_ tool: any AgentTool,
                         _ invocation: ToolInvocation,
                         watched: Bool = false) async -> ToolResult {
        // ⚠️ СТРОКА «ЖДУ» — ДЛЯ ЛЮБОГО ДЕЙСТВИЯ, А НЕ ТОЛЬКО ДЛЯ ПОДСТОРОЖЕННОГО.
        // Запись сторожем нарочно не ограничена (обрывать подтверждённую человеком
        // правку нельзя), и раньше именно на ней человек оставался бы с пустым экраном
        // дольше всего. Сказать «жду» можно и там, где прервать нельзя.
        let slowNotice = startSlowNotice()
        defer { slowNotice.cancel() }
        do {
            guard watched else { return try await tool.execute(invocation) }
            return try await Self.runWatched(tool: tool,
                                             invocation: invocation,
                                             seconds: Self.toolAnswerLimit)
        } catch is ToolTookTooLong {
            return ToolResult.failure(invocation,
                                      reason: AgentPrompt.toolTookTooLong,
                                      error: .toolTimedOut)
        } catch {
            return ToolResult.failure(invocation, reason: message(for: error))
        }
    }

    /// Выполнить действие с пределом по времени: что вернётся первым — то и ответ.
    ///
    /// ⚠️ Отменить уже начатое чтение мы не можем — оно висит внутри системного вызова.
    /// Но и держать из-за него весь разговор незачем: возвращаем честный отказ, а
    /// застрявшая работа доживает сама и никому больше не мешает.
    /// ⚠️ ГРУППА НАРОЧНО НЕ БРОСАЮЩАЯ, И ЭТО НЕ ПРИДИРЧИВОСТЬ К СТИЛЮ. В бросающей
    /// группе сторож обязан сообщать о себе ошибкой, а второй, проигравший участник —
    /// заснувший таймер — при отмене тоже бросает свою. Стоит этой чужой ошибке
    /// просочиться наружу, и КАЖДОЕ УСПЕШНОЕ чтение превратилось бы в отказ. Проверить
    /// это на телефоне я сейчас не могу, а цена ошибки — сломанное приложение у
    /// владельца. Поэтому результат передаётся значением: бросать тут нечему.

    /// Выполнить действие с пределом по времени: кто ответил первым — тот и ответ.
    ///
    /// ⚠️⚠️ ПОЧЕМУ ЗДЕСЬ НЕ ГРУППА ЗАДАЧ, ХОТЯ ЭТО НАПРАШИВАЕТСЯ. Первая редакция
    /// была на группе, и она НЕ РАБОТАЛА, хотя выглядела правильной: группа перед
    /// выходом ДОЖИДАЕТСЯ всех своих участников, а `cancelAll()` только помечает их
    /// отменёнными. Внутри чтения стоят обычные блокирующие ожидания — они про отмену
    /// не знают и не узнают. То есть сторож честно замечал бы просрочку и всё равно
    /// висел бы ровно столько, сколько висит чтение. Сторож, который не отпускает, —
    /// это не сторож, а украшение.
    ///
    /// Поэтому оба участника запускаются отдельно и НЕ ожидаются: ответ забирает тот,
    /// кто успел первым, проигравший доживает сам и никого не держит. Пропуск следит,
    /// чтобы ответ был отдан ровно один раз.
    /// Тексты подсказок, которые мы этой модели уже отправляли.
    ///
    /// ⚠️ Помним ТЕКСТ, а не счётчик: подсказки у нас разные, и «третья по счёту»
    /// ничего не значит, а «ровно эта, второй раз» значит всё.
    private var sentNudges: Set<String> = []

    /// Занять подсказку: `true` — отправляем впервые, `false` — уже посылали, повторять нельзя.
    private func claimNudge(_ text: String) -> Bool {
        sentNudges.insert(text).inserted
    }

    private nonisolated static func runWatched(tool: any AgentTool,
                                               invocation: ToolInvocation,
                                               seconds: TimeInterval) async throws -> ToolResult {
        let gate = OnceGate()
        return try await withCheckedThrowingContinuation { continuation in
            Task.detached {
                do {
                    let value = try await tool.execute(invocation)
                    if gate.claim() { continuation.resume(returning: value) }
                } catch {
                    if gate.claim() { continuation.resume(throwing: error) }
                }
            }
            Task.detached {
                try? await Task.sleep(nanoseconds: UInt64(seconds * 1_000_000_000))
                if gate.claim() { continuation.resume(throwing: ToolTookTooLong()) }
            }
        }
    }

    // MARK: - Запись результата

    private func record(_ result: ToolResult,
                        for invocation: ToolInvocation,
                        diff: FileDiff?,
                        restorePointID: UUID? = nil) {
        // ⚠️ ЕДИНСТВЕННОЕ МЕСТО, ЧЕРЕЗ КОТОРОЕ ПРОХОДИТ ИТОГ ЛЮБОГО ДЕЙСТВИЯ — поэтому
        // журнал записываем здесь, а не в каждой ветке отдельно: иначе новый инструмент
        // однажды заведут, а записать в журнал забудут. В журнал идёт и то, что увидел
        // человек, и то, что ЦЕЛИКОМ ушло модели: разбирать поломки без второго нельзя —
        // ровно так 10.08.2026 искали причину, по которой помощник ходил по кругу.
        EngineJournal.shared.noteToolResult(result)
        let attached = result.outcome == .success ? diff : nil
        append(.tool, result.userSummary, diff: attached, restorePointID: restorePointID)
        // ⚠️ Тот же приём, что и для вызова: в историю — короткий след, а цена настоящая,
        // по ПОЛНОМУ телу ответа. Именно здесь наш счётчик раньше врал сильнее всего:
        // страница файла уходит модели целиком (~700 токенов), а в истории оседало
        // 300 знаков итога (~150). Три страницы — и разница уже больше половины окна.
        history.append(role: .tool,
                       text: "\(result.toolName): \(ConversationHistory.shorten(result.userSummary, to: 300))",
                       topic: Self.topic(of: result, invocation: invocation),
                       modelTokens: result.payload.estimatedTokens + focusCost(for: result))

        // ⚠️ ИМЕНА ФАЙЛОВ ЗАПОМИНАЕМ ОТДЕЛЬНО ОТ ЛЕНТЫ, И ВОТ ЗАЧЕМ. В памяти разговора
        // от просмотра папки остаётся строка «list_files: Найдено: 8 записей» — сами
        // имена туда не кладутся, они дорогие. Но когда разговор сворачивается, модель
        // остаётся вообще без списка и первым же ходом обходит папку заново: 300…600
        // токенов на восстановление того, что мы только что выбросили. Двадцать имён
        // в карточке-переносе стоят 60…80 и снимают этот повтор.
        if invocation.kind == .listFiles,
           result.outcome == .success,
           case .lines(let listed) = result.payload {
            history.noteFolderListing(path: invocation.path, lines: listed)
            // Толчкам нужен КОНКРЕТНЫЙ файл — берём его отсюда же, из настоящего
            // списка папки, а не выдумываем имя.
            sawFolderListing = true
            if Self.appliesRealUseFixes {
                // ⚠️ ДОПОЛНЯЕМ, А НЕ ЗАТИРАЕМ: модель заглянула в подпапку — и
                // непрочитанные файлы корня исчезли бы из подсказок насовсем.
                for file in Self.readableFiles(among: listed, insideFolder: invocation.path)
                where !listedFiles.contains(file) {
                    listedFiles.append(file)
                }
            }
        }

        // Приложение ведёт строку «сейчас делаю» само: работа идёт над тем файлом,
        // который агент только что тронул. Модель на это никак не влияет.
        let touched = invocation.path.trimmingCharacters(in: .whitespacesAndNewlines)
        if !touched.isEmpty { focusSubject = touched }

        switch result.outcome {
        case .success:
            invalidTurnStreak = 0
            didAnythingSucceed = true
            // Факт, по которому потом ловится «рассказал о проекте, не читая»:
            // отмечаем только НАСТОЯЩЕЕ чтение файла, список папки чтением не считается.
            if invocation.kind == .readFile {
                didReadAnyFile = true
                didReadThisTurn = true
                readFiles.insert(normalizedPath(invocation.path))
                // ⚠️ СНИМАЕМ ПРИЗНАК «ПРОСИЛИ ФАЙЛ, КОТОРОГО НЕТ» НА ПЕРВОМ ЖЕ УДАЧНОМ
                // ЧТЕНИИ. Он заведён ради одного случая: человек назвал несуществующий
                // файл, и честный ответ — сказать об этом, а не идти читать полпапки.
                // Но снимался он только при полном сбросе разговора — то есть ОДИН
                // промах по имени глушил раннюю подсказку до самого конца, включая
                // все следующие задачи того же разговора, где промаха уже не было.
                didHitMissingFile = false
            }
            // Ходит по папкам — считаем; открыл файл — счёт обнуляем.
            listsWithoutRead = invocation.kind == .listFiles ? listsWithoutRead + 1 : 0
            // А этот признак живёт ровно один ход: он нужен следующей фразе модели,
            // чтобы отличить пересказ только что прочитанного от отговорки.
            lastStepWasRead = invocation.kind == .readFile
            // Получилось — значит прежние неудачные подходы к этому месту в памяти
            // держать незачем: они уже ни на что не влияют, а место занимают.
            history.noteAttemptSucceeded()
        case .failed:
            if case .fileNotFound = result.failure { didHitMissingFile = true }
            // «Файл изменился снаружи» — не кривой ход модели, а изменившийся мир.
            // Наказывать её за это счётчиком нельзя: два таких случая подряд
            // останавливали задачу совсем, хотя модель ни при чём.
            // ⚠️ И ЕЩЁ ДВА ОТКАЗА, ЗА КОТОРЫЕ НАКАЗЫВАТЬ НЕ ЗА ЧТО. «Это файл, а не
            // папка» и «это папка, а не файл» несут в себе ГОТОВЫЙ ВЫХОД: там прямо
            // сказано, чем позвать вместо. Живая переписка владельца 09.09.2026: три
            // таких подряд (BIBLE.md, build_linux.sh, build_windows.ps1) — и задача
            // умерла как «два неверных действия», хотя ломалось приложение, а не модель.
            // Текст мы починили; осталось перестать за него казнить.
            if !result.isFileChangedSinceDiff,
               !Self.isNamingMixUp(result.failure),
               !Self.isNotOurFault(result.failure) {
                invalidTurnStreak += 1
            }
            lastStepWasRead = false
            // ⚠️ А вот схлопывание тут ОДИНАКОВОЕ для обоих случаев, и это не оплошность:
            // длинный текст ошибки бесполезен в памяти независимо от того, кто виноват.
            history.noteAttemptFailed(what: Self.attemptLabel(invocation))
        case .rejectedByUser:
            lastStepWasRead = false
        }
        noteContextPressure()
    }

    /// Разговор подошёл к пределу контекста: подрезаем историю и помечаем,
    /// что следующую задачу начнём новым разговором с пересказом.
    ///
    /// ⚠️ Смотрим на РЕЗУЛЬТАТ сворачивания. Когда сворачивать уже нечего (всё защищено:
    /// системная инструкция, последний результат инструмента, хвост разговора),
    /// прежний код всё равно ставил пометку и писал в ленту «Переписка стала длинной…» —
    /// и повторял это после КАЖДОГО следующего шага. Выглядело как поломка.
    ///
    /// ⚠️ Про схлопывание устаревшего человеку НЕ говорим вообще, и это осознанно:
    /// схлопывание ничего не теряет (модель видит след «(ранее читал …)» и при нужде
    /// перечитает), а лента человека не беднеет ни на строку. Сообщать не о чем.
    private func noteContextPressure() {
        // ⚠️ Смотрим на то, сколько занято У ДВИЖКА, а не на длину нашей ленты.
        // Раньше сравнивали с бюджетом короткие следы («read_file: показаны строки…»)
        // и потому не замечали, что кэш движка уже забит страницами файлов целиком.
        if history.engineTokens >= AgentLimits.contextRestartThreshold(forCeiling: contextCeiling) {
            needsSessionRestart = true
        }

        guard history.needsCompaction else { return }
        let didFold = history.compact()
        needsSessionRestart = true

        guard didFold, !didWarnAboutTrim else { return }
        didWarnAboutTrim = true
        append(.system, Self.historyFoldedNotice)
    }

    // MARK: - Тема и цена хода (что можно будет выбросить потом)

    /// Про что был вызов модели. Знать это надо заранее: когда запись применят
    /// или отклонят, мы по теме найдём её и заменим одной строкой.
    private static func topic(of invocation: ToolInvocation) -> ConversationHistory.Topic {
        guard invocation.kind == .writeFile else { return .plain }
        return .fileWrite(path: invocation.path, lines: lineFragment(of: invocation))
    }

    /// Про что был ответ инструмента. Отказы темы не получают: заменять их нечем
    /// и незачем — они и так короткие.
    private static func topic(of result: ToolResult,
                              invocation: ToolInvocation) -> ConversationHistory.Topic {
        guard result.outcome == .success, let kind = invocation.kind else { return .plain }
        switch kind {
        case .readFile:
            return .fileRead(path: invocation.path, lines: shownLines(of: result))
        case .listFiles:
            return .folderList(path: invocation.path)
        case .writeFile, .finish, .webSearch:
            return .plain
        }
    }

    /// Сколько токенов ход модели занял в кэше движка. Считаем по аргументам целиком —
    /// в них и лежит весь новый текст файла, ради которого всё это и затевалось.
    private static func callTokens(_ invocation: ToolInvocation) -> Int {
        var total = ConversationHistory.estimateTokens(invocation.rawName)
        for (key, value) in invocation.arguments {
            total += ConversationHistory.estimateTokens(key)
            total += ConversationHistory.estimateTokens(value)
        }
        return total
    }

    /// «12–18» — какие строки файла тронул вызов. Пусто — про строки речи не было.
    private static func lineFragment(of invocation: ToolInvocation) -> String {
        guard let from = invocation.rawFromLine?.trimmingCharacters(in: .whitespaces),
              !from.isEmpty else { return "" }
        let to = invocation.rawToLine?.trimmingCharacters(in: .whitespaces) ?? ""
        return to.isEmpty ? from : "\(from)–\(to)"
    }

    /// «1–66» из оговорки инструмента чтения. Пусто — файл показан целиком
    /// или оглавлением, и номера строк в след не идут.
    private static func shownLines(of result: ToolResult) -> String {
        guard case .fields(let values) = result.payload,
              let shown = values["shown"],
              shown.hasPrefix(Self.shownLinesPrefix) else { return "" }
        let tail = shown.dropFirst(Self.shownLinesPrefix.count)
        if let cut = tail.range(of: " из ") {
            return String(tail[tail.startIndex..<cut.lowerBound])
        }
        return String(tail)
    }

    /// ⚠️ Строку собирает инструмент чтения («строки 1–66 из 221»). Разойдётся с ним —
    /// след потеряет номера строк, но ничего не сломается: будет «(ранее читал файл …)».
    private static let shownLinesPrefix = "строки "

    /// Старые ходы свёрнуты в выжимку — модель помнит, что делала, но не платит за подробности.
    private static let historyFoldedNotice =
        "Переписка стала длинной — старые шаги свернул в короткую выжимку. В ленте всё осталось."

    /// Разговор с моделью пришлось начать заново прямо посреди задачи.
    ///
    /// ⚠️ ЗДЕСЬ ГОВОРИМ И ЧТО ОСТАЛОСЬ, И ЧТО ПРОПАЛО. Прежняя строка обещала
    /// «продолжаю с того же места» и умалчивала о потере — а дальше помощник переспрашивал
    /// про уже прочитанный файл, и со стороны это выглядело как «вдруг всё забыл».
    /// Теперь человек заранее знает: задача и шаги при мне, текст файлов — нет.
    /// Длиннее делать нельзя: это строка в ленте, а не абзац объяснений.
    private static let conversationFoldedNotice =
        "Память разговора кончилась — свернул переписку. Задача и что уже сделано остались "
        + "со мной, текст прочитанных файлов забыт: понадобится — прочитаю заново."

    // MARK: - Управление ходом

    /// Запускает задачу как отменяемую и ждёт её окончания.
    private func startRun(_ body: @escaping @Sendable @MainActor (Int) async -> Void) async {
        activeRunID += 1
        let runID = activeRunID

        let task = Task { @MainActor [weak self] in
            await body(runID)
            self?.clearTask(runID)
        }
        currentTask = task
        await task.value
    }

    private func clearTask(_ runID: Int) {
        if runID == activeRunID { currentTask = nil }
    }

    /// Ход устарел: его отменили или начали новый.
    private func isStale(_ runID: Int) -> Bool {
        runID != activeRunID || Task.isCancelled
    }

    // MARK: - Модель говорит вместо того, чтобы делать

    /// Что сказать модели, если она заговорила вместо работы.
    /// nil — фраза законная: останавливаемся и ждём человека.
    ///
    /// ⚠️ ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. Живая переписка владельца 09.08.2026: на «изучи проект»
    /// модель отвечает «Я готов изучить, укажите действие», на «дай список» — «Я начну
    /// с просмотра папки» и не начинает. Человек четыре раза подряд пишет «И», «Давай».
    /// Модель на 2 млрд параметров вежлива до бесполезности, и уговаривать её должен
    /// не человек, а приложение — оно видит, что действия не было, лучше человека.
    ///
    /// ⚠️ Ядра это не касается ни одной строкой: подталкиваем к list_files и read_file,
    /// которые и так выполняются без спроса. Запись файла как требовала карточку
    /// и нажатие, так и требует.
    private func talkNudge(for text: String,
                           answersFreshRead: Bool) -> (userText: String, modelText: String)? {
        // ⚠️⚠️ РАЗГОВОР ТОЛЧКАМИ НЕ ПОДГОНЯЮТ. Человек спросил «Кто ты» — ответ словами
        // и есть выполненная просьба, а не увиливание. Именно здесь ломалось всё:
        // приложение принимало ответ на вопрос за отговорку и гнало модель читать файлы,
        // к которым человек её не посылал. Толчок остаётся ровно там, ради чего заведён, —
        // когда человека просили сделать что-то с файлами.
        guard !isChatTurn else { return nil }

        // Уговоров на задачу — не больше трёх: дальше это уже спор с моделью,
        // а человек в это время смотрит на крутящийся индикатор. Он всегда должен
        // иметь возможность остановить агента и просто поговорить.
        guard talkNudges < Self.talkNudgeLimit else { return nil }

        // 0. ОБЕЩАНИЕ ПРИСЛАТЬ ФАЙЛ — САМАЯ ПЕРВАЯ ПРОВЕРКА, И ЭТО НЕ СЛУЧАЙНО.
        //
        // ⚠️ Правило «файл человеку отдаёт приложение» раньше висело строкой в постоянной
        // инструкции и стоило 33 токена КАЖДЫЙ ход. Теперь оно уходит модели только когда
        // она действительно пообещала невозможное. Проверка стоит выше поблажки для
        // пересказа прочитанного нарочно: «вот, держите готовый файл» модель говорит
        // как раз в конце длинного содержательного ответа, то есть ровно там, где
        // поблажка ниже вернула бы nil и человек остался бы ждать несуществующую посылку.
        if Self.promisesToSendFile(text) {
            talkNudges += 1
            return (AgentPrompt.promisedToSendFileNotice, AgentPrompt.appHandsFileOver)
        }

        // 1. ПЕРЕСКАЗ ТОЛЬКО ЧТО ПРОЧИТАННОГО — ЭТО РАБОТА, А НЕ ОТГОВОРКА.
        //
        // ⚠️ Самая дорогая ошибка прежней проверки, живая переписка 10.08.2026.
        // Модель читает файл и рассказывает, что в нём, — а в конце вежливо добавляет
        // «если нужно что-то конкретное — дай знать». Слово «конкретн» стоит в списке
        // отговорок, и приложение толкало модель дальше ровно за то, ради чего её
        // и звали. Три файла, три толчка, и в конце — ложное «осталась на месте».
        // Признак берём делом: прошлый шаг был удачным чтением, а ответ длинный, то есть
        // в нём есть содержимое, а не одна фраза. Короткая отписка сюда не попадает.
        if answersFreshRead, text.count > Self.substantialAnswerCharacters { return nil }

        // 1б. «ТАКОГО ФАЙЛА НЕТ» — ЭТО ВЫПОЛНЕННАЯ ПРОСЬБА, А НЕ ОТГОВОРКА.
        //
        // ⚠️ Живой прогон 08.09.2026: человек просит todo.md, файла нет, помощник
        // честно об этом говорит и перечисляет, что есть, — и получает толчок за
        // вежливую концовку «если вы имели в виду другой файл…». Дальше он от
        // послушности перечитывает всю папку: одиннадцать шагов вместо двух.
        // Требовать от него «сделай шаг» тут не за что: сделать нечего, файла нет.
        if Self.appliesRealUseFixes, didHitMissingFile, Self.saysFileIsMissing(text) {
            return nil
        }

        // 2. Настоящий выбор из НАЗВАННЫХ вариантов — законная остановка.
        //
        // ⚠️ ПЛАНКА ПОДНЯТА ПОСЛЕ ЖИВОГО ПРОГОНА 09.08.2026. Раньше вопрос сохранял
        // остановку, если в нём было «какой», «который» или «что именно», — и модель
        // обошла правило по-честному: писала абзац рассуждений и кончала его словами
        // «Что именно вы хотите, чтобы я изучил?». Цикл вставал, человек в третий раз
        // писал одну и ту же задачу. Теперь вопрос останавливает, только если модель
        // УЖЕ что-то сделала и предлагает выбор между названными вариантами («…a.swift
        // или b.swift?»). Всё остальное — «уточните задачу» — отговорка, а не вопрос.
        // ⚠️ ГЕЙТ ПО ЧТЕНИЮ, А НЕ ПО «ХОТЬ ЧТО-ТО ПОЛУЧИЛОСЬ». Просмотр папки тоже
        // «получился», и на нём модель выскакивала из ВСЕХ проверок разом: «Я прочитал
        // содержимое файлов. Посмотреть config.json или main.py?» — законная остановка,
        // враньё в первой половине фразы никто уже не смотрел.
        let choiceIsHonest = Self.appliesRealUseFixes ? didReadAnyFile : didAnythingSucceed
        if choiceIsHonest, Self.offersRealChoice(text) { return nil }

        // 3. ⚠️⚠️ ЗАЯВИЛА, ЧТО ЧИТАЛА, А ЧТЕНИЯ НЕ БЫЛО. САМАЯ ВЕРХНЯЯ СЛОВЕСНАЯ ПРОВЕРКА.
        //
        // Живая переписка владельца 07.09.2026, третий ход: на «прочитай файлы и скажи
        // что там» модель ответила «Я прочитал содержимое файлов…» и пересказала их
        // ПО ИМЕНАМ, не сделав ни одного вызова. Раньше этот ответ сюда даже не доходил:
        // он вежливо кончался словами «сформулируйте вашу задачу», и первой срабатывала
        // проверка на выпрашивание — модель получала «не проси уточнений» вместо
        // «ты не читал». Порога по длине тут нет нарочно: «Файлы прочитаны» — четырнадцать
        // знаков, а вреда от такой фразы столько же, сколько от абзаца.
        if Self.appliesRealUseFixes, !didReadAnyFile, Self.claimsHavingRead(text) {
            talkNudges += 1
            return (AgentPrompt.claimedReadingNotice,
                    AgentPrompt.claimedReadButDidNot(file: suggestedFileToRead, sawFolder: sawFolderListing))
        }

        // 3б. РАССКАЗЫВАЕТ О ФАЙЛЕ, КОТОРОГО НЕ ОТКРЫВАЛА, — ХОТЯ ДРУГИЕ ЧИТАЛА.
        //
        // ⚠️ САМЫЙ КОВАРНЫЙ СЛУЧАЙ, И ПРОВЕРКА ВЫШЕ ЕГО НЕ ЛОВИТ. «Читала ли она
        // хоть что-нибудь» после первого же честного чтения молчит до конца разговора,
        // а врать модель начинает как раз дальше: один файл открыт по-настоящему,
        // а рассказ идёт про все пять. Здесь спрашиваем не «читала вообще», а
        // «читала ЭТОТ» — и называем ровно тот файл, о котором она сочиняет.
        if Self.appliesRealUseFixes, let invented = inventedFile(in: text) {
            talkNudges += 1
            return (AgentPrompt.toldAboutUnreadFileNotice,
                    AgentPrompt.toldAboutUnreadFile(invented))
        }

        // 4. РАССКАЗЫВАЕТ О ПРОЕКТЕ, НЕ ОТКРЫВ НИ ОДНОГО ФАЙЛА.
        //
        // ⚠️ ПОДНЯТО ВЫШЕ СЛОВЕСНЫХ ПРОВЕРОК 07.09.2026, И ЭТО ГЛАВНАЯ ПРАВКА ПОРЯДКА.
        // Здесь мы опираемся на ФАКТ (читала или нет), а ниже — на угаданные обороты
        // речи. Факт всегда вернее догадки по словам, значит и спрашивать его надо
        // первым. Живой случай: модель перечислила файлы, описала каждый по имени
        // и закончила «Что именно вас интересует?» — срабатывала проверка на
        // выпрашивание, и модель слышала «не проси уточнений» вместо единственно
        // полезного «открой файл». Три хода уговоров и ноль чтений.
        // ⚠️ И РОВНО ОДНО ИСКЛЮЧЕНИЕ — ВОПРОСЫ-ПЕРЕСЧЁТЫ. На «сколько тут файлов» и
        // «перечисли, что лежит» правильный ответ — это перечисление имён: оно всегда
        // длиннее восьмидесяти знаков и всегда без единого чтения. Без этой оговорки
        // помощник, сделавший ровно то, о чём просили, получал бы подряд толчки
        // «открой файл, по именам не суди», а человек читал бы в ленте, что помощника
        // одёргивают за верно выполненную работу.
        // ⚠️ «НЕ ЧИТАЛ» СЧИТАЕТСЯ ДВУМЯ СПОСОБАМИ, И ВТОРОЙ ДОБАВЛЕН 10.09.2026.
        // Первый — за весь разговор не открыто ни одного файла. Второй — человек
        // ПРЯМО СЕЙЧАС попросил прочитать, а в этом ходу не открыто ничего: старое
        // чтение двухходовой давности его просьбу не закрывает. Без второго условия
        // задача «Окей, прочитай файлы и скажи что там» проваливалась 3 раза из 3.
        if Self.appliesRealUseFixes, !asksForCount,
           !didReadAnyFile || (wantsFileRead && !didReadThisTurn),
           text.count > Self.substantialAnswerCharacters {
            talkNudges += 1
            return (AgentPrompt.judgedWithoutReadingNotice,
                    AgentPrompt.readBeforeJudging(file: suggestedFileToRead, sawFolder: sawFolderListing))
        }

        // 5. Просит уточнить уже названную задачу.
        if Self.asksToClarify(text) {
            talkNudges += 1
            return (AgentPrompt.askedToClarifyNotice,
                    AgentPrompt.stopAskingStartWorking(file: suggestedFileToRead, sawFolder: sawFolderListing))
        }

        // ⚠️⚠️ РАБОТА СДЕЛАНА И ОТВЕТ ДАН — БОЛЬШЕ НЕ ТОЛКАЕМ. Правка по замеру
        // 09.09.2026, и вот что было в ленте. На «Расскажи про проект этот» помощник
        // прочитал README и дал верный, подробный ответ про проект — а в конце вежливо
        // предложил помощь дальше. Слово из этого предложения попало в список оборотов
        // «собирается, но не делает», и приложение одёрнуло его: «сделай шаг, а не
        // рассказывай». Он пошёл читать ещё файлы, которых никто не просил.
        // Разница с настоящей отговоркой ровно одна и она проверяется фактом: там
        // модель НЕ ЧИТАЛА НИЧЕГО и предлагала вместо работы поговорить, здесь работа
        // сделана и рассказана. Вежливость в конце выполненной работы — не отговорка.
        if Self.appliesRealUseFixes, didReadAnyFile,
           text.count > Self.substantialAnswerCharacters,
           !Self.asksToClarify(text) {
            return nil
        }

        // 4. Собирается что-то сделать или выпрашивает разрешение — значит, пусть делает.
        // ⚠️ Идёт ПЕРЕД поблажкой для коротких вопросов ниже: «Что дальше?» — как раз
        // короткий вопрос, и именно его человек читал четыре раза подряд.
        if Self.begsOrAnnounces(text) {
            talkNudges += 1
            return (AgentPrompt.talkedInsteadOfActingNotice,
                    AgentPrompt.actInsteadOfTalking(
                        file: Self.appliesRealUseFixes ? suggestedFileToRead : "",
                        sawFolder: Self.appliesRealUseFixes && sawFolderListing))
        }

        // Прежнее место проверки «рассказывает, не открыв ни одного файла»: в плече
        // «до» она обязана стоять ровно здесь, ПОСЛЕ словесных, — иначе мы сравнивали
        // бы не с тем, что было у владельца на телефоне.
        if !Self.appliesRealUseFixes, !didReadAnyFile,
           text.count > Self.substantialAnswerCharacters {
            talkNudges += 1
            return (AgentPrompt.judgedWithoutReadingNotice, AgentPrompt.readBeforeJudging())
        }

        // 6. Короткая живая реплика с вопросом («Чем помочь?») — не отговорка, а разговор.
        if text.count <= 60, text.hasSuffix("?") { return nil }

        // 7. Объявила работу сделанной — либо соврала, либо пора закрывать задачу.
        if Self.claimsWorkDone(text) {
            talkNudges += 1
            // ⚠️ СМОТРИМ НА ВЕСЬ РАЗГОВОР, А НЕ НА ОДНУ ЗАДАЧУ. Замер 09.09.2026:
            // человек написал «Ну?», помощник ответил «Я прочитал BIBLE.md и вывел
            // его содержимое» — ЧИСТАЯ ПРАВДА, файл он читал ходом раньше, — и получил
            // «сказал, что сделал, — на самом деле нет». Признак «хоть что-то удалось»
            // обнуляется на каждой фразе человека, а память о чтении живёт весь
            // разговор; ложное обвинение во вранье хуже пропущенного.
            if didAnythingSucceed || didReadAnyFile {
                // Работа была — значит осталось закрыть задачу итогом, а не начинать снова.
                return (AgentPrompt.finishInsteadOfTalkingNotice, AgentPrompt.callFinishNow)
            }
            return (AgentPrompt.claimedWorkNotDoneNotice, AgentPrompt.claimedWorkNotDone)
        }
        return nil
    }

    /// Возражение на finish, если закрывать задачу ещё рано. nil — итог принимаем.
    private func finishObjection(_ invocation: ToolInvocation) -> (userText: String, modelText: String)? {
        // В разговоре закрывать нечего: человек спросил, модель ответила. Требовать
        // от неё «сначала сделай, потом отчитывайся» тут не за что.
        if isChatTurn { return nil }
        if !didAnythingSucceed {
            return (AgentPrompt.claimedWorkNotDoneNotice, AgentPrompt.finishWithoutWork)
        }
        // Итог с рассказом о содержимом, а файлов никто не открывал.
        // ⚠️ Кроме вопросов-пересчётов: там перечисление имён и ЕСТЬ верный ответ.
        if !asksForCount,
           !didReadAnyFile || (Self.appliesRealUseFixes && wantsFileRead && !didReadThisTurn),
           invocation.summary.count > Self.substantialAnswerCharacters {
            return (AgentPrompt.judgedWithoutReadingNotice,
                    AgentPrompt.readBeforeJudging(file: suggestedFileToRead, sawFolder: sawFolderListing))
        }
        return nil
    }

    /// Сколько раз за задачу приложение подталкивает модель к действию.
    private static let talkNudgeLimit = 3
    /// Длиннее этого ответ считаем содержательным рассказом, а не репликой в разговоре.
    private static let substantialAnswerCharacters = 80

    /// Вопрос с НАЗВАННЫМИ вариантами: «main.swift или app.swift?».
    /// Простое «какой файл?» сюда не попадает — это работа модели, а не человека.
    private static func offersRealChoice(_ text: String) -> Bool {
        guard text.contains("?") else { return false }
        return text.lowercased().contains(" или ")
    }

    /// Просьба уточнить задачу, которую человек уже назвал.
    private static func asksToClarify(_ text: String) -> Bool {
        let lower = text.lowercased()
        for marker in clarifyMarkers where lower.contains(marker) { return true }
        return false
    }

    /// Обещание («я начну», «сейчас прочитаю») или выпрашивание разрешения.
    private static func begsOrAnnounces(_ text: String) -> Bool {
        let lower = text.lowercased()
        for marker in intentMarkers where lower.contains(marker) { return true }
        return false
    }

    /// Обещание отдать файл человеку самой моделью: «отправляю», «прикрепляю», «вот файл».
    ///
    /// ⚠️ ОБОРОТ ОБЯЗАН БЫТЬ ПАРНЫМ — «глагол отправки» И «файл» рядом, а не по
    /// отдельности. Одно только «отправ» сидит в «отправной точке» и в разговоре про
    /// отправку формы, а одно «файл» стоит чуть ли не в каждом ответе агента по файлам.
    /// Ловить их врозь значило бы толкать модель за нормальную работу — ровно та ошибка,
    /// на которой уже обожглись со словом «конкретн».
    private static func promisesToSendFile(_ text: String) -> Bool {
        let lower = text.lowercased()
        guard sendVerbMarkers.contains(where: { lower.contains($0) }) else { return false }
        return sendObjectMarkers.contains(where: { lower.contains($0) })
    }

    /// Глаголы «отдать наружу». «скачай»/«скачать» тут же: модель иногда предлагает
    /// человеку ссылку на скачивание, которой не существует.
    private static let sendVerbMarkers = [
        "отправляю", "отправлю", "отправил", "высылаю", "вышлю", "выслал",
        "присылаю", "пришлю", "прислал", "прикрепляю", "прикреплю", "прикрепил",
        "во вложении", "вложение", "скачайте", "скачать по ссылке", "передаю вам"
    ]

    /// К чему относится обещание. Без этого списка глагол один ничего не значит.
    private static let sendObjectMarkers = ["файл", "документ", "архив", ".md", ".txt", ".swift"]

    /// Файл, о содержимом которого модель говорит, ни разу его не открыв.
    /// nil — таких нет.
    ///
    /// ⚠️ Одного упоминания имени МАЛО: «в папке есть config.json» — это честный
    /// пересказ списка, а не выдумка. Придирка включается только вместе со словами
    /// о содержимом («я прочитал», «содержит», «в нём указано»), то есть ровно там,
    /// где модель выдаёт догадку за прочитанное.
    private func inventedFile(in text: String) -> String? {
        let lower = text.lowercased()
        // ⚠️ ИМЯ ФАЙЛА И ЗАЯВЛЕНИЕ О СОДЕРЖИМОМ ДОЛЖНЫ СТОЯТЬ В ОДНОМ ПРЕДЛОЖЕНИИ.
        // Иначе честный ответ ловится на своей же честности: помощник цитирует README,
        // а внутри README написано «Запуск — из файла src/main.py» — и имя файла,
        // которого он не открывал, оказывается в его сообщении по совершенно
        // законной причине.
        for sentence in Self.sentences(of: lower) {
            guard Self.claimsHavingRead(sentence) || Self.claimsKnowingContents(sentence)
            else { continue }
            for file in listedFiles where !readFiles.contains(normalizedPath(file)) {
                let name = (file.split(separator: "/").last.map(String.init) ?? file).lowercased()
                guard name.count >= 4, sentence.contains(name) else { continue }
                return file
            }
        }
        return nil
    }

    /// Разбить текст на предложения.
    ///
    /// ⚠️ ТОЧКА РАЗДЕЛЯЕТ ПРЕДЛОЖЕНИЯ ТОЛЬКО ПЕРЕД ПРОБЕЛОМ ИЛИ В КОНЦЕ. Внутри
    /// «config.json» она часть имени файла, и резать по ней нельзя: имя разваливалось
    /// на «config» и «json», проверка переставала видеть файл целиком и пропускала
    /// враньё, ради которого заведена.
    private static func sentences(of text: String) -> [String] {
        var result: [String] = []
        var current = ""
        let characters = Array(text)
        for (index, character) in characters.enumerated() {
            let breaks: Bool
            switch character {
            case "\n", ";", ":", "!", "?":
                breaks = true
            case ".":
                let next = index + 1 < characters.count ? characters[index + 1] : " "
                breaks = next == " " || next == "\n"
            default:
                breaks = false
            }
            if breaks {
                if !current.isEmpty { result.append(current) }
                current = ""
            } else {
                current.append(character)
            }
        }
        if !current.isEmpty { result.append(current) }
        return result
    }

    /// Говорит о содержимом файла, не заявляя прямо «я прочитал».
    private static func claimsKnowingContents(_ text: String) -> Bool {
        let lower = text.lowercased()
        for marker in contentClaimMarkers where lower.contains(marker) { return true }
        return false
    }

    /// ⚠️ НЕ private по той же причине — общий список с замером.
    static let contentClaimMarkers = [
        "содержит", "в нём указан", "в нем указан", "в файле указан", "внутри файла",
        "содержимое файла", "в этом файле находится", "файл описывает", "судя по содержимому"
    ]

    /// Модель сообщает, что запрошенного файла нет.
    private static func saysFileIsMissing(_ text: String) -> Bool {
        let lower = text.lowercased()
        for marker in missingFileMarkers where lower.contains(marker) { return true }
        return false
    }

    private static let missingFileMarkers = [
        "не найден", "не нашёл", "не нашел", "нет файла", "файла нет",
        "не удалось найти", "не существует", "отсутствует"
    ]

    /// Модель говорит, что уже читала файлы или знает их содержимое.
    ///
    /// ⚠️ Обороты взяты ДОСЛОВНО из переписки владельца, а не придуманы: именно
    /// такими словами модель врала. Список нарочно узкий — сюда не должно попадать
    /// честное «сейчас прочитаю» и пересказ действительно прочитанного (тот случай
    /// отсекается раньше, признаком didReadAnyFile).
    private static func claimsHavingRead(_ text: String) -> Bool {
        let lower = text.lowercased()
        for marker in readClaimMarkers where lower.contains(marker) { return true }
        return false
    }

    /// ⚠️ НЕ private: этим же списком проверяет замер. Два отдельных списка уже
    /// начали расходиться молча — и это ровно тот способ, которым замер тихо
    /// перестаёт ловить то, ради чего заведён.
    static let readClaimMarkers = [
        "я прочитал", "я прочла", "я прочёл", "я прочел", "прочитал содержимое",
        "прочитав содержимое", "изучил содержимое", "изучил файл", "ознакомился с содержим",
        "ознакомился с файл", "я просмотрел содержимое", "мною были просмотрены",
        "файлы прочитаны", "файл прочитан", "содержимое файлов:", "вот содержимое",
        "я открыл файл", "i have read", "судя по содержимому"
    ]

    /// Файлы папки в том порядке, в каком их разумно открывать.
    ///
    /// ⚠️ Папки и ссылки отбрасываем нарочно: read_file на папке — неудачный ход,
    /// а толчок обязан вести к успеху с первого раза, иначе он хуже молчания.
    /// README идёт первым: на просьбу «расскажи, что это за папка» он и есть ответ.
    /// Служебные файлы с точки в начале (.gitignore и подобные) — последними:
    /// человеку они не интересны, а место в разговоре занимают.
    static func readableFiles(among lines: [String], insideFolder folder: String = "") -> [String] {
        let prefix: String = {
            let clean = folder.trimmingCharacters(in: CharacterSet(charactersIn: " /"))
            return clean.isEmpty ? "" : clean + "/"
        }()
        let files = lines.compactMap { line -> String? in
            guard !line.isEmpty, !line.hasSuffix("/"), !line.contains(" ("),
                  !line.hasPrefix("⚠️"),
                  // Служебная отметка пустой папки — не файл. Без этой строчки толчок
                  // звал открыть файл с именем «(пусто)» и тратил ход впустую.
                  !line.hasPrefix("("),
                  // Файлы, которые приложение само читать запрещает: звать к ним —
                  // гарантированный отказ. Толчок обязан вести к успеху с первого раза.
                  !Self.isProtectedName(line)
            else { return nil }
            // Список подпапки приходит именами внутри неё — путь достраиваем,
            // иначе read_file получит имя, которого в корне нет.
            return line.hasPrefix(prefix) ? line : prefix + line
        }
        func rank(_ name: String) -> Int {
            let last = name.split(separator: "/").last.map(String.init) ?? name
            if last.lowercased().hasPrefix("readme") { return 0 }
            if last.hasPrefix(".") { return 2 }
            return 1
        }
        return files.enumerated()
            .sorted { (rank($0.element), $0.offset) < (rank($1.element), $1.offset) }
            .map(\.element)
    }

    /// Имена, которые приложение отказывается читать (ключи, пароли, настройки сборки).
    /// Список нарочно грубый и с запасом: лишний пропущенный файл стоит ничего,
    /// а толчок к запрещённому файлу стоит целого хода.
    static func isProtectedName(_ path: String) -> Bool {
        let name = (path.split(separator: "/").last.map(String.init) ?? path).lowercased()
        let endings = [".pem", ".key", ".p12", ".keystore", ".jks", ".mobileprovision"]
        if endings.contains(where: { name.hasSuffix($0) }) { return true }
        let words = ["secret", "credential", "password", "token", "id_rsa", ".env"]
        return words.contains { name.contains($0) }
    }

    /// Отчёт о сделанном.
    private static func claimsWorkDone(_ text: String) -> Bool {
        let lower = text.lowercased()
        for marker in doneMarkers where lower.contains(marker) { return true }
        return false
    }

    // ⚠️ Списки нарочно грубые, по кускам слов: точного разбора русского языка тут нет
    // и не нужно. Цена ошибки в обе стороны маленькая — лишний толчок стоит одного
    // хода, пропущенная отговорка стоит человеку слова «давай», написанного в третий раз.
    // Ошибаться безопаснее в сторону «подтолкнуть».
    //
    // ⚠️ И главное: словами ловится не всё. Самое вредное — «рассказал о проекте, не
    // читая» — ловится не списком, а ФАКТОМ (didReadAnyFile). Списки тут вспомогательные.

    /// ⚠️ Ровно те обороты, которыми модель отказывалась работать в живой переписке
    /// владельца. «что именно» и «конкретн» раньше считались признаком осмысленного
    /// вопроса и СОХРАНЯЛИ остановку — теперь наоборот: задача уже названа, и просьба
    /// назвать её ещё раз — отговорка.
    private static let clarifyMarkers = [
        "уточните", "что именно", "конкретн", "не понял", "не поняла",
        "предоставьте", "дайте мне", "что вы хотите", "чего вы хотите",
        "какую задачу", "сформулируйте", "поясните", "объясните", "инструкци"
    ]

    /// ⚠️ Куски слов подобраны так, чтобы НЕ задевать соседние смыслы, и каждая
    /// поблажка тут выстрадана: «готов » с пробелом — иначе ловится «готово» (это уже
    /// отчёт о работе, у него свой ответ); «могу ли» вместо «могу» — иначе ловится
    /// обычное «чем могу помочь».
    private static let intentMarkers = [
        "я готов", "готов ", "начну", "начнём", "начинаю", "приступ", "собираюсь",
        "далее я", "сейчас я", "теперь я", "могу ли", "можно ли", "разреш", "позвол",
        "хотите", "желаете", "если нужно", "давайте",
        "укажите", "скажите", "уточните", "подтвердите", "сообщите", "дайте знать",
        "мне нужно", "жду ", "ожидаю", "что дальше", "что мне",
        "прочитаю", "посмотрю", "запишу", "создам", "исправлю", "сделаю", "изучу"
    ]

    // MARK: - Разговор или задача

    /// Человек заговорил с помощником, а не поставил задачу по файлам.
    ///
    /// ⚠️ ПРАВИЛА ТУТ НАРОЧНО ТУПЫЕ И ДЕШЁВЫЕ — ни одного лишнего хода к модели.
    /// Порядок проверок и есть вся логика, и он выбран так, чтобы ошибиться в сторону
    /// «это задача»: задача — привычное поведение, а вот принять просьбу за болтовню
    /// значило бы не сделать работу, о которой попросили.
    ///
    /// Разговором считаем только короткое сообщение, В КОТОРОМ ЧЕЛОВЕК ОБРАЩАЕТСЯ
    /// К САМОМУ ПОМОЩНИКУ («кто ты», «что умеешь», «привет») и при этом не называет
    /// ни файла, ни действия. Всё остальное — задача, как и раньше.
    static func looksLikeChat(_ text: String, afterFileWork: Bool = false) -> Bool {
        let clean = text.trimmingCharacters(in: .whitespacesAndNewlines)
        // Длинное сообщение — это уже не «привет»: там наверняка есть работа.
        guard clean.count <= chatMessageCharacters else { return false }

        let lower = clean.lowercased()

        // Назван файл или путь — разговором это быть перестало.
        if mentionsFile(lower) { return false }

        // ⚠️ СПРОСИЛИ ПРО ПАПКУ, ПРОЕКТ ИЛИ КОД — ЭТО РАБОТА, ДАЖЕ ЕСЛИ РЯДОМ «ПРИВЕТ».
        //
        // Живой случай 07.09.2026: первая фраза владельца — «Привет что это за папка
        // ваще». Слово «привет» стоит в списке разговорных, приказного глагола в фразе
        // нет — и помощник вежливо поздоровался, а про папку смолчал. Человеку
        // пришлось спрашивать второй раз теми же словами. Здороваться в ответ он
        // по-прежнему будет: на голое «Привет» ни одного из этих слов нет.
        if Self.appliesRealUseFixes {
            for marker in projectMarkers where lower.contains(marker) { return false }
        }

        // Есть приказ-глагол — значит человек просит сделать, а не спрашивает.
        for verb in actionMarkers where lower.contains(verb) { return false }

        // ⚠️ ОБЫЧНЫЙ ВОПРОС БЕЗ ФАЙЛОВ И БЕЗ ПРИКАЗА — ЭТО РАЗГОВОР, А НЕ ЗАДАЧА.
        //
        // Живая переписка 20.08.2026: посреди работы человек спросил «Сколько ехать
        // из Шереметьево до Белоозерского». Ни файла, ни папки, ни глагола — и
        // приложение заводило под это ЗАДАЧУ, после чего гнало модель толчками
        // «не описывай намерения — читай файлы». Человек спрашивал про дорогу,
        // а помощник лез в его код.
        //
        // Проверка стоит ПОСЛЕ слов про папку и проект нарочно: «В каком файле
        // указан порт?» — тоже вопрос, но работа, и он отсеивается выше.
        // ⚠️ ТОЛЬКО ПОКА С ФАЙЛАМИ ЕЩЁ НЕ РАБОТАЛИ. Посреди работы короткий вопрос
        // («а что там ещё есть?») — продолжение задачи, и объявлять его болтовнёй значит
        // отключить на нём все проверки разом, включая проверку на враньё.
        if Self.appliesRealUseFixes, !afterFileWork, isPlainQuestion(lower) { return true }

        // Короткая реплика целиком («ок», «понял», «спасибо») — тоже разговор.
        // ⚠️ Сверяем ЦЕЛИКОМ, а не вхождением: кусок «ок» сидит внутри «блок», «токен»,
        // «окно», и по вхождению обычная задача превратилась бы в болтовню.
        let bare = lower.trimmingCharacters(in: CharacterSet(charactersIn: " .!?…,"))
        if shortReplies.contains(bare) { return true }

        for marker in chatMarkers where lower.contains(marker) { return true }
        return false
    }

