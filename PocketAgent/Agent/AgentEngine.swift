    // MARK: - Возврат применённой правки («Вернуть, как было»)
    //
    // ⚠️⚠️ МОДЕЛЬ ЗДЕСЬ НЕ УЧАСТВУЕТ НИ ОДНОЙ СТРОКОЙ, И ЭТО ГЛАВНОЕ.
    // Ни один вызов ниже не трогает `history` и не зовёт `sendToModel`: возврат
    // не попадает в память разговора вообще. Причины две, и обе важные:
    //   • НАДЁЖНОСТЬ. Прежний текст не сочиняется, а списывается с диска слово в слово.
    //     Попроси мы модель на 2 млрд параметров «верни как было» — получили бы
    //     «похоже на прежнее», то есть тихую потерю кусков файла.
    //   • ЦЕНА. Всё, что попало в память разговора, уходит модели КАЖДЫЙ следующий ход.
    //     Расскажи мы ей про откат — платили бы за него токенами до конца задачи,
    //     а памяти всего 4096.
    //
    // ⚠️ ЗАПИСЬ ПРИ ЭТОМ ИДЁТ ТОЙ ЖЕ ЕДИНСТВЕННОЙ ДОРОГОЙ: показанный человеку дифф →
    // хранилище предпросмотров → write_file со сверкой содержимого файла на диске.
    // Второй двери в файлы человека у продукта не появилось.

    /// «Вернуть, как было»: собираем карточку «до и после». На диск ничего не пишем.
    public func requestUndo(pointID: UUID) async {
        // Возврат — это спокойное решение человека, а не гонка с ходом модели.
        guard !snapshot.isBusy,
              snapshot.pendingAction == nil,
              snapshot.pendingUndo == nil else { return }
        guard let workspace = workspace, let pendingDiffs = pendingDiffs else { return }

        guard let point = RestorePointStore.point(withID: pointID) else {
            append(.system, UndoTexts.textLost)
            refreshUndoAvailability()
            return
        }

        // Прежний текст читается с диска ВНЕ главного потока: это до 256 КБ, и лента
        // не должна замирать в тот самый миг, когда человек нажал кнопку.
        var previousText: String?
        if !point.wasMissing {
            // Читаем до 256 КБ с диска — на файле из облака это те же секунды тишины,
            // что и везде. Человек только что нажал кнопку и смотрит на ленту.
            let slowNotice = startSlowNotice()
            previousText = await Task.detached { RestorePointStore.previousText(of: point) }.value
            slowNotice.cancel()
            guard previousText != nil else {
                // Файл с прежним текстом не прочитался: обещать возврат больше нельзя.
                append(.system, UndoTexts.textLost)
                RestorePointStore.forget(point.id)
                refreshUndoAvailability()
                return
            }
        }

        do {
            // Текст «после» — это либо прежнее содержимое, либо пустота: так человек
            // видит, что именно исчезнет, если правка создавала файл.
            let diff = try workspace.revertDiff(relativePath: point.relativePath,
                                                previousText: previousText ?? "")

            // Файл уже и так в прежнем виде: его вернул сам человек или удалил.
            // Возвращать нечего — и точка эта больше не нужна.
            //
            // ⚠️ У созданного файла вопрос ДРУГОЙ: не «совпадает ли текст», а «есть ли
            // файл вообще». Пустой созданный файл совпадает с пустым текстом побайтово —
            // и по общей проверке мы бы решили, что удалять нечего, оставив его на диске.
            let nothingToDo = point.wasMissing ? diff.isNewFile : diff.isIdenticalToDisk
            if nothingToDo {
                append(.system, UndoTexts.alreadyAsBefore(path: point.relativePath))
                RestorePointStore.forget(point.id)
                refreshUndoAvailability()
                return
            }

            let invocation = ToolInvocation(rawName: ToolKind.writeFile.rawValue,
                                            callID: "",
                                            arguments: ["path": point.relativePath,
                                                        "content": previousText ?? ""])
            // ⚠️ Дифф удаления в хранилище предпросмотров НЕ кладём: писать по нему
            // нечего, а лежи он там — по нему можно было бы записать пустой файл.
            if !point.wasMissing {
                pendingDiffs.put(diff, for: invocation.id)
            }

            let action = PendingAction(invocation: invocation,
                                       preview: .diff(diff),
                                       title: UndoTexts.title(path: point.relativePath))
            snapshot.pendingUndo = PendingUndo(id: point.id,
                                               action: action,
                                               isDeletion: point.wasMissing)
        } catch {
            append(.system, message(for: error))
        }
    }

    /// Человек согласился — вот здесь и происходит запись на диск.
    public func confirmUndo() async {
        guard var undo = snapshot.pendingUndo, !undo.isApplying else { return }
        undo.isApplying = true
        snapshot.pendingUndo = undo

        let pointID = undo.id
        let didRevert = undo.isDeletion
            ? await applyUndoDeletion(undo)
            : await applyUndoWrite(undo)

        snapshot.pendingUndo = nil

        // ⚠️ ТОЧКУ УБИРАЕМ ТОЛЬКО ПОСЛЕ УДАЧИ. Возврат мог не состояться честно —
        // файл изменился после правки, и мы отказались затирать чужую работу.
        // Выброси мы точку и тогда, человек лишился бы возможности вернуться к ней
        // после того, как разберётся с файлом, — то есть наказание за нашу же
        // осторожность.
        if didRevert {
            // Кнопка переходит к предыдущей правке: так человек отступает по одному шагу.
            RestorePointStore.forget(pointID)
            // Файл на диске стал другим — прежние отметки «эти строки модель уже видела»
            // врут. Не забыть их значит на следующую просьбу прочитать файл ответить
            // «ты это уже видел» и показать текст, которого в файле больше нет.
            forgetReadPages()
        }
        refreshUndoAvailability()
    }

    /// Человек передумал.
    public func cancelUndo() async {
        guard let undo = snapshot.pendingUndo else { return }
        // Показанный дифф забираем сразу: от него отказались, а он держит в памяти
        // полную копию файла.
        registry.tool(for: undo.action.invocation)?.discardPreview(for: undo.action.invocation.id)
        _ = pendingDiffs?.take(undo.action.invocation.id)
        snapshot.pendingUndo = nil
        append(.system, UndoTexts.cancelled)
    }

    /// Обычный возврат: кладём прежний текст обратно тем же write_file.
    /// Возвращает true, если файл и правда вернулся.
    private func applyUndoWrite(_ undo: PendingUndo) async -> Bool {
        guard let tool = registry.tool(for: undo.action.invocation) else {
            append(.system, UndoTexts.textLost)
            return false
        }

        let result = await execute(tool, undo.action.invocation)
        switch result.outcome {
        case .success:
            let diff = undo.action.fileDiff
            append(.tool,
                   UndoTexts.restored(path: undo.action.invocation.path,
                                      added: diff?.addedCount ?? 0,
                                      removed: diff?.removedCount ?? 0),
                   diff: diff)
            return true
        default:
            // Самый частый честный отказ: файл успел измениться после правки.
            // Тогда возврат отменяется целиком — молча затирать чужие изменения нельзя.
            append(.system, result.isFileChangedSinceDiff
                   ? UndoTexts.changedSince(path: undo.action.invocation.path)
                   : result.userSummary)
            return false
        }
    }

    /// Возврат созданного файла — это его удаление.
    ///
    /// ⚠️ ЗДЕСЬ ЕДИНСТВЕННОЕ МЕСТО ВО ВСЁМ ПРИЛОЖЕНИИ, ГДЕ ФАЙЛ УДАЛЯЕТСЯ, и удаляется
    /// он только тот, который приложение само же и создало на глазах у человека.
    /// Модели такого действия не дано вовсе — ни инструмента, ни описания.
    ///
    /// ⚠️ Перед удалением содержимое сверяется заново: между показом карточки и нажатием
    /// файл мог измениться (человек дописал его сам, папка догрузилась из облака).
    /// Разошлось — отказываемся: удалить чужую работу молча хуже, чем не удалить ничего.
    private func applyUndoDeletion(_ undo: PendingUndo) async -> Bool {
        let path = undo.action.invocation.path
        guard let workspace = workspace, let shown = undo.action.fileDiff else {
            append(.system, UndoTexts.textLost)
            return false
        }

        do {
            let fresh = try workspace.revertDiff(relativePath: path, previousText: "")
            guard fresh.oldText == shown.oldText else {
                append(.system, UndoTexts.changedSince(path: path))
                return false
            }
            let url = try workspace.resolve(path)
            try FileManager.default.removeItem(at: url)
            append(.tool, UndoTexts.deleted(path: path))
            return true
        } catch {
            append(.system, message(for: error))
            return false
        }
    }

    /// Запомнить прежнее содержимое только что применённой правки.
    /// nil — возврат этой правки мы не обещаем (файл слишком велик, папки нет).
    private func rememberRestorePoint(for action: PendingAction) -> UUID? {
        guard let diff = action.fileDiff,
              let folderPath = snapshot.folder?.url.path else { return nil }
        let point = RestorePointStore.remember(relativePath: diff.relativePath,
                                               folderPath: folderPath,
                                               previousText: diff.isNewFile ? nil : diff.oldText)
        snapshot.undoablePointID = point?.id
        return point?.id
    }

    /// У какой правки сейчас живёт кнопка «Вернуть, как было».
    private func refreshUndoAvailability() {
        guard let folderPath = snapshot.folder?.url.path else {
            snapshot.undoablePointID = nil
            return
        }
        snapshot.undoablePointID = RestorePointStore.latest(inFolder: folderPath)?.id
    }

    // MARK: - Ошибки и лента

    private func handle(_ error: Error) {
        if error is CancellationError {
            snapshot.state = .idle
            return
        }
        if let agentError = error as? PocketAgentError, agentError == .generationCancelled {
            snapshot.state = .idle
            return
        }
        let text = message(for: error)
        // Точная суть — в журнал, чтобы экран мог показать её второй строкой,
        // а кнопка «Скопировать подробности» отдала целиком. В боевой сборке
        // это единственный способ понять, что на самом деле случилось.
        //
        // ⚠️ Но только если движок не записал ЭТУ ЖЕ поломку раньше нас. У него текст
        // библиотеки на руках, а до нас доезжает уже наша русская фраза — перезаписать
        // его запись значит своими руками стереть единственную точную улику.
        if RuntimeJournal.shared.lastFailure?.human != text {
            RuntimeJournal.shared.recordFailure(stage: "ход агента",
                                                human: text,
                                                technical: RuntimeJournal.technicalText(for: error))
        }
        fail(text)
    }

    private func fail(_ text: String) {
        append(.system, text)
        snapshot.state = .failed(message: text)
    }

    /// Текст ошибки для человека. Системные английские фразы сюда не проходят.
    private func message(for error: Error) -> String {
        SystemErrorText.russian(for: error)
    }

    private func append(_ author: ChatAuthor,
                        _ text: String,
                        diff: FileDiff? = nil,
                        restorePointID: UUID? = nil) {
        let clean = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !clean.isEmpty else { return }
        // ⚠️ ОДНА И ТА ЖЕ СЛУЖЕБНАЯ СТРОКА ПОДРЯД — НЕ ПОВТОРЯЕТСЯ. Строка «жду»
        // появляется на каждом медленном действии, а на папке из облака медленным
        // может оказаться каждый шаг: за одну задачу в ленту легло бы два десятка
        // одинаковых фраз. Это ровно тот визуальный мусор, за который владелец ругал
        // 10.08.2026. Настоящие сообщения дублей не образуют — они всегда разные.
        if author == .system, snapshot.messages.last?.text == clean,
           snapshot.messages.last?.author == .system {
            return
        }
        snapshot.messages.append(ChatMessage(author: author,
                                             text: clean,
                                             diff: diff,
                                             restorePointID: restorePointID))
        if snapshot.messages.count > messageLimit {
            snapshot.messages.removeFirst(snapshot.messages.count - messageLimit)
        }
    }

    /// Строка вызова инструмента для истории (в ленту чата не идёт).
    private func describe(_ invocation: ToolInvocation) -> String {
        let arguments = invocation.arguments
            .sorted { $0.key < $1.key }
            .map { "\($0.key)=\(ConversationHistory.shorten($0.value, to: 120))" }
            .joined(separator: ", ")
        return "вызов \(invocation.rawName)(\(arguments))"
    }
}

