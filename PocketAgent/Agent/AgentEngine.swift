//
//  AgentEngine.swift
//  PocketAgent
//
//  Цикл «один шаг — подтверждение». Здесь живёт вся машина состояний агента.
//
//  Как идёт ход:
//    задача человека → модель предлагает ОДНО действие →
//      • list_files / read_file — выполняем сразу (они ничего не портят),
//      • write_file — показываем дифф и ЖДЁМ «Применить» или «Отклонить»,
//      • finish — задача закончена;
//    результат (в том числе отказ и ошибка) возвращается в модель тем же каналом,
//    и она делает следующий шаг. Никакой автономной беготни без человека.
//
//  Три предохранителя:
//    1. Жёсткий предел шагов на задачу (AgentLimits.maxSteps).
//    2. Не больше двух кривых вызовов подряд — потом останавливаемся с понятным текстом.
//    3. Отмена в любой момент: текущая задача снимается, ответ модели прерывается.
//
//  Тип называется AgentSession — так его знают остальные модули (UI и сборка).
//

