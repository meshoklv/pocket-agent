    /// Один и тот же файл, записанный по-разному, — это один файл.
    ///
    /// ⚠️⚠️ БЕЗ ЭТОГО ВСЯ ПОДСКАЗКА «СЛЕДУЮЩИЙ НЕПРОЧИТАННЫЙ» БЕСПОЛЕЗНА. В список
    /// папки ложится путь, каким его выдало приложение («README.md»), а в «прочитано» —
    /// путь, каким его НАПИСАЛА МОДЕЛЬ. А она пишет «sklad-main/README.md» (лишняя
    /// приставка имени папки — самая частая её ошибка, ради неё заведён отдельный
    /// разбор в SafePath), «./README.md», «/README.md», «readme.md». Чтение при этом
    /// проходит, а сравнение строк — нет, и подсказка до конца разговора зовёт
    /// открыть файл, который уже открыт. Человек видит ровно прежнее топтание.
    private func normalizedPath(_ path: String) -> String {
        var value = path.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        while value.hasPrefix("./") { value.removeFirst(2) }
        while value.hasPrefix("/") { value.removeFirst() }
        while value.hasSuffix("/") { value.removeLast() }
        if let folder = snapshot.folder?.displayName.lowercased(), !folder.isEmpty,
           value.hasPrefix(folder + "/") {
            value.removeFirst(folder.count + 1)
        }
        return value
    }
