    /// Имя файла или путь в тексте.
    /// ⚠️ Точку ищем ТОЛЬКО со слипшейся буквой («README.md», «01-кто.md»): точка в конце
    /// фразы («как дела.») именем файла не является, и ловить её нельзя.
    private static func mentionsFile(_ text: String) -> Bool {
        if text.contains("/") { return true }
        return text.range(of: "\\.[a-zа-яё]{1,6}", options: .regularExpression) != nil
    }

