//
//  LiteRTRuntime.swift
//  PocketAgent / Runtime
//
//  Единственная реализация ModelRuntime — и единственное место в проекте (кроме
//  LiteRTToolSchemas.swift), где написано import LiteRTLM. Остальные модули знают
//  только протокол из Contracts.swift.
//
//  Главное решение продукта живёт в одной строке: automaticToolCalling: false.
//  С ним sendMessage НЕ выполняет инструменты сам, а возвращает нам их вызовы —
//  мы показываем человеку предпросмотр и ждём кнопку.
//
//  ⚠️ Ход, на котором модель выбирает инструмент, делается ТОЛЬКО через sendMessage.
//  Стриминговый путь во фреймворке игнорирует automaticToolCalling и выполняет
//  инструменты сам, не отдавая вызовы наружу. Поэтому стриминг вынесен в
//  отдельный протокол PlainTextStreaming и в цикле агента не используется.
//
//  ⚠️ ЛЕСЕНКА НАСТРОЕК — второе решение этого файла, и вот откуда оно взялось.
//  Gemma 4 E4B на телефоне владельца РАБОТАЕТ — в приложении Google, на том же самом
//  iPhone. У нас на любое сообщение библиотека отвечает «Native sendMessage returned null»:
//  внутренний вызов вернул пустоту. Значит дело не в модели и не в телефоне, а в том, чем
//  НАША настройка движка отличается от рабочей. Проверить это отсюда нельзя — телефон
//  один, и он у владельца. Поэтому проверяет само приложение: при первом же неответе оно
//  идёт по лесенке настроек, меняя за раз ровно одну вещь, и каждую ступеньку пишет
//  в журнал. Удачная ступенька запоминается за этой моделью навсегда.
//
//  ⚠️ Порядок ступенек — по убыванию подозрительности и по возрастанию цены. Первые
//  ступеньки пересобирают только разговор (секунды), поздние — весь движок (десяток секунд
//  и гигабайты). Полный проход по лесенке делается ОДИН раз за запуск приложения.
//
//  ⚠️ Ступенька, на которой приложение упало, больше не повторяется НИКОГДА: перед каждой
//  попыткой на диск кладётся метка, и если при следующем запуске она нашлась — значит эта
//  ступенька роняет приложение. Такую ступеньку молча пропускаем.
//
//  ⚠️ ПАМЯТЬ РАЗГОВОРА: СКОЛЬКО ПРОСИТЬ — РЕШАЕТ ЧЕЛОВЕК, А НЕ ЭТОТ ФАЙЛ.
//  Размер выбирается на странице «О программе» (ContextSizeSettings), от 4 096 до 32 000,
//  и движок просто читает выбор. Мы не запрещаем большие значения и не пробуем их тайком:
//  философия проекта — предупреждение, а не запрет. Поедет ли 32 000 на этом телефоне,
//  заранее не знает никто — покажет только живой запуск. Разбор — design notes.
//
//  ⚠️ ИМЕННО ПОЭТОМУ ЗДЕСЬ ЕСТЬ КРАХ-БЕЗОПАСНОСТЬ. Слишком большое окно может закрыть
//  приложение целиком прямо на создании движка. Перед каждым таким вызовом на диск
//  атомарно ложится отметка «прошу столько-то»; уцелела при следующем запуске — значит
//  на этом мы и закрылись. Тогда приложение возвращает безопасные 4 096, ПЕРЕСТАВЛЯЕТ
//  выбор человека на них же и говорит ему об этом строкой на той же странице, где он
//  выбирал. Молчать нельзя: человек решил бы, что настройка не работает.
//
//  Отступаем в трёх случаях, и каждый пишется в журнал: (1) прошлый запуск закрылся
//  с отметкой на диске; (2) движок с этим числом вообще не создался; (3) на нём пришёл
//  пустой или неразборчивый ответ. Поднять число обратно — одно касание.
//

import Foundation
import LiteRTLM

public actor LiteRTModelRuntime: ModelRuntime, PlainTextStreaming, ModelBackendDiagnostics, ModelRuntimeFactsProviding {

    /// Куда пишем события: запуск, выбор расчёта, каждый ход и каждая ошибка.
    ///
    /// ⚠️ В журнал уходят ТОЛЬКО события. Ни текста задачи человека, ни ответа модели,
    /// ни содержимого файлов здесь быть не должно — см. правило приватности
    /// у самого RuntimeJournal.
    ///
    /// ⚠️ ЗДЕСЬ `EngineJournal`, А НЕ `RuntimeJournal`, И ЭТО ОДНА СТРОКА РАДИ ТРЁХ ВЕЩЕЙ.
    /// Имена методов у них совпадают намеренно, поэтому смена типа НИЧЕГО не меняет в местах
    /// вызова — но каждое событие этого файла разом получает: последний фильтр приватности
    /// (в точных текстах ошибок работы с файлами лежат пути внутри папки человека, а журнал
    /// он пересылает наружу кнопкой), ограничение длины строки (разбор ошибки библиотеки
    /// бывает на килобайты) и дубль в системный лог телефона (журнал можно снять проводом
    /// после поломки, ничего не прося у человека).
    private var journal: EngineJournal { EngineJournal.shared }

    // MARK: - Настройки

    /// Сколько токенов памяти разговора просим у движка ПРЯМО СЕЙЧАС.
    ///
    /// ⚠️ ЭТО ВЫБОР ЧЕЛОВЕКА, А НЕ НАША ДОГАДКА. Число живёт в настройках приложения
    /// и меняется на странице «О программе» — от 4 096 до 32 000. Своей копии решения
    /// здесь нет намеренно: разъедься экран и движок, человек двигал бы настройку,
    /// которую никто не читает.
    ///
    /// ⚠️ Мы не запрещаем большие значения и не «пробуем осторожно» за спиной человека.
    /// Наше дело — сделать так, чтобы неудачный выбор стоил одного перезапуска
    /// и был честно назван (см. отметку на диске ниже и `retreatToSafeContext`).
    private var contextCeiling: Int {
        ContextSizeSettings.chosenTokens
    }

    /// Отступить к безопасному размеру, переставить выбор человека и сказать об этом.
    ///
    /// - Parameters:
    ///   - asked: с каким числом не получилось.
    ///   - reason: что именно случилось — уходит человеку в журнал.
    ///   - function/line: откуда позвали. ⚠️ ЗАЩЕЛКИВАЮТСЯ НА СТОРОНЕ ВЫЗЫВАЮЩЕГО, потому
    ///     что отступать мы умеем из четырёх разных мест (метка прошлого запуска, движок
    ///     не создался, пустой ответ, неразборчивый ответ). Все они пишут в журнал одну
    ///     и ту же фразу, и без места вызова разбирать по журналу нечего: 09.08.2026
    ///     именно этого и не хватило, чтобы понять, кто отобрал у человека 32 000.
    private func retreatToSafeContext(from asked: Int,
                                      reason: String,
                                      function: StaticString = #function,
                                      line: UInt = #line) {
        // Настройку переписываем насовсем: иначе следующий запуск пошёл бы в то же
        // падение. Поднять число обратно — одно касание на той же странице.
        ContextSizeSettings.retreat(from: asked)
        journal.noteRetreat(from: asked,
                            to: AgentLimits.contextTokenBudget,
                            reason: reason,
                            // ⚠️ Тот же признак, что и в подборе настроек: пустой ответ после
                            // «Стоп» ничего не доказывает, и отступление на нём — почти
                            // наверняка наша ошибка. В журнале это должно быть видно сразу.
                            stoppedByPerson: didStopByPerson,
                            abortsInARow: UserDefaults.standard.integer(forKey: Self.contextAbortCountKey),
                            calledFrom: "\(function) строка \(line)")
    }

    // MARK: - Лесенка настроек

    /// Ступеньки лесенки: чем отличается наша настройка от той, на которой модель отвечает.
    ///
    /// ⚠️ ПОРЯДОК ВАЖЕН И ОБОСНОВАН. Сверху — самое подозрительное и самое дешёвое
    /// (пересобрать только разговор — секунды), снизу — дорогое (пересобрать движок:
    /// десяток секунд и гигабайты). Меняем за раз ровно одну вещь, накопительно:
    /// ступенька включает в себя всё, что включили ступеньки выше.
    private enum LaunchStep: Int, CaseIterable {
        /// Как приложение работает обычно.
        case ours = 0
        /// Не навязываем «без размышлений» — берём то, что заложено в самой модели.
        case thinkingDefault
        /// Настройки выбора слов как в примерах Google, а не наши строгие.
        case googleSampler
        /// Не навязываем размер памяти разговора — берём число из самой модели.
        case modelOwnCache
        /// Другой расчёт: видеочип вместо процессора.
        ///
        /// ⚠️ ПОДНЯТА ВЫШЕ «без списка действий» — ЭТО ИСПРАВЛЕНИЕ ЖИВОГО ПРОМАХА 09.08.2026.
        /// Ступеньки накопительные, и когда видеочип стоял ПОСЛЕ отключения действий, вышло
        /// вот что: на видеочипе модель наконец заговорила — но действия к тому моменту были
        /// уже отключены, и приложение объявило человеку «с файлами эта модель работать
        /// не сможет, только разговаривать». Это был НЕПРОВЕРЕННЫЙ вывод: связка «видеочип
        /// плюс действия» не пробовалась вообще ни разу. Теперь сначала меняем расчёт,
        /// а действия отключаем только если и это не помогло.
        case otherBackend
        /// Без списка действий: отделяет «модель не отвечает» от «ломается разбор вызовов».
        case withoutTools
        /// Ответ по частям, а не одним куском: официальный пример Google работает именно так.
        case streaming
        /// И, последней, части для картинок и звука.
        case withExecutors

        /// Что именно поменяли на этой ступеньке — строкой для журнала.
        var journalName: String {
            switch self {
            case .ours:            return "как обычно"
            case .thinkingDefault: return "не запрещаю модели размышлять"
            case .googleSampler:   return "выбор слов как у Google"
            case .modelOwnCache:   return "размер памяти разговора — из самой модели"
            case .withoutTools:    return "без списка действий"
            case .streaming:       return "ответ по частям"
            case .otherBackend:    return "другой расчёт (видеочип вместо процессора)"
            case .withExecutors:   return "с частями для картинок и звука"
            }
        }
    }

    /// Что именно включено на ступеньке. Собирается накопительно в `recipe(for:)`.
    private struct LaunchRecipe: Equatable {
        /// Размер памяти разговора. nil — «сколько скажет сама модель».
        var maxTokens: Int?
        /// Принудительный расчёт: true — видеочип, false — процессор, nil — как решим сами.
        var forceGPU: Bool?
        /// Поднимать ли исполнителей картинок и звука.
        var executors: Bool
        /// Настройки выбора слов: наши строгие или как в примерах Google.
        var googleSampler: Bool
        /// Отдавать ли модели список действий.
        var tools: Bool
        /// Запрещать ли модели размышления.
        var thinkingOff: Bool
        /// Забирать ответ по частям (потоком) вместо одного куска.
        var streaming: Bool
        /// Держать ли форму вызова принудительно (движок отсекает буквы, ломающие схему).
        var constrainedCalls: Bool

        /// Нужно ли пересобирать сам движок, или хватит нового разговора.
        /// Движок держит размер памяти разговора, расчёт и исполнителей — остальное живёт
        /// в разговоре и меняется за секунды.
        func needsNewEngine(comparedTo other: LaunchRecipe) -> Bool {
            maxTokens != other.maxTokens
                || forceGPU != other.forceGPU
                || executors != other.executors
        }
    }

    /// Где помним ступеньку, на которой ЭТА модель заговорила.
    private static let launchStepKeyPrefix = "pocketagent.runtime.launchStep."
    /// Где помним, что прошли всю лесенку и не помогло ничего.
    private static let ladderFailedPrefix = "pocketagent.runtime.ladderFailed."
    /// Где помним ступеньки, на которых приложение падало. Их больше не трогаем.
    private static let ladderBannedPrefix = "pocketagent.runtime.ladderBanned."

    /// Агенту нужна предсказуемость, а не творчество.
    private static let samplerTopK: Int = 40
    private static let samplerTopP: Float = 0.95
    private static let samplerTemperature: Float = 0.2

    /// Те же настройки, но как в примерах Google для этой линейки моделей.
    /// ⚠️ Числа не наши: 64 / 0,95 / 1,0 — из конфигурации Google для iOS.
    private static let googleSamplerTopK: Int = 64
    private static let googleSamplerTopP: Float = 0.95
    private static let googleSamplerTemperature: Float = 1.0

    /// Ключи, которыми переживаем падение на GPU: если приложение убили прямо во время
    /// инициализации на GPU, в следующий раз идём сразу на CPU и не зацикливаем краш.
    ///
    /// ⚠️ Сама метка «попытка началась» лежит НЕ в настройках, а отдельным файлом:
    /// UserDefaults сбрасываются на диск не мгновенно, и при жёстком отстреле процесса
    /// системой (ровно тот случай, ради которого метка заведена) значение могло не долететь.
    private static let gpuBannedKey  = "pocketagent.runtime.gpuDisabled"
    /// Сколько раз подряд попытка на GPU обрывалась вместе с приложением.
    private static let gpuAbortCountKey = "pocketagent.runtime.gpuAbortCount"
    /// Один оборванный запуск ещё ничего не значит: человек мог сам смахнуть приложение
    /// из многозадачности, пока шло «Готовим движок». Баним только после второго подряд.
    private static let gpuAbortsBeforeBan = 2
    /// Версия системы и сборки, на которых GPU забанили. Сменилась — бан снимаем сами:
    /// иначе один неудачный запуск НАВСЕГДА оставлял человека на CPU (вдвое медленнее),
    /// а единственная кнопка снятия бана ниоткуда не вызывалась.
    private static let gpuBanStampKey = "pocketagent.runtime.gpuDisabled.stamp"

    /// Сколько раз подряд приложение умирало, пока просило увеличенную память разговора.
    ///
    /// ⚠️ ЗАВЕДЕНО ПО ЖИВОЙ ЖАЛОБЕ 09.08.2026: «поставил 32 000, поработало два раза,
    /// потом само вернулось на 4 096». На телефоне владельца нашлась несмахнутая метка
    /// `context-attempt.flag` со словами «32000 / создание движка» — то есть приложение
    /// закрылось, пока поднимало движок, и следующий запуск засчитал это как приговор
    /// выбору человека. Но закрыться нас может заставить что угодно: человек сам смахнул
    /// приложение из многозадачности, пока шло «Готовим движок» (это десяток секунд
    /// и гигабайты весов), встала новая сборка из TestFlight, система выгрузила нас
    /// из фона. Ни одно из этого не доказывает, что телефон не тянет выбранный размер.
    private static let contextAbortCountKey = "pocketagent.runtime.contextAbortCount"
    /// Считаем обрывы и переставляем выбор человека только со второго подряд —
    /// ровно та же мерка, что у видеочипа (`gpuAbortsBeforeBan`), и по той же причине.
    private static let contextAbortsBeforeRetreat = 2

    // MARK: - Состояние

    /// Описание модели, с которой движок работает ПРЯМО СЕЙЧАС.
    ///
    /// ⚠️ ИМЕННО ПЕРЕМЕННАЯ, А НЕ КОНСТАНТА, и это принципиально. Движок создаётся один
    /// раз за запуск приложения, значит снятое при создании описание — это снимок «что
    /// было на старте». Пока оно было константой, файл владельца на 3,66 ГБ проходил
    /// установку и тут же получал «Файл модели повреждён. Скачайте заново.»: быстрая
    /// проверка сверяла его с чужим размером 2,01 ГБ. Заодно по чужой модели считались
    /// оба порога памяти. Теперь описание берётся от НАЙДЕННОГО файла — см. ensureModelFile().
    private var model: ModelDescriptor

    /// Что модель умеет кроме текста. Считывается из её файла перед созданием движка.
    private var modalities: ModelModalities = .textOnly

    /// На какой ступеньке лесенки движок работает прямо сейчас.
    private var launchStep: LaunchStep = .ours

    /// Ступенька, которую приказано взять при следующей сборке движка.
    /// Ставится только на время подъёма по лесенке и тут же снимается.
    private var forcedStep: LaunchStep?

    /// Под каким ключом помним ступеньку для файла, который сейчас открыт.
    private var ladderMemoryKey: String = ""

    /// Модель уже ответила на этой ступеньке — лесенка больше не нужна.
    private var isStepConfirmed = false

    /// По лесенке в этом запуске уже ходили. Один проход — и всё.
    private var didWalkLadder = false

    /// Отметку «пробовал увеличенную память разговора» с прошлого запуска уже смотрели.
    /// Смотреть надо ровно ОДИН раз за запуск приложения: движок пересобирается и на
    /// лесенке, и после отступления, а прошлый запуск у нас всё равно один.
    private var didCheckContextAttemptMark = false

    /// На увеличенном окне уже был ход, который вернулся живым (пусть даже пустым).
    /// Дальше отметка на диске не нужна: падение внутри первого ответа мы пережили.
    /// Сбрасывается вместе с созданием нового движка — окно у него своё.
    private var didSurviveRaisedTurn = false

    /// Про удачу увеличенного окна в журнал уже написали. Повторять каждый ход незачем.
    private var didConfirmRaisedContext = false

    /// Пошёл бы обычный запуск на видеочип. Снимается один раз перед подъёмом,
    /// чтобы ступенька «другой расчёт» не перевернулась из-за скачка свободной памяти.
    private var baseWouldUseGPU = false

    private var engine: Engine?
    private var conversation: Conversation?

    private var status: ModelRuntimeStatus = .idle
    private var statusListeners: [UUID: AsyncStream<ModelRuntimeStatus>.Continuation] = [:]

    private var systemPrompt: String = ""
    private var declarations: [ToolDeclaration] = []

    private var isPreparing = false
    private var isGenerating = false

    /// Под какой выбор человека подняты веса, лежащие в памяти ПРЯМО СЕЙЧАС.
    ///
    /// ⚠️ Ради одного-единственного сравнения: «то ли самое в памяти, что человек выбрал
    /// минуту назад». Без него подготовка отвечала «и так готово» на любую просьбу —
    /// в том числе на просьбу поставить другую модель, и смена модели не работала вовсе.
    /// nil — в памяти ничего нет.
    private var loadedChoiceMark: String?

    /// Тот же признак, но для модели, которая поднимается ПРЯМО СЕЙЧАС. Нужен, чтобы
    /// отличить «просят ту же самую, что уже грузится» (тогда молчим — про неё и так
    /// рассказывает полоса состояния) от «просят другую» (тогда обязаны сказать словами).
    private var preparingChoiceMark: String?

    /// Система попросила освободить память, пока мы поднимали движок.
    ///
    /// ⚠️ ЗАЧЕМ ФЛАГ. `await engine.initialize()` — точка, в которой актор впускает другие
    /// вызовы. Прилетевшее ровно сюда предупреждение о памяти звало unload(), обнуляло
    /// движок, а вернувшийся prepare() тут же присваивал engine заново и ставил «готово» —
    /// то есть возвращал в память ровно то, что система просила освободить. Дальше система
    /// убивала приложение, и человек видел «приложение просто вылетает».
    private var unloadRequested = false

    /// Текущий ход прерван человеком или уходом в фон.
    /// Нужен, чтобы ошибка оборванной генерации не выглядела как поломка модели.
    private var didCancelCurrentTurn = false

    /// Ход оборвал ЧЕЛОВЕК, а не модель.
    ///
    /// ⚠️ ЗАЧЕМ ОТДЕЛЬНОЕ ИМЯ ДЛЯ ОДНОЙ ПРОВЕРКИ — ЭТО ИСПРАВЛЕНИЕ ЖИВОЙ ЖАЛОБЫ
    /// 09.08.2026 («хочу 32 000, а получаю 4 096»). Нажатие «Стоп» не приводит к ошибке:
    /// сбор ответа по частям просто прекращается и возвращает ПУСТОЕ сообщение. А пустой
    /// ответ на увеличенном размере памяти разговора считался доказательством, что размер
    /// телефону не по силам, — и выбор человека переставлялся на безопасный. То есть
    /// человек нажимал «Стоп», а приложение молча отбирало у него настройку.
    /// Проверка «остановил ли человек» уже была в подборе настроек и в разборе ошибок,
    /// а в отступлении по размеру её не было; теперь у всех трёх мест она одна и та же.
    private var didStopByPerson: Bool { didCancelCurrentTurn || Task.isCancelled }

    /// Вызовы инструментов, которые модель попросила сверх первого и которые мы
    /// намеренно не выполняем. Им нужно отправить отказ вместе со следующим ответом.
    private var unansweredCalls: [(name: String, id: String)] = []

    /// Какой бэкенд в итоге поднялся — для экрана диагностики.
    public private(set) var activeBackendName: String = "—"

    /// Сколько памяти разговора движок дал НА САМОМ ДЕЛЕ — для счётчика в чате.
    ///
    /// ⚠️ Пишется в момент, когда движок УЖЕ поднялся, а не когда мы попросили.
    /// Просьба и выдача расходятся: ступенька лесенки «сколько скажет сама модель»
    /// не задаёт размер вовсе, а прошлое отступление к безопасному числу помнится
    /// на диске между запусками. Показывать константу вместо выданного числа —
    /// значит врать человеку в счётчике, ради которого всё и затевалось.
    private var grantedContextTokens = AgentLimits.contextTokenBudget

    /// - Parameter model: с чего начинаем. Это ТОЛЬКО ответ на вопрос «что качать, если
    ///   на телефоне нет ничего»: как только найдётся готовый файл, описание сменится
    ///   на его собственное.
    public init(model: ModelDescriptor = ModelSpec.descriptor) {
        self.model = model
    }

    // MARK: - Статус

    public func currentStatus() async -> ModelRuntimeStatus { status }

    public func statusStream() async -> AsyncStream<ModelRuntimeStatus> {
        let (stream, continuation) = AsyncStream<ModelRuntimeStatus>.makeStream(
            bufferingPolicy: .bufferingNewest(8)
        )
        let id = UUID()
        statusListeners[id] = continuation
        continuation.yield(status)
        continuation.onTermination = { [weak self] _ in
            Task { await self?.dropListener(id) }
        }
        return stream
    }

    private func dropListener(_ id: UUID) {
        statusListeners[id] = nil
    }

    private func setStatus(_ newStatus: ModelRuntimeStatus) {
        guard newStatus != status else { return }
        status = newStatus
        for listener in statusListeners.values {
            listener.yield(newStatus)
        }
    }

    // MARK: - Подготовка модели

    /// Чем помечен выбор человека прямо сейчас: путь файла внутри приложения, а если
    /// файла нет — опознаватель модели из справочника. Пустая строка — не выбирал ничего.
    ///
    /// ⚠️ Метка нужна ровно для сравнения «то же самое или уже другое» и ни для чего
    /// больше. Сравнивать сами описания моделей нельзя: одна и та же модель приезжает
    /// то из справочника, то разобранная из файла, и по значению они не совпадут.
    private static func choiceMark() -> String {
        guard let choice = ModelSpec.choice else { return "" }
        if let path = choice.relativePath, !path.isEmpty { return path }
        return choice.descriptor.id
    }

    public func prepare() async throws {
        // Веса уже в памяти. Прежде чем ответить «и так готово», спрашиваем главное:
        // ТА ЛИ это модель, которую человек выбрал?
        //
        // ⚠️ ЖИВАЯ ЖАЛОБА ВЛАДЕЛЬЦА 10.08.2026: «при попытке сменить модель, которая
        // в папке, — не выходит вообще никак». Здесь стоял голый ответ «готово»: человек
        // нажимал на другую модель, приложение запоминало выбор, звало подготовку — и она
        // молча возвращала успех, не тронув ничего. В памяти оставались прежние веса,
        // строка «работает сейчас» оставалась у старой модели, и сделать было нельзя ничего.
        if case .ready = status, engine != nil {
            let wanted = Self.choiceMark()
            guard wanted != loadedChoiceMark else {
                // Молчать нельзя даже про «ничего не делаю»: без этой строки разобрать
                // жалобу «нажал — и ничего» по журналу было невозможно.
                journal.record(.engine, "Эта модель уже загружена — заново не поднимаю",
                               detail: "в памяти: \(model.fileName)")
                return
            }
            // Две модели по 3–5 ГБ телефон не удержит: прежние веса отдаём ДО загрузки новых.
            journal.record(.engine, "Человек выбрал другую модель — меняю",
                           detail: "было: \(model.fileName) · стало: \(ModelSpec.fileName)")
            await unload()
        }

        guard !isPreparing else {
            // ⚠️ И ЗДЕСЬ МОЛЧАЛИВОГО «УСПЕХА» БЫТЬ НЕ МОЖЕТ. Та же самая модель уже
            // поднимается — это правда, и человеку про неё рассказывает полоса состояния.
            // А вот если просят ДРУГУЮ, ответить «сделано» значит соврать: подготовка идёт
            // за прежнюю, и новую никто не возьмёт.
            guard Self.choiceMark() != preparingChoiceMark else { return }
            journal.record(.failure, "Просят другую модель, пока идёт подготовка прежней",
                           detail: "готовлю: \(model.fileName)")
            throw ModelChoiceProblem(
                text: "Сейчас загружается модель «\(model.displayName)». Дождитесь, пока она "
                    + "поднимется, или отмените загрузку — и выберите другую."
            )
        }

        isPreparing = true
        preparingChoiceMark = Self.choiceMark()
        unloadRequested = false
        defer {
            isPreparing = false
            preparingChoiceMark = nil
        }

        // Засечка на всю подготовку: её время попадёт в строку «Модель загружена и готова».
        // ⚠️ Именно здесь, а не после поиска файла: скачивание модели — тоже подготовка,
        // и человек, у которого «всё висит», должен видеть в журнале настоящие минуты.
        journal.startStage(.prepare)
        journal.record(.engine, "Готовлю модель к работе")

        // ⚠️ СТРОГО ДО ПЕРВОГО ОБРАЩЕНИЯ К `contextCeiling`. Здесь решается, просить ли
        // сегодня увеличенное окно: если прошлый запуск на нём закрылся, отступаем сейчас,
        // а не после второго падения.
        consumePreviousContextAttempt()

        do {
            let modelURL = try await ensureModelFile()
            // Пока искали файл, выбор мог появиться сам (взяли то, что лежит на телефоне,
            // и запомнили). Обновляем метку, иначе просьба поднять ЭТУ ЖЕ модель, пришедшая
            // следом, была бы принята за просьбу поднять другую.
            preparingChoiceMark = Self.choiceMark()

            // Быстрая проверка обязательна всегда: файл могли обрезать или подменить.
            setStatus(.verifying)
            journal.record(.engine, "Проверяю файл модели",
                           detail: "файл: \(modelURL.lastPathComponent) · "
                                 + "размер: \(HumanFormat.bytes(ModelStorage.byteSize(of: modelURL))) · "
                                 + "ждём: \(HumanFormat.bytes(model.byteSize))")
            try ModelVerifier.quickCheck(modelURL, model: model)

            // С какой ступеньки лесенки поднимаемся. Заодно читается состав файла —
            // это мгновение, а нужно для порога памяти и для последней ступеньки.
            decideLaunchStep(for: modelURL)

            // Памяти может не хватить — лучше честно сказать, чем словить отстрел системой.
            let executorsNow = recipe(for: launchStep).executors
            journal.record(.engine, "Смотрю, хватит ли памяти",
                           detail: "свободно: \(Self.freeMemoryText()) · "
                                 + "нужно на процессоре: \(model.cpuMemoryNeedMB(multimodal: executorsNow)) МБ · "
                                 + "нужно на видеочипе: \(model.gpuMemoryNeedMB(multimodal: executorsNow)) МБ · "
                                 + "ступенька: \(launchStep.journalName)")
            try ensureEnoughMemoryForStep()

            setStatus(.loading)
            let created = try await makeEngine(modelPath: modelURL.path)

            // Пока мы поднимали движок, система попросила освободить память.
            // Отдаём созданное сразу и НЕ объявляем модель готовой: вернуть веса
            // в память после такой просьбы — почти гарантированный отстрел приложения.
            if unloadRequested {
                unloadRequested = false
                throw PocketAgentError.memoryPressureDuringLoad
            }
            // Спрашиваем память ещё раз: между проверкой и концом загрузки прошли секунды.
            try ensureEnoughMemoryForStep()

            engine = created
            // ⚠️ ПАРА «ПРОСИЛИ — ДАЛИ» ЗДЕСЬ ОБЯЗАТЕЛЬНА, И ЭТО ГЛАВНАЯ СТРОКА ЖУРНАЛА.
            // Раньше писался только запрошенный размер, и жалоба «поставил 32 000,
            // а получаю 4 096» по журналу не разбиралась вовсе: числа, которое движок
            // выдал на самом деле, в нём просто не было.
            journal.noteReady(modelName: model.displayName,
                              fileName: model.fileName,
                              fileSizeText: HumanFormat.bytes(model.byteSize),
                              backend: activeBackendName,
                              askedTokens: recipe(for: launchStep).maxTokens,
                              grantedTokens: grantedContextTokens,
                              chosenTokens: contextCeiling,
                              stepNumber: launchStep.rawValue,
                              stepName: launchStep.journalName,
                              freeMemoryMB: MemoryGate.availableMemoryMB())
            // ⚠️ ИМЕННО ЗДЕСЬ, А НЕ В НАЧАЛЕ ПОДГОТОВКИ. Пока мы искали файл, выбор мог
            // ПОЯВИТЬСЯ сам: человек ничего не выбирал, а приложение взяло то, что лежит
            // на телефоне, и запомнило это своим выбором. Снимок, сделанный до поиска,
            // тут же разошёлся бы с настоящим — и следующая подготовка решила бы, что
            // человек переключился, и зря выгружала бы только что поднятые веса.
            loadedChoiceMark = Self.choiceMark()
            setStatus(.ready)
        } catch {
            engine = nil
            conversation = nil
            loadedChoiceMark = nil
            let human = Self.humanMessage(error)
            // Точная суть ошибки обязана дожить до боевой сборки: раньше она жила
            // только под #if DEBUG, и человек с телефоном видел общую фразу, по которой
            // диагностировать нечего.
            journal.recordFailure(stage: "загрузка модели",
                                  human: human,
                                  technical: RuntimeJournal.technicalText(for: error))
            setStatus(.failed(message: human))
            throw error
        }
    }

    /// Возвращает путь к готовому файлу модели, при необходимости скачав его.
    ///
    /// ⚠️ ПОРЯДОК ЗДЕСЬ — ЭТО ОТВЕТ НА ВОПРОС «КАКУЮ МОДЕЛЬ ЧЕЛОВЕК ЗАКАЗАЛ».
    /// Раньше первой же строкой бралась ЛЮБАЯ годная модель, лежащая на телефоне. Пока
    /// модель была одна, это работало; с появлением списка получилось враньё: человек
    /// выбирал в списке одну модель, жал «Скачать» — а приложение молча запускало ту,
    /// что уже лежала рядом, и рапортовало «готово». Теперь выбор человека главнее
    /// всего, что нашлось на телефоне.
    private func ensureModelFile() async throws -> URL {
        // Что человек выбрал в списке. Описание, снятое при СОЗДАНИИ движка, — это снимок
        // «что было на старте приложения»: выбор, сделанный после запуска, туда не попадает,
        // и качалась бы старая модель, а экран показывал бы имя новой.
        var choice = ModelSpec.choice
        model = ModelSpec.descriptor

        // 1. Человек указал КОНКРЕТНЫЙ файл на телефоне («Использовать эту модель»
        //    или установка из «Файлов»). Он и работает — пока файл на месте.
        if let chosenPath = choice?.relativePath, !chosenPath.isEmpty {
            let chosenURL = ModelStorage.url(forContainerRelativePath: chosenPath)
            if FileManager.default.fileExists(atPath: chosenURL.path) {
                // Описание берём от САМОГО файла: он мог смениться под тем же именем.
                if let file = ModelDiscovery.describe(chosenURL) {
                    model = file.descriptor
                }
                journal.record(.engine, "Беру файл, который выбрал человек",
                               detail: "файл: \(chosenURL.lastPathComponent) · "
                                     + "размер: \(HumanFormat.bytes(ModelStorage.byteSize(of: chosenURL)))")
                return chosenURL
            }
            // Файла больше нет — человек удалил его из «Файлов» или недокачал. Держаться
            // за мёртвый выбор нельзя: иначе приложение упирается в «файла нет» при каждом
            // запуске и выбраться из этого нечем. Забываем выбор и идём обычным путём.
            let lostName = choice?.descriptor.displayName ?? chosenURL.lastPathComponent
            journal.record(.failure, "Файл выбранной модели пропал с телефона",
                           detail: "ждали здесь: \(chosenPath) · "
                                 + "модель: \(lostName) · выбор снимаю")
            ModelSpec.clearSelection()
            choice = nil
            model = ModelSpec.descriptor
            // Список на экране всё ещё помнит пропавший файл — пересматриваем папки
            // сейчас же. Иначе человек читал бы «файла нет» и одновременно видел его
            // строкой в списке, а взамен мы взяли бы такой же призрак из старого списка.
            ModelDiscovery.refreshAndNotify()

            // ⚠️ И ВОТ ЗДЕСЬ МОЛЧАТЬ НЕЛЬЗЯ. Раньше приложение просто шло дальше и,
            // не найдя на телефоне ничего, принималось само качать модель по умолчанию —
            // гигабайты за чужой счёт и совсем не ту, которую человек выбирал. Если взамен
            // взять нечего, честно говорим, что случилось, и оставляем решение человеку.
            guard ModelStorage.readyModel() != nil else {
                throw ModelChoiceProblem(
                    text: "Модель «\(lostName)», с которой вы работали, пропала с телефона — "
                        + "файла больше нет. Положите файл обратно в папку приложения "
                        + "через «Файлы» или выберите другую модель в списке."
                )
            }
        }

        // 2. Человек выбрал модель в списке для загрузки. Ищем файл ИМЕННО ЕЁ —
        //    подставлять соседний файл вместо заказанного нельзя.
        if choice != nil {
            if let installed = ModelStorage.installedModelURL(for: model),
               ModelStorage.byteSize(of: installed) == model.byteSize {
                journal.record(.engine, "Беру уже установленную модель",
                               detail: "файл: \(installed.lastPathComponent) · "
                                     + "размер: \(HumanFormat.bytes(model.byteSize))")
                return installed
            }
        } else if let ready = ModelStorage.readyModel() {
            // 3. Человек не выбирал ничего — тогда берём то, что уже лежит на телефоне.
            // ⚠️ И СРАЗУ ПЕРЕНИМАЕМ ЕГО ОПИСАНИЕ. Дальше по нему идут быстрая проверка
            // размера, оба порога памяти и выбор «видеочип или процессор». Оставь здесь
            // описание, снятое при запуске приложения, — и файл владельца на 3,66 ГБ,
            // только что установленный, тут же получал бы «Файл модели повреждён»,
            // а памяти под него просили бы как под модель вдвое легче.
            model = ready.descriptor
            // ⚠️ И СРАЗУ ЗАПОМИНАЕМ ЭТОТ ФАЙЛ КАК ВЫБРАННЫЙ. Живая жалоба владельца
            // 10.08.2026: «почему-то по умолчанию аппка якобы видит гемма 4 E2B, хотя её
            // нету даже в папке». Причина ровно здесь: движок брал настоящий файл с
            // телефона, но выбор оставался ПУСТЫМ — а на пустой выбор всё приложение
            // (имя модели на экранах, «О программе», размер занятого места, удаление
            // и отмена загрузки) отвечало моделью по умолчанию из справочника. То есть
            // работала одна модель, а показывалась и удалялась совсем другая.
            ModelSpec.select(ready.descriptor, fileURL: ready.url)
            journal.record(.engine, "Беру модель, которая уже лежит на телефоне",
                           detail: "файл: \(ready.url.lastPathComponent) · "
                                 + "размер: \(HumanFormat.bytes(ready.descriptor.byteSize)) · "
                                 + "запомнил её как выбранную")
            return ready.url
        }

        // 4. Файла заказанной модели нет — качаем её.
        guard ModelStorage.hasEnoughFreeSpace(for: model) else {
            throw PocketAgentError.notEnoughDiskSpace
        }

        journal.record(.engine, "Файла нет на телефоне — скачиваю модель",
                       detail: "модель: \(model.displayName) · размер: \(HumanFormat.bytes(model.byteSize))")
        setStatus(.downloading(progress: ModelDownloader.shared.lastProgress))

        let downloadedURL = try await ModelDownloader.shared.download(model) { [weak self] progress in
            Task { await self?.setStatus(.downloading(progress: progress)) }
        }

        // Свежая загрузка — единственный момент, когда стоит платить за полный sha256
        // (несколько секунд чтения 2,6 ГБ). При каждом запуске это делать не нужно.
        setStatus(.verifying)
        let modelCopy = model
        do {
            try await Task.detached(priority: .userInitiated) {
                try ModelVerifier.verify(downloadedURL, model: modelCopy, checksum: .required)
            }.value
        } catch is CancellationError {
            // Человек ушёл с экрана или нажал «Стоп» — файл цел, трогать его нельзя.
            throw PocketAgentError.generationCancelled
        } catch {
            // ⚠️ ТУПИК, ИЗ КОТОРОГО НЕ БЫЛО ВЫХОДА. Скачанный файл не сошёлся с эталоном,
            // и приложение говорило «Файл модели повреждён. Скачайте заново» — а выполнить
            // этот совет было НЕЛЬЗЯ: битый файл оставался лежать целым по размеру,
            // и следующая попытка сразу отдавала его же, снова получая тот же отказ.
            // Человек упирался в одну и ту же надпись сколько угодно раз.
            // Теперь негодное убираем сами: нажатие «Продолжить» правда качает заново.
            if let known = error as? PocketAgentError, case .generationCancelled = known {
                throw known
            }
            try? FileManager.default.removeItem(at: downloadedURL)
            ModelStorage.clearResumeData(for: modelCopy)
            ModelDownloadPlanStore.clear(modelID: modelCopy.id)
            journal.record(.failure, "Скачанный файл не прошёл проверку — убрал его",
                           detail: "модель: \(modelCopy.displayName) · "
                                 + "причина: \(RuntimeJournal.technicalText(for: error))")
            ModelDiscovery.refreshAndNotify()
            throw ModelChoiceProblem(
                text: "Файл модели «\(modelCopy.displayName)» скачался испорченным — "
                    + "я его убрал, чтобы он не занимал место. Нажмите «Продолжить»: "
                    + "приложение скачает модель заново, с самого начала."
            )
        }

        // Скачанное закрепляем за выбором человека: со следующего запуска приложение
        // возьмёт именно этот файл, а не «первый годный, какой попался».
        ModelSpec.select(modelCopy, fileURL: downloadedURL)
        // ⚠️ И сразу перечитываем список файлов. Без этой строки только что скачанная
        // модель не появлялась в списке «уже на телефоне» до следующего возврата
        // в приложение: человек видел «модель готова» и пустой список под ним.
        ModelDiscovery.refreshAndNotify()

        return downloadedURL
    }

    // MARK: - Лесенка: с какой ступеньки поднимаем модель

    /// Что включено на этой ступеньке. Настройки НАКОПИТЕЛЬНЫЕ: каждая ступенька
    /// добавляет своё к тому, что уже включили ступеньки выше.
    private func recipe(for step: LaunchStep) -> LaunchRecipe {
        var value = LaunchRecipe(maxTokens: contextCeiling,
                                 forceGPU: nil,
                                 executors: false,
                                 googleSampler: false,
                                 tools: true,
                                 thinkingOff: true,
                                 streaming: false,
                                 constrainedCalls: true)

        // ⚠️ ПРИНУДИТЕЛЬНАЯ ФОРМА ВЫЗОВА ЖИВЁТ ТОЛЬКО НА НУЛЕВОЙ СТУПЕНЬКЕ, И ЭТО
        // СОЗНАТЕЛЬНО. Новой ступеньки под неё НЕ заводим: номера ступенек лежат
        // в настройках телефона («на этой модель заговорила», «на этой упала»), и
        // вставка новой посреди списка перенумеровала бы чужую память — запомненное
        // «упало на видеочипе» вдруг стало бы означать другую настройку. Поэтому
        // принуждение просто снимается первым же отступлением: молчит модель —
        // лесенка сама уходит на ступеньку без него, и это тот же предохранитель,
        // что уже работает для размышлений и выбора слов.
        if step != .ours { value.constrainedCalls = false }

        if step.rawValue >= LaunchStep.thinkingDefault.rawValue { value.thinkingOff = false }
        if step.rawValue >= LaunchStep.googleSampler.rawValue   { value.googleSampler = true }
        if step.rawValue >= LaunchStep.modelOwnCache.rawValue   { value.maxTokens = nil }
        if step.rawValue >= LaunchStep.withoutTools.rawValue    { value.tools = false }
        if step.rawValue >= LaunchStep.streaming.rawValue       { value.streaming = true }
        // Наша прикидка памяти могла зря загнать модель на процессор — пробуем наоборот.
        if step.rawValue >= LaunchStep.otherBackend.rawValue    { value.forceGPU = !baseWouldUseGPU }
        if step.rawValue >= LaunchStep.withExecutors.rawValue   { value.executors = true }

        return value
    }

    /// Пошёл бы обычный запуск на видеочип. Нужно, чтобы ступенька «другой расчёт»
    /// действительно меняла расчёт, а не повторяла то же самое.
    ///
    /// ⚠️ Ответ ЗАПОМИНАЕТСЯ на весь подъём по лесенке, а не считается каждый раз:
    /// свободная память гуляет, и пересчёт на каждом шаге мог бы посреди подъёма
    /// перевернуть решение — «другой расчёт» вдруг оказался бы тем же самым.
    private func rememberWhetherGPUWouldBeUsed() {
        baseWouldUseGPU = !UserDefaults.standard.bool(forKey: Self.gpuBannedKey)
            && MemoryGate.canUseGPU(model)
            && model.hardware != .browserOnly
    }

    /// Решить, с какой ступеньки начинать, и записать решение в журнал.
    ///
    /// ⚠️ ПОРЯДОК ИСТОЧНИКОВ — ЭТО И ЕСТЬ ВСЯ ЛОГИКА:
    ///   1. приказ подъёма (мы прямо сейчас на лесенке) — главнее всего;
    ///   2. ступенька, на которой эта модель уже отвечала, — берём сразу её;
    ///   3. иначе начинаем как обычно, с нулевой.
    private func decideLaunchStep(for url: URL) {
        modalities = ModelVerifier.modalities(of: url, descriptor: model)
        ladderMemoryKey = Self.ladderKey(fileName: url.lastPathComponent,
                                         byteSize: ModelStorage.byteSize(of: url),
                                         contextTokens: contextCeiling)

        // 1. Идём по лесенке — ступенька уже выбрана за нас.
        if let forced = forcedStep {
            launchStep = forced
            noteStepChosen(.climbing)
            return
        }

        // Метка осталась с прошлого запуска — значит на той ступеньке приложение УПАЛО.
        // Записываем её в чёрный список и больше никогда не трогаем.
        if let crashed = Self.consumeCrashedLadderStep(), crashed.key == ladderMemoryKey,
           let step = LaunchStep(rawValue: crashed.step) {
            banStep(step)
            journal.record(.failure,
                           "В прошлый раз приложение закрылось на настройке «\(step.journalName)» — "
                         + "больше её не пробую")
        }

        isStepConfirmed = false
        didWalkLadder = didLadderFail()
        rememberWhetherGPUWouldBeUsed()

        if modalities.isMultimodal {
            journal.record(.engine, "Эта модель умеет не только текст",
                           detail: modalities.journalLine)
        }

        // 2. Прошлый раз нашёл рабочую настройку для ЭТОГО файла.
        if let remembered = rememberedStep() {
            launchStep = remembered
            isStepConfirmed = true
            didWalkLadder = true
            noteStepChosen(.remembered)

            // ⚠️ ЗАПОМНЕННАЯ СТУПЕНЬКА МОЖЕТ ОТМЕНИТЬ ВЫБОР ЧЕЛОВЕКА, И МОЛЧАТЬ ОБ ЭТОМ
            // НЕЛЬЗЯ. Ступеньки накопительные: начиная с «размер памяти разговора —
            // из самой модели» размер не задаётся ВООБЩЕ, и движок отдаёт свои 4 096.
            // Ключ памяти теперь включает выбранный размер, поэтому чужой опыт сюда
            // не приедет — но подобрать такую ступеньку можно и ПРИ ЭТОМ САМОМ размере,
            // и тогда выбор снова не действует. На странице «О программе» при этом
            // написано выбранное число, и человек считает, что настройка сломана
            // (живая жалоба 09.08.2026). Значит приложение обязано сказать это словами.
            if remembered.rawValue >= LaunchStep.modelOwnCache.rawValue,
               contextCeiling > AgentLimits.contextTokenBudget {
                journal.record(.engine,
                               "На этой настройке размер памяти разговора берёт сама модель — "
                             + "выбранные \(ContextSizeSettings.text(contextCeiling)) сейчас не действуют",
                               detail: "настройку подобрало приложение, когда модель молчала на этом размере · "
                                     + "хотите вернуть свой размер — выберите другое число и вернитесь к этому: "
                                     + "подбор начнётся заново")
            }
        } else {
            launchStep = .ours
            noteStepChosen(.fresh)
            if didWalkLadder {
                journal.record(.engine, "Все настройки для этой модели уже перебирали — "
                                      + "заново по кругу не пойду")
            }
        }
    }

    /// Записать в журнал ступеньку, с которой поднимаемся: номер, название, откуда взялась,
    /// под каким ключом памяти и что именно она поменяла.
    ///
    /// ⚠️ ОТДЕЛЬНЫМ МЕТОДОМ, ПОТОМУ ЧТО МЕСТ ВЫБОРА ЧЕТЫРЕ (приказ подъёма, запомненная,
    /// обычная и смена настроек без пересборки движка), а строка в журнале обязана быть
    /// одна и та же. Разъедься эти четыре строки — и по журналу нельзя было бы сравнить
    /// два запуска между собой, а именно этим разбор поломки и занимается.
    private func noteStepChosen(_ origin: EngineJournal.StepOrigin) {
        let plan = recipe(for: launchStep)
        journal.noteLadderStep(number: launchStep.rawValue,
                               name: launchStep.journalName,
                               origin: origin,
                               askedTokens: plan.maxTokens,
                               toolsOn: plan.tools,
                               chosenTokens: contextCeiling,
                               memoryKey: ladderMemoryKey)
    }

    /// Ключ памяти: имя файла и его размер. Файл могли подменить под тем же именем —
    /// тогда это другая модель, и прошлый вывод к ней не относится.
    ///
    /// ⚠️ В КЛЮЧ ВХОДИТ НОМЕР СБОРКИ, И ЭТО ИСПРАВЛЕНИЕ ЖИВОГО ПРОМАХА 09.08.2026.
    /// Перебор однажды закончился на ступеньке «без списка действий» — и приложение
    /// запомнило её НАВСЕГДА. Дальше вышла новая сборка, где порядок ступенек исправлен
    /// (видеочип пробуется раньше отключения действий), но память об этом не знала:
    /// модель по-прежнему поднималась без единого действия. Владелец получил агента,
    /// который не умеет ни читать, ни писать файлы, — и тот принялся ВЫДУМЫВАТЬ:
    /// присылал в чат строчки вроде «cat README.md» и уверял, что всё прочитал,
    /// хотя не сделал ни одного шага. Это худший исход из возможных: не отказ, а враньё.
    /// Сменилась сборка — прошлый вывод перепроверяется заново.
    ///
    /// ⚠️ И РАЗМЕР ПАМЯТИ РАЗГОВОРА ТОЖЕ ВХОДИТ В КЛЮЧ — ЭТО ИСПРАВЛЕНИЕ ЖИВОЙ ЖАЛОБЫ
    /// 09.08.2026 («поставил 32 000, поработало два раза, потом сбросилось на 4 096»).
    /// Ступеньки накопительные, и начиная с «размер памяти разговора — из самой модели»
    /// размер не задаётся ВООБЩЕ. Раз запомнив такую ступеньку, приложение отменяло выбор
    /// человека при каждом следующем запуске — молча, оставляя на экране написанные
    /// 32 000. Ничего не сбрасывалось: настройка была цела, её просто перестали спрашивать.
    ///
    /// ⚠️ ПОЧЕМУ ИМЕННО КЛЮЧ, А НЕ «ЗАБЫТЬ СТУПЕНЬКУ ПРИ СМЕНЕ РАЗМЕРА». Мы ничего
    /// не стираем. Опыт, добытый при 4 096, ВЕРЕН — но верен ровно для 4 096: он и получен
    /// был при другом окне, и переносить его на 32 000 было ошибкой. Другой размер —
    /// другой ключ: по нему запомненного нет, запуск начинается с обычной ступеньки
    /// и с числом человека. Вернулся на 4 096 — вернулась и прежняя память, целиком.
    /// Это тот же принцип, по которому память забывается при смене сборки: изменились
    /// условия — вывод не переносится. Не «чинить» обратно на общий ключ.
    private static func ladderKey(fileName: String, byteSize: Int64, contextTokens: Int) -> String {
        return "\(fileName)|\(byteSize)|сборка\(Self.buildStamp)|память\(contextTokens)"
    }

    /// Отпечаток установленной сборки: номер плюс время самой программы.
    ///
    /// ⚠️ ОДНОГО НОМЕРА СБОРКИ МАЛО. У сборок, которые собираются на Маке для проверки,
    /// номер всегда «1» — и память перебора не сбрасывалась бы между ними, то есть
    /// исправление порядка ступенек не проверилось бы вовсе. Время программы меняется
    /// при каждой установке, поэтому берём и его.
    private static let buildStamp: String = {
        let number = Bundle.main.infoDictionary?["CFBundleVersion"] as? String ?? "?"
        let stamp: String
        if let path = Bundle.main.executableURL?.path,
           let date = try? FileManager.default.attributesOfItem(atPath: path)[.modificationDate] as? Date {
            stamp = String(Int(date.timeIntervalSince1970))
        } else {
            stamp = "?"
        }
        return "\(number)-\(stamp)"
    }()

    /// Ступенька, на которой эта модель однажды ответила.
    private func rememberedStep() -> LaunchStep? {
        guard !ladderMemoryKey.isEmpty,
              let raw = UserDefaults.standard.object(forKey: Self.launchStepKeyPrefix + ladderMemoryKey) as? Int
        else { return nil }
        return LaunchStep(rawValue: raw)
    }

    /// Запомнить ступеньку, на которой пришёл настоящий ответ.
    private func rememberStepWorked(_ step: LaunchStep) {
        guard !ladderMemoryKey.isEmpty else { return }
        UserDefaults.standard.set(step.rawValue, forKey: Self.launchStepKeyPrefix + ladderMemoryKey)
        UserDefaults.standard.removeObject(forKey: Self.ladderFailedPrefix + ladderMemoryKey)
    }

    /// Запомнить, что прошли всю лесенку и не помогло ничего. Иначе каждый запуск
    /// заново тратил бы минуты на бесполезные пересборки движка.
    private func rememberLadderFailed() {
        guard !ladderMemoryKey.isEmpty else { return }
        UserDefaults.standard.set(true, forKey: Self.ladderFailedPrefix + ladderMemoryKey)
    }

    private func didLadderFail() -> Bool {
        guard !ladderMemoryKey.isEmpty else { return false }
        return UserDefaults.standard.bool(forKey: Self.ladderFailedPrefix + ladderMemoryKey)
    }

    /// Ступеньки, на которых приложение падало.
    private func bannedSteps() -> Set<Int> {
        guard !ladderMemoryKey.isEmpty,
              let raw = UserDefaults.standard.array(forKey: Self.ladderBannedPrefix + ladderMemoryKey) as? [Int]
        else { return [] }
        return Set(raw)
    }

    private func banStep(_ step: LaunchStep) {
        guard !ladderMemoryKey.isEmpty else { return }
        var all = bannedSteps()
        all.insert(step.rawValue)
        UserDefaults.standard.set(Array(all).sorted(), forKey: Self.ladderBannedPrefix + ladderMemoryKey)
    }

    // MARK: Метка «пробуем ступеньку» — отдельным файлом, чтобы пережить падение

    /// ⚠️ Ровно та же хитрость, что и с меткой попытки на видеочипе, и по той же причине:
    /// падение приложения настройки на диск не сбрасывает, а файл с `.atomic` доходит сразу.
    private static func ladderAttemptFileURL() -> URL? {
        guard let base = try? FileManager.default.url(for: .applicationSupportDirectory,
                                                      in: .userDomainMask,
                                                      appropriateFor: nil,
                                                      create: true) else { return nil }
        return base.appendingPathComponent("ladder-attempt.flag")
    }

    private static func markLadderAttempt(key: String, step: LaunchStep) {
        guard let url = ladderAttemptFileURL() else { return }
        try? Data("\(step.rawValue)\n\(key)".utf8).write(to: url, options: .atomic)
    }

    private static func clearLadderAttemptMark() {
        guard let url = ladderAttemptFileURL() else { return }
        try? FileManager.default.removeItem(at: url)
    }

    /// Осталась ли метка с прошлого запуска — то есть упали ли мы на ступеньке.
    private static func consumeCrashedLadderStep() -> (step: Int, key: String)? {
        guard let url = ladderAttemptFileURL(),
              let data = try? Data(contentsOf: url),
              let text = String(data: data, encoding: .utf8) else { return nil }
        try? FileManager.default.removeItem(at: url)

        let parts = text.split(separator: "\n", maxSplits: 1, omittingEmptySubsequences: false)
        guard parts.count == 2, let step = Int(parts[0]) else { return nil }
        return (step: step, key: String(parts[1]))
    }

    // MARK: Метка «пробую увеличенную память разговора» — тоже файлом

    /// ⚠️ ПОЧЕМУ ФАЙЛ, А НЕ НАСТРОЙКИ. Известная беда увеличенного окна — не ошибка,
    /// а падение приложения ЦЕЛИКОМ прямо на создании движка. Настройки система сбрасывает
    /// на диск когда сочтёт нужным, и при таком отстреле значение до диска не долетает —
    /// то есть защита пропала бы ровно в том случае, ради которого заведена. Файл с `.atomic`
    /// доходит сразу. Тот же приём уже работает для видеочипа и для ступенек лесенки.
    private static func contextAttemptFileURL() -> URL? {
        guard let base = try? FileManager.default.url(for: .applicationSupportDirectory,
                                                      in: .userDomainMask,
                                                      appropriateFor: nil,
                                                      create: true) else { return nil }
        return base.appendingPathComponent("context-attempt.flag")
    }

    /// - Parameter phase: на чём именно мы сейчас (для журнала при следующем запуске):
    ///   «создание движка» или «первое сообщение».
    ///
    /// ⚠️ Номера сборки здесь НЕТ, и это отличие от памяти лесенки. Там мы забываем вывод
    /// при обновлении, потому что вывод делали МЫ и могли ошибиться. Здесь на диске лежит
    /// факт: приложение закрылось на этом числе. Факт обновлением не отменяется, а поднять
    /// число обратно человек может одним касанием — это его настройка, а не наш запрет.
    private static func markContextAttempt(tokens: Int, phase: String) {
        guard let url = contextAttemptFileURL() else { return }
        try? Data("\(tokens)\n\(phase)".utf8).write(to: url, options: .atomic)
    }

    private static func clearContextAttemptMark() {
        // ⚠️ СНЯЛИ МЕТКУ — ЗНАЧИТ МЫ ЖИВЫ, И СЧЁТЧИК ОБРЫВОВ ОБНУЛЯЕТСЯ. Считать надо
        // именно ПОДРЯД идущие: два несчастья, разделённые месяцем удачной работы, —
        // это не «телефон не тянет», а два разных случая. Без обнуления счётчик копился
        // бы годами и однажды снёс бы выбор человека на ровном месте.
        UserDefaults.standard.set(0, forKey: contextAbortCountKey)
        guard let url = contextAttemptFileURL() else { return }
        try? FileManager.default.removeItem(at: url)
    }

    /// Осталась ли метка с прошлого запуска — то есть убило ли нас на попытке.
    /// Метку сразу снимаем: она одноразовая.
    private static func consumeCrashedContextAttempt() -> (tokens: Int, phase: String)? {
        guard let url = contextAttemptFileURL(),
              let data = try? Data(contentsOf: url),
              let text = String(data: data, encoding: .utf8) else { return nil }
        try? FileManager.default.removeItem(at: url)

        let parts = text.split(separator: "\n", maxSplits: 1, omittingEmptySubsequences: false)
        guard parts.count == 2, let tokens = Int(parts[0]) else { return nil }
        return (tokens: tokens, phase: String(parts[1]))
    }

    /// Разобрать прошлую попытку увеличенного окна ДО того, как мы позовём движок.
    ///
    /// ⚠️ ПОРЯДОК ЗДЕСЬ И ЕСТЬ ВСЯ КРАХ-БЕЗОПАСНОСТЬ: метка кладётся на диск ПЕРЕД
    /// созданием движка и снимается сразу после удачи. Уцелела — значит удачи не было,
    /// а приложение между «положил» и «снял» закрылось не по своей воле. Это единственный
    /// признак, который переживает падение, и трактуем мы его в самую осторожную сторону.
    ///
    /// ⚠️ СЧИТАЕМ ОБРЫВЫ, А НЕ ОТСТУПАЕМ С ПЕРВОГО — ЭТО ИСПРАВЛЕНИЕ ЖИВОЙ ЖАЛОБЫ
    /// 09.08.2026 («поставил 32 000, поработало два раза, потом само вернулось на 4 096»).
    /// Раньше здесь стояло «один промах — и отступаем», и рассуждение было такое:
    /// неудачный видеочип — это медленнее, а неудачный размер памяти — это приложение,
    /// которое не открывается. Рассуждение оказалось неверным по факту: если движок
    /// честно НЕ СОЗДАЛСЯ, мы отступаем прямо на месте и в тот же заход (см. ветку
    /// `allowContextRetreat` в `makeEngine`) — приложение открывается само. Эта же метка
    /// ловит совсем другое: смерть всего процесса. А умереть нас заставляет что угодно —
    /// человек смахнул приложение из многозадачности, пока шло «Готовим движок»
    /// (десяток секунд и гигабайты весов), встала новая сборка, система выгрузила нас
    /// из фона. Засчитывать это как приговор ВЫБОРУ ЧЕЛОВЕКА нельзя: он ставил число
    /// сам, а мы стирали его молча и с первого раза.
    ///
    /// Поэтому мерка тут ровно та же, что у видеочипа: два обрыва подряд. Цена ошибки
    /// в худшем случае — второй неудачный запуск, а не потерянная настройка.
    private func consumePreviousContextAttempt() {
        guard !didCheckContextAttemptMark else { return }
        didCheckContextAttemptMark = true

        guard let crashed = Self.consumeCrashedContextAttempt() else { return }
        // Отступать некуда — мы и так на безопасном дне (метку могло оставить
        // отступление, которое само не пережило перезапуска).
        guard crashed.tokens > AgentLimits.contextTokenBudget else { return }

        // ⚠️ УЖЕ ВЗВЕДЁННАЯ МЕТКА АМНИСТИРУЕТСЯ САМА, ОТДЕЛЬНОГО КОДА НЕ НУЖНО, и вот
        // почему это здесь написано. На телефоне владельца 09.08.2026 метка лежала
        // ПРЯМО СЕЙЧАС («32000 / создание движка»), и по старому правилу первое же
        // открытие приложения снесло бы его выбор. Счётчика в настройках нет —
        // `integer(forKey:)` вернёт 0, значит этот обрыв станет ПЕРВЫМ, а не последним,
        // и выбор уцелеет. Специальной разовой поблажки писать не надо: правило само
        // трактует прошлое в пользу человека.
        let defaults = UserDefaults.standard
        let aborted = defaults.integer(forKey: Self.contextAbortCountKey) + 1
        defaults.set(aborted, forKey: Self.contextAbortCountKey)

        journal.record(.failure,
                       "В прошлый раз приложение закрылось, когда я просил "
                     + "\(ContextSizeSettings.text(crashed.tokens)) токенов памяти разговора",
                       detail: "обрыв \(aborted)-й подряд из \(Self.contextAbortsBeforeRetreat), "
                             + "после которых выбор переставляется · "
                             + "шаг: \(crashed.phase)")

        // ⚠️ ПЕРВЫЙ ОБРЫВ ВЫБОР НЕ ТРОГАЕТ. Пробуем то же число ещё раз: смерть процесса
        // сама по себе не отличает «телефону не по силам» от «человек смахнул приложение».
        guard aborted >= Self.contextAbortsBeforeRetreat else {
            journal.record(.engine,
                           "Пробую тот же размер памяти разговора ещё раз — "
                         + "одного закрытия мало, чтобы менять ваш выбор")
            return
        }

        retreatToSafeContext(from: crashed.tokens,
                             reason: "приложение закрылось на шаге «\(crashed.phase)»")
    }

    /// Сколько памяти нужно этой модели на текущей ступеньке.
    private func requiredMemoryMB(for step: LaunchStep) -> Int {
        let executors = recipe(for: step).executors
        return model.hardware == .gpuOnly
            ? model.gpuMemoryNeedMB(multimodal: executors)
            : model.cpuMemoryNeedMB(multimodal: executors)
    }

    /// Тот же гейт памяти, что был, но с учётом частей для картинок и звука.
    ///
    /// ⚠️ СВОЙ, А НЕ `MemoryGate.ensureEnoughMemory(for:)`: у того мерка всегда текстовая,
    /// и с картинками и звуком он пропустил бы вперёд заведомо безнадёжную загрузку —
    /// а дальше система молча убила бы приложение на середине.
    private func ensureEnoughMemoryForStep() throws {
        let available = MemoryGate.availableMemoryMB()
        let required = requiredMemoryMB(for: launchStep)
        guard available < required else { return }
        // Не отказываем, только пишем в журнал — см. LlamaRuntime (владелец 23.09.2026:
        // лимит памяти снят, прикидка не вправе запрещать запуск).
        journal.record(.engine, "Памяти по прикидке впритык — всё равно пробую",
                       detail: "свободно \(available) МБ · прикидка \(required) МБ")
    }

    /// Размер памяти разговора словами — для журнала.
    private static func cacheText(_ tokens: Int?) -> String {
        guard let tokens else { return "как в самой модели" }
        return "\(tokens) токенов"
    }

    /// Создание движка: сначала GPU, при неудаче — CPU.
    ///
    /// - Parameter allowContextRetreat: можно ли, если движок не создался вовсе, отступить
    ///   к безопасной памяти разговора и пересобрать его ещё раз. Ровно один раз: иначе
    ///   телефон, на котором увеличенное окно не поднимается, вообще не смог бы запустить
    ///   модель — человек получил бы «не удалось запустить» при каждом открытии приложения.
    private func makeEngine(modelPath: String, allowContextRetreat: Bool = true) async throws -> Engine {
        // Кэш обязателен: модель может лежать в бандле, а он только для чтения.
        let cacheDir = try ModelStorage.engineCacheDirectory().path
        let defaults = UserDefaults.standard

        // Система или сборка обновились — прошлый бан GPU больше ничего не значит.
        let stamp = Self.environmentStamp()
        if defaults.bool(forKey: Self.gpuBannedKey),
           defaults.string(forKey: Self.gpuBanStampKey) != stamp {
            defaults.set(false, forKey: Self.gpuBannedKey)
        }

        // Прошлый запуск начал инициализацию на GPU и не закончил её — значит нас убили
        // на этом месте. Один такой случай ещё ничего не доказывает: человек мог сам
        // смахнуть приложение из многозадачности, телефон мог разрядиться, система могла
        // выгрузить нас по памяти. Поэтому считаем обрывы и баним только со второго.
        if Self.consumeAbortedGPUAttempt() {
            let aborted = defaults.integer(forKey: Self.gpuAbortCountKey) + 1
            defaults.set(aborted, forKey: Self.gpuAbortCountKey)
            if aborted >= Self.gpuAbortsBeforeBan {
                Self.banGPU(reasonStamp: stamp)
            }
        }

        // Признак «это GPU» несём рядом со значением, а НЕ сравнением backend == .gpu:
        // Backend — case с параметром (.cpu() со скобками), и его соответствие Equatable
        // фреймворком не обещано. Так попытки не зависят от чужой синтезированной равности.
        // GPU просит заметно больше памяти, чем CPU (по замерам Google 1450 МБ против 607).
        // Не хватает под GPU — молча идём на CPU, а не падаем целиком.
        let gpuFitsInMemory = MemoryGate.canUseGPU(model)
        let plan = recipe(for: launchStep)

        if plan.forceGPU == nil {
            if defaults.bool(forKey: Self.gpuBannedKey) {
                journal.record(.backend, "Видеочип отключён после прошлых неудач — считаю на процессоре")
            } else if !gpuFitsInMemory {
                journal.record(.backend, "Под видеочип не хватает памяти — считаю на процессоре",
                               detail: "свободно: \(Self.freeMemoryText()) · "
                                     + "нужно на видеочипе: \(model.gpuMemoryRequirementMB) МБ")
            }
        }

        var attempts: [(isGPU: Bool, backend: Backend)] = []

        // ⚠️ НА СТУПЕНЬКЕ «ДРУГОЙ РАСЧЁТ» РАСЧЁТ ЗАДАН ЖЁСТКО — И ЗАПАСНОГО ПУТИ НЕТ.
        // Смысл ступеньки в том, чтобы проверить ИМЕННО ЭТОТ расчёт; молча свалившись
        // на прежний, мы получили бы «ступенька прошла», а работало бы ровно то, что уже
        // не работало. Заодно здесь мы намеренно не смотрим ни на наш порог памяти для
        // видеочипа, ни на прошлый бан: и то, и другое — наши прикидки, а проверяем мы
        // как раз их. Не поднялось — лесенка просто идёт дальше.
        if let forced = plan.forceGPU {
            attempts.append(forced ? (isGPU: true, backend: .gpu) : (isGPU: false, backend: .cpu()))
        } else {
            // Прикидка памяти больше не запрещает видеочип сборке, у которой другого
            // пути нет (владелец 23.09.2026: лимит снят — пусть решает система).
            if !defaults.bool(forKey: Self.gpuBannedKey),
               gpuFitsInMemory || model.hardware == .gpuOnly {
                // TODO(API): у Backend в LiteRTLM 0.15.0 `.cpu()` — кейс с параметрами,
                // а `.gpu` пишется БЕЗ скобок. Если компилятор скажет «Member 'gpu' expects
                // argument» — дописать скобки: `.gpu()`. Сверять по исходникам пакета
                // (Vendor/LiteRTLM/Sources/LiteRTLM/Config.swift), а не по памяти.
                attempts.append((isGPU: true, backend: .gpu))
            }

            // ⚠️ ПОПЫТКА НА ПРОЦЕССОРЕ ГОДИТСЯ НЕ ВСЕГДА. У сборки «только для видеочипа»
            // запасного пути нет физически: внутри файла стоит запрет, и на процессоре она
            // не поднимется никогда. Пока попытка добавлялась безусловно, выходило вот что:
            // видеочипу не хватило памяти → единственной попыткой оставался процессор →
            // движок падал → человек читал «не удалось запустить, закройте другие приложения
            // или скачайте модель заново» и делал бесполезное — ни то, ни другое не помогает.
            // Владелец так это и описал: «должна спокойно грузиться, а почему-то не грузится».
            // Теперь в таком случае честно говорим про память, а не изображаем попытку.
            if model.hardware != .gpuOnly {
                attempts.append((isGPU: false, backend: .cpu()))
            }
        }

        guard !attempts.isEmpty else {
            journal.record(.backend,
                           "Эта модель работает только на видеочипе, а памяти ему не хватает",
                           detail: "свободно: \(Self.freeMemoryText()) · "
                                 + "нужно на видеочипе: \(model.gpuMemoryRequirementMB) МБ")
            throw PocketAgentError.notEnoughMemory(availableMB: MemoryGate.availableMemoryMB(),
                                                   requiredMB: model.gpuMemoryRequirementMB)
        }

        var lastError: Error?

        // Просим ли мы у движка БОЛЬШЕ безопасного дна. Смотрим именно на то, что уйдёт
        // в движок сейчас, а не на запомненный потолок: на ступеньке «размер из самой
        // модели» мы не просим ничего, и приписывать её неудачу увеличенному окну нельзя.
        let askedTokens = plan.maxTokens ?? 0
        let askingRaised = askedTokens > AgentLimits.contextTokenBudget
        if askingRaised {
            journal.record(.engine,
                           "Прошу память разговора \(ContextSizeSettings.text(askedTokens)) токенов — "
                         + "так выбрано в «О программе»",
                           detail: "безопасное значение: \(ContextSizeSettings.text(AgentLimits.contextTokenBudget)) · "
                                 + "свободно: \(Self.freeMemoryText()) · "
                                 + "поедет или нет — покажет только живой запуск")
        }

        for attempt in attempts {
            let isGPU = attempt.isGPU
            if isGPU { Self.markGPUAttemptStarted() }
            // ⚠️ ОТМЕТКА ЛОЖИТСЯ НА ДИСК ДО ТОГО, КАК МЫ ПОЗОВЁМ ДВИЖОК. Именно здесь
            // приложение может закрыться целиком, и тогда единственное, что переживёт
            // падение, — этот файл. Снимается сразу после удачного создания.
            if askingRaised { Self.markContextAttempt(tokens: askedTokens, phase: "создание движка") }
            let backendWord = isGPU ? "видеочипе" : "процессоре"
            // ⚠️ ЗДЕСЬ ЖЕ ЗАСЕКАЕТСЯ ВРЕМЯ ПОПЫТКИ (это делает сам noteLoadAttempt).
            // Создание движка — десяток секунд и гигабайты весов; попытка, уложившаяся
            // в сотые доли секунды, означает, что библиотека даже не бралась за файл.
            journal.noteLoadAttempt(fileName: URL(fileURLWithPath: modelPath).lastPathComponent,
                                    fileSizeText: HumanFormat.bytes(model.byteSize),
                                    backend: backendWord,
                                    askedTokens: plan.maxTokens,
                                    chosenTokens: contextCeiling,
                                    freeMemoryMB: MemoryGate.availableMemoryMB(),
                                    needMemoryMB: isGPU
                                        ? model.gpuMemoryNeedMB(multimodal: plan.executors)
                                        : model.cpuMemoryNeedMB(multimodal: plan.executors),
                                    stepNumber: launchStep.rawValue,
                                    stepName: launchStep.journalName,
                                    executors: plan.executors)

            do {
                // ⚠️ Исполнители картинок и звука — ВСЕГДА на процессоре, даже когда сам
                // текст считает видеочип. Так это показано в примере Google для Swift
                // (backend: .gpu, visionBackend: .cpu(), audioBackend: .cpu()).
                //
                // ⚠️ И по умолчанию их НЕТ, даже у мультимодальной модели. Официальный
                // пример Google для iOS гоняет мультимодальную Gemma 4, не передавая их
                // вовсе, — значит «молчит без них» неправда, а памяти они просят изрядно.
                // Поэтому они — последняя ступенька лесенки, а не первая.
                let executors: Backend? = plan.executors ? .cpu() : nil
                let config = try EngineConfig(
                    modelPath: modelPath,
                    backend: attempt.backend,
                    visionBackend: executors,
                    audioBackend: executors,
                    maxNumTokens: plan.maxTokens,
                    cacheDir: cacheDir
                )
                let engine = Engine(engineConfig: config)
                // Занимает секунды. Engine — actor, поэтому главный поток не блокируется.
                try await engine.initialize()

                Self.clearGPUAttemptMark()
                // Движок создался и не убил приложение — на этом шаге попытка удалась.
                Self.clearContextAttemptMark()
                if isGPU { defaults.set(0, forKey: Self.gpuAbortCountKey) }
                activeBackendName = isGPU ? "GPU" : "CPU"
                // Размер памяти разговора запоминаем ровно здесь: движок поднялся именно
                // с этим числом. `plan.maxTokens == nil` — это ступенька «сколько скажет
                // сама модель»: спросить у библиотеки выданный размер нечем (в её API
                // такого вопроса нет), поэтому берём безопасные 4096 — ровно под них
                // скомпилированы все Gemma, и ровно столько стоит в примерах Google.
                grantedContextTokens = plan.maxTokens ?? AgentLimits.contextTokenBudget
                // Окно у нового движка своё — значит и «пережили ли мы на нём первый ход»
                // надо выяснять заново, а не наследовать от прошлого.
                didSurviveRaisedTurn = false
                // ⚠️ «Просил — дали — выбор человека» тремя числами В ОДНОЙ СТРОКЕ.
                // Расхождение между вторым и третьим и есть та самая поломка, за которой
                // 09.08.2026 пришлось лезть в телефон владельца: движок отдал свои 4 096,
                // а на странице «О программе» у человека по-прежнему стояли 32 000.
                journal.noteLoadResult(backend: backendWord,
                                       askedTokens: plan.maxTokens,
                                       grantedTokens: grantedContextTokens,
                                       chosenTokens: contextCeiling,
                                       freeMemoryMB: MemoryGate.availableMemoryMB())
                return engine
            } catch {
                lastError = error
                Self.clearGPUAttemptMark()
                // Ошибка — это не падение: мы живы и сами её поймали. Метку снимаем,
                // иначе следующий запуск счёл бы честную ошибку падением приложения.
                Self.clearContextAttemptMark()
                // Числа повторяются намеренно: строка неудачи должна читаться сама по себе,
                // без поиска строки выше. Следующая строка журнала («Пробую поднять модель
                // на процессоре») и покажет, что мы перешли на запасной расчёт.
                journal.noteLoadFailed(backend: backendWord,
                                       askedTokens: plan.maxTokens,
                                       freeMemoryMB: MemoryGate.availableMemoryMB(),
                                       error: error)
                // Один раз откатились — дальше на этом устройстве не тратим время,
                // но помним, на какой версии системы это случилось.
                //
                // ⚠️ КРОМЕ ПОПЫТОК НА ЛЕСЕНКЕ. Когда мы меняем настройки, неудача может
                // быть про НИХ, а не про видеочип, — а бан остался бы навсегда и оставил
                // человека на вдвое более медленном расчёте из-за чужой беды.
                //
                // ⚠️ И КРОМЕ ПОПЫТОК С УВЕЛИЧЕННЫМ ОКНОМ — ПО ТОЙ ЖЕ ПРИЧИНЕ. Увеличенное
                // окно просит заметно больше памяти, и не поднявшийся с ним видеочип
                // не доказывает, что видеочип плох: с обычным окном он, скорее всего,
                // поднимется. Забань мы его здесь — человек навсегда остался бы
                // на процессоре из-за нашей же проверки гипотезы. Ниже мы отступим
                // к безопасному окну и попробуем видеочип честно, ещё раз.
                if isGPU, launchStep == .ours, !askingRaised {
                    Self.banGPU(reasonStamp: Self.environmentStamp())
                }
            }
        }

        // ⚠️ ДВИЖОК НЕ СОЗДАЛСЯ ВООБЩЕ, А МЫ ПРОСИЛИ БОЛЬШЕ ОБЫЧНОГО — СНАЧАЛА ПОДОЗРЕВАЕМ
        // СЕБЯ. Без этого телефон, которому увеличенное окно не по силам, не запустил бы
        // модель НИКОГДА: человек видел бы «не удалось запустить» при каждом открытии
        // и не имел бы ни одной кнопки, чтобы это исправить. Отступаем, запоминаем
        // и пересобираем ровно один раз — вторая неудача уже про модель, а не про окно.
        if allowContextRetreat, askingRaised {
            retreatToSafeContext(from: askedTokens,
                                 reason: "движок не создался с этим размером памяти разговора")
            return try await makeEngine(modelPath: modelPath, allowContextRetreat: false)
        }

        // ⚠️ Без своей приставки: перевод ошибки движка уже начинается со слов
        // «Не удалось запустить модель…». С приставкой человек читал это дважды подряд
        // в одном предложении — видно на разборе от владельца 09.08.2026.
        throw PocketAgentError.generationFailed(
            Self.humanMessage(lastError ?? PocketAgentError.runtimeNotReady)
        )
    }

    /// Разрешить попытку на GPU заново.
    /// Зовётся сама при смене версии системы или сборки приложения, а ещё её дёргает
    /// кнопка «Попробовать ускорение заново» в «О программе» — раньше снять бан было нечем.
    public func allowGPUAgain() {
        UserDefaults.standard.set(false, forKey: Self.gpuBannedKey)
        UserDefaults.standard.set(0, forKey: Self.gpuAbortCountKey)
        UserDefaults.standard.removeObject(forKey: Self.gpuBanStampKey)
        Self.clearGPUAttemptMark()
    }

    /// Отключено ли сейчас ускорение — для строки в «О программе».
    public func isGPUDisabled() -> Bool {
        UserDefaults.standard.bool(forKey: Self.gpuBannedKey)
    }

    // MARK: Метка «попытка на GPU началась» — отдельным файлом

    /// Файл-метка. Именно файл, а не UserDefaults: запись файла с `.atomic` доходит
    /// до диска сразу, а настройки система сбрасывает когда сочтёт нужным — и при
    /// жёстком отстреле процесса метка терялась вместе с защитой, ради которой заведена.
    private static func gpuAttemptFileURL() -> URL? {
        guard let base = try? FileManager.default.url(for: .applicationSupportDirectory,
                                                      in: .userDomainMask,
                                                      appropriateFor: nil,
                                                      create: true) else { return nil }
        return base.appendingPathComponent("gpu-attempt.flag")
    }

    private static func markGPUAttemptStarted() {
        guard let url = gpuAttemptFileURL() else { return }
        let stamp = "\(Date().timeIntervalSince1970)"
        try? Data(stamp.utf8).write(to: url, options: .atomic)
    }

    private static func clearGPUAttemptMark() {
        guard let url = gpuAttemptFileURL() else { return }
        try? FileManager.default.removeItem(at: url)
    }

    /// Была ли прошлая попытка оборвана вместе с приложением. Метку сразу снимаем.
    private static func consumeAbortedGPUAttempt() -> Bool {
        guard let url = gpuAttemptFileURL(),
              FileManager.default.fileExists(atPath: url.path) else { return false }
        try? FileManager.default.removeItem(at: url)
        return true
    }

    /// Запретить GPU и записать, при какой версии системы это случилось.
    private static func banGPU(reasonStamp: String) {
        UserDefaults.standard.set(true, forKey: gpuBannedKey)
        UserDefaults.standard.set(reasonStamp, forKey: gpuBanStampKey)
    }

    /// Сколько памяти ещё можно занять, готовой строкой для журнала.
    ///
    /// ⚠️ На симуляторе и в части конфигураций система отвечает «не знаю», и MemoryGate
    /// отдаёт `Int.max`. Печатать в журнал двадцатизначное число — значит подсунуть
    /// человеку выдуманный факт; честнее написать «неизвестно».
    private static func freeMemoryText() -> String {
        let megabytes = MemoryGate.availableMemoryMB()
        return megabytes == Int.max ? "неизвестно" : "\(megabytes) МБ"
    }

    /// «Версия системы + версия сборки» — метка окружения для бана GPU.
    private static func environmentStamp() -> String {
        let os = ProcessInfo.processInfo.operatingSystemVersion
        let build = Bundle.main.infoDictionary?["CFBundleVersion"] as? String ?? "?"
        return "\(os.majorVersion).\(os.minorVersion).\(os.patchVersion)-\(build)"
    }

    // MARK: - Разговор

    public func beginSession(systemPrompt: String, tools: [ToolDeclaration]) async throws {
        guard let engine else { throw PocketAgentError.runtimeNotReady }

        self.systemPrompt = systemPrompt
        self.declarations = tools
        LiteRTToolSchemas.warnIfOutOfSync(with: tools)

        // Старый разговор отпускаем ДО создания нового: у Conversation нет close(),
        // нативная память освобождается только в deinit.
        conversation = nil
        unansweredCalls = []

        let plan = recipe(for: launchStep)

        let sampler: SamplerConfig
        do {
            sampler = plan.googleSampler
                ? try SamplerConfig(topK: Self.googleSamplerTopK,
                                    topP: Self.googleSamplerTopP,
                                    temperature: Self.googleSamplerTemperature,
                                    seed: 0)
                : try SamplerConfig(topK: Self.samplerTopK,
                                    topP: Self.samplerTopP,
                                    temperature: Self.samplerTemperature,
                                    seed: 0)
        } catch {
            throw PocketAgentError.generationFailed(Self.humanMessage(error))
        }

        // Системное сообщение фреймворк сам переведёт в роль .system.
        // TODO(API): у Swift-части пакета конструктор Message помечен как ранний, и авторы
        // собираются перевести его на форму `from:`. Перед первой сборкой сверить обе формы
        // (позиционный текст + role и вариант contents:role:) по исходникам 0.15.0.
        let systemMessage = Message(systemPrompt, role: .system)

        // ⚠️ ПУСТОЙ СПИСОК ДЕЙСТВИЙ ПЕРЕДАЁМ НАПРЯМУЮ, А НЕ ЧЕРЕЗ tools(matching:).
        // Тот на пустой список отдаёт ВСЕ известные действия (так задумано для обычной
        // работы) — и ступенька «без списка действий» проверяла бы ровно то же самое.
        let toolSchemas = plan.tools ? LiteRTToolSchemas.tools(matching: tools) : []

        // ⚠️ ЗАМОК НА ФОРМЕ ВЫЗОВА СНИМАЕТСЯ САМ, ЕСЛИ ОДНАЖДЫ ПОМЕШАЛ НАЧАТЬ РАЗГОВОР.
        // Это не перестраховка ради перестраховки: библиотека приезжает к нам готовым
        // двоичным файлом, и собран ли в нём тот самый ограничитель, из исходников
        // не видно — заголовков C у нас нет вовсе. Не соберись он — разговор не создался бы
        // ВООБЩЕ, и лесенка настроек тут не спасла бы: она ходит по неудачным ОТВЕТАМ,
        // а до ответа дело бы не дошло. Приложение оказалось бы мёртвым до переустановки.
        // Поэтому отметку о такой неудаче переживаем на диске, ровно как бан видеочипа.
        let constrainedCalls = plan.constrainedCalls && !Self.isConstrainedDecodingBanned

        let config = ConversationConfig(
            systemMessage: systemMessage,
            tools: toolSchemas,
            samplerConfig: sampler,
            // Для модели на 2 млрд параметров «размышления» — потраченные токены.
            // ⚠️ Но это НАШЕ решение, а не требование модели: на ступеньке
            // «не запрещаю размышлять» мы вообще ничего не навязываем и берём то,
            // что заложено в самой модели, — Gemma 4 с этим режимом живёт по-своему.
            thinkingConfig: plan.thinkingOff ? ThinkingConfig(enableThinking: false) : nil,
            // ← ГЛАВНОЕ: инструменты не выполняются сами, вызовы возвращаются нам.
            automaticToolCalling: false,
            // ⚠️ ЭТО НЕ «ФОРМАТ ОТВЕТА», А ЗАМОК НА ФОРМЕ ВЫЗОВА, и разница здесь
            // принципиальная. Поле включает у движка принудительную выдачу: на каждом
            // шаге отсекаются буквы, которые ломают синтаксис вызова действия. Схему
            // на СОДЕРЖИМОЕ файла мы при этом не навязываем никогда — для этого нужно
            // отдельно передать responseFormat в sendMessage, и мы его не передаём.
            // Так и задумано: замеры чужой работы «The Constraint Tax» показали, что
            // жёсткая схема на содержимое роняет осмысленность ответа почти вдвое,
            // тогда как замок на одной лишь форме вызова поднимает долю верных вызовов
            // у модели нашего размера с 49,5 % до 78,1 %.
            // До этой правки форму вызова у нас не держало ничто, кроме уговоров словами.
            enableResponseFormat: constrainedCalls
        )

        do {
            conversation = try await engine.createConversation(with: config)
            journal.record(.engine, "Начал разговор с моделью",
                           detail: "действий в наборе: \(toolSchemas.count) · "
                                 + "кэш разговора: \(Self.cacheText(plan.maxTokens)) · "
                                 + "выбор слов: \(plan.googleSampler ? "как у Google" : "наш строгий") · "
                                 + "размышления: \(plan.thinkingOff ? "запрещены нами" : "как в модели") · "
                                 + "ответ: \(plan.streaming ? "по частям" : "одним куском") · "
                                 + "форма вызова: \(constrainedCalls ? "держим принудительно" : "на совести модели")")
        } catch {
            // Разговор не создался, а замок на форме вызова был включён — пробуем ровно
            // один раз без него и запоминаем отказ навсегда. Один лишний вызов ценой
            // в доли секунды против неработающего приложения — обмен очевидный.
            if constrainedCalls {
                journal.record(.failure,
                               "Движок не принял принудительную форму вызова — "
                             + "начинаю разговор без неё и больше её не прошу")
                Self.banConstrainedDecoding()
                try await beginSession(systemPrompt: systemPrompt, tools: tools)
                return
            }
            let human = Self.humanMessage(error)
            journal.recordFailure(stage: "начало разговора",
                                  human: human,
                                  technical: RuntimeJournal.technicalText(for: error))
            throw PocketAgentError.generationFailed(human)
        }
    }

    /// Где помним, что движок не принял принудительную форму вызова.
    ///
    /// ⚠️ Отметка ОБЩАЯ на приложение, а не на модель, и это осознанно: ограничитель
    /// либо собран в библиотеке, либо нет — от того, какой файл модели открыт, это
    /// не зависит. Снимается она сама вместе со сменой версии сборки (там может
    /// приехать другая библиотека) — ровно тем же приёмом, что и бан видеочипа.
    private static let constrainedBanKey = "pocketagent.runtime.constrainedCallsDisabled"
    private static let constrainedBanStampKey = "pocketagent.runtime.constrainedCallsDisabled.stamp"

    private static var isConstrainedDecodingBanned: Bool {
        guard UserDefaults.standard.bool(forKey: constrainedBanKey) else { return false }
        let stamp = UserDefaults.standard.string(forKey: constrainedBanStampKey)
        guard stamp == environmentStamp() else {
            // Сборка сменилась — прежний отказ ничего не доказывает про нынешнюю библиотеку.
            UserDefaults.standard.removeObject(forKey: constrainedBanKey)
            UserDefaults.standard.removeObject(forKey: constrainedBanStampKey)
            return false
        }
        return true
    }

    private static func banConstrainedDecoding() {
        UserDefaults.standard.set(true, forKey: constrainedBanKey)
        UserDefaults.standard.set(environmentStamp(), forKey: constrainedBanStampKey)
    }

    public func send(userText: String) async throws -> ModelTurn {
        let trimmed = userText.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else {
            throw PocketAgentError.generationFailed("Пустой запрос.")
        }
        // Человек начал новый ход сам — отвечать на отброшенные вызовы прошлого хода
        // уже некуда: их id относятся к другому шагу.
        unansweredCalls = []
        return try await performTurn(Message(trimmed, role: .user))
    }

    public func send(toolResult: ToolResult) async throws -> ModelTurn {
        // Ответ инструмента уходит модели тем же каналом и при отказе человека —
        // модель обязана узнать, что действие не выполнено.
        // TODO(API): сверить с исходниками пакета 0.15.0 фабрику Content.toolResponse
        // (порядок и имена меток name/response/id) и конструктор Message(contents:role:).
        let response = Content.toolResponse(name: toolResult.toolName,
                                            response: toolResult.payload.jsonObject,
                                            id: toolResult.callID)

        // Модель за один ход могла попросить несколько инструментов. Выполняем мы РОВНО
        // ОДИН (продуктовое решение), но остальные вызовы обязаны получить ответ:
        // иначе модель считает их выполненными, а протокол вызовов ругается на
        // неотвеченные id. Отказы отправляем вместе с настоящим ответом.
        var contents = [response]
        for skipped in unansweredCalls {
            contents.append(Content.toolResponse(
                name: skipped.name,
                response: ["error": Self.oneActionPerTurnNotice],
                id: skipped.id
            ))
        }
        unansweredCalls = []

        return try await performTurn(Message(contents: contents, role: .tool))
    }

    /// Что отвечаем на лишние вызовы инструментов в одном ходе.
    private static let oneActionPerTurnNotice =
        "За один ход выполняется ровно одно действие. Это действие не выполнено — "
        + "повтори его следующим ходом, если оно всё ещё нужно."

    /// Отступить на безопасный размер памяти разговора и повторить тот же ход.
    ///
    /// ⚠️ Размер кэша задаётся при СОЗДАНИИ движка, а не разговора, — поэтому пересобрать
    /// приходится всё: движок, разговор, системную инструкцию и набор действий. Это секунды
    /// и случается один раз: выбор человека при этом переставляется на безопасный,
    /// и он видит на странице «О программе», почему.
    /// Переписка человека при этом не теряется — цикл агента ведёт её у себя.
    private func retryWithSmallerContext(_ message: Message, reason: String) async throws -> Message {
        let asked = grantedContextTokens
        journal.record(.engine,
                       "Похоже, памяти разговора взято больше, чем телефон тянет — уменьшаю и пробую снова",
                       detail: "было: \(ContextSizeSettings.text(asked)) токенов · "
                             + "станет: \(ContextSizeSettings.text(AgentLimits.contextTokenBudget))")
        retreatToSafeContext(from: asked, reason: reason)

        let revived = try await restartEngine(at: launchStep)
        journal.record(.engine, "Движок перезапущен на безопасном размере памяти разговора")
        return try await revived.sendMessage(message)
    }

    // MARK: - Подъём по лесенке

    /// Пройти по лесенке настроек, пока модель не заговорит.
    ///
    /// ⚠️ РАДИ ЭТОГО ВСЁ И ЗАТЕВАЛОСЬ. Эта же модель на этом же телефоне отвечает
    /// в приложении Google — значит рабочая настройка существует, и наша от неё чем-то
    /// отличается. Проверить на месте нечем: телефон один и он у владельца. Поэтому
    /// проверяет само приложение — по одной настройке за раз, с записью в журнал.
    ///
    /// ⚠️ ГРАНИЦЫ. Один проход за запуск приложения; ступеньки, на которых приложение
    /// падало, пропускаются навсегда; удачная — запоминается за этой моделью; если
    /// не помогла ни одна, это тоже запоминается, и в следующий раз лесенки не будет.
    ///
    /// - Returns: ответ модели, если какая-то ступенька помогла. nil — не помогла ни одна.
    private func climbLadder(_ message: Message) async throws -> Message? {
        didWalkLadder = true
        let startedAt = launchStep
        let banned = bannedSteps()
        var interrupted = false

        journal.record(.engine, "Модель не отвечает — иду по настройкам, меняя по одной",
                       detail: "начинаю после ступеньки: \(startedAt.journalName)")

        for step in LaunchStep.allCases where step.rawValue > startedAt.rawValue {
            // Человек нажал «Стоп» или свернул приложение — подбор бросаем немедленно.
            // Подъём по лесенке долгий, и молча продолжать его после отказа нельзя.
            if didCancelCurrentTurn || Task.isCancelled {
                journal.record(.engine, "Подбор настроек прерван — так решил человек")
                interrupted = true
                break
            }
            if banned.contains(step.rawValue) {
                journal.record(.engine, "Пропускаю настройку «\(step.journalName)» — "
                                      + "на ней приложение уже падало")
                continue
            }
            if step == .withExecutors, !modalities.isMultimodal {
                journal.record(.engine, "Пропускаю настройку «\(step.journalName)» — "
                                      + "в этой модели картинок и звука нет")
                continue
            }

            // Отдельной строки «пробую такую-то» здесь больше нет: полное описание ступеньки
            // (номер, название, откуда взялась, что просит у движка) пишет `noteStepChosen`
            // внутри `attempt` — обоими путями, и с пересборкой движка, и без неё.
            // Здесь только засечка: сколько эта проба заняла.
            journal.startStage(.ladderStep)

            do {
                let reply = try await attempt(step: step, message: message)
                if !Self.isEmptyReply(reply) {
                    journal.noteLadderOutcome(number: step.rawValue,
                                              name: step.journalName,
                                              answered: true)
                    noteModelAnswered(at: step)
                    return reply
                }
                journal.noteLadderOutcome(number: step.rawValue,
                                          name: step.journalName,
                                          answered: false,
                                          note: "ответа всё равно нет")
            } catch {
                journal.noteLadderFailed(number: step.rawValue,
                                         name: step.journalName,
                                         error: error)
            }
        }

        // ⚠️ «Не помогло ничего» записываем ТОЛЬКО если действительно прошли всё до конца.
        // Прерванный человеком подбор — это не приговор настройкам: запиши мы его как
        // неудачу, приложение больше никогда бы не попробовало подобрать их заново.
        if interrupted {
            didWalkLadder = false
        } else {
            journal.record(.failure, "Прошёл все настройки — модель так и не ответила",
                           detail: "модель: \(model.displayName) · файл: \(model.fileName)")
            rememberLadderFailed()
        }

        // ⚠️ ВОЗВРАЩАЕМСЯ К ОБЫЧНОЙ НАСТРОЙКЕ, И ЭТО ОБЯЗАТЕЛЬНО. Лесенка не помогла —
        // значит нельзя оставлять приложение на последней пробе: там может не быть списка
        // действий или стоять чужой расчёт, и человек молча получил бы полуживой агент.
        // Заодно это оживляет разговор, если последняя ступенька его уронила.
        if launchStep != .ours || conversation == nil {
            journal.record(.engine, "Возвращаю обычную настройку — ни одна проба не помогла")
            _ = try? await restartEngine(at: .ours)
        }
        return nil
    }

    /// Одна ступенька: перестроить ровно то, что нужно, и повторить тот же вопрос.
    ///
    /// ⚠️ Движок пересобираем ТОЛЬКО когда поменялось то, что он держит (размер памяти
    /// разговора, расчёт, исполнители) — это десяток секунд и гигабайты. Всё остальное
    /// живёт в разговоре и стоит секунды.
    private func attempt(step: LaunchStep, message: Message) async throws -> Message {
        let before = recipe(for: launchStep)
        let after = recipe(for: step)

        // Метка на диске: если приложение сейчас упадёт, при следующем запуске мы
        // увидим её и больше эту ступеньку не тронем.
        Self.markLadderAttempt(key: ladderMemoryKey, step: step)
        defer { Self.clearLadderAttemptMark() }

        let conversationToUse: Conversation
        // Движок мог не пережить прошлую ступеньку — тогда пересобираем его в любом случае,
        // иначе все оставшиеся ступеньки подряд упрутся в «движок не запущен».
        if after.needsNewEngine(comparedTo: before) || engine == nil {
            conversationToUse = try await restartEngine(at: step)
        } else {
            launchStep = step
            // Движок не пересобираем — значит `decideLaunchStep` не позовут, и ступенька
            // осталась бы в журнале неназванной. Пишем её здесь тем же событием.
            noteStepChosen(.climbing)
            let prompt = systemPrompt
            let tools = declarations
            try await beginSession(systemPrompt: prompt, tools: tools)
            guard let alive = conversation else { throw PocketAgentError.sessionNotStarted }
            conversationToUse = alive
        }

        // Ответ по частям — отдельный путь: именно так работает официальный пример Google,
        // а у нас пустоту возвращает как раз обычный, «одним куском».
        // ⚠️ Поток разрешён только БЕЗ списка действий: с инструментами он выполняет их сам,
        // не спрашивая человека, — а это прямо против главного правила приложения.
        if after.streaming {
            guard !after.tools else { throw PocketAgentError.runtimeNotReady }
            return try await collectStreamedAnswer(conversationToUse, message: message)
        }
        return try await conversationToUse.sendMessage(message)
    }

    /// Забрать ответ по частям и собрать в одно сообщение.
    private func collectStreamedAnswer(_ conversation: Conversation,
                                       message: Message) async throws -> Message {
        var text = ""
        for try await chunk in conversation.sendMessageStream(message) {
            if Task.isCancelled {
                try? conversation.cancel()
                break
            }
            for content in chunk.contents {
                if case .text(let piece) = content { text += piece }
            }
        }
        return Message(text, role: .model)
    }

    /// Пересобрать движок и разговор на заданной ступеньке.
    ///
    /// ⚠️ Размер памяти разговора, расчёт и исполнители задаются при СОЗДАНИИ движка,
    /// а не разговора, — поэтому пересобирать приходится всё: движок, разговор, системную
    /// инструкцию и набор действий. Переписка человека при этом не теряется: её ведёт
    /// цикл агента.
    private func restartEngine(at step: LaunchStep) async throws -> Conversation {
        let prompt = systemPrompt
        let tools = declarations

        conversation = nil
        engine = nil
        setStatus(.idle)

        // ⚠️ ДАЁМ ПАМЯТИ ВЕРНУТЬСЯ. Веса освобождаются, когда умирает последняя ссылка
        // на движок, но система отдаёт эту память не в тот же миг. На разборе от владельца
        // перезапуск случился мгновенно и увидел 1516 МБ свободных вместо 3343 — движок
        // не создался, и человек получил «Разговор не начат» на ровном месте.
        // Ждём, пока свободная память вернётся хотя бы к тому, что нужно этой модели.
        await waitForMemoryToSettle(atLeast: requiredMemoryMB(for: step))

        // Приказ действует ровно на одну сборку движка и снимается сразу же:
        // иначе следующий обычный запуск унаследовал бы ступеньку от неудачной попытки.
        forcedStep = step
        defer { forcedStep = nil }

        // isPreparing/isGenerating сняты не будут: prepare() смотрит только на свой флаг,
        // а мы сейчас внутри хода — поэтому вызываем его напрямую и сразу открываем сессию.
        try await prepare()
        try await beginSession(systemPrompt: prompt, tools: tools)

        guard let revived = conversation else { throw PocketAgentError.sessionNotStarted }
        return revived
    }

    /// Стоит ли вообще идти по лесенке.
    private var canClimbLadder: Bool {
        !didWalkLadder && !isStepConfirmed
    }

    /// Ответ, в котором нет ни слова и ни одного вызова действия.
    private static func isEmptyReply(_ reply: Message) -> Bool {
        reply.toolCalls.isEmpty
            && reply.toString.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }

    /// Модель заговорила — запоминаем настройку за этой моделью, чтобы следующий запуск
    /// сразу шёл к ней, а не перебирал всё заново.
    private func noteModelAnswered(at step: LaunchStep) {
        launchStep = step

        // ⚠️ ЕДИНСТВЕННОЕ НАСТОЯЩЕЕ ДОКАЗАТЕЛЬСТВО, ЧТО ВЫБРАННЫЙ РАЗМЕР РАБОТАЕТ, —
        // ВОТ ЭТО: живая модель на живом телефоне ответила словами. Ни закрытый баг
        // в чужом трекере, ни слова инженера в обсуждении доказательством не были.
        // Пишем один раз за запуск: человек копирует журнал кнопкой и должен видеть пару
        // «попросил столько-то — получилось», а не одну и ту же строку после каждого хода.
        if !didConfirmRaisedContext, grantedContextTokens > AgentLimits.contextTokenBudget {
            didConfirmRaisedContext = true
            journal.record(.engine,
                           "Память разговора \(ContextSizeSettings.text(grantedContextTokens)) работает — "
                         + "модель на ней ответила",
                           detail: "выбор человека принят движком без отступления")
        }

        guard !isStepConfirmed else { return }
        isStepConfirmed = true
        rememberStepWorked(step)
        journal.record(.engine, "Настройка подошла: \(step.journalName) — запомнил её для этой модели")

        // ⚠️ Об этом человек обязан знать прямо, а не догадываться по поведению:
        // без списка действий модель может только разговаривать, а работать
        // с файлами — нет. Это половина приложения.
        if !recipe(for: step).tools {
            journal.record(.failure,
                           "Отвечает только без списка действий — с файлами эта модель работать не сможет, "
                         + "только разговаривать")
        }
    }

    /// Отправить сообщение в текущий разговор.
    ///
    /// ⚠️ ОТДЕЛЬНЫМ МЕТОДОМ, И ЭТО НЕ КРАСОТА, А ПАМЯТЬ. Пока ссылка на разговор жила
    /// локальной переменной внутри всего хода, старый разговор оставался жив до конца
    /// метода — даже после `conversation = nil`. А значит и веса модели не освобождались.
    /// Из-за этого перезапуск движка на меньшей памяти падал: на разборе от владельца
    /// 09.08.2026 в момент перезапуска свободной памяти было 1516 МБ вместо 3343, и движок
    /// не создался вовсе. Здесь ссылка умирает вместе с возвратом из метода.
    private func sendToConversation(_ message: Message) async throws -> Message {
        guard let conversation else { throw PocketAgentError.sessionNotStarted }

        // ⚠️ ВТОРОЕ МЕСТО, ГДЕ УВЕЛИЧЕННОЕ ОКНО МОЖЕТ УБИТЬ ПРИЛОЖЕНИЕ, — ПЕРВОЕ СООБЩЕНИЕ.
        // По тем же замерам совсем большое окно роняет библиотеку не на создании движка,
        // а внутри первого же ответа. Отметка живёт ровно один ход и снимается, как только
        // вызов вернулся хоть чем-нибудь: вернулся — значит мы живы, а пустой ответ лечится
        // отступлением этажом выше. Держать её дольше нельзя: человек, который открыл
        // приложение и отложил телефон, не написав ни слова, получил бы «попытка провалилась»
        // на ровном месте — это была бы догадка, выданная за факт.
        let raisedTurn = grantedContextTokens > AgentLimits.contextTokenBudget && !didSurviveRaisedTurn
        if raisedTurn {
            Self.markContextAttempt(tokens: grantedContextTokens, phase: "первое сообщение")
        }
        defer {
            if raisedTurn {
                Self.clearContextAttemptMark()
                didSurviveRaisedTurn = true
            }
        }

        // На запомненной ступеньке «ответ по частям» ходим тем же путём, каким модель
        // однажды заговорила, — иначе следующий же ход снова упёрся бы в пустоту.
        if recipe(for: launchStep).streaming {
            return try await collectStreamedAnswer(conversation, message: message)
        }
        return try await conversation.sendMessage(message)
    }

    /// Подождать, пока система вернёт освобождённую память. Не дольше секунды:
    /// не вернулась — идём дальше и честно падаем с понятной ошибкой, а не висим.
    private func waitForMemoryToSettle(atLeast requiredMB: Int) async {
        for _ in 0..<10 {
            let free = MemoryGate.availableMemoryMB()
            if free == Int.max || free >= requiredMB { return }
            try? await Task.sleep(nanoseconds: 100_000_000)
        }
        journal.record(.engine, "Памяти так и не прибавилось — пробую запуститься как есть",
                       detail: "свободно: \(Self.freeMemoryText()) · нужно: \(requiredMB) МБ")
    }

    /// Один ход. Только sendMessage, никакого стриминга — см. шапку файла.
    private func performTurn(_ message: Message) async throws -> ModelTurn {
        guard conversation != nil else { throw PocketAgentError.sessionNotStarted }
        guard !isGenerating else {
            throw PocketAgentError.generationFailed("Предыдущий ответ ещё не готов.")
        }

        isGenerating = true
        didCancelCurrentTurn = false
        defer { isGenerating = false }

        // ⚠️ ЗАСЕЧКА ХОДА — САМАЯ ЦЕННАЯ УЛИКА ЖУРНАЛА. Ровно по нулевому времени
        // генерации 09.08.2026 удалось доказать, что модель не считала вовсе, а разговор
        // был мёртв: без замера «ответила пусто за 0,00 с» и «думала 14 с и ответила пусто»
        // выглядят в журнале одинаково, а лечатся совершенно по-разному.
        journal.startStage(.turn)

        var reply: Message
        do {
            // TODO(API): Conversation — обычный class (не actor, не Sendable).
            // В строгой конкурентности Swift 6 здесь будет предупреждение о передаче
            // non-Sendable типа через границу актора — проверить на сборке.
            reply = try await sendToConversation(message)

            // ⚠️ ГЛАВНЫЙ ПРИЗНАК СЛИШКОМ БОЛЬШОГО КЭША РАЗГОВОРА — НЕ ПАДЕНИЕ, А МОЛЧАНИЕ.
            // По замерам автора отчёта на его связке модели
            // и устройства увеличенное окно давало ровно это: «no crash, but no output».
            // Поэтому пустой ответ на увеличенном окне мы НЕ отдаём лесенке настроек:
            // перебирать восемь ступенек, каждая из которых пересобирает движок, ради
            // подозрения, которое проверяется одной пересборкой, — это минуты пустого
            // ожидания для человека. Сначала отступаем к безопасному размеру, помним
            // это до следующей сборки и повторяем тот же ход; лесенка — только если
            // и на безопасном размере модель промолчала (то есть беда не в окне).
            if Self.isEmptyReply(reply),
               !didStopByPerson,
               grantedContextTokens > AgentLimits.contextTokenBudget,
               let smaller = try? await retryWithSmallerContext(
                   message, reason: "на этом размере модель ответила пусто") {
                reply = smaller
            }

            // ⚠️ ОТВЕТА НЕТ — ИДЁМ ПО ЛЕСЕНКЕ НАСТРОЕК. Эта же модель отвечает
            // в приложении Google на этом же телефоне, значит рабочая настройка есть,
            // и отличается она чем-то в НАШЕЙ. Один проход за запуск, каждая ступенька
            // в журнале, удачная запоминается за моделью.
            if Self.isEmptyReply(reply), canClimbLadder,
               let better = try await climbLadder(message) {
                reply = better
            }
        } catch {
            // Ход прервали мы сами (кнопка «Стоп» или уход в фон). Движок сообщает об этом
            // своей ошибкой, и без этой проверки прерывание выглядело для агента как
            // поломка: человек возвращался из мессенджера и видел «Не получилось».
            if didCancelCurrentTurn {
                didCancelCurrentTurn = false
                throw PocketAgentError.generationCancelled
            }

            // ⚠️ КРИВОЙ ОТВЕТ МОДЕЛИ — НЕ ПАДЕНИЕ ЗАДАЧИ.
            // Первый же живой запуск это и показал: человек написал «Привет», модель
            // на приветствие слепила негодный вызов инструмента, библиотека его отвергла —
            // и вся задача умерла красным «Не получилось. Модель ответила неразборчиво».
            // Для модели на 2 млрд параметров кривой ответ — рядовое событие, ровно как
            // пустой ход, и лечится тем же: отдаём ход пустым, а цикл агента сам просит
            // модель повторить и останавливается только после нескольких подряд.
            if Self.isGarbledAnswer(error) {
                // Помечаем ОТДЕЛЬНО от обычного пустого хода: наружу и то, и другое
                // уходит пустым ходом, а человеку в ленте нужно видеть разницу —
                // «промолчала» и «ответила мусором» лечатся одинаково, но выглядят
                // по-разному, и молчать об этом нельзя.
                journal.noteGarbledAnswer()
                journal.record(.turn, "Модель ответила неразборчиво — прошу её повторить",
                               detail: RuntimeJournal.technicalText(for: error))

                // Пока сидим на увеличенном кэше — сначала подозреваем именно его,
                // а не модель: тот же баг проявляется и мусором, и пустотой.
                if !didStopByPerson,
                   grantedContextTokens > AgentLimits.contextTokenBudget,
                   let smaller = try? await retryWithSmallerContext(
                       message, reason: "на этом размере модель ответила неразборчиво") {
                    noteTurnDone()
                    return interpret(smaller)
                }
                // ⚠️ И ЗДЕСЬ ТОЖЕ ЛЕСЕНКА — ЭТО ГЛАВНЫЙ ВХОД В НЕЁ, А НЕ ЗАПАСНОЙ.
                // «Native sendMessage returned null» — то, что владелец видит на Gemma 4 E4B, —
                // прилетает именно СЮДА: библиотека не возвращает пустой ответ, она бросает
                // ошибку разбора. Значит перебирать настройки надо в первую очередь отсюда.
                if canClimbLadder, let better = try? await climbLadder(message) {
                    noteTurnDone()
                    return interpret(better)
                }
                noteTurnDone()
                return .text("")
            }

            // Отмену в журнал ошибок не пишем: человек сам нажал «Стоп» или свернул
            // приложение, ломаться тут нечему, а «последней ошибкой» это стало бы
            // и заслонило настоящую.
            if !(error is CancellationError) {
                journal.recordFailure(stage: "ход модели",
                                      human: Self.humanMessage(error),
                                      technical: RuntimeJournal.technicalText(for: error))
            }
            throw Self.mapGenerationError(error)
        }

        noteTurnDone()
        return interpret(reply)
    }

    /// Итог хода: сколько занял и сколько памяти разговора съедено по мнению ДВИЖКА.
    ///
    /// ⚠️ ЯВНЫМ ВЫЗОВОМ У КАЖДОГО ВЫХОДА, А НЕ ЧЕРЕЗ `defer`, И ЭТО НАРОЧНО. `defer`
    /// сработал бы и на брошенной ошибке, и на нажатии «Стоп» — то есть журнал получил бы
    /// «Ход закончен» там, где хода не было вовсе. Выдуманное событие хуже отсутствующего:
    /// разбирать по нему потом будут всерьёз.
    private func noteTurnDone() {
        journal.noteTurnFinished(engineTokens: engineTokenCount(),
                                 limitTokens: grantedContextTokens,
                                 stepNumber: launchStep.rawValue,
                                 stepName: launchStep.journalName)
    }

    /// Сколько памяти разговора занято ПО МНЕНИЮ ДВИЖКА. nil — движка нет или он не сказал.
    /// ⚠️ Не путать с нашей оценкой в цикле агента: она намеренно завышена, и расхождение
    /// между числами — само по себе улика.
    private func engineTokenCount() -> Int? {
        guard let conversation else { return nil }
        return try? conversation.getTokenCount()
    }

    /// Превратить ответ модели в ход агента: заявка на действие или текст.
    ///
    /// ⚠️ Вынесено отдельно, потому что зовётся из ДВУХ мест: обычный ход и ход,
    /// повторённый после перезапуска движка на меньшей памяти разговора.
    private func interpret(_ reply: Message) -> ModelTurn {
        // TODO(API): сверить с исходниками пакета 0.15.0: свойства reply.toolCalls
        // и reply.toString, а также тип поля arguments у элемента toolCalls
        // (код рассчитывает на [String: Any] — см. ToolInvocation.init(rawName:callID:rawArguments:)).
        let calls = reply.toolCalls
        if !Self.isEmptyReply(reply) {
            // Модель заговорила — значит настройка рабочая. Запоминаем её.
            noteModelAnswered(at: launchStep)
        }
        if let call = calls.first {
            // Берём ТОЛЬКО первый вызов: один шаг — одно подтверждение.
            // Остальные запоминаем, чтобы следующим сообщением честно ответить на них
            // отказом, а не делать вид, что их не было.
            unansweredCalls = calls.dropFirst().map { (name: $0.name, id: $0.id) }
            #if DEBUG
            if !unansweredCalls.isEmpty {
                print("[LiteRTRuntime] Модель попросила \(calls.count) действий за ход; выполняем первое, на остальные отвечаем отказом.")
            }
            #endif

            // Аргументы приходят нетипизированным словарём — приводим их
            // единственной точкой конвертации из Contracts.swift.
            let invocation = ToolInvocation(rawName: call.name,
                                            callID: call.id,
                                            rawArguments: call.arguments)
            // ⚠️ В журнал идут САМИ ПАРАМЕТРЫ — путь, номера строк, содержимое.
            // Раньше писали только их количество, из осторожности. По решению владельца
            // (10.08.2026) продукт закрытый и личный, а «параметров: 2» не даёт разобрать
            // ничего: 10.08 помощник восемь раз подряд просил файл с опечаткой в имени,
            // и по журналу это было не видно — пришлось лезть в телефон за перепиской.
            journal.noteToolInvocation(invocation, concurrentCalls: calls.count)
            return .toolRequest(invocation)
        }

        // ⚠️ Пустой ответ — НЕ ошибка. Модель на 2 млрд параметров регулярно отдаёт пустой
        // ход после длинного результата инструмента. Раньше это считалось падением, и вся
        // задача умирала с красным баннером; теперь пустой ход отдаём как есть, а цикл
        // агента просто просит модель повторить.
        let text = reply.toString.trimmingCharacters(in: .whitespacesAndNewlines)
        // Ответ модели пишем в журнал ЦЕЛИКОМ (длинный — с явной пометкой, сколько срезано).
        // Именно текст ответа и показывает, почему приложение сочло ход неразборчивым.
        if text.isEmpty {
            // Настройку пишем всегда: по этой строке в журнале и видно,
            // на чём именно модель промолчала.
            journal.record(.turn, "Модель ответила пусто",
                           detail: "настройка: \(launchStep.journalName)"
                                 + (modalities.isMultimodal ? " · модель не только текстовая" : ""))
        } else {
            journal.noteModelAnswerText(text)
        }

        // ⚠️ МОДЕЛЬ МОГЛА ПОЗВАТЬ ДЕЙСТВИЕ СВОИМ ПИСЬМОМ, А НЕ ЧЕРЕЗ БИБЛИОТЕКУ.
        // Замер 07.09.2026: LFM2.5-2.6B в нашем же формате `.litertlm` набрала 4 из 26
        // не потому, что плоха, а потому что зовёт действия текстом вида
        // «<|tool_call_start|>[read_file(path='README.md')]<|tool_call_end|>».
        // Библиотека такого не понимает и отдаёт нам как обычные слова — приложение
        // видело «ответила словами» и засчитывало провал при полностью верном
        // поведении модели. Разбор — в Runtime/TextualToolCalls.swift, там же
        // объяснено, почему он не является ни дырой в подтверждении записи,
        // ни отменой правила «не показывать модели синтаксис вызова».
        if !text.isEmpty,
           let parsed = TextualToolCalls.parse(text, known: declarations.map(\.name)) {
            let invocation = ToolInvocation(rawName: parsed.name,
                                            callID: UUID().uuidString,
                                            arguments: parsed.arguments)
            journal.record(.turn,
                           "Модель позвала действие текстом, а не через библиотеку",
                           detail: "разобрано как \(parsed.name); "
                                 + "так пишут вызовы LFM2.5 и другие не-Gemma модели")
            journal.noteToolInvocation(invocation, concurrentCalls: 1)
            unansweredCalls = []
            return .toolRequest(invocation)
        }

        return .text(text)
    }

    public func cancelTurn() async {
        didCancelCurrentTurn = true
        guard let conversation, isGenerating else { return }
        // Актор реентерабелен: пока performTurn ждёт ответа, этот вызов проходит.
        // TODO(API): если cancel() у Conversation НЕ бросает, компилятор предупредит
        // «No calls to throwing functions occur within 'try' expression» — тогда убрать
        // `try?` здесь и в runPlainStream. Сверять по исходникам пакета 0.15.0.
        try? conversation.cancel()
    }

    public func endSession() async {
        unansweredCalls = []
        conversation = nil
        systemPrompt = ""
        declarations = []
        isGenerating = false
    }

    public func unload() async {
        // Явных close()/release() у движка нет — освобождение только через deinit,
        // то есть через обнуление сильных ссылок.
        if engine != nil {
            journal.record(.engine, "Модель выгружена из памяти")
        }
        unansweredCalls = []
        conversation = nil
        engine = nil
        // В памяти больше ничего не лежит — и метки о том, «под какой выбор» оно лежало,
        // тоже быть не должно: иначе следующая подготовка сравнивала бы с призраком.
        loadedChoiceMark = nil
        isGenerating = false
        activeBackendName = "—"
        setStatus(.idle)
    }

    public func usedTokens() async -> Int? {
        guard let conversation else { return nil }
        return try? conversation.getTokenCount()
    }

    /// Потолок памяти разговора, который движок выдал этой сессии.
    ///
    /// Дёшево: отдаём уже записанное число, в библиотеку не ходим. Движка ещё нет —
    /// значит и разговора нет, и честнее назвать безопасный размер, чем ноль:
    /// ноль на экране прочитался бы как «памяти нет вовсе».
    public func contextLimitTokens() async -> Int { grantedContextTokens }

    // MARK: - Диагностика для «О программе»

    /// На чём считает модель прямо сейчас: «GPU», «CPU» или «—».
    public func backendName() async -> String { activeBackendName }

    /// Ускорение отключено после неудачных попыток.
    public func isAccelerationDisabled() async -> Bool { isGPUDisabled() }

    /// Кнопка «Попробовать ускорение заново».
    public func enableAccelerationAgain() async { allowGPUAgain() }

    /// Что загружено ПРЯМО СЕЙЧАС — для строки состояния на экране чата.
    ///
    /// ⚠️ Отвечает движок, а не список на экране подготовки: список знает, что человек
    /// выбрал, а движок — что он на самом деле открыл. Файл могли положить через «Файлы»,
    /// и в каталоге его нет вовсе.
    public func runtimeFacts() async -> ModelRuntimeFacts {
        ModelRuntimeFacts(isLoaded: engine != nil,
                          modelName: model.displayName,
                          fileName: model.fileName,
                          byteSize: model.byteSize,
                          backendName: activeBackendName)
    }

    // MARK: - Жизненный цикл приложения

    /// Приложение уходит в фон: генерацию всё равно прервёт система,
    /// прерываем сами и аккуратно.
    public func handleEnteredBackground() async {
        await cancelTurn()
    }

    /// Система жалуется на память: выгружаем веса целиком.
    /// Разговор при этом теряется — иначе нас убьют совсем.
    ///
    /// ⚠️ Если движок прямо сейчас поднимается, взводим флаг: prepare() увидит его
    /// после `await engine.initialize()` и НЕ вернёт веса в память. Без флага уже
    /// выгруженное тут же грузилось обратно, и система убивала приложение.
    public func handleMemoryWarning() async {
        journal.record(.engine, "Система попросила освободить память — выгружаю модель",
                       detail: "свободно: \(Self.freeMemoryText()) · "
                             + "шла загрузка: \(isPreparing ? "да" : "нет")")
        if isPreparing { unloadRequested = true }
        await unload()
    }

    // MARK: - Стриминг (только текст, без инструментов)

    /// ⚠️ Использовать ТОЛЬКО для чисто текстовых ответов. В разговоре с инструментами
    /// стриминг игнорирует automaticToolCalling: false и выполняет их сам.
    /// Поэтому здесь заводится ОТДЕЛЬНЫЙ разговор вообще без инструментов.
    public nonisolated func streamPlainText(prompt: String) -> AsyncThrowingStream<String, Error> {
        let (stream, continuation) = AsyncThrowingStream<String, Error>.makeStream()
        let task = Task { [weak self] in
            guard let self else {
                continuation.finish(throwing: PocketAgentError.runtimeNotReady)
                return
            }
            await self.runPlainStream(prompt: prompt, continuation: continuation)
        }
        continuation.onTermination = { _ in task.cancel() }
        return stream
    }

    private func runPlainStream(prompt: String,
                                continuation: AsyncThrowingStream<String, Error>.Continuation) async {
        guard let engine else {
            continuation.finish(throwing: PocketAgentError.runtimeNotReady)
            return
        }

        do {
            let sampler = try SamplerConfig(topK: Self.samplerTopK,
                                            topP: Self.samplerTopP,
                                            temperature: Self.samplerTemperature,
                                            seed: 0)
            // TODO(API): проверить на сборке, что systemMessage и tools у ConversationConfig
            // имеют значения по умолчанию — здесь они намеренно опущены (разговор без инструментов).
            let config = ConversationConfig(
                samplerConfig: sampler,
                thinkingConfig: ThinkingConfig(enableThinking: false),
                automaticToolCalling: false
            )
            // Разговор живёт только внутри этого метода и не покидает актор.
            let plain = try await engine.createConversation(with: config)

            // Метод не async и не throws — ошибки прилетают при итерации.
            for try await chunk in plain.sendMessageStream(Message(prompt, role: .user)) {
                if Task.isCancelled {
                    try? plain.cancel()
                    break
                }
                // TODO(API): проверить на сборке, что contents перебирается циклом
                // (в примере Google берут только chunk.contents.first).
                for content in chunk.contents {
                    if case .text(let piece) = content {
                        continuation.yield(piece)
                    }
                }
            }
            continuation.finish()
        } catch {
            continuation.finish(throwing: Self.mapGenerationError(error))
        }
    }

    // MARK: - Ошибки человеческим языком

    /// Модель ответила так, что библиотека не смогла это разобрать.
    ///
    /// ⚠️ Именно эти три вида, и никакие другие. «Разговор оборвался», «движок не запущен»,
    /// «зациклилась» — настоящие поломки, и прятать их за молчаливым повтором нельзя:
    /// повтор в мёртвом разговоре не сработает никогда, а человек будет ждать.
    private static func isGarbledAnswer(_ error: Error) -> Bool {
        guard let liteRT = error as? LiteRTLMError,
              case .conversation(let conversationError) = liteRT else { return false }
        switch conversationError {
        case .invalidJson, .invalidResponse, .failedToSerializeMessage:
            return true
        default:
            return false
        }
    }

    private static func mapGenerationError(_ error: Error) -> Error {
        if error is CancellationError { return PocketAgentError.generationCancelled }
        if let known = error as? PocketAgentError { return known }
        return PocketAgentError.generationFailed(humanMessage(error))
    }

    /// Текст ошибки движка ПО-РУССКИ.
    ///
    /// ⚠️ У LiteRTLMError все тексты зашиты по-английски («Failed to create engine.»,
    /// «Conversation is not alive.»), и раньше они подставлялись прямо в русскую фразу:
    /// человек читал «Модель не смогла ответить: Failed to create engine.» и не понимал
    /// ни что случилось, ни что делать. Разбираем по видам ошибки и говорим по-русски;
    /// английский оригинал остаётся только в отладочной сборке.
    private static func humanMessage(_ error: Error) -> String {
        if let liteRT = error as? LiteRTLMError {
            return russian(for: liteRT)
        }
        if let known = error as? PocketAgentError {
            return known.errorDescription ?? SystemErrorText.russian(for: error)
        }
        return SystemErrorText.russian(for: error)
    }

    /// Перевод ошибок движка на человеческий русский: что случилось и что делать.
    ///
    /// ⚠️ Английского оригинала здесь БОЛЬШЕ НЕТ — ни в боевой сборке, ни в отладочной.
    /// Раньше он приклеивался к фразе под `#if DEBUG`, и получалось худшее из двух:
    /// человеку с телефоном — общая фраза без единого факта, нам — двуязычная строка
    /// прямо в интерфейсе. Теперь точный текст библиотеки уходит в журнал событий
    /// (RuntimeJournal) и показывается на экране отдельной технической строкой.
    private static func russian(for error: LiteRTLMError) -> String {
        let text: String
        switch error {
        case .engine(let engineError):
            switch engineError {
            case .notInitialized, .alreadyInitialized:
                text = "Движок модели не запущен. Перезапустите приложение."
            case .failedToCreateEngine, .failedToCreateSettings:
                text = "Не удалось запустить модель. Закройте другие приложения и попробуйте снова, "
                    + "а если не поможет — скачайте модель заново в разделе подготовки."
            case .failedToCreateConversation, .failedToCreateConversationConfig, .failedToCreateSessionConfig:
                text = "Не удалось начать разговор с моделью. Нажмите «Новая задача»."
            default:
                text = "Модель не запустилась. Перезапустите приложение."
            }
        case .conversation(let conversationError):
            switch conversationError {
            case .notAlive:
                text = "Разговор с моделью оборвался. Нажмите «Новая задача» — переписка начнётся заново."
            case .recurringToolCallLimitExceeded:
                text = "Модель зациклилась на одном и том же действии. Начните новую задачу и опишите её попроще."
            case .invalidJson, .invalidResponse, .failedToSerializeMessage:
                text = "Модель ответила неразборчиво. Повторите последний шаг."
            case .failedToStartStream:
                text = "Модель не начала отвечать. Повторите последний шаг."
            default:
                text = "Модель не смогла ответить. Повторите последний шаг."
            }
        case .config:
            text = "Настройки модели не подошли этому телефону. Перезапустите приложение."
        case .tool:
            text = "Модель попросила действие, которого нет. Повторите последний шаг."
        case .message:
            text = "Сообщение для модели не собралось. Повторите последний шаг."
        }

        return text
    }
}

// MARK: - Беда с выбранной моделью

/// Беда, про которую человек обязан узнать словами: выбранный файл пропал, или его
/// просят сменить в неподходящий момент.
///
/// ⚠️ Своим типом, а не общим `PocketAgentError`, намеренно: текст здесь собирается
/// на месте и называет КОНКРЕТНУЮ модель и КОНКРЕТНЫЙ файл. Готовой фразы «на все случаи»
/// у этой беды нет — а безликое «файл модели не найден» человеку не говорит ничего.
struct ModelChoiceProblem: HumanReadableError {
    let text: String
    var errorDescription: String? { text }
}

