//
//  AppDelegate.swift
//  PocketAgent
//
//  Делегат нужен ради двух вещей.
//
//  1. Обязательный метод фоновой загрузки. Когда загрузка файла модели завершается при
//     закрытом приложении, система будит процесс и передаёт сюда обработчик завершения.
//     Не вызвать его — система считает, что приложение зависло, и в следующий раз хуже
//     планирует загрузку; события фоновой сессии при этом могут не доставиться вовсе.
//     Обработчик просто кладём в ModelDownloader.
//
//  2. Поиск моделей, положенных человеком в папку «Файлы».
//     ⚠️ События «в закрытое приложение положили файл» в iOS НЕ существует: разбудить
//     приложение из-за изменения собственной Documents система не умеет. Поэтому ищем
//     сами — при запуске и при каждом возврате из фона. Типовой случай ровно такой:
//     человек свернул приложение, открыл «Файлы», положил файл модели и вернулся.
//     Поиск дешёвый (перечисление трёх папок плюс первые 32 байта каждого файла),
//     но идёт вне главного потока, чтобы не задержать появление экрана.
//

import UIKit

final class AppDelegate: NSObject, UIApplicationDelegate {

    func application(_ application: UIApplication,
                     didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]? = nil) -> Bool {
        Self.makeFolderVisibleInFiles()
        // Поиск при запуске нужен отдельно от подписки ниже: приложение могут поднять
        // прямо в фон (система будит его ради докачки модели), и тогда «стало активным»
        // не случится вовсе. Лишний повтор безвреден — поиск ничего не меняет.
        Self.rescanModels()

        // Возврат из фона — второй и главный момент поиска: файл кладут именно так.
        NotificationCenter.default.addObserver(forName: UIApplication.didBecomeActiveNotification,
                                               object: nil,
                                               queue: .main) { _ in
            Self.rescanModels()
            // Повтор через несколько секунд: файл могли положить прямо сейчас, и тогда
            // первый поиск застаёт его недокопированным. Второй заход снимет пометку
            // «ещё копируется» сам, без единого нажатия.
            DispatchQueue.main.asyncAfter(deadline: .now() + 4) {
                Self.rescanModels()
            }
        }
        return true
    }

    /// Поискать модели и сказать экранам, что список изменился.
    ///
    /// ⚠️ Работа с диском — только в фоновой очереди. Сообщение рассылается на главном
    /// потоке: его слушают экраны, а трогать их состояние из чужого потока нельзя.
    /// Пустое сообщение не шлём: без изменений экранам нечего перерисовывать.
    static func rescanModels() {
        DispatchQueue.global(qos: .userInitiated).async {
            // Сравниваем не только состав списка, но и размер с годностью: файл мог
            // дописаться до конца или выгрузиться из облака, а имя при этом не менялось.
            let fingerprint: ([DiscoveredModelFile]) -> [String] = { list in
                list.map { "\($0.id)|\($0.byteSize)|\($0.isUsable)" }
            }
            let before = fingerprint(ModelDiscovery.cached)
            let after = fingerprint(ModelDiscovery.rescan())
            guard before != after else { return }
            DispatchQueue.main.async {
                NotificationCenter.default.post(name: .pocketAgentModelsChanged, object: nil)
            }
        }
    }

    /// Показать папку приложения в «Файлах».
    ///
    /// ⚠️ Одних ключей `UIFileSharingEnabled` и `LSSupportsOpeningDocumentsInPlace`
    /// НЕДОСТАТОЧНО: на части систем, пока папка `Documents` пуста, «Файлы» не рисуют её
    /// вовсе, а на остальных человек открывает папку и видит нулевое содержимое —
    /// и не понимает, туда ли он вообще попал. Кладём короткую подсказку: она и
    /// открывает папку, и сразу объясняет, какой файл нужен и где его взять.
    ///
    /// ⚠️ Текст переписан по фактам. Прежний советовал файл «gemma-4-E2B-it.litertlm,
    /// 2,41 ГБ», которого в репозитории нет, и называл три разных размера подряд, тогда
    /// как приложение принимало РОВНО ОДИН файл. Человек читал подсказку, приносил файл
    /// и получал отказ «нужен ровно 2,01 ГБ». Теперь приложение принимает любую Gemma,
    /// и подсказка говорит ровно это.
    private static func makeFolderVisibleInFiles() {
        guard let docs = FileManager.default.urls(for: .documentDirectory,
                                                  in: .userDomainMask).first else { return }
        let readme = docs.appendingPathComponent("Как положить модель.txt")
        guard !FileManager.default.fileExists(atPath: readme.path) else { return }

        let text = """
        Карманный агент — папка для моделей

        Положите файл модели прямо сюда, в эту папку. Приложение находит его
        само: при запуске и каждый раз, когда вы возвращаетесь в приложение.
        Нажимать ничего не нужно — модель появится на экране подготовки.

        Какие файлы подходят:
        • любой файл с расширением .litertlm семейства Gemma
        • тот же файл, что вы уже скачали в Google AI Edge Gallery, — подойдёт

        Какие НЕ подходят:
        • файлы со словом «-web» в имени — это сборка для браузера
        • сборки под чужое железо: в имени есть qualcomm, mediatek,
          intel или Google_Tensor — они для других телефонов и ноутбуков

        Где взять (скачивается без регистрации):
        huggingface.co/litert-community/gemma-4-E2B-it-litert-lm
        • gemma-4-E2B-it-gpu.litertlm — 2,01 ГБ, самый лёгкий из подходящих
        • gemma-4-E2B-it.litertlm — 2,59 ГБ, работает и без видеочипа
        huggingface.co/litert-community/gemma-4-E4B-it-litert-lm
        • gemma-4-E4B-it.litertlm — 3,66 ГБ, умнее; нужен телефон
          с большим запасом памяти

        Скачивать удобнее на компьютере и перекидывать сюда кабелем,
        по AirDrop или через iCloud Drive. Файл большой — дождитесь,
        пока копирование дойдёт до конца.

        Место: файл можно оставить лежать прямо здесь — приложение работает
        с ним на месте и не делает второй копии. Как только вы нажмёте
        «Использовать эту модель», файл перестанет попадать в резервную
        копию iCloud — она от него не распухнет. До этого приложение ваш
        файл не трогает вообще.

        После того как модель на месте, интернет не нужен совсем —
        она работает прямо на телефоне.
        """
        try? text.write(to: readme, atomically: true, encoding: .utf8)
    }

    /// Система разбудила приложение ради фоновой сессии загрузки модели.
    func application(_ application: UIApplication,
                     handleEventsForBackgroundURLSession identifier: String,
                     completionHandler: @escaping () -> Void) {
        // Идентификатор сверяем: у приложения может появиться и другая фоновая сессия.
        // ⚠️ Сессий загрузки теперь несколько — по одной на каждый одновременный кусок
        // файла (иначе все куски идут по одному соединению и скорости не прибавляется).
        // Поэтому сверяем не с одним именем, а со всем списком: разбудить нас могли
        // ради любой из них, и ответить надо именно по ней.
        guard ModelDownloader.handles(sessionIdentifier: identifier) else {
            completionHandler()
            return
        }
        // ⚠️ СНАЧАЛА поднимаем сессию, и только потом кладём обработчик.
        // Сессия создаётся лениво: при пробуждении в фоне её объекта ещё нет, а значит
        // делегат не подключён — система не доставит ни «файл докачан», ни «события
        // закончились». Итог был именно такой: скачанные 2,59 ГБ система выбрасывала
        // из временной папки, и человек открывал приложение снова на нуле процентов.
        ModelDownloader.shared.activateSession()
        ModelDownloader.shared.setBackgroundCompletionHandler(completionHandler, for: identifier)
    }

    /// Системе не хватает памяти. Веса модели — самое крупное, что мы держим.
    func applicationDidReceiveMemoryWarning(_ application: UIApplication) {
        NotificationCenter.default.post(name: .pocketAgentMemoryPressure, object: nil)
    }

    // MARK: - Файл прислали из другого приложения

    /// Отложенный файл: его прислали, а спросить про него ещё некому.
    ///
    /// ⚠️ ЗАЧЕМ «ЯЩИК», А НЕ ОДНО СООБЩЕНИЕ. Приложение могут запустить самим этим
    /// действием: человек в «Файлах» жмёт «Поделиться → Карманный агент», система
    /// поднимает приложение и сразу отдаёт файл сюда — раньше, чем появится первый
    /// экран. Сообщение в этот момент слушать некому, и файл пропал бы молча.
    /// Поэтому URL и рассылается сообщением, и кладётся сюда: экран забирает его
    /// при появлении. Читается и пишется только с главного потока.
    private static var incomingFile: IncomingFile?

    /// Присланный файл и то, чей он теперь.
    struct IncomingFile {
        let url: URL
        /// Система отдала нам НАШУ СОБСТВЕННУЮ КОПИЮ файла, а не оригинал.
        ///
        /// ⚠️ Это не мелочь, а вопрос уборки. Приложение-отправитель может не уметь
        /// отдавать оригинал «на месте» — тогда iOS молча кладёт копию к нам в
        /// `Documents/Inbox` и присылает адрес копии. Убирать её обязаны МЫ: сама
        /// система эту папку не чистит никогда. А `Documents` у нас видна человеку
        /// в «Файлах» — то есть каждый присланный файл оставался бы там навсегда,
        /// вторым экземпляром, и человек не понимал бы, откуда он взялся.
        let isOurCopy: Bool
    }

    /// Забрать отложенный файл (и освободить ящик).
    static func takeIncomingFile() -> IncomingFile? {
        let file = incomingFile
        incomingFile = nil
        return file
    }

    /// Человек прислал нам файл из другого приложения («Поделиться», «Открыть в»).
    ///
    /// ⚠️ Здесь НИЧЕГО не копируется и никуда не кладётся. Файл живёт у себя, а мы
    /// только передаём его экрану — тот покажет человеку, что именно произойдёт,
    /// и спросит разрешения. Правило продукта одно на всё приложение: папку человека
    /// меняет только нажатие человека.
    func application(_ app: UIApplication,
                     open url: URL,
                     options: [UIApplication.OpenURLOptionsKey: Any] = [:]) -> Bool {
        guard url.isFileURL else { return false }
        // Система говорит прямо, оригинал это или наша копия. Ключа нет — считаем копией:
        // прибрать чужой оригинал мы всё равно не сможем (ниже это проверяется ещё раз
        // по тому, лежит ли файл внутри нашей папки «Входящие»), а вот не прибрать свою
        // копию — значит оставить мусор в папке, которую человек видит.
        let inPlace = options[.openInPlace] as? Bool ?? false
        Self.incomingFile = IncomingFile(url: url, isOurCopy: !inPlace)
        NotificationCenter.default.post(name: .pocketAgentFileReceived, object: nil)
        return true
    }
}

public extension Notification.Name {
    /// Система пожаловалась на память — можно выгружать модель.
    static let pocketAgentMemoryPressure = Notification.Name("pocketagent.memory.pressure")
    /// Нам прислали файл из другого приложения — надо спросить человека, что с ним делать.
    static let pocketAgentFileReceived = Notification.Name("pocketagent.file.received")
}
