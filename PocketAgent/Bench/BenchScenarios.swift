    ///
    /// Ключ понимает список через запятую («read-answer,find-port») и приставку
    /// со звёздочкой («real-*») — чинить один разговор и ждать при этом весь набор
    /// бессмысленно, а набор растёт.
    ///
    /// ⛔ В режиме настоящей папки владельца берётся ТОЛЬКО набор `ownerFolder`.
    /// Это второй замок безопасности: даже ошибись кто-нибудь в ключе «прогнать
    /// только эти», задача, которая пишет файлы, в его папку не попадёт — её
    /// просто нет в списке, из которого этот режим выбирает.
    static var selected: [BenchScenario] {
        let pool = BenchMode.usesOwnerFolder ? ownerFolder : all
        guard let only = BenchMode.onlyScenario else { return pool }
        let wanted = only.split(separator: ",")
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
        guard !wanted.isEmpty else { return pool }
        return pool.filter { scenario in
            wanted.contains { pattern in
                pattern.hasSuffix("*")
                    ? scenario.id.hasPrefix(String(pattern.dropLast()))
                    : scenario.id == pattern
            }
        }
    }
