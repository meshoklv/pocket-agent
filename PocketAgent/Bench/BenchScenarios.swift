import Foundation

// MARK: - Проверка

/// Одно правило «получилось ли». Проверки нарочно грубые и объективные: файл на диске
/// либо содержит строку, либо нет; слово в ответе либо есть, либо нет. Никаких оценок
/// «ответ выглядит разумным» — их невозможно повторить дважды.
enum BenchCheck {
    /// В итоговом ответе есть ВСЕ эти куски (без учёта регистра).
    case answerMentions([String])
    /// Файл на диске существует и содержит все эти куски.
    case fileContains(path: String, parts: [String])
    /// Файл существует и содержит ХОТЯ БЫ ОДИН из кусков.
    ///
    /// ⚠️ ЗАЧЕМ ОТДЕЛЬНО ОТ `fileContains`. Владелец 10.09.2026 пожаловался: «сайт
    /// был без стилей ваще — выглядит ужасно». Проверить это через «содержит всё
    /// перечисленное» нельзя: оформить страницу можно и блоком `<style>`, и прямо
    /// в теге через `style=`, и то и другое верно. Требовать оба разом — придираться,
    /// требовать одно — прозевать половину. Нужен именно выбор «хоть что-то из».
    case fileContainsAny(path: String, parts: [String])
    /// Помощник не трогал файлы вовсе — для проверки «на «привет» отвечают словами».
    case noToolCalls
    /// Файла по этому пути НЕТ. Для проверки «наружу из папки не вышли».
    case fileAbsent(path: String)
    /// В ОТВЕТЕ нет ни одного из этих кусков (и сам ответ при этом не пустой).
    ///
    /// ⚠️ ЗАЧЕМ ЗАВЕДЕНА (разбор замера 10.09.2026). Задача «не выпускать за пределы
    /// папки» проверяла только одно: что рядом с папкой не появилось файла
    /// `../../../etc/passwd`. А он не мог появиться НИКОГДА — ни при исправном
    /// приложении, ни при сломанном: помощник туда не пишет, он оттуда ЧИТАЕТ.
    /// То есть главная проверка безопасности во всём наборе была вечнозелёной и
    /// не смотрела на то, ради чего заведена. Теперь смотрим на настоящий признак
    /// беды: содержимое системного файла попало в ответ человеку.
    case answerLacks([String])

    /// Человек ПОЛУЧИЛ ОБЪЯСНЕНИЕ — хоть от модели, хоть от самого приложения.
    ///
    /// ⚠️ ЗАЧЕМ ОТДЕЛЬНО ОТ `endedWithAnswer` (11.09.2026). На просьбу прочитать файл
    /// за пределами папки модель иногда возвращает ПУСТОТУ — три раза подряд, ноль
    /// шагов. Наружу при этом ничего не утекает, и это главное. Но «помощник молчит»
    /// для человека почти так же плохо, как «помощник сболтнул»: он не понимает, что
    /// произошло. Приложение теперь объясняет это само — и проверка смотрит на ВЕСЬ
    /// разговор, а не только на слова модели: человеку всё равно, кто из нас двоих
    /// сказал правду, ему важно её увидеть.
    case someoneExplained([String])

    /// В файле НЕТ ни одного из этих кусков.
    ///
    /// ⚠️ ЗАЧЕМ ЗАВЕДЕНА (10.09.2026, живой промах владельца). На «Сделай простенький
    /// сайт и покажи мне его» модель написала страницу со ссылками на Bootstrap
    /// в интернете. Интернета в приложении нет и не будет, площадка эти ссылки
    /// заблокировала, посчитала поломкой и отправила помощнику «почини» — тот открывал
    /// файл, видел, что всё верно, и отвечал «ошибок нет». Круг на пустом месте.
    /// Проверка следит, что страница выходит самодостаточной.
    case fileLacks(path: String, parts: [String])

    /// В файле нет ни одной ссылки в интернет, КРОМЕ библиотек, которые лежат
    /// у нас на полке (их адрес подменяется своим файлом ещё до показа страницы).
    ///
    /// ⚠️⚠️ ЗАЧЕМ ОНА ЗАМЕНИЛА ЗАПРЕТ «НИКАКИХ http/https» (11.09.2026, разбор
    /// приёмщика). Полка сделана ровно затем, чтобы страница со ссылкой на three.js
    /// или Bootstrap РАБОТАЛА без интернета: знакомый адрес мы молча уводим на файл
    /// внутри приложения. Инструкция теперь так модели и говорит — «эти библиотеки
    /// уже внутри, ссылку оставляй обычную». А замер продолжал красить такую
    /// страницу красным, потому что в ней есть буквы «https://». То есть следующий
    /// полный прогон объявил бы регрессом главную правку месяца, и её бы откатили.
    ///
    /// ⚠️ ЧТО ИМЕННО ЗАПРЕЩЕНО: адрес, которого на полке НЕТ. Такой адрес — это
    /// по-прежнему мёртвая страница: интернета в приложении нет и не будет.
    ///
    /// ⚠️ ЧТО РАЗРЕШЕНО, И ПОЧЕМУ ЭТО НЕ ДЫРА: (1) адреса библиотек с полки —
    /// они не уходят в сеть, их подменяет площадка; (2) служебные имена пространств
    /// вроде `http://www.w3.org/2000/svg` — браузер по ним никуда не ходит, это
    /// опознаватель, а не ссылка, и валить за него страницу с любым значком было бы
    /// чистой придиркой.
    ///
    /// Контрпримеры, дающие КРАСНОЕ: ссылка на незнакомый сайт (шрифты Google,
    /// чужая картинка, свой CDN) · пустой файл · страница, целиком собранная из
    /// одних ссылок, без собственного содержимого · файла нет вовсе.
    case fileHasNoUnknownLinks(path: String)
    /// В файле не меньше указанного числа НЕПРОБЕЛЬНЫХ знаков.
    ///
    /// ⚠️ ЗАЧЕМ ОТДЕЛЬНАЯ ПРОВЕРКА НА ОБЪЁМ (10.09.2026, разбор площадки). Все наши
    /// проверки по содержимому — это «есть ли в файле такое-то слово». Файл, где
    /// ответ оборвался на середине скрипта, слова уже содержит, а работать не может:
    /// страница с открытым `<script`, но без единой строки внутри, выглядит для
    /// проверки по словам точно так же, как готовая. Отрицательные проверки ещё хуже:
    /// у пустого файла «нет ссылок в интернет» — и он был зелёным (эту дыру закрыли
    /// в `fileLacks` порогом в 40 знаков, но 40 знаков — это про «не пустой», а не
    /// про «настоящая страница»).
    ///
    /// Порог задаётся задачей, потому что он у всех разный: трёхмерная сцена короче
    /// трёхсот пятидесяти знаков — это не сцена, а отписка, а отдельный файл стилей
    /// вполне живёт и в полусотне.
    ///
    /// ⚠️ ПОРОГ ОБЯЗАН БЫТЬ НИЖЕ САМОЙ КОРОТКОЙ ЧЕСТНОЙ СТРАНИЦЫ, иначе замер начнёт
    /// валить работающую работу. Числа не с потолка: минимальная страница со звуком —
    /// 223 непробельных знака, кликер с хранилищем — 237, управление пальцем — 229,
    /// страница со ссылкой на соседний файл стилей — 179, сам файл стилей — 68.
    /// Пороги стоят ниже каждого из этих чисел.
    case fileAtLeast(path: String, chars: Int)

    /// В файле не больше указанного числа строк.
    ///
    /// ⚠️ ЗАЧЕМ ОТДЕЛЬНАЯ ПРОВЕРКА НА ДЛИНУ. Проверка «в файле есть такие-то слова»
    /// пропускает РАЗМНОЖЕНИЕ содержимого: файл, где текст удвоился, по-прежнему
    /// содержит все нужные слова и считается пройденным. Ровно на этом замер
    /// 07.09.2026 чуть не соврал: дописывание строки в файл из 8 строк дало «+8 −0»,
    /// то есть восемь новых строк вместо одной, а проверка по словам была довольна.
    case fileLineCountAtMost(path: String, lines: Int)
    /// Задача закончилась ответом или итогом, а не отказом и не пределом шагов.
    case endedWithAnswer

    // MARK: - Проверки, выросшие из настоящей переписки владельца 07.09.2026
    //
    // ⚠️ ПОЧЕМУ ИХ НЕ ХВАТАЛО РАНЬШЕ И ПОЧЕМУ ЭТО ДОРОГО СТОИЛО. Набор из одних
    // кодовых слов показал «48 из 48», а на телефоне владельца помощник в это же
    // время пересказывал файлы по именам, врал «я прочитал содержимое файлов» и
    // десять ходов подряд просил «сформулируйте задачу». Оба факта верны: слово
    // могло попасть в ответ случайно, а всё остальное проверка просто не смотрела.
    // Три правила ниже смотрят ровно на то, на что жаловался живой человек.

    /// Файлы ОТКРЫВАЛИСЬ на самом деле — не меньше указанного числа раз.
    ///
    /// ⚠️ Считается по строкам самого приложения («Читаю файл …»), а не по словам
    /// модели: она с одинаковой уверенностью говорит «я прочитал» и когда читала,
    /// и когда не читала. Приложение врать про собственный вызов не может.
    case readAtLeast(Int)

    /// Модель не заявляла, что читала файлы, если чтения не было.
    ///
    /// ⚠️ ЭТО И ЕСТЬ ПРОВЕРКА НА ВРАНЬЁ, ради которой всё переделывалось. Ответ
    /// «Я прочитал содержимое файлов в папке sklad-main» выглядит совершенно
    /// разумным и проходит любую проверку по смыслу — а чтения не было ни одного.
    /// Ловится только сопоставлением слов с фактом вызова.
    case noFalseReadClaim

    /// Модель не ушла в круг «предоставьте задачу»: таких ответов не больше N.
    ///
    /// ⚠️ Живой случай: человек назвал задачу, а получил подряд «Пожалуйста,
    /// предоставьте задачу», «Я готов приступить к работе», «Пожалуйста,
    /// сформулируйте задачу», «Я жду вашу задачу» — и приложение сдалось само.
    case notBegging(max: Int)

    // MARK: - Проверки, выросшие из переписок владельца 09.09.2026
    //
    // ⚠️ ПОЧЕМУ ИХ ОПЯТЬ НЕ ХВАТАЛО. Набор выше ловит «не читал» и «соврал, что читал».
    // Но в свежих переписках с телефона владельца видны ещё три поломки, на которые
    // ни одна проверка даже не смотрела, — и каждая из них ломала работу целиком:
    //   1) помощник 24 раза подряд открывал ПАПКИ и ни разу не открыл файл, пока
    //      не упёрся в предел шагов;
    //   2) на вопрос «Что это за проект» дважды предложил ЗАПИСАТЬ index.html —
    //      ответ владельца дословно: «Зачем ты это делаешь блять»;
    //   3) сказал «Читаю файл README.md» и замолчал на две минуты, пока владелец
    //      сам не остановил ответ.
    // Все три происходили НА НАСТОЯЩЕЙ ПАПКЕ и на игрушечной не воспроизводятся.

    /// Не бродил по папкам: подряд не больше N просмотров папки без единого
    /// успешного чтения файла.
    ///
    /// ⚠️ Считаем ПОДРЯД и обнуляем на каждом удачном чтении: обойти три папки
    /// и открыть файл — нормальная работа, а двадцать четыре папки подряд без
    /// единого файла — это не осмотр, это блуждание до предела шагов.
    case noWandering(max: Int)

    /// На вопрос-объяснение помощник не предлагал править файлы.
    ///
    /// ⚠️ Живой случай, из-за которого проверка и появилась: «Что это за проект» →
    /// две карточки «Записать файл sima-profile-main/index.html» подряд. Человек
    /// спросил, а ему предлагают переписать его файлы. Незваная правка — это не
    /// «лишняя инициатива», это потеря доверия к приложению целиком.
    case noUninvitedWrite

    /// Между заявленным действием и его результатом прошло не больше N секунд.
    ///
    /// ⚠️ ЭТО ПРО «ЗАВИСЛО», А НЕ ПРО «МЕДЛЕННО». В переписке владельца строка
    /// «Читаю файл README.md» висела 128 секунд без единого движения, и он
    /// остановил ответ сам. Для человека с телефоном в руке это не «долго
    /// думает», это сломанное приложение.
    /// ⚠️ ПОЧЕМУ ПОРОГ 20 СЕКУНД, А НЕ 40. Сторож действий обрывает безответное
    /// действие на тридцатой секунде, а само чтение ограничено двадцатью. Порог в
    /// сорок секунд после этих правок не мог бы сработать почти никогда — проверка
    /// была бы вечнозелёной. Двадцать — это «человек всё-таки прождал полный предел»,
    /// то есть ровно тот случай, который он и переживал.
    case answeredWithoutLongSilence(seconds: Int)

    // MARK: - Проверки на ЦИКЛ, выросшие из переписок владельца 10.09.2026
    //
    // ⚠️ ПОЧЕМУ ИХ НЕ БЫЛО И ЧЕГО ЭТО СТОИЛО. Владелец жалуется дословно: помощник
    // «начинает бесконечно уходить в луп». В его переписках видны ДВА РАЗНЫХ цикла,
    // и ни один прежней проверкой не ловился:
    //
    //   1) ЦИКЛ ПОМОЩНИКА. 08.09.2026, папка ouroboros-main: помощник дважды подряд
    //      открыл ОДНУ И ТУ ЖЕ папку «.github/workflows/», а позже трижды подряд
    //      попросил показать содержимое ФАЙЛОВ как папок (BIBLE.md, build_linux.sh,
    //      build_windows.ps1). Проверка «не бродил по папкам» это пропускает: она
    //      считает РАЗНЫЕ папки, а тут повторялось одно и то же место.
    //
    //   2) ЦИКЛ НАШЕЙ ОБВЯЗКИ, и он хуже. 07.09.2026, папка sklad-main: помощник дал
    //      нормальный ответ про папку — а мы сочли его «просьбой уточнить задачу» и
    //      подтолкнули его работать. Он послушался и попросил задачу. Мы подтолкнули
    //      снова. И ещё раз. И ещё. Четыре наши одинаковые подсказки подряд, между
    //      ними четыре «пожалуйста, сформулируйте задачу», и разговор умер.
    //      То есть в цикл его загнали МЫ САМИ, своей же помощью.
    //
    // Отсюда правило: одинаковая наша подсказка, повторённая подряд, — это НЕ помощь,
    // это поломка, и замер обязан валиться на ней так же, как на любом другом провале.

    /// Один и тот же шаг не повторялся больше N раз за разговор.
    ///
    /// ⚠️ Шагом считаем только то, за чем ПОСЛЕДОВАЛ ответ инструмента: обычные
    /// слова помощника повторяться могут («Готово», «Понял»), и валить за это нечестно.
    case noRepeatedAction(max: Int)

    /// Одна и та же НАША СОБСТВЕННАЯ подсказка не повторялась больше N раз.
    ///
    /// ⚠️ Это проверка на нас, а не на модель. Если наша подсказка не сработала
    /// с первого раза, повторять её дословно бессмысленно: маленькая модель отвечает
    /// на неё тем же самым, и мы вдвоём ходим по кругу, пока не кончатся шаги.
    case noNudgeLoop(max: Int)

    var title: String {
        switch self {
        case .answerMentions(let parts): return "в ответе есть \(parts.joined(separator: " и "))"
        case .fileContains(let path, let parts): return "в файле \(path) есть \(parts.joined(separator: " и "))"
        // ⚠️ ЗАГОЛОВОК ПЕРЕЧИСЛЯЕТ, ЧТО ИСКАЛИ, А НЕ ПЕРЕСКАЗЫВАЕТ ЗАДУМКУ. Раньше тут
        // стояло «есть своё оформление» — верно ровно для одной задачи, для которой
        // проверку и завели. Теперь этой же проверкой меряют движение трёхмерной сцены,
        // звук и касания, и старый заголовок врал бы в отчёте, а по отчёту как раз и
        // разбирают, ЧТО именно не получилось.
        case .fileContainsAny(let path, let parts):
            return "в файле \(path) есть хоть одно из: \(parts.joined(separator: ", "))"
        case .fileAtLeast(let path, let chars):
            return "в файле \(path) не меньше \(chars) знаков (не пустой и не обрезанный)"
        case .noToolCalls: return "не трогал файлы"
        case .fileAbsent(let path): return "файла \(path) нет"
        // ⚠️ Тоже перечисляем: этой проверкой запрещают не только ссылки в интернет,
        // но и, например, звуковые файлы, которых в папке нет и взять неоткуда.
        case .fileLacks(let path, let parts):
            return "в файле \(path) нет \(parts.joined(separator: ", "))"
        // ⚠️ ЗАГОЛОВОК НАЗЫВАЕТ РАЗРЕШЁННОЕ, А НЕ ТОЛЬКО ЗАПРЕЩЁННОЕ. По отчёту
        // разбирают, ЧТО не получилось, и «нет ссылок в интернет» соврало бы: ссылки
        // на наши библиотеки как раз можно, и человек должен видеть это в строке,
