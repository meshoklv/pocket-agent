// MARK: - Ссылки в интернет: что считать бедой, а что нет
//
// ⚠️ ПОЧЕМУ ЭТО ЛЕЖИТ ЗДЕСЬ, А НЕ В ПОДСЧЁТЕ ОЦЕНКИ. Правило «что запрещено» и
// объяснение «почему запрещено именно это» должны лежать рядом, иначе через месяц
// кто-нибудь поправит одно и не заметит второго. В подсчёте оценки остаётся одна
// строка — вызов.

extension BenchCheck {

    /// Один найденный адрес и место, где он лежит в файле.
    struct FoundAddress {
        let value: String
        let start: Int
        /// Индекс СРАЗУ ЗА последним символом адреса.
        let end: Int
    }

    /// Прошёл ли файл проверку «нет ссылок на то, чего нет на полке».
    static func hasNoUnknownLinks(fileAt url: URL) -> Bool {
        guard let text = try? String(contentsOf: url, encoding: .utf8) else { return false }
        let chars = Array(text)
        let addresses = externalAddresses(in: chars)
        // ⚠️⚠️ ПУСТОТА И «СТРАНИЦА ИЗ ОДНИХ ССЫЛОК» ОБЯЗАНЫ ДАВАТЬ КРАСНОЕ.
        // Проверка устроена как отрицание, а отрицание всегда верно для пустого
        // файла — ровно на этом уже обжигался `fileLacks`. Поэтому считаем
        // СОБСТВЕННОЕ содержимое: всё, что осталось, когда выкинуты подключения
        // библиотек. Страница из трёх тегов `<script src="…с полки…">` и больше
        // ничего — это не сайт, и зелёной она быть не должна.
        guard ownContent(chars, besides: addresses) >= 40 else { return false }
        return unknownAddresses(among: addresses.map(\.value)).isEmpty
    }

    /// Сколько в файле СОБСТВЕННОГО содержимого — без подключений библиотек.
    ///
    /// ⚠️ ВЫКИДЫВАЕМ ТЕГ ЦЕЛИКОМ, А НЕ ОДИН АДРЕС. Вычесть только буквы адреса мало:
    /// у `<script src="…"></script>` остаётся ещё три десятка знаков обвязки, и
    /// страница из одних подключений опять выглядела бы «непустой». Адрес внутри
    /// скрипта (например в `import`) тегом не окружён — там выкидывается он один.
    static func ownContent(_ chars: [Character], besides addresses: [FoundAddress]) -> Int {
        guard !chars.isEmpty else { return 0 }
        var skip = [Bool](repeating: false, count: chars.count)
        for address in addresses {
            var from = address.start
            var to = min(address.end, chars.count)
            // Шаг влево до `<`. Наткнулись на `>` раньше — значит адрес не в теге.
            var left = address.start
            var openAt: Int?
            var steps = 0
            while left >= 0, steps < 400 {
                if chars[left] == "<" { openAt = left; break }
                if chars[left] == ">" { break }
                left -= 1
                steps += 1
            }
            if let openAt {
                var right = to
                var closeAt: Int?
                steps = 0
                while right < chars.count, steps < 400 {
                    if chars[right] == ">" { closeAt = right; break }
                    if chars[right] == "<" { break }
                    right += 1
                    steps += 1
                }
                if let closeAt {
                    from = openAt
                    to = closeAt + 1
                }
            }
            guard from < to else { continue }
            for index in from..<min(to, chars.count) { skip[index] = true }
        }
        var own = 0
        for (index, character) in chars.enumerated() where !skip[index] && !character.isWhitespace {
            own += 1
        }
        return own
    }

    /// Адреса, которых на полке нет, — из-за них страница и останется голой.
    static func unknownAddresses(among addresses: [String]) -> [String] {
        let shelf = PlaygroundShelf.shared
        return addresses.filter { address in
            if isHarmlessNamespace(address) { return false }
            // Спрашиваем полку обеими формами: нам важно «знаем ли мы такую
            // библиотеку вообще», а не какую именно сборку она отдаст.
            if shelf.shelfAddress(forExternal: address, wantsModule: false) != nil { return false }
            if shelf.shelfAddress(forExternal: address, wantsModule: true) != nil { return false }
            return true
        }
    }

    /// Это не ссылка, а служебное имя пространства — браузер по нему никуда не ходит.
    ///
    /// ⚠️ БЕЗ ЭТОГО СПИСКА ПРОВЕРКА КРАСНЕЛА БЫ НА КАЖДОМ ЗНАЧКЕ. Любая картинка
    /// внутри страницы начинается с `<svg xmlns="http://www.w3.org/2000/svg">` —
    /// это опознаватель формата, никакой загрузки за ним нет. Валить за него
    /// работающую страницу значило бы повторить ту же ошибку, ради которой
    /// вся эта проверка и заводится.
    static func isHarmlessNamespace(_ address: String) -> Bool {
        let lower = address.lowercased()
        let marks = ["//www.w3.org/", "//w3.org/", "//schema.org", "//www.schema.org",
                     "//purl.org/", "//ns.adobe.com/", "//creativecommons.org/ns"]
        return marks.contains { lower.contains($0) }
    }

    /// Все интернет-адреса, которые вообще встречаются в тексте страницы.
    ///
    /// ⚠️ РАЗБОР НАРОЧНО ГРУБЫЙ, НО В БЕЗОПАСНУЮ СТОРОНУ: лучше заметить лишний
    /// адрес (и разобраться), чем прозевать настоящий выход в сеть.
    static func externalAddresses(in chars: [Character]) -> [FoundAddress] {
        // Кавычки, скобки и угловые знаки адрес не продолжают.
        let stops: Set<Character> = ["\"", "'", "`", "<", ">", ")", "\\", "}", "]"]
        var found: [FoundAddress] = []
        var i = 0
        while i < chars.count {
            var isStart = false
            if hasPrefix(chars, at: i, "http://") || hasPrefix(chars, at: i, "https://") {
                isStart = true
            } else if chars[i] == "/", i + 1 < chars.count, chars[i + 1] == "/" {
                // ⚠️ «//cdn…» СЧИТАЕМ АДРЕСОМ ТОЛЬКО ТАМ, ГДЕ ОН СТОИТ ЗНАЧЕНИЕМ —
                // сразу за кавычкой, знаком равенства или скобкой. Иначе каждая
                // строчка комментария `// считаем очки` в скрипте превращалась бы
                // в «ссылку в интернет», и замер валил бы честные страницы пачками.
                let before = i > 0 ? chars[i - 1] : " "
                isStart = before == "\"" || before == "'" || before == "=" || before == "("
            }
            guard isStart else {
                i += 1
                continue
            }
            var j = i
            var value = ""
            while j < chars.count, !chars[j].isWhitespace, !stops.contains(chars[j]) {
                value.append(chars[j])
                j += 1
            }
            // Знак препинания в конце фразы адресом не является.
            while let last = value.last, ".,;:!?".contains(last) { value.removeLast() }
            if value.count > 8 {
                found.append(FoundAddress(value: value, start: i, end: i + value.count))
            }
            i = max(j, i + 1)
        }
        return found
    }

    /// Начинается ли текст с этого куска (без учёта регистра).
    ///
    /// ⚠️ Сравниваем строками, а не собранным символом: у части букв нижний регистр
    /// состоит из двух знаков, и попытка уложить их в один Character уронила бы замер.
    private static func hasPrefix(_ chars: [Character], at i: Int, _ needle: String) -> Bool {
        let n = Array(needle).map { String($0) }
        guard i >= 0, i + n.count <= chars.count else { return false }
        for k in 0..<n.count where chars[i + k].lowercased() != n[k] { return false }
        return true
    }
}

