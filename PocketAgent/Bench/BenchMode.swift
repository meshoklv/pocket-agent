//
//  Выключатель ЗАМЕРА: приложение запускается, само прогоняет набор задач на живой
//  модели живого телефона и кладёт рядом отчёт с оценками. Человек в это время
//  ничего не нажимает.
//
//  ЗАЧЕМ ЭТО ВООБЩЕ ПОЯВИЛОСЬ (06.09.2026). Владелец сказал прямо: «условно 3 запуска
//  из 10 успешных». Числа «3 из 10» у нас не было ни одного — ни до правок, ни после:
//  всё, что мы про модель знали, добывалось чтением переписок задним числом. Значит
//  и любая правка оценивалась на глаз. Замер закрывает ровно эту дыру: одна и та же
//  дюжина задач, один и тот же телефон, одна и та же модель — и число до правки
//  и после. Без него «стало лучше» — это мнение, а не факт.
//
//  ⚠️ ПОЧЕМУ ЗАМЕР ГОНЯЕТСЯ НА ТЕЛЕФОНЕ, А НЕ НА МАКЕ. Модель считает на видеочипе
//  телефона; на симуляторе движок Apple не работает вовсе, а движок Google ведёт себя
//  иначе. Замер, снятый не на том железе, отвечал бы не на тот вопрос.
//
//  КАК ЗАПУСКАТЬ (с Мака, приложение уже стоит на телефоне):
//
//      xcrun devicectl device process launch --device <UDID> --console pocket-agent \
//          -PocketAgentBench YES -PocketAgentBenchRepeats 3
//
//  Аргументы «-Ключ Значение» система сама кладёт в домен аргументов UserDefaults —
//  он временный, на диск не пишется и старше всех остальных. Тот же приём, что
//  у демонстрационного режима (Demo/DemoMode.swift), и намеренно тот же: два разных
//  способа читать флаги разошлись бы через месяц.
//
//  Ключи:
//    -PocketAgentBench YES          — включить замер
//    -PocketAgentBenchRepeats N     — сколько раз прогнать каждую задачу (по умолчанию 1)
//    -PocketAgentBenchArm before    — прогнать со СНЯТЫМИ правками (для честного «до/после»)
//    -PocketAgentBenchModel <файл>  — какой моделью считать (имя файла или папки)
//    -PocketAgentBenchOnly <id>     — прогнать одну задачу по её опознавателю
//    -PocketAgentBenchOwnerFolder YES — считать в НАСТОЯЩЕЙ папке владельца (только чтение!)
//
//  ⚠️ Про последний ключ отдельно: он берёт папку, которую владелец выбрал сам
//  (в том числе в iCloud), НИЧЕГО в ней не раскладывает и НИЧЕГО не записывает —
//  каждое предложение записи автоматически отклоняется. Это единственный способ
//  померить приложение в настоящих условиях, а не на игрушечной папке из шести файлов.
//

// ⚠️ ВЕСЬ ЗАМЕР — ТОЛЬКО ОТЛАДОЧНАЯ СБОРКА, как и демонстрация. На телефон владельца
// по проводу уезжает именно Debug (tools/mac/pa-ship.sh), поэтому замер там доступен,
// а в TestFlight и в магазин он не попадает: там это мёртвый код и служебные тексты.
#if DEBUG

import Foundation

enum BenchMode {

    /// Включён ли замер. Считается один раз: переключать режим на ходу нельзя.
    static let isEnabled: Bool = flag("PocketAgentBench", env: "POCKET_AGENT_BENCH")

    /// Сколько раз гонять каждую задачу. Маленькая модель отвечает по-разному от раза
    /// к разу, и один прогон — это не замер, а анекдот. Три прогона уже показывают,
    /// «иногда получается» или «получается всегда».
    static let repeats: Int = {
        let value = UserDefaults.standard.integer(forKey: "PocketAgentBenchRepeats")
        if value > 0 { return value }
        // Запасной путь — переменная окружения: аргументы запуска у devicectl
        // приходится передавать через разделитель «--», и это легко потерять.
        if let raw = ProcessInfo.processInfo.environment["POCKET_AGENT_BENCH_REPEATS"],
           let parsed = Int(raw), parsed > 0 {
            return parsed
        }
        return 1
    }()

    /// «before» — прогнать со снятыми правками этого захода, чтобы получить честное
    /// число ДО на том же самом железе, той же модели и в тот же вечер.
    /// Всё остальное (в том числе пустое значение) — «after», обычное поведение.
    static let isBeforeArm: Bool = {
        let value = UserDefaults.standard.string(forKey: "PocketAgentBenchArm")
            ?? ProcessInfo.processInfo.environment["POCKET_AGENT_BENCH_ARM"]
        return value?.lowercased() == "before"
    }()

    /// Чем считать поиск в интернете у владельца: «on» / «off». Пусто — не вмешиваться.
    ///
    /// ⚠️ ЗАЧЕМ ЭТО ЕСТЬ. Оборванный замер один раз уже оставил на телефоне владельца
    /// свои значения, и следующий прогон записал их в отчёт как «настройки владельца» —
    /// то есть закрепил поломку. Слепок на диске (см. BenchRunner) чинит это на будущее,
    /// но настройку, испорченную ДО его появления, вернуть нечем. Этот ключ — ровно
    /// такая лопата: сказать замеру, каким было настоящее значение, чтобы он его вернул.
    static let ownerWebSearch: Bool? = {
        let value = UserDefaults.standard.string(forKey: "PocketAgentBenchOwnerWeb")
            ?? ProcessInfo.processInfo.environment["POCKET_AGENT_BENCH_OWNER_WEB"]
        switch value?.lowercased() {
        case "on", "1", "yes", "true": return true
        case "off", "0", "no", "false": return false
        default: return nil
        }
    }()

    /// Какая модель была у владельца на самом деле — вернуть именно её.
    ///
    /// ⚠️ Такая же лопата, как `ownerWebSearch`, и по той же причине: оборванный
    /// прогон (Мак ушёл в сон посреди сравнения моделей) оставляет выбранной чужую
    /// модель, а слепка на диске у старых сборок ещё нет. Имя файла или папки.
    static let ownerModel: String? = {
        let value = UserDefaults.standard.string(forKey: "PocketAgentBenchOwnerModel")
            ?? ProcessInfo.processInfo.environment["POCKET_AGENT_BENCH_OWNER_MODEL"]
        guard let value, !value.isEmpty else { return nil }
        return value
    }()

    /// Каким файлом модели считать. Пусто — та модель, что выбрана в приложении.
    static let modelFileName: String? = {
        let value = UserDefaults.standard.string(forKey: "PocketAgentBenchModel")
            ?? ProcessInfo.processInfo.environment["POCKET_AGENT_BENCH_MODEL"]
        guard let value, !value.isEmpty else { return nil }
        return value
    }()

    /// ⚠️⚠️ ЗАМЕР В НАСТОЯЩЕЙ ПАПКЕ ВЛАДЕЛЬЦА — И ТОЛЬКО НА ЧТЕНИЕ.
    ///
    /// ЗАЧЕМ. Всё, что замер раскладывал сам, — это игрушка: шесть файлов внутри
    /// приложения, один уровень вложенности, README на восемь строк. У владельца
    /// в работе настоящие репозитории: 35 записей в корне, вложенность в четыре
    /// уровня, README на 39 КБ, папка tests на сотни файлов — и лежит всё это
    /// в iCloud, то есть за медленным файл-провайдером, который умеет отдавать
    /// файлы не сразу. Ровно в этих условиях помощник у него и ломался, а замер
    /// их не воспроизводил ВООБЩЕ. Отсюда и «мои реальные тесты не совпадают
    /// с твоими. Ваще никак».
    ///
    /// Включённый ключ означает: свою папку замер НЕ раскладывает, а берёт ту,
    /// которую владелец выбрал сам (ProjectRoot.restore() поднимает сохранённую
    /// закладку — тот же путь, каким папка возвращается после перезапуска).
    ///
    /// ⛔⛔ И ГЛАВНОЕ: В ЭТОМ РЕЖИМЕ ЗАМЕР НЕ ИМЕЕТ ПРАВА ИЗМЕНИТЬ НИ ОДНОГО ФАЙЛА.
    /// Любое предложение записи автоматически ОТКЛОНЯЕТСЯ, задачи берутся только
    /// на чтение, а раскладка файлов запрещена насмерть. Как именно это заперто —
    /// см. BenchRunner: `decideOnPendingAction` и `seedFolder`.
    static let usesOwnerFolder: Bool = flag("PocketAgentBenchOwnerFolder",
                                            env: "POCKET_AGENT_BENCH_OWNER_FOLDER")

    /// Проверить ТОЛЬКО площадку и выйти. Модель для этого не нужна — секунды.
    ///
    /// ⚠️ Отдельным ключом, а не задачей в наборе: остальные задачи гоняют живую
    /// модель по несколько минут каждая, а здесь проверяется устройство площадки —
    /// обход папки, невидимая проверка страницы и граница. Смешивать их в одном
    /// прогоне значит ждать час ради проверки, которая занимает секунды.
    static let checksPlaygroundOnly: Bool = flag("PocketAgentBenchPlayground",
                                                 env: "POCKET_AGENT_BENCH_PLAYGROUND")

    /// Прогнать только одну задачу — когда чиним что-то конкретное и незачем ждать час.
    static let onlyScenario: String? = {
        let value = UserDefaults.standard.string(forKey: "PocketAgentBenchOnly")
            ?? ProcessInfo.processInfo.environment["POCKET_AGENT_BENCH_ONLY"]
        guard let value, !value.isEmpty else { return nil }
        return value
    }()

    /// Какой вариант системной инструкции проверяем.
    ///
    /// ⚠️ ЗАЧЕМ ЭТО ЕСТЬ. Разбор нашей же инструкции (10.09.2026) нашёл в ней прямое
    /// противоречие: первая строка приказывает «делай сразу, не спрашивай», а шестая
    /// разрешает «спрашивай, только если без ответа никак». Для модели на 4 млрд это
    /// читается как «спрашивать можно» — и это ровно то самое «сформулируйте задачу»,
    /// которым владелец получал десять ходов подряд. Плюс чужие замеры («curse of
    /// instructions») показывают: доля выполненных указаний падает тем быстрее, чем
    /// их больше, даже когда каждое по отдельности модели по силам.
    ///
    /// ⛔ НО ЭТО ГИПОТЕЗА, А НЕ ЗНАНИЕ. Ровно так же «очевидной» выглядела глубина
    /// просмотра в два уровня — и оказалась хуже на шесть прогонов. Поэтому короткий
    /// вариант живёт под выключателем и сравнивается числом на одном и том же наборе,
    /// а не внедряется на веру.
    static let promptVariant: String = {
        let value = UserDefaults.standard.string(forKey: "PocketAgentBenchPrompt")
            ?? ProcessInfo.processInfo.environment["POCKET_AGENT_BENCH_PROMPT"]
        return (value ?? "").lowercased()
    }()

    /// Флаг из аргумента запуска или из переменной окружения.
    private static func flag(_ key: String, env: String) -> Bool {
        if UserDefaults.standard.bool(forKey: key) { return true }
        guard let raw = ProcessInfo.processInfo.environment[env]?.lowercased() else { return false }
        return raw == "1" || raw == "yes" || raw == "true"
    }
}

#endif
