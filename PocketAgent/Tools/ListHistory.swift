import Foundation

/// Что делать с просьбой показать папку, которую модель в этом разговоре уже видела.
public enum ListAdvice: Equatable, Sendable {

    /// Показывать как просили. Обычный случай.
    case asAsked

    /// Ровно эту папку с ровно этим содержимым модель уже получала — но впервые.
    /// Список не повторяем, отвечаем короткой строкой; ход считается УДАЧНЫМ.
    ///
    /// ⚠️ Первый повтор прощаем нарочно. В длинном разговоре модель законно смотрит
    /// корень заново на новом ходу человека — и объявить это неудачей значило бы
    /// наказать её за нормальную работу. Ровно так же устроена память о чтении:
    /// там «читать нечего» становится неудачей только с третьей просьбы подряд.
    case alreadySeen(note: String)

    /// Просит одно и то же снова и снова. Ход обязан быть засчитан как НЕУДАЧНЫЙ,
    /// иначе круг не кончится: любой успех обнуляет счётчик кривых ходов, и повторять
    /// можно до самого предела шагов — ровно это и было в переписке владельца.
    case stuck(note: String)
}

/// Какие папки и в каком виде модель уже получила за этот разговор.
///
/// Один экземпляр на сессию агента — как и память о прочитанном.
public final class ListHistory: @unchecked Sendable {

    private let lock = NSLock()
    /// путь → отпечаток выдачи, которую мы за него отдали.
    private var seen: [String: String] = [:]
    /// Сколько раз подряд модель просила уже виденное. Нужен, чтобы не повторять
    /// одну и ту же отповедь бесконечно, а сказать жёстче.
    private var repeatsInARow = 0

    public init() {}

    /// Ключ пути: пустая строка, «.» и «/» — это одна и та же папка (корень проекта).
    private static func key(_ relativePath: String) -> String {
        let trimmed = relativePath.trimmingCharacters(in: CharacterSet(charactersIn: " /\n\t"))
        return trimmed == "." ? "" : trimmed.lowercased()
    }

    /// Отпечаток выдачи: имена и их порядок. Размеры и оговорки нарочно не берём —
    /// от них отпечаток менялся бы на ровном месте (например, папка догрузилась
    /// из облака и пропала оговорка), и глушение бы не сработало.
    public static func fingerprint(of listing: WorkspaceListing) -> String {
        listing.entries.map { $0.relativePath }.joined(separator: "\n")
    }

    /// Спросить ДО того, как отдавать список модели.
    public func advice(forPath relativePath: String, fingerprint: String) -> ListAdvice {
        lock.lock(); defer { lock.unlock() }
        guard seen[Self.key(relativePath)] == fingerprint else { return .asAsked }
        repeatsInARow += 1
        let text = note(afterRepeats: repeatsInARow)
        return repeatsInARow >= 2 ? .stuck(note: text) : .alreadySeen(note: text)
    }

    /// Запомнить, что такую выдачу мы уже отдали.
    public func remember(path relativePath: String, fingerprint: String) {
        lock.lock(); defer { lock.unlock() }
        seen[Self.key(relativePath)] = fingerprint
        repeatsInARow = 0
    }

    /// Забыть всё про папку: мы в неё только что записали, и старый список — ложь.
    ///
    /// ⚠️ Забываем и саму папку, и все её родительские: файл, появившийся в глубине,
    /// меняет выдачу каждой папки над ним.
    public func forget(path relativePath: String) {
        lock.lock(); defer { lock.unlock() }
        var current = Self.key(relativePath)
        while true {
            seen.removeValue(forKey: current)
            guard let slash = current.lastIndex(of: "/") else { break }
            current = String(current[current.startIndex..<slash])
        }
        seen.removeValue(forKey: "")
    }

    /// Что сказать модели вместо повтора списка.
    ///
    /// ⚠️ ТЕКСТ РАЗНЫЙ НА ПЕРВЫЙ И НА ТРЕТИЙ РАЗ, И ЭТО НЕ УКРАШЕНИЕ. Повторять
    /// дословно одну и ту же фразу маленькой модели бессмысленно: она отвечает на неё
    /// тем же самым, и мы вдвоём ходим по кругу. Ровно так наша собственная подсказка
    /// четыре раза подряд убила живой разговор владельца 07.09.2026. Поэтому на третий
    /// раз говорим не «посмотри другое», а «смотреть больше нечего, отвечай».
    private func note(afterRepeats count: Int) -> String {
        count >= 3
            ? "Эту папку ты смотришь уже третий раз, и она не менялась. "
            + "Папки больше не смотри: открой файл из списка через read_file "
            + "или ответь человеку тем, что уже знаешь, и вызови finish."
            : "Эту папку ты в этом разговоре уже смотрел, содержимое то же самое. "
            + "Повторять список незачем — открой нужный файл через read_file "
            + "или ответь и вызови finish."
    }
}
