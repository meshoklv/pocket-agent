//  трижды подряд попросил показать содержимое ФАЙЛОВ как папок.
//
//  У чтения такая память есть давно (ReadHistory) и работает: «уже прочитан целиком —
//  второй раз не читаю». У просмотра папок её не было вовсе — просто потому, что
//  сначала болело чтение. Теперь болит это.
//
//  ⚠️ ПОЧЕМУ НЕ «ПРОСТО ЗАПОМНИТЬ ПУТЬ». Папка могла измениться — мы сами только что
//  записали в неё файл, или человек положил туда что-то через «Файлы». Поэтому
//  помним не путь, а ОТПЕЧАТОК ВЫДАЧИ: тот же путь с изменившимся содержимым — это
//  новый, честный просмотр, и мы его не глушим. Ровно тот же принцип, что у чтения:
//  отдать устаревшее страшнее, чем заплатить за лишний шаг.
//
//  ⚠️ ПОЧЕМУ ПОВТОР СЧИТАЕТСЯ НЕУДАЧНЫМ ХОДОМ. Ответ «ты это уже видел» сам по себе
//  успех: ошибки нет, шаг прошёл. А значит счётчик кривых ходов в движке обнулится,
//  и модель сможет повторять один и тот же просмотр до самого предела шагов, пока
//  человек смотрит на крутящийся кружок. Поэтому повтор — это неудача, и дальше
//  срабатывает обычная честная остановка.
